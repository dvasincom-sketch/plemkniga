import { NextResponse, type NextRequest } from 'next/server'
import {
  DEMO_HOST,
  DEMO_READY,
  SITE_HOSTS,
  isProductAsset,
  isSiteHost,
  redirectToSite,
  rewriteToSite,
} from '@/lib/hosts'

/**
 * Разведение двух доменов по одному приложению.
 *
 * `plem.online` — витрина продукта, `holstein.plem.online` — действующая
 * племенная книга. Разбор, почему так, — в `lib/hosts.ts`.
 *
 * ## Переписывание, а не перенаправление
 *
 * Адрес в строке браузера остаётся коротким: человек видит
 * `plem.online`, а отвечает ему страница `/site`. Перенаправление
 * показало бы служебный путь и стоило бы лишнего перехода на каждом
 * открытии главной.
 *
 * ## Почему проверяется, не переписан ли адрес уже
 *
 * Промежуточный обработчик срабатывает и на внутренних переходах.
 * Без этой проверки `/site` превратился бы в `/site/site`, и первый же
 * переход внутри витрины упал бы в «страница не найдена» — причём
 * только на боевом домене, где обработчик и работает.
 *
 * ## Чего обработчик не трогает
 *
 * Статику, служебные адреса Next и панель Payload. Переписать `/_next`
 * значило бы отдать витрине запрос за собственным скриптом страницы —
 * и получить белый экран вместо сайта. Отдельно исключён `/api`:
 * там живёт REST Payload, и на витринном домене он должен отвечать
 * так же, как на книжном, — иначе интеграции сломаются от смены адреса.
 */
export function middleware(request: NextRequest) {
  const host = request.headers.get('host')

  /*
   * Показательный домен, пока за ним нет своих данных.
   *
   * Приложение одно, база одна: арендатор меняет имя и реквизиты,
   * но не записи. В день, когда `demo.plem.online` заработал,
   * он немедленно начал показывать двести восемьдесят тысяч настоящих
   * голштинских животных под словом «демонстрация» — чужие данные,
   * выданные за примерные.
   *
   * Заслонка стоит здесь, а не в каждой странице: обработчик видит
   * все адреса разом, и забыть его в одном месте нельзя. Снимается
   * переменной `DEMO_READY=1` на том развёртывании, где стенд поднят
   * со своей базой.
   */
  if (!DEMO_READY && host && host.toLowerCase().split(':')[0] === DEMO_HOST) {
    const url = request.nextUrl.clone()
    if (url.pathname !== '/demo-soon') {
      url.pathname = '/demo-soon'
      return NextResponse.rewrite(url)
    }
    return NextResponse.next()
  }

  /*
   * На домене книги сквозные страницы больше не живут: «Соответствие»,
   * карта ICAR и описание интерфейса переехали на витрину, потому что
   * отвечают на вопросы о продукте, а не о племенной книге ассоциации.
   *
   * Перенаправление постоянное (308, а не 301): 308 сохраняет метод
   * запроса, и машинный `openapi.json` доедет до нового адреса тем же
   * способом, каким его запросили.
   */
  if (!isSiteHost(host)) {
    /*
     * Материалы витрины на домене книги не отдаются: запись работы
     * в кабинете — рассказ о продукте, и под именем Ассоциации она
     * выглядит чужой. Перенаправление, а не «не найдено»: файл
     * существует, просто живёт по другому адресу.
     */
    if (isProductAsset(request.nextUrl.pathname)) {
      return NextResponse.redirect(
        new URL(`https://${SITE_HOSTS[0]}${request.nextUrl.pathname}`),
        308,
      )
    }

    const away = redirectToSite(request.nextUrl.pathname)
    if (away) return NextResponse.redirect(new URL(away), 308)
    return NextResponse.next()
  }

  /*
   * Само превращение адреса живёт в `lib/hosts.ts`: обработчик
   * не проверить без поднятого Next, а функцию — можно, и `check:hosts`
   * это делает. Здесь остаётся только решение «переписывать или нет».
   *
   * Корень превращается в `/site`, а не в `/site/`: лишняя косая черта
   * на конце — другой адрес для поисковика и повод для перенаправления,
   * которого мы как раз избегаем.
   */
  const next = rewriteToSite(request.nextUrl.pathname)
  if (!next) return NextResponse.next()

  const url = request.nextUrl.clone()
  url.pathname = next

  return NextResponse.rewrite(url)
}

export const config = {
  /*
   * Что обработчик вообще видит. Отрицательный отбор, а не список
   * страниц: страницы добавляют часто, исключения — почти никогда,
   * и перечислять надо то, что меняется реже.
   *
   * `favicon.ico`, `robots.txt` и `sitemap.xml` браузеры и поисковики
   * просят от корня, и подмена им пути ничего хорошего не даёт.
   */
  matcher: ['/((?!_next/|api/|admin/|favicon\\.ico|robots\\.txt|sitemap\\.xml).*)'],
}
