import type { CollectionConfig } from 'payload'
import { ACCESS_SCOPES, toOptions } from '@/lib/dictionaries'
import { relId } from '@/lib/visibility'

/**
 * Ссылка на просмотр: показать записи тому, у кого нет учётной записи.
 *
 * ## Зачем, если есть точечный доступ
 *
 * Точечный доступ (`access-grants`) выдаётся **хозяйству** — тому, кто уже
 * в системе, у кого есть организация и вход. Так и должно быть: доступ
 * между участниками книги обязан быть именованным.
 *
 * Но половина запросов приходит не оттуда. Покупатель без учётной записи,
 * ветеринар, оценщик, эксперт выставки, страховой агент — им нужно
 * посмотреть три записи один раз и больше никогда. Заводить каждому
 * организацию в книге ради одного просмотра абсурдно, а отправлять
 * выгрузку в файле — значит отдать данные навсегда и без следа.
 *
 * Ссылка отвечает ровно на это: показать названное, названным объёмом,
 * до названной даты.
 *
 * ## Почему срок обязателен
 *
 * Бессрочная ссылка — это выгрузка, только притворяющаяся доступом:
 * отправленная однажды, она живёт в чужой переписке годами и открывается
 * теми, кому её переслали. У точечного доступа срок можно не ставить,
 * потому что там на другом конце известное хозяйство, которое отвечает
 * за своих людей. Здесь на другом конце неизвестно кто, и единственное,
 * чем владелец управляет после отправки, — дата.
 *
 * ## Чем ссылка отличается от публичного показа
 *
 * Публичный показ (`publicVisible`/`publicDetails`) — решение «пусть видят
 * все». Ссылка — «пусть видит тот, кому я её дал», и объём выбирается
 * отдельно: можно открыть происхождение, не открывая продуктивность.
 * Поэтому ссылка работает и для записи, закрытой от книги: владелец
 * открывает не всем, а адресату.
 *
 * ## Чего ссылка не делает
 *
 * Не даёт править. Не показывает записи чужих хозяйств, даже если их номера
 * подставить в адрес: при открытии сверяется не только токен, но и то, что
 * запись входит **в эту** ссылку. И не продлевается сама: истёкшая ссылка
 * не воскресает, владелец выпускает новую.
 */

export const ShareLinks: CollectionConfig = {
  slug: 'share-links',
  labels: { singular: 'Ссылка на просмотр', plural: 'Ссылки на просмотр' },
  admin: {
    group: 'Доступ',
    useAsTitle: 'note',
    defaultColumns: ['note', 'owner', 'expiresAt', 'opens', 'revokedAt'],
  },
  access: {
    /*
     * Читает владелец и Ассоциация. Посетитель по ссылке эту коллекцию
     * не читает вовсе: страница просмотра ищет ссылку сама,
     * `overrideAccess`, по токену из адреса. Открыть коллекцию анониму
     * значило бы отдать список всех выданных ссылок тому, у кого
     * случайно оказалась одна.
     */
    read: ({ req }) => {
      const user = req.user as { role?: string | null; organization?: unknown } | null
      if (!user) return false
      if (user.role === 'admin' || user.role === 'association') return true
      const org = relId(user.organization)
      return org ? { owner: { equals: org } } : false
    },
    create: () => false,
    update: () => false,
    delete: () => false,
  },
  fields: [
    {
      /*
       * Токен — и адрес, и пароль одновременно. Поэтому он длинный
       * и случайный: подобрать его перебором должно быть невозможно,
       * а не трудно. Значение выдаёт `newShareToken()`, здесь поле
       * только хранится.
       */
      name: 'token',
      type: 'text',
      required: true,
      unique: true,
      index: true,
      label: 'Токен ссылки',
      admin: { readOnly: true },
    },
    {
      type: 'row',
      fields: [
        {
          name: 'owner',
          type: 'relationship',
          relationTo: 'organizations',
          required: true,
          index: true,
          label: 'Хозяйство',
        },
        {
          name: 'createdBy',
          type: 'relationship',
          relationTo: 'users',
          label: 'Кто выпустил',
        },
      ],
    },
    {
      name: 'animals',
      type: 'relationship',
      relationTo: 'animals',
      hasMany: true,
      required: true,
      label: 'Записи',
    },
    {
      name: 'scopes',
      type: 'select',
      hasMany: true,
      required: true,
      label: 'Что открыто',
      options: toOptions(ACCESS_SCOPES),
    },
    {
      type: 'row',
      fields: [
        {
          /*
           * Срок обязателен — в отличие от точечного доступа, где пустое
           * значение означает «бессрочно». Разбор в шапке файла.
           */
          name: 'expiresAt',
          type: 'date',
          required: true,
          index: true,
          label: 'Действует до',
        },
        { name: 'revokedAt', type: 'date', label: 'Отозвана', admin: { readOnly: true } },
      ],
    },
    {
      name: 'note',
      type: 'text',
      label: 'Для кого',
      admin: { description: 'Видно только вам: «Иванову на осмотр», «в страховую»' },
    },
    {
      type: 'row',
      fields: [
        {
          /*
           * Счётчик открытий — единственное, что владелец узнаёт
           * о судьбе ссылки после отправки. Ноль через неделю говорит
           * «не дошла», двадцать — «переслали дальше». Ни то ни другое
           * система за него не решает, но молчать об этом нельзя.
           */
          name: 'opens',
          type: 'number',
          defaultValue: 0,
          label: 'Открытий',
          admin: { readOnly: true },
        },
        {
          name: 'lastOpenedAt',
          type: 'date',
          label: 'Последнее открытие',
          admin: { readOnly: true },
        },
      ],
    },
  ],
}
