import type { CollectionConfig } from 'payload'
import { isAdmin, isAssociationAccess, isAuthenticated } from '@/access'
import { CHECKS } from '@/lib/checks-registry'

/**
 * Настройки автоматических проверок — сторона Ассоциации.
 *
 * ## Что здесь настраивается и почему только это
 *
 * Строка появляется только у тех проверок, которые Ассоциация решила
 * изменить. Отсутствие строки означает «как в реестре», а не «выключено»:
 * таблица хранит отклонения от умолчания, а не копию списка. Иначе при
 * появлении новой проверки её пришлось бы дописывать в базу отдельно,
 * и до этого момента она бы не работала — то есть новая проверка молча
 * не применялась бы, и заметили бы это нескоро.
 *
 * ## Почему код — текст, а не выбор из списка
 *
 * Соблазн сделать `code` полем `select` со значениями из реестра понятен:
 * в админке были бы человеческие подписи вместо строк. Но `select`
 * в PostgreSQL превращается в тип-перечисление, и тогда **каждая новая
 * проверка требовала бы миграции**. Проверки заводятся кодом, а не
 * администратором, и связывать их появление с походом в базу нельзя.
 *
 * Защита от опечатки при этом остаётся: хук ниже сверяет код с реестром
 * и не даёт сохранить настройку для проверки, которой нет.
 *
 * ## Кто настраивает
 *
 * Только Ассоциация, и сразу на всю книгу. Хозяйство настройки видит
 * в каталоге проверок, но не меняет: проверка — часть процедуры, которой
 * Ассоциация подтверждает записи, и подтверждение, прошедшее сквозь
 * фильтр, выставленный проверяемым, ничего не значит. Та же граница,
 * что в правах на заявку (решение №45).
 *
 * Порог, свой у каждого хозяйства, ломал бы главное свойство книги —
 * сравнимость записей между хозяйствами. Поэтому в таблице нет
 * и организации.
 */

const CODES = CHECKS.map((c) => c.code) as string[]

export const CheckSettings: CollectionConfig = {
  slug: 'check-settings',
  labels: { singular: 'Настройка проверки', plural: 'Настройки проверок' },
  admin: {
    useAsTitle: 'code',
    defaultColumns: ['code', 'enabled', 'severity', 'updatedBy'],
    group: 'Племенная книга',
  },
  access: {
    /*
     * Читать может любой вошедший: настройки показываются в каталоге
     * проверок, чтобы хозяйство видело действующие правила, а не те,
     * что были заложены в код. Скрывать их бессмысленно — по ним и так
     * судят по замечаниям.
     */
    read: isAuthenticated,
    create: isAssociationAccess,
    update: isAssociationAccess,
    delete: isAdmin,
  },
  defaultSort: 'code',
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'code',
          type: 'text',
          label: 'Код проверки',
          required: true,
          unique: true,
          index: true,
          admin: { description: 'Из реестра `src/lib/checks-registry.ts`' },
        },
        {
          name: 'enabled',
          type: 'checkbox',
          label: 'Проверка действует',
          defaultValue: true,
        },
        {
          /*
           * Пусто — существенность берётся из реестра. Отдельного значения
           * «как по умолчанию» в списке нет намеренно: пустое поле и так
           * читается именно так, а третий вариант в списке заставлял бы
           * выбирать между «не задано» и «как в реестре», хотя это одно
           * и то же.
           */
          name: 'severity',
          type: 'select',
          label: 'Существенность',
          options: [
            { value: 'fix', label: 'Требует исправления' },
            { value: 'note', label: 'На усмотрение' },
          ],
          admin: { description: 'Пусто — как задано в реестре' },
        },
      ],
    },
    {
      name: 'note',
      type: 'textarea',
      label: 'Почему изменено',
      admin: {
        description:
          'Настройку через год будет читать другой человек. Без причины он не поймёт, можно ли её вернуть',
      },
    },
    {
      name: 'updatedBy',
      type: 'relationship',
      relationTo: 'users',
      label: 'Кто менял',
      admin: { readOnly: true },
    },
  ],
  hooks: {
    beforeChange: [
      ({ data, req }) => {
        /*
         * Код сверяется с реестром. Настройка для несуществующей проверки
         * не сломает разбор — она просто никогда не применится, — и потому
         * опаснее ошибки: Ассоциация будет считать, что правило отключено,
         * а оно продолжит работать.
         */
        if (data?.code && !CODES.includes(String(data.code))) {
          throw new Error(
            `Проверки с кодом «${data.code}» не существует. ` +
              `Доступны: ${CODES.join(', ')}`,
          )
        }

        if (req.user) data.updatedBy = req.user.id
        return data
      },
    ],
  },
}
