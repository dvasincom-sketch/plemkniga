import type { CollectionConfig } from 'payload'
import { savedSearchDelete, savedSearchRead, savedSearchWrite } from '@/access'

/**
 * Именованный отбор животных (ТЗ, требование №6).
 *
 * ## Что сохраняется — вопрос, а не ответ
 *
 * Развилка здесь была настоящая: «сохраняемый набор животных» читается
 * и как условия отбора, и как перечень конкретных карточек. Выбраны
 * условия, и вот почему.
 *
 * Отборы, которые заводят на самом деле, звучат так: «коровы с удоем
 * от девяти тысяч», «первотёлки без отца», «всё, что не проверено
 * Ассоциацией». Это вопросы, и ценность их в том, что ответ меняется:
 * открыв такой набор через месяц, зоотехник хочет видеть, кто подходит
 * **сейчас**, а не кто подходил в марте. Перечень отвечал бы на другой
 * вопрос — «кого я тогда отобрал», — и для него в системе уже есть свой
 * ответ: отметки в таблице и ссылка на просмотр.
 *
 * Перечень к тому же дорог там, где условия бесплатны: он ссылается
 * на карточки, а карточки продают, архивируют и удаляют по сроку.
 * Набор из сорока трёх коров, в котором семь строк ведут в никуда,
 * — это не сохранённая работа, а её обломки.
 *
 * ## Почему хранится строка запроса, а не разобранные поля
 *
 * Условия отбора уже описаны — в `buildAnimalWhere`, который собирает их
 * из адреса страницы. Разложить те же условия по колонкам значило бы
 * описать их второй раз, и второе описание начало бы отставать от первого
 * при первом же новом поле: в форме оно есть, в наборе его нет, и человек
 * сохраняет отбор, теряя половину.
 *
 * Плата за это честная: набор — это ровно то, что было в адресе, и если
 * поле отбора когда-нибудь переименуют, старые наборы про него забудут.
 * Молча они при этом не соврут — неизвестный ключ `buildAnimalWhere`
 * просто не берёт в условия.
 *
 * ## Почему свой, а не сразу общий
 *
 * Отбор — черновик чаще, чем документ: его собирают на ходу, пробуют
 * пороги, сохраняют «на посмотреть». Будь все наборы общими, список
 * хозяйства из трёх человек за месяц превратился бы в свалку, в которой
 * не найти тот единственный, что действительно нужен всем. Поэтому набор
 * заводится личным, а общим становится отметкой — то есть решением,
 * а не побочным действием.
 */

export const SEARCH_PLACES = [
  { value: 'book', label: 'Книга' },
  { value: 'herd', label: 'Моё стадо' },
] as const

export const SEARCH_SCOPES = [
  { value: 'private', label: 'Только я' },
  { value: 'organization', label: 'Всё хозяйство' },
] as const

export const SavedSearches: CollectionConfig = {
  slug: 'saved-searches',
  labels: { singular: 'Отбор', plural: 'Сохранённые отборы' },
  admin: {
    useAsTitle: 'name',
    defaultColumns: ['name', 'place', 'scope', 'author', 'organization'],
    group: 'Племенная книга',
  },
  access: {
    read: savedSearchRead,
    create: savedSearchWrite,
    update: savedSearchWrite,
    delete: savedSearchDelete,
  },
  defaultSort: 'name',
  /*
   * Индекс по автору и месту, а не по одному автору: список открывают
   * всегда на конкретной странице, и «мои отборы книги» — это два
   * условия сразу. Второй индекс — по организации, для общих наборов:
   * их читает не автор, и по автору их не найти.
   */
  indexes: [{ fields: ['author', 'place'] }, { fields: ['organization', 'scope', 'place'] }],
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'name',
          type: 'text',
          label: 'Название',
          required: true,
          maxLength: 80,
          admin: { description: 'Как отбор назовут в списке: «Коровы на выбраковку»' },
        },
        {
          name: 'place',
          type: 'select',
          label: 'Где применяется',
          required: true,
          defaultValue: 'book',
          options: [...SEARCH_PLACES],
          /*
           * Место хранится потому, что одни и те же условия на двух
           * страницах означают разное: в книге отбор идёт по всем
           * хозяйствам, в кабинете — по своему стаду, и там доступны
           * поля, которых в книге нет вовсе. Открыть «свой» набор
           * в книге технически можно, и он даст не то, что ждали.
           */
        },
      ],
    },
    {
      name: 'query',
      type: 'text',
      label: 'Условия отбора',
      required: true,
      maxLength: 2000,
      admin: {
        readOnly: true,
        description: 'Строка запроса — то же, что стоит в адресе страницы после «?»',
      },
    },
    {
      type: 'row',
      fields: [
        {
          name: 'scope',
          type: 'select',
          label: 'Кто видит',
          required: true,
          defaultValue: 'private',
          options: [...SEARCH_SCOPES],
        },
        {
          name: 'author',
          type: 'relationship',
          relationTo: 'users',
          label: 'Автор',
          required: true,
          index: true,
          admin: { readOnly: true },
        },
        {
          name: 'organization',
          type: 'relationship',
          relationTo: 'organizations',
          label: 'Хозяйство',
          index: true,
          admin: {
            readOnly: true,
            description: 'Чьё это хозяйство — от него зависит, кому виден общий отбор',
          },
        },
      ],
    },
  ],
}
