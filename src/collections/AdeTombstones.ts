import type { CollectionConfig } from 'payload'
import { isAdmin } from '@/access'

/**
 * Надгробия: следы удалённых записей для ленты изменений.
 *
 * ## Зачем хранить то, чего больше нет
 *
 * Лента изменений отдаёт партнёру не состояние книги, а её правки:
 * появилось, изменилось, удалено. Первые два вида видны сами — у записи
 * меняется время правки. Третий не виден никак: удалённой строки в базе
 * нет, и сказать о ней нечего.
 *
 * Молчание здесь не безобидно. Партнёр, ведущий свою копию, оставит
 * у себя запись навсегда: он никогда не узнает, что её отозвали, и будет
 * считать по ней удои и отёлы. Расхождение копится тихо и обнаруживается
 * через месяцы — по числам, которые не сходятся, а не по ошибке.
 *
 * Поэтому удаление оставляет след: имя набора, идентификатор ресурса
 * в том виде, в каком он уезжал наружу, и время. Ни одного поля
 * из самой записи — надгробие не должно быть способом сохранить то,
 * что человек попросил удалить.
 *
 * ## Почему навсегда
 *
 * Соблазн подчищать старые надгробия велик: они бесполезны для всех,
 * кто уже забрал их из ленты. Но «все» — это те партнёры, о которых мы
 * знаем сегодня. Подписчик, вернувшийся с меткой полугодовой давности,
 * должен получить пропущенные удаления, иначе его копия останется
 * с призраками. Надгробие — это строка в сотню байт; хранить их дешевле,
 * чем однажды объяснять расхождение.
 *
 * ## Почему хозяйство хранится отдельным полем
 *
 * Лента сужается по правам: партнёр видит правки только тех хозяйств,
 * которые ему открыты. У живой записи хозяйство берётся по связи
 * с животным, а у надгробия связи нет — животного может уже не быть.
 * Поэтому хозяйство переписывается в само надгробие в момент удаления.
 *
 * Пустое значение означает «хозяйство определить не удалось» — так
 * бывает, когда животное удаляют вместе со всей его историей. Такие
 * надгробия видны всем, у кого есть доступ к обмену. Это осознанный
 * выбор из двух зол: показать посторонему идентификатор удалённой
 * записи — мелкая беда, скрыть удаление от того, кто ведёт копию, —
 * молчаливое расхождение данных.
 */
export const AdeTombstones: CollectionConfig = {
  slug: 'ade-tombstones',
  labels: { singular: 'Удалённый ресурс ADE', plural: 'Удалённые ресурсы ADE' },
  admin: {
    group: 'Служебные',
    defaultColumns: ['dataset', 'sourceId', 'deletedAt'],
    description: 'Следы удалённых записей — нужны ленте изменений обмена',
  },
  /*
   * Записывают только хуки, от лица системы. Ручное заведение надгробия
   * означало бы «сказать партнёру, что записи нет», не удаляя её, —
   * ровно тот случай, когда две системы расходятся по чьему-то недосмотру.
   */
  access: {
    read: isAdmin,
    create: () => false,
    update: () => false,
    delete: () => false,
  },
  indexes: [
    /*
     * Порядок в ленте — по времени удаления, а при совпадении по номеру.
     * Указатель повторяет этот порядок: без него обход ленты превращается
     * в сортировку всей таблицы на каждый запрос партнёра.
     *
     * Номера записи в перечне полей нет, хотя сортировка его использует.
     * Payload собирает составные указатели из объявленных полей, а `id`
     * к ним не относится — он первичный ключ, и попытка назвать его здесь
     * роняет всё приложение на разборе настроек: «Field id was not found».
     * Для отбора это ничего не меняет: строк с одинаковой миллисекундой
     * удаления в одном наборе единицы, и добор по ключу их не замедлит.
     */
    { fields: ['dataset', 'deletedAt'] },
  ],
  fields: [
    {
      name: 'dataset',
      type: 'text',
      required: true,
      index: true,
      label: 'Набор данных',
      admin: { description: 'Имя раздела стандарта: animals, test-day-results и прочие' },
    },
    {
      name: 'sourceId',
      type: 'text',
      required: true,
      label: 'Идентификатор ресурса',
      admin: { description: 'Ровно тот, под которым ресурс уезжал в обмен' },
    },
    {
      name: 'location',
      type: 'relationship',
      relationTo: 'organizations',
      label: 'Хозяйство',
      admin: { description: 'Пусто, если определить не удалось: тогда видно всем' },
    },
    {
      name: 'deletedAt',
      type: 'date',
      required: true,
      index: true,
      label: 'Когда удалено',
    },
  ],
}
