import type { CollectionConfig } from 'payload'
import { relId } from '@/lib/visibility'

/**
 * Реестр удалённых записей: след животного, которого больше нет в книге.
 *
 * ## Зачем он существует
 *
 * ТЗ (стр. 43) требовало, чтобы данные животных не удалялись никогда —
 * только уходили в архив. Требование разумное: по номеру животного строят
 * родословные, на него ссылаются свидетельства и чужие карточки, и запись,
 * пропавшая бесследно, превращает всё это в ссылки в пустоту.
 *
 * Но вечный архив оказался неработающим в другую сторону. Запись, залитую
 * по ошибке — не тем файлом, не в то хозяйство, с чужим номером, — убрать
 * было нечем: она навсегда оставалась в кабинете хозяйства и мозолила глаза
 * там, где должна быть только его собственная скотина.
 *
 * Развязка не в том, чтобы выбрать между «удалять» и «не удалять», а в том,
 * чтобы разделить карточку и след. Карточка — рабочий документ хозяйства,
 * и она уходит. След — строка этого реестра — остаётся навсегда. На вопрос
 * «что было под номером 3299729520066» книга отвечает и через десять лет,
 * даже если самой карточки давно нет.
 *
 * ## Почему это не копия карточки
 *
 * Соблазн сложить сюда всю запись целиком велик — и он неправ. Копия
 * карточки не удаление, а переименование: те же данные, только в другой
 * таблице и без проверок. Здесь лежит ровно то, что нужно, чтобы ответить
 * на вопрос «что здесь было и куда делось»: номер, кличка, хозяйство,
 * дата рождения, когда убрали и почему. Продуктивность, оценки, промеры
 * уходят вместе с карточкой — они и есть те данные, ради удаления которых
 * всё затевалось.
 *
 * ## Почему запись нельзя ни изменить, ни удалить
 *
 * Реестр, который можно поправить, — не реестр, а черновик. Если след
 * об ошибочной загрузке можно стереть вторым нажатием, то первое нажатие
 * ничего не гарантирует. Поэтому создаёт записи только система (сценарий
 * очистки, `overrideAccess`), а изменение и удаление закрыты всем, включая
 * администратора.
 */

const orgOf = (user: unknown): number | null =>
  relId((user as { organization?: unknown } | null)?.organization)

export const AnimalRemovals: CollectionConfig = {
  slug: 'animal-removals',
  labels: { singular: 'Удалённая запись', plural: 'Реестр удалённых записей' },
  admin: {
    group: 'Служебное',
    useAsTitle: 'identNumber',
    defaultColumns: ['identNumber', 'name', 'owner', 'removedAt'],
    description:
      'След записей, убранных из книги. Пополняется сценарием очистки архива, руками не правится.',
  },
  access: {
    /*
     * Видит Ассоциация — вся, и хозяйство — только свои удалённые записи.
     *
     * Показывать хозяйству чужие удаления нельзя: список ошибок соседа
     * не его дело. Прятать от него свои — тоже: именно к своим он
     * и приходит с вопросом «а куда делась корова».
     */
    read: ({ req }) => {
      const user = req.user as { role?: string | null; organization?: unknown } | null
      if (!user) return false
      if (user.role === 'admin' || user.role === 'association') return true
      const org = orgOf(user)
      return org ? { owner: { equals: org } } : false
    },
    create: () => false,
    update: () => false,
    delete: () => false,
  },
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'identNumber',
          type: 'text',
          required: true,
          index: true,
          label: 'Индивидуальный номер',
        },
        { name: 'name', type: 'text', label: 'Кличка' },
      ],
    },
    {
      type: 'row',
      fields: [
        {
          name: 'owner',
          type: 'relationship',
          relationTo: 'organizations',
          index: true,
          label: 'Хозяйство',
        },
        { name: 'birthDate', type: 'date', label: 'Дата рождения' },
      ],
    },
    {
      type: 'row',
      fields: [
        { name: 'archivedAt', type: 'date', label: 'Отправлено в архив' },
        { name: 'removedAt', type: 'date', required: true, label: 'Удалено из книги' },
      ],
    },
    {
      name: 'archivedBy',
      type: 'relationship',
      relationTo: 'users',
      label: 'Кто отправил в архив',
    },
    { name: 'archiveReason', type: 'text', label: 'Причина архивации' },
    {
      /*
       * Сколько связанных записей ушло вместе с карточкой.
       *
       * Без этого числа след говорит «карточки нет», но молчит о том,
       * что вместе с ней исчезли триста контрольных доек. Спросят об этом
       * не в день удаления, а через год, когда расходится статистика
       * хозяйства, — и ответить будет нечем.
       */
      name: 'removedRecords',
      type: 'number',
      label: 'Удалено связанных записей',
      admin: { description: 'Отёлы, дойки, осеменения, оценки — всё, что ссылалось на карточку' },
    },
  ],
}
