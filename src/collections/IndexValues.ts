import type { CollectionConfig } from 'payload'
import { indexValueRead } from '@/access'
import { WEIGHT_KINDS } from './IndexProfiles'
import { STATES, toOptions } from '@/lib/dictionaries'

/**
 * Рассчитанный индекс племенной ценности — по одной строке на пару
 * «животное + профиль».
 *
 * Зачем хранить то, что считается формулой. Две причины, и обе не про скорость.
 *
 * Первая — воспроизводимость. Индекс попадает в выпускаемые документы, а его
 * значение зависит от весов профиля и от базы сравнения. И то и другое
 * пересматривается. Через полгода к числу в бумажном свидетельстве возвращаются
 * с вопросом «откуда оно», и ответ должен лежать рядом с числом: какой профиль,
 * какая версия базы, когда посчитано.
 *
 * Вторая — порядок. Отсортировать книгу по индексу можно только по хранимому
 * числу: пока значение считалось на лету, порядок строился в памяти по порции
 * записей, и списки упирались в потолок.
 *
 * Строки служебные: их пишет пересчёт, а не человек. Поэтому коллекция скрыта
 * из админки и закрыта на запись — руками здесь делать нечего.
 */

export const IndexValues: CollectionConfig = {
  slug: 'index-values',
  labels: { singular: 'Значение индекса', plural: 'Значения индекса' },
  admin: { hidden: true, useAsTitle: 'profileName' },
  access: {
    read: indexValueRead,
    // Пишет только пересчёт, в обход правил доступа
    create: () => false,
    update: () => false,
    delete: () => false,
  },
  indexes: [
    // Порядок в списке: отбор по профилю, сортировка по значению
    { fields: ['profileKey', 'value'] },
    /*
     * Составного индекса «профиль + три условия + значение» здесь нет,
     * хотя напрашивается. Он был заведён и оказался мёртвым: планировщик
     * его ни разу не выбрал — идти по индексу значения назад и отбрасывать
     * лишнее ему дешевле, чем читать шестьдесят шесть мегабайт составного.
     * Проверено прогоном сценариев: без него страница по профилю занимает
     * те же 0,38 с. Разбор — docs/refaktoring-bazy.md, раздел 11.
     */
    /*
     * Процентиль: сколько ровесников по этому профилю ниже данного значения.
     * Три счёта на каждую карточку животного, и все три — по этим трём
     * колонкам. В отличие от прежнего составного индекса, этот заведён
     * по измерению, а не на всякий случай: без него карточка отвечала
     * 2,8 секунды, с ним — 0,2.
     */
    { fields: ['profileKey', 'birthYear', 'value'] },
    // Значение конкретного животного по конкретному профилю — ровно одно
    { fields: ['animal', 'profileKey'], unique: true },
  ],
  fields: [
    {
      name: 'animal',
      type: 'relationship',
      relationTo: 'animals',
      required: true,
      index: true,
    },
    {
      /*
       * Ключ профиля, а не связь: встроенные профили живут в коде и записи
       * в базе не имеют. Ключ одинаково описывает и встроенный профиль
       * (`association`), и собственный профиль хозяйства (`own:12`).
       */
      name: 'profileKey',
      type: 'text',
      label: 'Профиль',
      required: true,
      index: true,
    },
    {
      /*
       * Название и веса на момент расчёта. Профиль могут переименовать,
       * перенастроить и удалить — а документ, выпущенный с этим числом,
       * останется. Без снимка объяснить старое значение будет нечем.
       */
      name: 'profileName',
      type: 'text',
      label: 'Название профиля на момент расчёта',
    },
    {
      name: 'kind',
      type: 'select',
      options: [...WEIGHT_KINDS],
      defaultValue: 'selection',
    },
    {
      name: 'weights',
      type: 'json',
      label: 'Веса на момент расчёта',
    },
    {
      name: 'baseVersion',
      type: 'text',
      label: 'Версия базы сравнения',
    },
    /*
     * Копии полей животного, по которым отбирают всегда.
     *
     * Условие на связь Payload превращает в отдельный `left join` — по одному
     * на каждое условие. Страница книги отбирает по видимости, архиву
     * и владельцу, то есть тянула три копии таблицы животных: 1,3 секунды
     * на подсчёт итога вместо 0,19 с единственным join.
     *
     * Копии не расходятся с оригиналом: строка значения переписывается хуком
     * при каждом изменении животного, эти поля пишутся тогда же и оттуда же.
     * Читать их вместо `animal.*` умеет `prefixWhere` в `src/lib/index-column.ts`.
     */
    {
      type: 'row',
      fields: [
        {
          name: 'owner',
          type: 'relationship',
          relationTo: 'organizations',
          label: 'Владелец (копия)',
          index: true,
          admin: { readOnly: true },
        },
        {
          name: 'publicVisible',
          type: 'checkbox',
          label: 'Публичная (копия)',
          admin: { readOnly: true },
        },
        {
          name: 'archived',
          type: 'checkbox',
          label: 'В архиве (копия)',
          admin: { readOnly: true },
        },
        {
          // Книга по умолчанию показывает живых — условие стоит в каждом запросе
          /*
             Индексов на этих трёх копиях нет: по отдельности они бесполезны
             (два значения на два миллиона строк), а вместе их запрос всё равно
             не использует. Заведённые «на всякий случай», они занимали
             шестьдесят мегабайт и не пригодились ни разу.
          */
          name: 'state',
          type: 'select',
          options: toOptions(STATES),
          label: 'Состояние (копия)',
          admin: { readOnly: true },
        },
        {
          /*
           * Год рождения — для группы сравнения при расчёте процентиля.
           * Ровесники сравниваются с ровесниками: за пятнадцать лет база
           * сдвигается, и первотёлка рядом с быком 2010 года бессмысленна.
           *
           * Год, а не дата: группа всегда годовая, а числу вместо даты
           * не нужен ни разбор диапазона, ни приведение часовых поясов.
           */
          name: 'birthYear',
          type: 'number',
          label: 'Год рождения (копия)',
          admin: { readOnly: true },
        },
      ],
    },
    {
      /*
       * Из какой оценки посчитано. Веса и база сравнения записаны рядом,
       * а сами EBV — нет: раньше их было ровно по одному набору на животное,
       * и вопрос не стоял. С появлением истории он встал: через полгода
       * число в выпущенном документе нужно уметь объяснить целиком, а без
       * ссылки на строку оценки половина исходных данных теряется.
       */
      name: 'evaluation',
      type: 'relationship',
      relationTo: 'animal-evaluations',
      label: 'Оценка, по которой посчитано',
      index: true,
    },
    {
      name: 'value',
      type: 'number',
      label: 'Значение индекса',
      required: true,
      index: true,
    },
    {
      name: 'reliability',
      type: 'number',
      label: 'Достоверность, %',
    },
    {
      /** Сколько признаков профиля удалось учесть — по скольким есть оценки. */
      name: 'used',
      type: 'number',
    },
    {
      name: 'computedAt',
      type: 'date',
      label: 'Когда посчитано',
    },
  ],
}
