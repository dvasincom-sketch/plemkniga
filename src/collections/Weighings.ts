import type { CollectionConfig } from 'payload'
import { isAdmin, isAuthenticated, animalScopedReadFor, animalScopedMutate } from '@/access'
import { requireOwnAnimal, stampOwnerOrg } from '@/access/guards'
import { ownerOrgField, adeOriginField } from '@/collections/shared'
import { WEIGHING_SIGNS } from '@/lib/weighing'

/**
 * Взвешивания — живая масса как повторяемое событие.
 *
 * ## Чего не было
 *
 * Книга знала одну массу: телёнка при рождении, полем на отёле. Между тем
 * «Живая масса» — отдельный шаблон ФГИАС ПР и **ежемесячная отчётность**:
 * хозяйство взвешивает и сдаёт постоянно, а положить это было некуда.
 *
 * ## Почему коллекция, а не массив на животном
 *
 * В отличие от выставок, которых у животного единицы за жизнь, взвешиваний
 * десятки: ежемесячно за пять лет — шестьдесят строк. И спрашивают о них
 * не только в карточке: динамика массы по группе, средняя масса тёлок
 * к первому осеменению — вопросы к стаду, а не к животному.
 *
 * Устройство повторяет контрольные дойки: тот же состав (животное, дата,
 * число, номер лактации), та же видимость по животному, тот же индекс.
 * Совпадение не случайно — это одно и то же по форме событие.
 *
 * ## Признак взвешивания
 *
 * Реестр требует его ключом из своего справочника: «при рождении»,
 * «на возраст», «при первом осеменении» и так далее. Без признака число
 * ничего не значит — восемьсот килограммов при продаже и восемьсот
 * при выбытии говорят о разном.
 *
 * Хранится наш код, а ключ реестра подставляется на выгрузке
 * (`src/lib/weighing.ts`). Хранить чужой uuid в карточке значило бы
 * показывать зоотехнику `0e02446c-…` там, где он ждёт «При рождении».
 */
export const Weighings: CollectionConfig = {
  slug: 'weighings',
  labels: { singular: 'Взвешивание', plural: 'Взвешивания' },
  admin: {
    useAsTitle: 'date',
    defaultColumns: ['date', 'animal', 'weight', 'sign'],
    group: 'Воспроизводство',
  },
  access: {
    /*
     * Видимость наследуется от животного — как у доек и отёлов. Масса
     * чужой закрытой коровы такие же её данные, как удой.
     *
     * Область `production`: живая масса — показатель продуктивности,
     * и открывается она тем же точечным доступом, что дойки и лактации,
     * а не отдельным. Заводить пятую область ради одного числа значило
     * бы усложнить разговор о доступе ради строки в справочнике.
     */
    read: animalScopedReadFor('production'),
    create: isAuthenticated,
    update: animalScopedMutate,
    delete: isAdmin,
  },
  indexes: [{ fields: ['animal', 'date'] }],
  fields: [
    ownerOrgField,
    {
      type: 'row',
      fields: [
        {
          name: 'animal',
          type: 'relationship',
          relationTo: 'animals',
          label: 'Животное',
          required: true,
          index: true,
        },
        { name: 'date', type: 'date', label: 'Дата взвешивания', required: true },
        {
          name: 'weight',
          type: 'number',
          label: 'Живая масса, кг',
          required: true,
          min: 0,
          admin: { description: 'Положительное число, до двух знаков после запятой' },
        },
      ],
    },
    {
      type: 'row',
      fields: [
        {
          name: 'sign',
          type: 'select',
          label: 'Признак взвешивания',
          options: WEIGHING_SIGNS.map((s) => ({ value: s.value, label: s.label })),
          admin: {
            description:
              'Зачем взвешивали. Реестр требует его ключом: без признака число ' +
              'ничего не значит — 800 кг при продаже и 800 при выбытии говорят о разном',
          },
        },
        {
          /*
           * Номер лактации — только у самок и только при наличии лактации,
           * так помечено в контракте шаблона. Обязательным не делаем:
           * тёлку взвешивают до первого отёла, и требовать номер значило
           * бы запретить взвешивать молодняк.
           */
          name: 'lactationNumber',
          type: 'number',
          label: 'Номер лактации',
          min: 0,
          admin: {
            description:
              'Лактация, идущая на день взвешивания, — она же число состоявшихся отёлов. ' +
              'Только для самок при наличии лактации',
          },
        },
      ],
    },
    { name: 'note', type: 'textarea', label: 'Примечание' },
    adeOriginField,
  ],
  hooks: {
    /*
     * Те же два хука, что у доек: животное должно быть своим, а хозяйство
     * проставляется само. Правило доступа живёт в одном месте
     * (`access/guards.ts`), и повторять его здесь условиями значило бы
     * завести второе, которое однажды разойдётся с первым.
     */
    beforeChange: [requireOwnAnimal, stampOwnerOrg],
  },
}
