import type { CollectionConfig } from 'payload'
import { anyone, isAdmin } from '@/access'

/**
 * Прогон проверок: что проверялось, когда и с каким исходом.
 *
 * ## Почему хранится, а не считается на лету
 *
 * Проверки дорогие: осмотр базы открывает своё соединение, отчёты по стаду
 * — семь запросов по всему хозяйству. Считать их при каждом открытии
 * страницы значило бы устраивать себе нагрузку ровно тогда, когда кто-то
 * зашёл посмотреть, всё ли в порядке.
 *
 * Но дело не только в цене. Прогон — это факт с датой: «в ночь на
 * двадцать седьмое всё сошлось». Считать его заново при показе значит
 * подменить историю сиюминутным ответом и потерять единственное, ради
 * чего страница заводилась: видно, что систему проверяют регулярно.
 *
 * ## Почему одна запись на среду, а не на каждый прогон
 *
 * Меток две — «Прод» и «Разработка», — и повторный прогон той же среды
 * заменяет прежний. История прогонов звучит заманчиво, но отвечает
 * не на тот вопрос: смотрят сюда, чтобы узнать нынешнее состояние,
 * а не чтобы листать сто одинаковых зелёных ночей. Понадобится
 * история — она заводится отдельной коллекцией, а не превращением
 * этой в ленту.
 *
 * ## Почему результат лежит json, а не колонками
 *
 * Число проб меняется: сегодня их четыре, завтра шесть. Колонки под
 * каждую означали бы миграцию на всякое добавление, а находки внутри
 * пробы — список строк переменной длины, которому в колонке места нет.
 * Тот же довод, что у замеров.
 *
 * ## Почему видно всем
 *
 * Страница «Эволюция продукта» открыта, и зрелость системы — довод
 * в её пользу, а не тайна. В снимок попадают названия проверок, исход,
 * число находок и их короткие описания. Ни номеров животных, ни названий
 * хозяйств: находка формулируется как «отчёт 12, список 11», а не
 * «у коровы такой-то». За этим следят сами пробы (`probes.ts`).
 */
export const CheckRuns: CollectionConfig = {
  slug: 'check-runs',
  labels: { singular: 'Прогон проверок', plural: 'Прогоны проверок' },
  admin: {
    useAsTitle: 'label',
    defaultColumns: ['label', 'ranAt', 'ok', 'failed'],
    group: 'Служебные',
  },
  access: {
    read: anyone,
    /*
     * Создаёт и обновляет только маршрут прогона — через `overrideAccess`.
     * Открытого правила нет: запись, которую можно завести снаружи,
     * означала бы, что нарисовать себе зелёный статус может кто угодно.
     */
    create: () => false,
    update: () => false,
    delete: isAdmin,
  },
  defaultSort: 'label',
  indexes: [{ fields: ['label'] }],
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'label',
          type: 'text',
          label: 'Среда',
          required: true,
          unique: true,
          admin: {
            description:
              'Имя среды: «Прод», «Разработка». Повторный прогон заменяет прежний — ' +
              'смотрят сюда за нынешним состоянием, а не за лентой одинаковых ночей',
          },
        },
        { name: 'ranAt', type: 'date', label: 'Когда прогоняли', required: true },
      ],
    },
    {
      type: 'row',
      fields: [
        {
          name: 'ok',
          type: 'checkbox',
          label: 'Всё сошлось',
          admin: { description: 'Ни одна проба не нашла расхождений' },
        },
        { name: 'failed', type: 'number', label: 'Проб с находками' },
        { name: 'total', type: 'number', label: 'Проб прогнано' },
        { name: 'ms', type: 'number', label: 'Заняло, мс' },
      ],
    },
    {
      /*
       * Версия кода на момент прогона. Без неё зелёный результат
       * не привязан ни к чему: «всё сошлось» — но на какой сборке,
       * той ли, что развёрнута сейчас? Заполняется ручкой из
       * `CURRENT_VERSION`.
       */
      name: 'version',
      type: 'text',
      label: 'Версия платформы',
    },
    {
      name: 'results',
      type: 'json',
      label: 'Результаты проб',
      required: true,
      admin: { description: 'Массив: код пробы, исход, находки, длительность' },
    },
  ],
}
