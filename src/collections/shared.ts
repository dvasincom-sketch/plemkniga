import type { Field } from 'payload'

/**
 * Общие поля коллекций, привязанных к животному.
 *
 * Держать одно и то же описание в шести файлах — значит однажды поправить
 * пять из них. Здесь оно одно, и подпись в интерфейсе у всех одинаковая:
 * человек, увидев это поле в дойках и в отёлах, читает его одинаково.
 */

/**
 * Хозяйство, при котором запись появилась.
 *
 * Смысл и причина — в `stampOwnerOrg` (`src/access/guards.ts`). Коротко:
 * после продажи животного владелец отвечает за карточку, а штамп — за то,
 * кто собрал каждую отдельную строку истории.
 */
export const ownerOrgField: Field = {
  name: 'ownerOrg',
  type: 'relationship',
  relationTo: 'organizations',
  label: 'Хозяйство на момент записи',
  index: true,
  admin: {
    readOnly: true,
    position: 'sidebar',
    description: 'Проставляется автоматически, нужен для доступа прежнего владельца',
  },
  access: { update: () => false },
}

/**
 * Откуда запись приехала по обмену ICAR ADE.
 *
 * ## Зачем хранить чужой идентификатор
 *
 * На нём держится повторная отправка. Программа хозяйства, не дождавшись
 * ответа из-за сбоя сети, повторит запрос — так устроен любой honest
 * клиент, и так предписывает поступать сам стандарт. Без чужого
 * идентификатора второй запрос создал бы вторую запись, и книга удвоила
 * бы контрольное доение из-за оборванного соединения.
 *
 * Ключ составной: один и тот же `sourceId` у двух разных программ ничего
 * общего не означает — это их внутренние номера, и совпадение их
 * случайно. Уникальность стандарт обещает только внутри источника.
 *
 * ## Почему только для чтения
 *
 * Поле — не свойство события, а след того, как оно попало в книгу.
 * Правка вручную ломает единственное, ради чего оно заведено: позволив
 * поменять `sourceId`, мы разрешаем создать дубль следующей же отправкой.
 */
export const adeOriginField: Field = {
  name: 'ade',
  type: 'group',
  label: 'Приём по ICAR ADE',
  admin: {
    readOnly: true,
    position: 'sidebar',
    description: 'Заполняется только у записей, принятых обменом',
  },
  access: { update: () => false },
  fields: [
    { name: 'source', type: 'text', label: 'Источник (meta.source)', index: true },
    { name: 'sourceId', type: 'text', label: 'Идентификатор у источника', index: true },
  ],
}
