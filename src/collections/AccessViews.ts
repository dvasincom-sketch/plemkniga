import type { CollectionConfig } from 'payload'
import { ACCESS_SCOPES, toOptions } from '@/lib/dictionaries'
import { accessViewRead, isAdmin } from '@/access'

/**
 * Журнал просмотров: какое хозяйство и когда смотрело карточку.
 *
 * Две задачи в одной таблице, и это осознанно.
 *
 * **Первая — доверие к точечному доступу.** Хозяйство должно видеть, что
 * выданным грантом пользуются по назначению, — иначе оно перестанет его
 * выдавать, и весь механизм останется незаселённым. Это не контроль ради
 * контроля: это то, что делает возможной вторую выдачу.
 *
 * **Вторая — интерес к записи.** Сколько хозяйств посмотрело этого быка.
 * Число полезно владельцу и объясняет ему, зачем вообще держать данные
 * открытыми.
 *
 * Разводить это по двум таблицам было бы двумя местами, где записывается
 * одно и то же событие, — и однажды они разойдутся. Строка по гранту
 * отличается от обычной только заполненным полем `grant`.
 *
 * ## Строка на пару «животное + хозяйство», а не на каждый заход
 *
 * Уникальность считается по организациям, поэтому естественная единица
 * записи — пара. Отсюда три следствия, и все три полезные:
 *
 *  - число уникальных просмотров — это количество строк, считать нечего;
 *  - таблица ограничена сверху числом хозяйств, а не числом заходов:
 *    сорок два хозяйства на 280 тысяч животных, а не «все посетители книги
 *    за всё время», от чего мы и уходили;
 *  - владелец в журнале видит «кто и когда», а не сорок одинаковых строк
 *    подряд от одного зоотехника, который листал вкладки.
 *
 * Цена — истории отдельных заходов нет. Вместо неё `firstAt`, `at`
 * и `sessions`: когда впервые, когда в последний раз и сколько раз
 * возвращались. На вопрос «пользуются ли доступом» этого достаточно,
 * а на вопрос «что именно смотрели в четверг» журнал и не отвечал.
 *
 * ## Кого не считаем
 *
 * Себя (владелец у своей же записи), анонимов (их не по чему опознать,
 * а опознавать по cookie или адресу — слежка за посетителем, на которую
 * мы не подписывались) и Ассоциацию (она смотрит по долгу службы, и её
 * визиты в счётчике «сколько хозяйств заинтересовалось» — шум).
 *
 * Записи не создаются через API: их пишет серверный код после отдачи
 * страницы. Журнал, который можно пополнить снаружи, ничего не доказывает.
 */
export const AccessViews: CollectionConfig = {
  slug: 'access-views',
  labels: { singular: 'Просмотр карточки', plural: 'Журнал просмотров' },
  admin: {
    useAsTitle: 'id',
    defaultColumns: ['at', 'animal', 'viewerOrg', 'sessions', 'grant'],
    group: 'Племенная книга',
  },
  access: {
    read: accessViewRead,
    create: () => false,
    update: () => false,
    delete: isAdmin,
  },
  defaultSort: '-at',
  indexes: [
    /*
     * Пара «животное + смотревшее хозяйство» уникальна — на этом держится
     * весь счёт. Уникальность здесь не оптимизация, а правило: две строки
     * на одну пару означали бы, что одно хозяйство посчитано дважды,
     * и число уникальных просмотров перестало бы быть числом уникальных.
     */
    { fields: ['animal', 'viewerOrg'], unique: true },
    // Журнал хозяйства: «кто смотрел мои данные», сверху свежее
    { fields: ['owner', 'at'] },
    // Врезка на странице гранта и пересчёт его lastSeenAt
    { fields: ['grant', 'at'] },
  ],
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'animal',
          type: 'relationship',
          relationTo: 'animals',
          label: 'Животное',
          required: true,
          index: true,
        },
        {
          name: 'viewerOrg',
          type: 'relationship',
          relationTo: 'organizations',
          label: 'Кто смотрел',
          required: true,
          index: true,
        },
        {
          /*
           * Владелец данных — копия ради чтения журнала без join.
           *
           * Хозяйство открывает свой журнал условием «owner = моя
           * организация». Без копии это условие пришлось бы ставить
           * на поле связанной записи (`animal.owner`), а Payload
           * превращает такое в left join — то, от чего весь механизм
           * грантов и уходит. Тот же приём, что у копий полей животного
           * в строке значения индекса (решение №22).
           */
          name: 'owner',
          type: 'relationship',
          relationTo: 'organizations',
          label: 'Чьи данные (копия)',
          required: true,
          index: true,
          admin: { readOnly: true },
        },
      ],
    },
    {
      /*
       * По какому гранту смотрели в последний раз.
       *
       * Пусто — обычный просмотр открытой карточки. Это не пробел в данных,
       * а различие между двумя видами обращения: по гранту хозяйство
       * спрашивает «пользуются ли выданным», по обычному — «кому интересно
       * моё животное».
       */
      name: 'grant',
      type: 'relationship',
      relationTo: 'access-grants',
      label: 'По какому доступу',
      index: true,
    },
    {
      name: 'viewer',
      type: 'relationship',
      relationTo: 'users',
      label: 'Кто именно смотрел последним',
      admin: { readOnly: true, description: 'Право у хозяйства, но открывал карточку человек' },
    },
    {
      name: 'scopes',
      type: 'select',
      hasMany: true,
      label: 'Что было открыто в последний раз',
      options: toOptions(ACCESS_SCOPES),
    },
    {
      type: 'row',
      fields: [
        { name: 'firstAt', type: 'date', label: 'Впервые', required: true },
        {
          /*
           * Своё время последнего захода, а не `updatedAt`.
           *
           * `updatedAt` меняется от любой правки строки — например, если
           * когда-нибудь добавится поле и пройдёт перенос данных. «Когда
           * смотрели в последний раз» должно зависеть только от просмотра.
           */
          name: 'at',
          type: 'date',
          label: 'В последний раз',
          required: true,
          index: true,
        },
        {
          /*
           * Сколько раз возвращались. Заход считается новым, если прошло
           * больше получаса: переключение вкладок карточки — это один
           * взгляд на одно животное, а не четыре обращения.
           */
          name: 'sessions',
          type: 'number',
          label: 'Заходов',
          defaultValue: 1,
          min: 1,
        },
      ],
    },
  ],
}
