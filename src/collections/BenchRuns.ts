import type { CollectionConfig } from 'payload'
import { anyone, isAdmin } from '@/access'

/**
 * Замер производительности, снятый на этой машине.
 *
 * ## Почему замер всё-таки попал в базу
 *
 * Решение №134 положило отчёт файлом в репозиторий и обосновало это тем,
 * что замер — факт об одной версии кода на одном железе. Обоснование
 * не ложное, но оно решало не ту задачу. Замер, снятый на боевом сервере,
 * должен там же и показаться: данные сняты на этой машине, страница
 * на этой же машине, а между ними почему-то оказывались коммит и деплой.
 * Ждать автоматического обновления здесь естественно, и упираться
 * в стройность собственного объяснения не стоило.
 *
 * ## Почему файл при этом остался
 *
 * У двух источников разная природа, и ни один не заменяет другой.
 *
 * База отвечает на вопрос «как эта машина работает сейчас»: запись
 * появляется сразу после прогона, без чужого участия. Файл отвечает
 * на вопрос «как работали другие среды»: замер с машины разработчика
 * в боевую базу попасть не может и не должен, а сравнивать среды —
 * ровно то, ради чего вкладка и заведена.
 *
 * Поэтому вкладка сводит оба: файл даёт замеры, привезённые вместе
 * с кодом, база — снятый здесь. При совпадении меток побеждает база:
 * она свежее по определению.
 *
 * ## Почему видно всем
 *
 * Страница «Эволюция продукта» открыта, и цифры на ней — довод в пользу
 * системы, а не тайна. В отчёт попадает модель процессора, объём памяти,
 * версия PostgreSQL и несколько его настроек; ни адресов, ни имён баз,
 * ни тем более паролей там нет — `serverInfo` их не собирает.
 */
export const BenchRuns: CollectionConfig = {
  slug: 'bench-runs',
  labels: { singular: 'Замер', plural: 'Замеры производительности' },
  admin: {
    useAsTitle: 'label',
    defaultColumns: ['label', 'measuredAt', 'animals', 'runs'],
    group: 'Служебные',
  },
  access: {
    read: anyone,
    /*
     * Создаёт и обновляет только маршрут замера — через `overrideAccess`.
     * Открытого правила нет: запись, которую можно завести снаружи,
     * означала бы, что показать на витрине любые цифры может кто угодно.
     */
    create: () => false,
    update: () => false,
    delete: isAdmin,
  },
  defaultSort: 'label',
  indexes: [{ fields: ['label'] }],
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'label',
          type: 'text',
          label: 'Среда',
          required: true,
          unique: true,
          admin: {
            description:
              'Имя среды: «Прод». Повторный замер той же среды заменяет прежний — ' +
              'два замера одного места это не сравнение, а история',
          },
        },
        {
          name: 'measuredAt',
          type: 'date',
          label: 'Когда снят',
          required: true,
          admin: { date: { pickerAppearance: 'dayAndTime' } },
        },
      ],
    },
    {
      type: 'row',
      fields: [
        {
          name: 'animals',
          type: 'number',
          label: 'Животных в базе',
          required: true,
          admin: {
            description: 'Половина смысла всех остальных цифр: на разном объёме они разные',
          },
        },
        { name: 'runs', type: 'number', label: 'Прогонов на сценарий', required: true },
      ],
    },
    {
      /*
       * Строки и описание железа лежат как есть, а не разложены
       * по колонкам. Это снимок отчёта, а не сущность предметной области:
       * по нему не ищут, не отбирают и не соединяют его с другими
       * таблицами. Разложив его по полям, мы завели бы вторую схему
       * отчёта — рядом с той, что уже описана в `src/lib/bench-report.ts`,
       * — и они разошлись бы при первом же новом сценарии.
       */
      name: 'server',
      type: 'json',
      label: 'На чём мерили',
    },
    { name: 'rows', type: 'json', label: 'Строки замера', required: true },
    {
      name: 'notes',
      type: 'json',
      label: 'Замечания',
      admin: {
        description: 'То, из-за чего цифры можно понять неверно: объём базы, нехватка данных',
      },
    },
  ],
}
