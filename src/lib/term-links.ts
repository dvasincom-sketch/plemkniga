import { NOTES } from '@/lib/notes'
import { STUDIES } from '@/lib/studies'
import { BREED_PAGES } from '@/lib/breed-pages'
import { termBySlug, type Term } from '@/lib/terms'

/**
 * Связь словаря с тем, где эти слова работают.
 *
 * ## Что было не так
 *
 * Словарь вёл в разборы, а разборы в словарь — нет. Читатель разбора,
 * споткнувшийся о «сервис-период», уходил искать его на сторону, хотя
 * определение с нашими числами лежало через одну страницу. Внутренняя
 * связность при этом — не украшение: по ней ходит и читатель,
 * и поисковая система, и страница, на которую не ведёт ничего изнутри,
 * обходится последней.
 *
 * ## Почему объявление одно, а направления два
 *
 * Соблазн — расставить ссылки руками с обеих сторон: в разборе на
 * термин, в термине на разбор. Так получаются две правды об одной связи,
 * и расходятся они на первой же правке: кто-то добавит термин в разбор
 * и забудет дописать разбор в термин, а увидеть это нельзя ни с одной
 * из двух страниц.
 *
 * Поэтому объявляет связь только та сторона, которая про неё знает:
 * разбор, исследование или страница породы перечисляет термины,
 * которые в ней употреблены. Обратное направление — «где это работает» —
 * считается отсюда и потому не может отстать.
 *
 * ## Почему перечисляют не все термины, а употреблённые
 *
 * Список «все термины, как-то относящиеся к теме» — это не связь,
 * а оглавление словаря, приклеенное к каждой странице. Читатель
 * перестаёт его замечать после второй такой страницы. Перечисляются
 * те слова, о которые читатель этой страницы действительно спотыкается.
 */

export type TermUse = {
  kind: 'note' | 'study' | 'breed'
  title: string
  href: string
}

/** Как называется раздел, из которого пришла ссылка. */
export const USE_LABEL: Record<TermUse['kind'], string> = {
  note: 'Разбор',
  study: 'Исследование',
  breed: 'Порода',
}

/**
 * Где термин работает.
 *
 * Порядок — разборы, исследования, породы: от того, где слово разобрано
 * подробнее, к тому, где оно просто встретилось.
 */
export const usesOf = (slug: string): TermUse[] => [
  ...NOTES.filter((n) => n.terms?.includes(slug)).map(
    (n): TermUse => ({ kind: 'note', title: n.title, href: `/ru/razbory/${n.slug}` }),
  ),
  ...STUDIES.filter((s) => s.terms?.includes(slug)).map(
    (s): TermUse => ({ kind: 'study', title: s.title, href: `/ru/issledovaniya/${s.slug}` }),
  ),
  ...BREED_PAGES.filter((b) => b.terms?.includes(slug)).map(
    (b): TermUse => ({ kind: 'breed', title: b.title, href: `/ru/breeds/${b.slug}` }),
  ),
]

/**
 * Термины страницы — теми записями, что нашлись.
 *
 * Слаг, которого в словаре нет, молча пропускается здесь и громко
 * называется прогоном `check:terms`: страница из-за опечатки в списке
 * ломаться не должна, но и делать вид, что всё в порядке, нельзя.
 */
export const termsOf = (slugs: string[] | undefined): Term[] =>
  (slugs ?? []).map((s) => termBySlug(s)).filter((t): t is Term => t !== undefined)
