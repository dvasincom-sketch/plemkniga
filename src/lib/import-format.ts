export const columnsOf = (ds: Dataset): ImportColumn[] => ds.groups.flatMap((g) => g.columns)

/**
 * Заголовок файла → внутреннее поле.
 *
 * Собирается из реестра, а не пишется руками: колонка, попавшая в таблицу
 * на странице, но не в словарь разбора, — это обещание, которого система
 * не выполнит.
 */
export const headerMapOf = (ds: Dataset): Record<string, string> =>
  Object.fromEntries(
    columnsOf(ds).flatMap((c) => [
      [c.title.toLowerCase(), c.key],
      ...c.aliases.map((a) => [a.toLowerCase(), c.key] as const),
    ]),
  )

/**
 * Заголовок к нормальному виду.
 *
 * Кроме регистра и краёв схлопываются внутренние пробелы, и это не
 * причёсывание. В шаблонах ФГИАС ПР заголовки несут перевод строки внутри
 * себя — «КПП лаборатории ⏎ (при наличии)», «Дата мечения ⏎ УНСМ», —
 * а в выгрузках из программ учёта попадаются двойные пробелы. Пока
 * приведение делало только `trim` и `toLowerCase`, такой заголовок
 * не совпадал даже с точно выписанным синонимом: невидимый символ
 * посередине строки отличал их друг от друга, а человек, сверяя глазами,
 * видел одно и то же.
 */
export const normalizeHeader = (v: string) => v.trim().toLowerCase().replace(/\s+/g, ' ')

/**
 * Заголовки файла — внутренними ключами, плюс список неопознанных.
 *
 * Живёт здесь, а не в разборе загрузки, потому что разбор помечен
 * `'use server'` и наружу отдаёт только асинхронные функции. Проверке
 * форматов нужна ровно эта функция и именно та, которой пользуется
 * загрузка: своя копия сопоставления разошлась бы с настоящей в первый же
 * раз, когда правило меняют, — и проверка продолжила бы уверенно
 * рапортовать об успехе.
 */
export const matchHeader = (
  raw: string[],
  ds: Dataset,
): { header: string[]; unknown: string[] } => {
  const map = headerMapOf(ds)
  const header = raw.map((h) => map[normalizeHeader(h)] ?? '')
  const unknown = raw.filter((h, i) => h.trim() !== '' && header[i] === '')
  return { header, unknown }
}

/** Заголовки и строка-пример для файла-шаблона. */
/**
 * Какой это набор — по одной шапке файла.
 *
 * ## Зачем
 *
 * Выбор «что загружаем» стоял первым полем формы, и человек ошибался
 * в нём чаще, чем в самом файле: выгрузка из доильного зала уходила
 * в «Животные», файл отёлов — в «Осеменения». Ошибка обходилась дорого
 * и не сразу: набор решает, какие колонки искать, поэтому файл
 * отвергался словами «не найдены обязательные колонки», и человек шёл
 * править заголовки, которые были в полном порядке.
 *
 * Между тем ответ лежит в самом файле. Шапка отёлов и шапка доек
 * не похожи ни одной колонкой, кроме номера животного.
 *
 * ## Почему это не догадка
 *
 * Мы не угадываем смысл значений — мы читаем заголовки, которые человек
 * написал сам. Это чтение, а не предположение.
 *
 * Но там, где чтение не даёт однозначного ответа, система обязана
 * спросить, а не выбрать наугад. Поэтому распознавание возвращает три
 * исхода, и средний из них — не худший:
 *
 *   уверенно  — один набор явно впереди, грузим им и говорим, каким;
 *   неясно    — двое рядом или ни одного, показываем выбор человеку;
 *   пусто     — шапки нет вовсе.
 *
 * Ошибиться молча здесь означало бы завести отёлы животными.
 *
 * ## Как считается
 *
 * Очков столько, сколько колонок набора нашлось в шапке. Обязательные
 * весят втрое: колонка «Дата» есть у половины наборов, а «Номер отёла»
 * только у одного, и без веса общие колонки перетянули бы.
 *
 * Набор без единой обязательной колонки не участвует вовсе — грузить им
 * всё равно нечего, а в сравнении он бы шумел.
 *
 * Отрыв в полтора раза выбран не наугад: у настоящих файлов из хозяйств
 * разрыв между первым и вторым набором был не меньше трёхкратного,
 * а полтора берётся с запасом на файл, где заполнена половина колонок.
 */
export type DatasetGuess =
  | { kind: 'sure'; dataset: Dataset; matched: number }
  | { kind: 'unclear'; candidates: { dataset: Dataset; matched: number }[] }

export const detectDataset = (rawHeader: string[]): DatasetGuess => {
  const scored = DATASETS.map((ds) => {
    const map = headerMapOf(ds)
    const keys = new Set(
      rawHeader.map((h) => map[normalizeHeader(h)]).filter((k): k is string => Boolean(k)),
    )
    const cols = columnsOf(ds)
    const required = cols.filter((c) => c.required)
    const gotRequired = required.filter((c) => keys.has(c.key)).length
    return {
      dataset: ds,
      matched: keys.size,
      /* Обязательные весят втрое: они и отличают наборы друг от друга. */
      score: gotRequired === required.length ? keys.size + gotRequired * 2 : 0,
    }
  })
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score)

  const [first, second] = scored
  if (!first) return { kind: 'unclear', candidates: [] }

  /*
   * Одной узнанной колонки не хватает никогда, даже когда соперников нет.
   *
   * Номер животного есть во всех четырёх наборах, и файл, из которого
   * узналась только эта колонка, мы не поняли — мы поняли, что там есть
   * животные. У «Животных» номер вдобавок единственное обязательное поле,
   * поэтому такой файл выигрывал без борьбы: остальные наборы отпадали
   * по своим обязательным, и распознавание уверенно объявляло «Животные».
   *
   * Поймано проверкой на шапке из одного «Инд.№». Цена ошибки —
   * не пустая загрузка, а тихое обновление карточек по файлу, который
   * на самом деле про другое.
   */
  if (first.matched < 2) {
    return {
      kind: 'unclear',
      candidates: scored.slice(0, 3).map((r) => ({ dataset: r.dataset, matched: r.matched })),
    }
  }

  if (!second || first.score >= second.score * 1.5) {
    return { kind: 'sure', dataset: first.dataset, matched: first.matched }
  }
  return {
    kind: 'unclear',
    candidates: scored.slice(0, 3).map((r) => ({ dataset: r.dataset, matched: r.matched })),
  }
}

export const templateRowsOf = (ds: Dataset): { headers: string[]; example: string[] } => {
  /*
   * Колонки `importOnly` в образец не идут. Это номера, которые выдаёт
   * реестр: принять их надо, а просить заполнить нельзя — человеку негде
   * их взять, и просьба читается как приглашение выдумать.
   */
  const cols = columnsOf(ds).filter((c) => !c.importOnly)
  return { headers: cols.map((c) => c.title), example: cols.map((c) => c.example) }
}
