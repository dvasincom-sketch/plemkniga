export type ColumnKind =
  | 'text'
  | 'number'
  | 'date'
  | 'sex'
  /**
   * Значение ищется в справочнике книги — по названию или по ключу ФГИАС.
   *
   * Пришло на смену виду `breed`, который был прибит к одной коллекции.
   * Пока он был единственным, это не мешало: породу и правда искали только
   * среди пород. Мешать начало, когда понадобились линия, масть
   * и назначение — те самые колонки, которые есть в шаблоне ФГИАС
   * и которых у нас не было вовсе. Заводить `line`, `colour`, `purpose`
   * по образцу `breed` значило бы написать один и тот же разбор четыре
   * раза и разойтись в нём на пятый.
   *
   * Коллекция названа в самой колонке (`collection`), а не выведена
   * из ключа: `coatColor` живёт в `coat-colors`, и правило «имя поля равно
   * имени коллекции» сломалось бы на первой же паре.
   */
  | 'dictionary'
  | 'herd'
  | 'animal'
  | 'enum'

export type ImportColumn = {
  /** Куда попадает значение — путь в карточке животного. */
  key: string
  /** Канонический заголовок: он идёт в шаблон. */
  title: string
  /** Другие принимаемые написания. Регистр не важен. */
  aliases: string[]
  kind: ColumnKind
  /** Для `kind: 'dictionary'` — где искать значение. */
  collection?: string
  required?: boolean
  /**
   * Колонка принимается загрузкой, но не идёт в наш образец шаблона.
   *
   * Так помечены номера, которые выдаёт государственный реестр: базовый
   * и регистрационный. Принять их надо — обратный файл ФГИАС кладут
   * в ту же форму, что и всё остальное. А предложить в образце нельзя:
   * колонка, которую человеку негде взять, но которую у него просят
   * заполнить, — это приглашение выдумать значение. Выдуманный базовый
   * номер заводит в реестре второе животное рядом с настоящим.
   */
  importOnly?: boolean
  what: string
  example: string
  /** Оговорка, без которой колонку поймут неверно. */
  note?: string
  /**
   * Допустимые значения — только для `kind: 'enum'`.
   *
   * Принимается и код, и русское название: в выгрузках встречается
   * и «cow2», и «Корова 2 лакт.». Значение не из списка не роняет строку —
   * поле остаётся пустым, а само значение попадает в «не нашлись
   * в справочниках», как это давно устроено у породы и стада.
   */
  options?: readonly { value: string; label: string }[]
}

/**
 * Колонка со списком значений — вместе с описанием, собранным из самого
 * списка.
 *
 * Описание не пишется руками намеренно. В подсказке к «Возрастной группе»
 * стояло «Код группы: calf, heifer, firstCalf, cow, bull» — а группы `cow`
 * в справочнике нет, есть `cow2` и `cow3`. Файл, заполненный точно
 * по нашей же подсказке, база отвергала. Текст, переписанный от руки
 * с справочника, расходится с ним в тот день, когда справочник меняют;
 * собранный из справочника — не расходится никогда.
 */
const enumColumn = (
  c: Omit<ImportColumn, 'kind' | 'what' | 'example'> & {
    options: readonly { value: string; label: string }[]
    what: string
  },
): ImportColumn => ({
  ...c,
  kind: 'enum',
  what: `${c.what} Коды: ${c.options.map((o) => o.value).join(', ')}. Принимается и название.`,
  example: c.options[0]?.value ?? '',
})

export type ColumnGroup = {
  key: string
  label: string
  intro: string
  columns: ImportColumn[]
}

