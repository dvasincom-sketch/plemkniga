/**
 * Два домена на одном приложении.
 *
 * ## Что где живёт
 *
 * `plem.online` — витрина продукта: описание, возможности, приглашение
 * подключиться. Читают её ассоциации и хозяйства, которые ещё ничего
 * не ведут и решают, стоит ли.
 *
 * `holstein.plem.online` — действующая племенная книга Ассоциации
 * производителей КРС голштинской породы. Всё, что было и есть: кабинеты,
 * поиск по книге, выгрузки, обмен.
 *
 * ## Почему одно приложение, а не два
 *
 * Витрина рассказывает ровно о том, что делает книга, и рассказывает
 * теми же словами. Два развёртывания означали бы две копии этих слов
 * и два места, где их правят, — а правят их каждый раз, когда книга
 * что-то начинает уметь. Расхождение здесь особенно неприятно: витрина
 * обещает то, чего в книге уже нет, или молчит о том, что появилось.
 *
 * Тексты витрины — те же, что у страницы для стран ЕАЭС
 * (`lib/i18n/eaeu-messages.ts`), плюс несколько своих. Один набор,
 * шесть языков, одно место правки.
 *
 * ## Почему разделение по хосту, а не по пути
 *
 * Витрина обязана открываться по короткому адресу `plem.online`, а не
 * `plem.online/site`. Разделение по пути потребовало бы либо
 * перенаправления с корня (лишний переход и потеря адреса), либо двух
 * разных корневых страниц в одном дереве маршрутов — чего Next
 * не позволяет.
 *
 * Промежуточный обработчик переписывает адрес: на витринном домене
 * `/` превращается в `/site`, `/about` — в `/site/about`. Адрес
 * в строке браузера при этом не меняется, и человек про `/site`
 * не узнаёт вовсе.
 *
 * ## Почему список хостов, а не один
 *
 * Домен приходит и с `www`, и без; на время переезда работает старый
 * адрес на `twc1.net`; на своей машине это `localhost`. Гадать по одному
 * значению нельзя — перепутав, покажем витрину вместо кабинета
 * или наоборот.
 *
 * Переопределяется переменной среды `SITE_HOSTS` — через запятую.
 * Это нужно на предпросмотре, где домен временный и заранее неизвестен.
 */

/** Домены витрины продукта. */
export const SITE_HOSTS = (process.env.SITE_HOSTS ?? 'plem.online,www.plem.online')
  .split(',')
  .map((h) => h.trim().toLowerCase())
  .filter(Boolean)

/** Домен действующей племенной книги — для ссылок с витрины. */
export const BOOK_HOST = process.env.BOOK_HOST ?? 'holstein.plem.online'

export const BOOK_URL = `https://${BOOK_HOST}`

/**
 * Домен показательной книги.
 *
 * Та же система и тот же код, но другая книга: без государственного
 * учёта, без конкретной породы и без имени голштинской ассоциации
 * (`lib/tenant.ts`).
 *
 * Значение стоит по умолчанию, хотя книги ещё нет. Это не забывчивость:
 * заслонкой служит сама запись в системе доменных имён. Пока имя
 * не указывает на сервер, попасть сюда нельзя ниоткуда, а когда укажет —
 * посетитель сразу получит показательную книгу, а не голштинскую.
 * Обратный порядок — сперва направить имя, потом вписать его в код —
 * означал бы промежуток, в котором чужой домен отдаёт чужую книгу
 * с чужими реквизитами.
 *
 * Направлять имя на сервер до того, как появятся английские экраны,
 * не следует: полперевода вперемешку с русским хуже, чем ничего.
 */
export const DEMO_HOST = (process.env.DEMO_HOST ?? 'demo.plem.online').trim().toLowerCase()

export const DEMO_URL = `https://${DEMO_HOST}`

/**
 * Работает ли показательная книга на самом деле.
 *
 * ## Почему это переменная, а не константа `true`
 *
 * Имя `demo.plem.online` заведено и направлено на сервер, но книги
 * за ним нет, и это не забывчивость с настройкой — за ним нет **данных**.
 * Арендатор (`lib/tenant.ts`) меняет имя, реквизиты и подписи, но
 * не меняет базу: развёрнутая на том же приложении показательная книга
 * показала бы настоящих голштинских животных под словом «демонстрация».
 * Чужие данные, выданные за примерные, — худшее, что можно сделать
 * с доверием ассоциации, которая их нам доверила.
 *
 * Показательная книга поэтому требует своего развёртывания со своей
 * базой и своим наполнением. Пока его нет, витрина не должна на неё
 * ссылаться: ссылка в никуда дороже отсутствующей ссылки — по ней идут,
 * упираются в пустоту и делают вывод обо всём продукте.
 *
 * Включается переменной среды на том развёртывании, где демо
 * действительно поднято.
 */
export const DEMO_READY = process.env.DEMO_READY === '1'

/** Адрес показательной книги — или `null`, пока её нет. */
export const demoUrl = (): string | null => (DEMO_READY ? DEMO_URL : null)

/** Куда переписывается адрес на витринном домене. */
export const SITE_PREFIX = '/site'

/**
 * Почта продукта.
 *
 * Не почта Ассоциации. Прежде витрина писала на `info@holstein-russia.ru`,
 * и в самом домене ящика стояло имя страны и породы: хозяйство из другой
 * страны читало адрес как «это решение про Россию и про голштинов».
 * Письмо при этом шло разработчику.
 *
 * Лежит здесь, рядом с доменами, а не в наборе строк: адрес один
 * на все шесть языков и меняется вместе с доменом, а не с текстом.
 */
export const PRODUCT_MAIL = 'mail@plem.online'

/**
 * Витринный ли это хост.
 *
 * Порт отбрасывается: на своей машине хост приходит как
 * `plem.online:3000`, и сравнение целиком не сошлось бы. Регистр тоже —
 * заголовок `Host` регистронезависим, и браузеры этим пользуются.
 */
export const isSiteHost = (host?: string | null): boolean => {
  if (!host) return false
  const clean = host.toLowerCase().split(':')[0]!
  return SITE_HOSTS.includes(clean)
}

/**
 * Во что превращается адрес на витринном домене.
 *
 * `null` означает «переписывать не надо»: путь уже витринный.
 * Без этой проверки внутренний переход на `/site/ru` превратился бы
 * в `/site/site/ru` — и упал бы в «страница не найдена» только
 * на боевом домене, где обработчик и работает.
 *
 * Вынесено из обработчика отдельной функцией не ради красоты:
 * промежуточный обработчик не проверить без поднятого Next, а эту
 * функцию — можно (`npm run check:hosts`). Ошибка в приставке видна
 * лишь на настоящем домене, то есть в худшем месте из возможных.
 */
export const rewriteToSite = (pathname: string): string | null => {
  if (pathname === SITE_PREFIX || pathname.startsWith(`${SITE_PREFIX}/`)) return null
  return pathname === '/' ? SITE_PREFIX : `${SITE_PREFIX}${pathname}`
}

