/**
 * Страницы, которые говорят о продукте, а не о племенной книге
 * голштинской ассоциации.
 *
 * ## Почему они переехали на витринный домен
 *
 * «Соответствие стандартам», карта ICAR и описание интерфейса отвечают
 * на вопросы о **продукте**: по каким правилам он построен, чему
 * следует, как к нему подключиться. Задают их люди, которые ещё ничего
 * не ведут и решают, стоит ли, — то есть ровно читатели витрины.
 *
 * Пока они жили на домене книги, ссылка с витрины уводила посетителя
 * в чужой кабинет: другой знак в шапке, подвал с адресом и телефоном
 * самарской ассоциации, ощущение, что попал не туда. Обратно с такой
 * страницы почти никто не возвращается.
 *
 * ## Почему это переезд, а не копия
 *
 * Копия означала бы две страницы соответствия, которые расходятся
 * при первой же правке, — а страница, заявляющая соответствие
 * стандартам, обязана быть одна. Старые адреса на домене книги
 * перенаправляются сюда; ссылки, которые успели разойтись, продолжают
 * работать.
 *
 * ## Список, а не догадка по виду адреса
 *
 * Соблазн был опознавать «сквозные» страницы по признаку вроде «нет
 * `/account` в пути». Так нельзя: завтра у книги появится
 * `/certificates`, и он молча уедет на витрину вместе со всем
 * содержимым. Перечень короткий и меняется редко — пусть будет явным.
 */
export const SHARED_PATHS = [
  '/compliance',
  '/icar',
  '/api-docs',
  '/tour',
  '/ade',
  '/breeds',
  /*
   * «Эволюция продукта» была последней страницей о системе, которая
   * жила на домене книги. Она рассказывает, какие версии выходили
   * и чего ждать дальше, — про платформу, а не про голштинов, — и под
   * знаком Ассоциации выглядела рассказом Ассоциации о собственной
   * разработке.
   */
  '/evolution',
  /* Кто содержит платформу. Страницы с таким адресом в книге не было
     и нет: перенаправление заведено на случай, если адрес наберут
     руками, придя с подвала книги. */
  '/org',
] as const

/**
 * Машинные адреса, которые лежат внутри сквозных, но никуда не едут.
 *
 * `/ade` — страница о том, чем проверяется наш обмен; она про продукт
 * и живёт на витрине. `/ade/v1` — сам обмен, и он про книгу: там данные
 * книги, права на локации книги и токены, выданные на домене книги.
 * Слово в адресе одно, а хозяин разный, и правило «всё, что внутри
 * сквозного, тоже сквозное» здесь ошибается.
 *
 * Ошибалось оно молча и дорого. Обмен на домене книги отвечал 308
 * на витрину, где нет ни данных, ни входа; интегратор получал либо 404
 * после перехода, либо пустоту, а выглядело это как «в книге ничего нет».
 * Найдено не глазами, а первым же прогоном по сети (`check:ade-live`):
 * обычный запрос ответил 404 там, где обязан был ответить 200.
 *
 * Отдельно про безопасность: 308 сохраняет метод, и клиент, который
 * следует за перенаправлением сам, отправил бы POST с заголовком
 * `Authorization` на другой домен. Токен книги не должен уезжать
 * на витрину ни при каких обстоятельствах.
 *
 * Список, а не признак вроде «есть цифра версии»: машинных адресов мало,
 * и каждый должен быть назван осознанно.
 */
export const MACHINE_PATHS = ['/ade/v1'] as const

/** Сквозная ли это страница — сама или что-то внутри неё. */
export const isSharedPath = (pathname: string): boolean => {
  if (MACHINE_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`))) return false
  return SHARED_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`))
}

/**
 * Куда уводить со старого адреса на домене книги.
 *
 * `null` означает «оставить как есть». Перенаправление отдаётся только
 * для сквозных страниц: всё остальное на домене книги живёт у себя дома.
 */
export const redirectToSite = (pathname: string): string | null =>
  isSharedPath(pathname) ? `https://${SITE_HOSTS[0]}${pathname}` : null
