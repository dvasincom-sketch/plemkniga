/**
 * Запасные домены, показывающие ту же книгу.
 *
 * ## Зачем
 *
 * У площадки есть служебное имя вида `…twc1.net`, которое выдаётся
 * приложению при развёртывании и работает раньше, чем настроен
 * собственный домен. По нему открывается та же книга: это не вторая
 * система и не показательный стенд, а тот же кабинет с теми же данными,
 * просто по другому адресу.
 *
 * Само по себе это уже работало — неизвестный домен не витринный,
 * значит книга. Не работал **вход**: Payload сверяет источник запроса
 * со списком доверенных, и с незнакомого домена форма входа получает
 * отказ. Отказ при этом невнятный, и выглядит он как поломка входа
 * вообще, а не как незнакомый домен.
 *
 * ## Почему списком в переменной, а не «пускать любой домен»
 *
 * Разрешить всё значило бы принимать формы входа с любого сайта,
 * который поставит нас в рамку. Список короткий и меняется при переезде,
 * то есть ровно тогда, когда о нём и вспоминают.
 */
export const ALT_HOSTS = (process.env.ALT_HOSTS ?? '')
  .split(',')
  .map((h) => h.trim().toLowerCase())
  .filter(Boolean)

/**
 * Доверенные источники запросов — для проверки подлинности в Payload.
 *
 * Собирается из тех же настроек, из которых работает разведение
 * доменов. Отдельный список означал бы, что при переезде надо вспомнить
 * про два места, а вспоминают всегда про одно.
 */
export const trustedOrigins = (): string[] => {
  const hosts = [BOOK_HOST, ...SITE_HOSTS, ...ALT_HOSTS, DEMO_HOST].filter(Boolean)
  const origins = hosts.map((h) => `https://${h}`)

  /*
   * Свой адрес разработки и явно заданный адрес сервера. Последний
   * бывает нужен, когда приложение стоит за прокси под именем,
   * которого нет ни в одном списке выше.
   */
  const server = process.env.NEXT_PUBLIC_SERVER_URL
  return [...new Set([...origins, ...(server ? [server] : []), 'http://localhost:3000'])]
}

