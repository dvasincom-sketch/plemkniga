/**
 * Исследования — раздел витрины, где опубликованная работа переводится
 * в список того, что нужно, чтобы проверить её на живой племенной книге.
 *
 * ## Чем это не является
 *
 * Это не пересказ. Довод против пересказа записан в шапке `lib/notes.ts`
 * и остаётся в силе: пересказ чужой статьи стоит ровно столько, сколько
 * стоит наше чтение этой статьи, а проверить его читатель может только
 * сходив в первоисточник. Заводить ради этого раздел незачем — первоисточник
 * и так по ссылке.
 *
 * Это и не разбор. Разбор объясняет, как устроено то, что уже считает книга,
 * и весь его материал у нас на руках. Здесь материала как раз нет: работа
 * чужая, выборка чужая, метод чужой. Общего у двух разделов только рамка —
 * закреплённый порядок частей и обязательный раздел о том, чего работа
 * не доказывает.
 *
 * ## Что тут вместо пересказа
 *
 * Вопрос, которого не задаёт никто, кроме нас: **что нужно, чтобы проверить
 * это на нашей базе**. Ответ на него состоит из вещей, которых нет ни в
 * статье, ни в её пересказе: какие поля книги для этого читаются, сколько
 * записей с этими полями у нас есть, чего не хватает и почему наш ответ
 * будет отличаться от опубликованного. Проверить такой текст можно, не
 * выходя с сайта: поля названы теми же именами, что стоят в коде, а числа
 * посчитаны кодом, а не набраны руками.
 *
 * Отсюда же следует, что раздел стареет вместе с книгой, а не вместе
 * с работой: исчезнет поле — исчезнет строка, появится — появится.
 *
 * ## Шесть частей, и порядок не переставляется
 *
 * Что утверждает работа; что нужно для проверки; что у нас есть сегодня;
 * чего не хватает; чем наш ответ будет отличаться; чего пересчёт
 * не докажет. Порядок закреплён не здесь, а в обвязке
 * (`components/site/StudyFrame.tsx`) — как у словаря: он и есть жанр,
 * и оставлять его на усмотрение пишущего значило бы получить шесть
 * разных жанров на шести страницах.
 *
 * Тип требует все шесть. Часть, которую нечем наполнить, — не повод
 * завести страницу без неё, а признак того, что работа для этого раздела
 * не годится: сказать «чего пересчёт не докажет» можно всегда, и молчание
 * здесь означает не отсутствие оговорок, а нежелание их называть.
 *
 * ## Главное правило: не утверждать того, чего мы не читали
 *
 * У каждой работы стоит `read`. `full` — прочитан полный текст; `abstract` —
 * только открытая часть: название, аннотация, объём выборки. При `abstract`
 * страница не вправе пересказывать выводы: всё, что она говорит о работе,
 * должно проверяться по её открытой части, а недостающее называется
 * недостающим. Это не осторожность ради приличия — на выводе, вычитанном
 * из чужого пересказа аннотации, строится потом список полей, и ошибка
 * доезжает до соискателя, который придёт эти поля просить.
 *
 * ## Почему числа в третьей части считаются, а не пишутся
 *
 * «У нас 15 значений перечислений и девять колен родословной» — обещание,
 * которое проверяется одним переходом в код. Написанное руками, оно
 * разойдётся с кодом на первой же правке и разойдётся молча: страницу
 * читает человек, а поля правит другой человек, и сверить их некому.
 * Поэтому всё, что можно посчитать, посчитано здесь же, из тех же
 * модулей, откуда это берут книга и обмен.
 *
 * Считать можно не всё. Сколько в базе записей контроля с проставленным
 * методом — витрина не знает и знать не должна: она отдельный домен, она
 * не ходит в базу и обязана открываться, когда база недоступна. Такие
 * строки стоят с `count: null` и подписью, что счёт не считался. Пустое
 * место честнее правдоподобного числа: правдоподобное число в разделе
 * про воспроизводимость расчёта — это ровно та ошибка, против которой
 * раздел заведён.
 *
 * ## Почему только по-русски
 *
 * Тот же довод, что у разборов, словаря и страниц пород: перевод текста,
 * вся ценность которого в точности формулировок, на шесть языков — это
 * пять машинных переводов и обесцененный оригинал.
 */

/** Работа, которую воспроизводим. */
export type StudyWork = {
  title: string
  /**
   * Авторы так, как их удалось установить по открытой части.
   *
   * Поле обязательно и при этом иногда заполняется словами «список
   * не установлен». Необязательным его делать нельзя: пропущенное поле
   * читается как «авторов нет», а названная невозможность установить —
   * как то, чем она является, то есть как состояние нашего знания.
   */
  authors: string
  journal: string
  year: number
  url: string
  /** Объём выборки — числом из открытой части, а не из нашего пересказа. */
  sample: string
  /** Что мы прочли: полный текст или только открытую часть. */
  read: 'full' | 'abstract'
}

/**
 * Поле книги, которое работа заставляет прочесть.
 *
 * Имя пишется так, как оно стоит в коде, а не так, как называется в
 * интерфейсе: соискатель, который придёт с этой страницей, будет искать
 * поле, а не подпись. Состояние — три значения, потому что промежуточное
 * здесь самое частое: поле есть, но заполнено не у всех, или выводится
 * из соседних вместо того, чтобы храниться.
 */
export type StudyField = {
  /** Где лежит: коллекция, массив внутри карточки, модуль расчёта. */
  where: string
  /** Имя поля в коде. */
  name: string
  /** Что это и зачем оно работе. */
  what: string
  state: 'yes' | 'partial' | 'no'
}

/**
 * Строка третьей части: сколько у нас есть.
 *
 * `count: null` означает ровно одно — счёт не считался, и почему,
 * сказано в `from`. Ноль означает другое: посчитали и не нашли,
 * обычно потому, что такого хранилища в книге нет вовсе.
 */
export type StudyHolding = {
  what: string
  count: number | null
  unit: string
  /** Откуда взялось число — или почему его нет. */
  from: string
}

export type StudySource = {
  title: string
  url?: string
  what?: string
}

/** Абзацы одной части. Пустой массив запрещён типом ниже. */
type Paragraphs = [string, ...string[]]

export type Study = {
  slug: string
  title: string
  /** Одна строка, ради которой страницу открыли. */
  lead: string
  /** Дата, ISO. Не «обновлено»: это высказывание о состоянии базы. */
  date: string
  author: string
  authorUrl?: string
  work: StudyWork

  /** 1. Что утверждает работа — одной фразой, с числом. */
  claim: Paragraphs
  /** 2. Что нужно для проверки. */
  needed: Paragraphs
  /** Поля книги поимённо — к части 2. */
  fields: [StudyField, ...StudyField[]]
  /** 3. Что у нас есть сегодня. */
  have: Paragraphs
  /** Счёт к части 3. Числа приходят из кода. */
  holdings: [StudyHolding, ...StudyHolding[]]
  /** 4. Чего не хватает — и это же задача для соискателя. */
  missing: Paragraphs
  /** 5. Чем наш ответ будет отличаться. */
  difference: Paragraphs
  /** 6. Чего пересчёт не докажет. */
  limits: Paragraphs

  /** Куда идти дальше: разбор, раздел книги, статья словаря. */
  see?: { label: string; href: string }[]
  sources: StudySource[]
}

