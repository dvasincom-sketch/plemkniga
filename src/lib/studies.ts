export const studyBySlug = (slug: string): Study | undefined =>
  STUDIES.find((s) => s.slug === slug)

/**
 * Сколько полей из списка есть, сколько заполнено не у всех и скольких нет.
 *
 * Считается по самому списку, а не пишется рядом с ним. Пиши мы это словами,
 * первая же дописанная строка сделала бы подпись неверной — и неверной
 * молча, потому что смотрит на список читатель, а правит его автор.
 */
export const fieldTally = (study: Study): { yes: number; partial: number; no: number } => ({
  yes: study.fields.filter((f) => f.state === 'yes').length,
  partial: study.fields.filter((f) => f.state === 'partial').length,
  no: study.fields.filter((f) => f.state === 'no').length,
})

/**
 * Сколько требований какого рода — по тому же правилу, что и счёт полей.
 *
 * Считается из списка, а не пишется рядом. Здесь у этого есть и второй
 * смысл: подпись «расчётов три, вне книги одно» отвечает на вопрос,
 * который читатель задаёт первым, — много ли из названного зависит от нас.
 */
export const demandTally = (study: Study): Record<StudyDemandKind, number> => ({
  field: study.demands.filter((d) => d.kind === 'field').length,
  intake: study.demands.filter((d) => d.kind === 'intake').length,
  calc: study.demands.filter((d) => d.kind === 'calc').length,
  outside: study.demands.filter((d) => d.kind === 'outside').length,
})

/**
 * Сколько требований набралось по всему разделу.
 *
 * Число стоит на указателе и растёт с каждой разобранной работой. В этом
 * и смысл раздела: пока оно растёт, раздел работает; когда оно перестанет
 * расти при новых страницах, значит, работы берутся не те.
 */
export const demandTotal = (studies: Study[] = STUDIES): number =>
  studies.reduce((n, s) => n + s.demands.length, 0)
