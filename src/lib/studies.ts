/**
 * Сколько полей из списка есть, сколько заполнено не у всех и скольких нет.
 *
 * Считается по самому списку, а не пишется рядом с ним. Пиши мы это словами,
 * первая же дописанная строка сделала бы подпись неверной — и неверной
 * молча, потому что смотрит на список читатель, а правит его автор.
 */
export const fieldTally = (study: Study): { yes: number; partial: number; no: number } => ({
  yes: study.fields.filter((f) => f.state === 'yes').length,
  partial: study.fields.filter((f) => f.state === 'partial').length,
  no: study.fields.filter((f) => f.state === 'no').length,
})
