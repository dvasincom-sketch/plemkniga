/**
 * Исследования — раздел витрины, где опубликованная работа переводится
 * в список того, что книга обязана научиться хранить и считать.
 *
 * ## Чем это не является
 *
 * Это не пересказ. Довод против пересказа записан в шапке `lib/notes.ts`
 * и остаётся в силе: пересказ чужой статьи стоит ровно столько, сколько
 * стоит наше чтение этой статьи, а проверить его читатель может только
 * сходив в первоисточник. Заводить ради этого раздел незачем — первоисточник
 * и так по ссылке.
 *
 * Это и не разбор. Разбор объясняет, как устроено то, что уже считает книга,
 * и весь его материал у нас на руках. Здесь материала как раз нет: работа
 * чужая, выборка чужая, метод чужой. Общего у двух разделов только рамка —
 * закреплённый порядок частей и обязательный раздел о том, чего работа
 * не доказывает.
 *
 * ## Чем раздел был и почему этого оказалось мало
 *
 * Начинался он с вопроса, которого не задаёт никто, кроме нас: что нужно,
 * чтобы проверить это на нашей базе. Каждая страница добросовестно называла
 * поля, которые для проверки читаются, счёт по тем из них, что считаются
 * из кода, и перечень того, чего не хватает. Форма была верной, а действие
 * получилось обратным задуманному.
 *
 * Перечень отсутствий, адресованный соискателю, закрепляет нынешние
 * возможности системы. Он объясняет, почему мы чего-то не можем, — и на этом
 * заканчивается. Прочитанный подряд, раздел выглядел рядом уважительных
 * причин: суточных удоев нет и не будет, генотипов нет сознательно,
 * энергокоррекция не считается, счёт по живой книге не считался. Каждое
 * утверждение по отдельности верно; вместе они складываются в оправдание.
 *
 * Верно же обратное: чужая работа — это заявка на данные, которых у нас
 * ещё нет. Она приходит из популяции, где эти данные собрали, и тем самым
 * доказывает, что собрать их можно. Значит, «у нас такого не хранится» — не
 * конец разговора, а его начало: дальше идёт вопрос, что именно завести,
 * чтобы в следующий раз ответ был другим.
 *
 * Отсюда седьмая часть, ради которой раздел и ведётся: что завести в книге,
 * чтобы вопрос стал проверяемым. Она адресована в первую очередь нам,
 * и только во вторую — соискателю. Раздел ведётся ради того, чтобы список
 * таких заявок рос и закрывался: работа, из которой не следует ни одной
 * задачи, в разделе не нужна, и это закреплено типом — `demands` не может
 * быть пустым.
 *
 * ## Что проверяется в самих требованиях
 *
 * Требование пишется так, чтобы его можно было взять и сделать: «завести
 * поле такое-то в такой-то записи», «принять такой-то ресурс обмена»,
 * «посчитать такую-то строку в сводке качества». Места называются теми же
 * именами, что стоят в коде, — как и поля во второй части. Требование вида
 * «расширить модель данных» не требование, а настроение: его нельзя ни
 * оценить, ни закрыть, ни заметить, что оно уже закрыто.
 *
 * Отсюда же следует, что раздел стареет вместе с книгой, а не вместе
 * с работой: исчезнет поле — исчезнет строка, появится — закроется
 * требование.
 *
 * ## Семь частей, и порядок не переставляется
 *
 * Что утверждает работа; что нужно для проверки; что у нас есть сегодня;
 * чего не хватает; чем наш ответ будет отличаться; чего пересчёт
 * не докажет; что завести в книге. Порядок закреплён не здесь, а в обвязке
 * (`components/site/StudyFrame.tsx`) — как у словаря: он и есть жанр,
 * и оставлять его на усмотрение пишущего значило бы получить семь
 * разных жанров на семи страницах.
 *
 * Требования стоят последними, после оговорок, и это не небрежность.
 * Оговорки ограничивают наш будущий ответ, а требования — то, ради чего
 * страница написана; последнее слово на странице остаётся за работой,
 * которую надо сделать, а не за причинами, по которым её пока не сделали.
 *
 * Тип требует все семь. Часть, которую нечем наполнить, — не повод
 * завести страницу без неё, а признак того, что работа для этого раздела
 * не годится: сказать «чего пересчёт не докажет» можно всегда, и молчание
 * здесь означает не отсутствие оговорок, а нежелание их называть.
 *
 * ## Главное правило: не утверждать того, чего мы не читали
 *
 * У каждой работы стоит `read`. `full` — прочитан полный текст; `abstract` —
 * только открытая часть: название, аннотация, объём выборки. При `abstract`
 * страница не вправе пересказывать выводы: всё, что она говорит о работе,
 * должно проверяться по её открытой части, а недостающее называется
 * недостающим. Это не осторожность ради приличия — на выводе, вычитанном
 * из чужого пересказа аннотации, строится потом список полей и список
 * требований, и ошибка доезжает до соискателя, который придёт эти поля
 * просить, — а теперь ещё и до того, кто пойдёт эти поля заводить.
 *
 * Поэтому же `read` не служебная пометка, а часть текста: обвязка печатает
 * её и подписью в паспорте работы, и отдельным предупреждением под ним.
 * Читатель обязан знать, на чём стоит страница, до первого утверждения —
 * прятать это в код значило бы продавать сильное обещание и отдавать
 * слабое.
 *
 * ## Почему числа в третьей части считаются, а не пишутся
 *
 * «У нас 15 значений перечислений и девять колен родословной» — обещание,
 * которое проверяется одним переходом в код. Написанное руками, оно
 * разойдётся с кодом на первой же правке и разойдётся молча: страницу
 * читает человек, а поля правит другой человек, и сверить их некому.
 * Поэтому всё, что можно посчитать, посчитано здесь же, из тех же
 * модулей, откуда это берут книга и обмен.
 *
 * Считать можно не всё. Сколько в базе записей контроля с проставленным
 * методом — витрина не знает и знать не должна: она отдельный домен, она
 * не ходит в базу и обязана открываться, когда база недоступна. Такие
 * строки стоят с `count: null` и подписью, что счёт не считался. Пустое
 * место честнее правдоподобного числа: правдоподобное число в разделе
 * про воспроизводимость расчёта — это ровно та ошибка, против которой
 * раздел заведён.
 *
 * ## Почему только по-русски
 *
 * Тот же довод, что у разборов, словаря и страниц пород: перевод текста,
 * вся ценность которого в точности формулировок, на шесть языков — это
 * пять машинных переводов и обесцененный оригинал.
 */

/** Работа, которую воспроизводим. */
export type StudyWork = {
  title: string
  /**
   * Авторы так, как их удалось установить по открытой части.
   *
   * Поле обязательно и при этом иногда заполняется словами «список
   * не установлен». Необязательным его делать нельзя: пропущенное поле
   * читается как «авторов нет», а названная невозможность установить —
   * как то, чем она является, то есть как состояние нашего знания.
   */
  authors: string
  journal: string
  year: number
  url: string
  /** Объём выборки — числом из открытой части, а не из нашего пересказа. */
  sample: string
  /** Что мы прочли: полный текст или только открытую часть. */
  read: 'full' | 'abstract'
}

/**
 * Поле книги, которое работа заставляет прочесть.
 *
 * Имя пишется так, как оно стоит в коде, а не так, как называется в
 * интерфейсе: соискатель, который придёт с этой страницей, будет искать
 * поле, а не подпись. Состояние — три значения, потому что промежуточное
 * здесь самое частое: поле есть, но заполнено не у всех, или выводится
 * из соседних вместо того, чтобы храниться.
 */
export type StudyField = {
  /** Где лежит: коллекция, массив внутри карточки, модуль расчёта. */
  where: string
  /** Имя поля в коде. */
  name: string
  /** Что это и зачем оно работе. */
  what: string
  state: 'yes' | 'partial' | 'no'
}

/**
 * Строка третьей части: сколько у нас есть.
 *
 * `count: null` означает ровно одно — счёт не считался, и почему,
 * сказано в `from`. Ноль означает другое: посчитали и не нашли,
 * обычно потому, что такого хранилища в книге нет вовсе.
 */
export type StudyHolding = {
  what: string
  count: number | null
  unit: string
  /** Откуда взялось число — или почему его нет. */
  from: string
}

/**
 * Какого рода работа стоит за требованием.
 *
 * Четыре значения, и делят они не по трудоёмкости, а по тому, кто может
 * это закрыть. Поле заводится правкой коллекции; загрузка и обмен требуют
 * согласия того, кто данные шлёт; расчёт пишется на уже лежащем материале
 * и потому обычно дешевле всего; последнее не закрывается нами вовсе.
 *
 * Различать это важнее, чем кажется. Список, где «завести колонку в наборе
 * загрузки» и «дождаться, пока стандарт назовёт код» лежат вперемешку,
 * читается как одинаково недостижимый — и ни одна строка из него не берётся
 * в работу.
 */
export type StudyDemandKind = 'field' | 'intake' | 'calc' | 'outside'

/**
 * Требование к книге: что завести, чтобы вопрос работы стал проверяемым.
 *
 * `what` пишется так, чтобы это можно было взять и сделать: с именем
 * коллекции, набора загрузки или модуля расчёта. `why` объясняет не пользу
 * вообще, а невозможность: без чего именно вопрос не проверяется. `where`
 * называет место в коде и потому пусто ровно у того, что вне книги.
 */
export type StudyDemand = {
  /** Что завести — с именем места, а не «расширить модель данных». */
  what: string
  /** Почему без этого вопрос не проверяется. */
  why: string
  kind: StudyDemandKind
  /** Куда это ложится: файл, коллекция, набор загрузки. */
  where?: string
}

export type StudySource = {
  title: string
  url?: string
  what?: string
}

/** Абзацы одной части. Пустой массив запрещён типом ниже. */
type Paragraphs = [string, ...string[]]

export type Study = {
  slug: string
  title: string
  /** Одна строка, ради которой страницу открыли. */
  lead: string
  /** Дата, ISO. Не «обновлено»: это высказывание о состоянии базы. */
  date: string
  author: string
  authorUrl?: string
  work: StudyWork

  /** 1. Что утверждает работа — одной фразой, с числом. */
  claim: Paragraphs
  /** 2. Что нужно для проверки. */
  needed: Paragraphs
  /** Поля книги поимённо — к части 2. */
  fields: [StudyField, ...StudyField[]]
  /** 3. Что у нас есть сегодня. */
  have: Paragraphs
  /** Счёт к части 3. Числа приходят из кода. */
  holdings: [StudyHolding, ...StudyHolding[]]
  /** 4. Чего не хватает — и это же задача для соискателя. */
  missing: Paragraphs
  /** 5. Чем наш ответ будет отличаться. */
  difference: Paragraphs
  /** 6. Чего пересчёт не докажет. */
  limits: Paragraphs
  /**
   * 7. Что завести в книге, чтобы вопрос стал проверяемым.
   *
   * Непустой по типу: страница исследования, из которой не следует ни одной
   * задачи, не нужна. Это не формальность — работа, не потребовавшая от нас
   * ничего, либо разобрана невнимательно, либо взята не та.
   */
  demands: [StudyDemand, ...StudyDemand[]]

  /** Термины словаря, употреблённые на странице (`lib/term-links.ts`). */
  terms?: string[]
  /** Куда идти дальше: разбор, раздел книги, статья словаря. */
  see?: { label: string; href: string }[]
  sources: StudySource[]
}

