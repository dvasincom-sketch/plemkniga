/**
 * Как эти же четыре признака раскладываются в карточке.
 *
 * ## Почему хранение и показ разошлись
 *
 * `HEALTH_TRAITS` — список полей: по нему строится группа `health`
 * в коллекции, по нему же ходят выгрузки и снимки оценок. Трогать его
 * ради вида карточки нельзя: это переезд колонок в базе ради
 * расположения таблиц на экране.
 *
 * Показ при этом обязан разойтись с хранением, потому что «лёгкость
 * отёла» и «смертность приплода» отвечают не на вопрос о здоровье
 * дочерей, а на вопрос об отёле: легко ли отелится корова и выживет ли
 * телёнок. В CDCB, у Lactanet и у европейцев это отдельная группа —
 * и не из любви к порядку, а потому что покупатель семени задаёт про
 * отёлы отдельный вопрос, обычно раньше вопроса о долголетии.
 *
 * ## Почему списки заданы ключами, а не копией строк
 *
 * Копия рано или поздно разойдётся с оригиналом: единицу измерения
 * поправят в одном месте, и карточка станет показывать старую. Здесь
 * берётся ссылка на ту же запись, а недостающий ключ роняет модуль
 * при загрузке — громко и сразу. Тихо пропустить его было бы хуже:
 * признак просто исчез бы из карточки, и заметили бы это не скоро.
 */
const healthTrait = (key: string) => {
  const found = HEALTH_TRAITS.find((t) => t.key === key)
  if (!found) throw new Error(`Признак здоровья «${key}» отсутствует в HEALTH_TRAITS`)
  return found
}

