/**
 * Слова самой страницы раздела книги — те, что не приходят из данных.
 *
 * ## Почему они здесь, а не в общем наборе строк
 *
 * Общие наборы (`page-messages`, `site-messages`) устроены как
 * `Record<Locale, …>` и требуют все шесть языков разом. Для подписей
 * навигации это правильно. Здесь же среди строк — двенадцать подписей
 * под рисунками, и каждая объясняет, что именно на рисунке видно; это
 * такой же длинный текст, как сам разбор раздела, и переводится он вместе
 * с ним, а не отдельно.
 *
 * ## Почему подписи под рисунками — текст, а не часть рисунка
 *
 * Подпись говорит, **что** на рисунке важно. Внутри рисунка её пришлось бы
 * рисовать, то есть переводить перерисовкой. Снаружи она обычный абзац:
 * язык меняется, картинка остаётся.
 *
 * ## Слова внутри самих рисунков
 *
 * Их здесь нет и не должно быть: у экранов свой набор строк
 * (`lib/book-screens-text.ts`), потому что подписи полей и колонок живут
 * вместе с рисунком, а не со страницей вокруг него. Какое-то время
 * экраны оставались русскими на всех языках, и английская страница
 * выходила текстом на одном языке и картинкой на другом; теперь они
 * переводятся вместе.
 *
 * ## Четыре языка добавлены переводом, а не вычиткой
 *
 * Казахский, армянский, белорусский и киргизский написаны переводом
 * с русского оригинала с оглядкой на английский, и носитель языка их
 * не читал. Признак `reviewed` у этих четырёх снят в `i18n/locales.ts`,
 * и потому над текстом страницы стоит оговорка на языке самой страницы
 * (`i18n/translated.ts`, `noticeFor`): термины отрасли могут быть
 * переданы неточно, а числа и источники под ними одинаковы на всех
 * языках. Снимается оговорка только вместе с вычиткой — не раньше.
 */

