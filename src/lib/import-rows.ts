/**
 * Строки файла, которые не строки данных.
 *
 * ## Откуда взялся модуль
 *
 * Прогон `check:import-formats` по набору чужих форматов нашёл четыре
 * молчаливые порчи, и три из них живут не в значении ячейки, а в самой
 * строке: «Итого» заводит карточку животного, номер `1,23E+11` уезжает
 * в книгу следом от Excel, а одно животное тремя строками теряет две
 * лактации из трёх. Четвёртая — пол словами — рядом, в `parseSex`.
 *
 * Разбор значения (`import-values`) о строке ничего не знает и знать
 * не должен: он видит ячейку. Поэтому решения о строке собраны здесь,
 * а не там.
 *
 * ## Общее правило всех четырёх
 *
 * Ни одно из них не чинит данные догадкой. Служебная строка отсеивается
 * и называется; испорченный номер отвергается с объяснением, как его
 * починить; повтор номера отвергается, потому что выбрать «верную» строку
 * нельзя; непонятый пол не подставляется молча, а попадает в протокол.
 * Тот же довод, что у единиц измерения в решении №226: угадать можно,
 * но система, угадавшая неверно и промолчавшая, хуже спросившей.
 */

/**
 * Слова, которыми подписывают итоги и подписи в печатных отчётах.
 *
 * Список нарочно короткий и проверяется на **точное** совпадение всей
 * ячейки, а не на вхождение. Вхождение поймало бы кличку «Итого-2»
 * и номер, в котором случайно оказалось «всего»; отсеять настоящую
 * корову ради красоты отчёта — обмен не в нашу пользу.
 *
 * Клички сюда попасть не могут: сравнивается ячейка номера, а не клички.
 */
const SERVICE_WORDS = new Set([
  'итого',
  'итог',
  'всего',
  'всего по ферме',
  'всего по стаду',
  'всего по хозяйству',
  'в среднем',
  'среднее',
  'итого по группе',
  'подпись',
  'зоотехник',
  'зоотехник-селекционер',
  'главный зоотехник',
  'руководитель',
  'исполнитель',
  'дата',
  'x',
  'х',
])

/**
 * Строка подводит итог или подписывает отчёт, а не описывает животное.
 *
 * Проверяется ячейка номера: она у нас единственная обязательная,
 * и именно её непустота пропускала «Итого» через все заслоны.
 */
export const isServiceRow = (ident: string): boolean =>
  SERVICE_WORDS.has(ident.trim().toLowerCase().replace(/\s+/g, ' '))

/**
 * Номер, который Excel показал научной записью.
 *
 * `1,23E+11` — не номер и не число, а след того, как длинное число
 * не поместилось в столбец. Восстановить исходные цифры нельзя: `1,23E+11`
 * это и `123000000000`, и `123456789012`, округлённые до трёх знаков.
 * Поэтому строка отвергается с объяснением, а не «расшифровывается»:
 * подставить сюда `123000000000` значило бы завести животное с номером,
 * которого не существует, и сделать это молча.
 */
export const isMangledNumber = (ident: string): boolean =>
  /^[+-]?\d+([.,]\d+)?[eE][+-]?\d+$/.test(ident.trim())

/**
 * Пол из ячейки — с ответом «не понял», а не с молчаливым умолчанием.
 *
 * ## Что было
 *
 * Разбор знал десять написаний, и всё прочее возвращал пустотой; выше
 * по потоку пустота превращалась в «женский». Файл с быками, где пол
 * записан «бычок», молча заводил стадо коров — про умолчание сказано
 * в описании формата, но описание читают после, а не до.
 *
 * ## Что добавлено и чего не добавлено
 *
 * Добавлены слова, которыми пол пишут в выгрузках: тёлка, тёлочка,
 * нетель, корова — женский; бычок, бык, бугай — мужской. Все они
 * однозначны.
 *
 * Не добавлены цифровые коды `1` и `2`. В одной программе учёта единица
 * означает быка, в другой корову, и узнать, в какой из них собран файл,
 * по самому файлу нельзя. Угадать здесь — значит перевернуть пол всему
 * стаду с вероятностью один к двум и не сказать об этом; поэтому цифра
 * возвращается как непонятое значение и попадает в протокол приёмки.
 */
const FEMALE = new Set([
  'ж',
  'f',
  'female',
  'женский',
  'самка',
  'тёлка',
  'телка',
  'тёлочка',
  'телочка',
  'нетель',
  'корова',
  'первотёлка',
  'первотелка',
])

const MALE = new Set(['м', 'm', 'male', 'мужской', 'самец', 'бычок', 'бык', 'бугай', 'производитель'])

export type SexRead = { value?: 'female' | 'male'; problem?: string }

export function parseSex(raw?: string): SexRead {
  const s = (raw ?? '').trim().toLowerCase()
  if (!s) return {}
  if (FEMALE.has(s)) return { value: 'female' }
  if (MALE.has(s)) return { value: 'male' }
  return { problem: `«${raw}» — не пол; животное записано коровой, проверьте колонку` }
}

/**
 * Номера, встречающиеся в файле больше одного раза.
 *
 * ## Почему отвергаются все строки повтора, а не лишние
 *
 * Так выглядит выгрузка «по строке на лактацию»: одно животное,
 * три строки, в каждой свой удой. Прежнее поведение — последняя строка
 * переписывает предыдущие — теряло две лактации из трёх и не говорило
 * об этом ни слова.
 *
 * Оставить первую строку было бы не лучше: «первая» и «последняя» здесь
 * одинаково произвольны. У файла, собранного по лактациям, нет строки,
 * которую можно назвать верной, — верны все три, просто не в этом наборе.
 * Поэтому обе строки отклоняются с причиной, которая называет и беду,
 * и выход: лактации грузятся своим набором.
 *
 * Сравнение идёт по написанию номера как есть. Приводить его к общему
 * виду (как это делает `identKey` при поиске животного) здесь нельзя:
 * `0012345` и `12345` — разные строки файла, и объявить их одним
 * животным значило бы принять решение за хозяйство ровно там, где
 * ведущие нули и есть предмет спора.
 */
export const duplicateIdents = (idents: string[]): Map<string, number> => {
  const count = new Map<string, number>()
  for (const id of idents) {
    const key = id.trim()
    if (!key) continue
    count.set(key, (count.get(key) ?? 0) + 1)
  }
  for (const [k, n] of count) if (n < 2) count.delete(k)
  return count
}
