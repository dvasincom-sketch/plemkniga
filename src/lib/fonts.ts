import { Unbounded } from 'next/font/google'

/**
 * Гарнитура знака ПЛЕМ.
 *
 * ## Почему через `next/font`, а не ссылкой на Google Fonts
 *
 * `next/font` скачивает файлы шрифта **во время сборки** и отдаёт их
 * со своего домена. Это не оптимизация, а условие работы: страница,
 * тянущая шрифт с `fonts.googleapis.com` в момент открытия, зависит
 * от доступности чужого сервиса — того самого, доступ к которому у нас
 * может пропасть. Знак продукта, не отрисовавшийся из-за чужого домена,
 * — плохое первое впечатление.
 *
 * Второе следствие важнее первого: имя гарнитуры не уезжает в разметку
 * запросом, и браузер не показывает пустое место, пока шрифт едет.
 *
 * ## Чем платим
 *
 * Сборка перестаёт быть полностью автономной: машине, которая собирает,
 * нужен один раз достучаться до Google. Сорвётся — сборка упадёт,
 * и это лучше, чем молча собраться без шрифта. Если станет мешать,
 * лечится переходом на `next/font/local` с файлом в репозитории.
 *
 * ## Почему только два начертания
 *
 * В знаке ровно одно слово и ровно один вес. Просить переменный шрифт
 * целиком — это сотни килобайт ради четырёх букв. Восьмисотое взято
 * основным, семисотое — запасным на случай, если восьмисотое сочтут
 * тяжёлым.
 *
 * Кириллица объявлена явно: без неё «ПЛЕМ» отрисуется запасной
 * гарнитурой, и знака не будет вовсе — при том, что латинские буквы
 * на той же странице встанут верно, и подмена окажется незаметной
 * для того, кто её допустил.
 */
export const unbounded = Unbounded({
  subsets: ['cyrillic', 'latin'],
  weight: ['700', '800'],
  /*
   * `swap`: пока шрифт грузится, слово рисуется запасной гарнитурой,
   * а не остаётся невидимым. Знак — не тот случай, ради которого стоит
   * держать пустое место в шапке.
   */
  display: 'swap',
  variable: '--font-plem',
})
