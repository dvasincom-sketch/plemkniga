/**
 * Страницы отдельных пород.
 *
 * ## Зачем они
 *
 * Справок про породы в сети сотни, и все переписаны друг у друга.
 * У нас есть то, чего нет ни в одной: **состояние породы в учёте**.
 * Есть ли код ICAR, есть ли ключ государственного реестра, ведётся ли
 * книга — и если нет, то чего именно не хватает. Наберите название
 * любой малочисленной породы и попробуйте узнать, ведётся ли по ней
 * племенная книга: ответа нет нигде.
 *
 * Разбор замысла и границ — `docs/kontent-plan.md`.
 *
 * ## Откуда числа
 *
 * Из ГИСЦ ВНИИплем: институт Министерства сельского хозяйства, который
 * ведёт государственные племенные книги. Взяты как есть, со ссылкой
 * на страницу породы, и подписаны точно: это **племенное** поголовье,
 * а не всё поголовье страны. Разница огромна — у чёрно-пёстрой
 * в племенном учёте сто десять тысяч голов при более чем половине
 * всего молочного скота России.
 *
 * Год, к которому относятся значения, источник не называет. Мы это
 * говорим вслух и не подставляем год сами: «данные ВНИИплем на дату
 * чтения» — честно, «данные за 2025 год» — выдумка.
 *
 * ## Что здесь наше, а что чужое
 *
 * Числа чужие и помечены источником. Текст — свой: пересказ чужой
 * справки своими словами остаётся чужой справкой, а нам нужен ответ
 * на вопрос, которого в справках нет. Поэтому у каждой породы есть
 * `note` — абзац о том, что означает её нынешнее состояние для того,
 * кто собирается с ней работать.
 *
 * ## Почему только по-русски
 *
 * Витрина шестиязычная, но пятьдесят пять пород на шесть языков —
 * триста тридцать страниц, из которых пять шестых машинный перевод
 * справочного текста. Это определение мусорного сайта. Породные
 * страницы живут по-русски и появляются на другом языке тогда, когда
 * его кто-то проверит.
 */

export type BreedFacts = {
  slug: string
  name: string
  url: string
  /** Племенное поголовье, тыс. голов. */
  stock: number
  /** Из них коров, тыс. голов. */
  cows: number
  /** Удой, кг. */
  milk: number
  fat: number
  protein: number
  variants?: { name: string; stock: number; cows: number; milk: number; fat: number; protein: number }[]
}

