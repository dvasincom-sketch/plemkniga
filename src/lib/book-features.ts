/**
 * Разделы книги: короткая подпись на витрине и разбор на своей странице.
 *
 * ## Почему у каждого раздела своя страница
 *
 * Перечень из двенадцати подписей отвечает на вопрос «что здесь есть»
 * и немедленно рождает следующий: «а что это значит». Одна строка
 * ответить на него не может, а раздувать её до абзаца — значит
 * превратить читаемый перечень в стену, которую пролистывают целиком.
 *
 * Отдельная страница решает обе задачи сразу: список остаётся списком,
 * а тот, кого зацепило конкретное, получает разбор — с оговорками,
 * пределами и тем, чего в разделе нет.
 *
 * ## Почему разбор здесь, а не в разметке страниц
 *
 * Двенадцать почти одинаковых страниц, набранных вручную, разойдутся
 * оформлением в первый же месяц. Здесь — только содержание; вид у всех
 * один и живёт в одном шаблоне.
 *
 * ## Правило для текста
 *
 * У каждого раздела названы **пределы**. Раздел без пределов читается
 * как реклама, а первый же специалист спросит именно про них: сколько
 * поколений, какая точность, что будет, если данных нет. Отвечать надо
 * до вопроса (`docs/golos.md`, правило четвёртое).
 */

