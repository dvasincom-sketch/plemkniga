import type { Payload } from 'payload'
import type { User } from '@/payload-types'
import { relId } from '@/lib/visibility'

/**
 * Роли внутри хозяйства и что они позволяют.
 *
 * ## Зачем они понадобились
 *
 * До сих пор у хозяйства была одна роль на всех: любой сотрудник мог
 * продать животное, выпустить ссылку на всё стадо и подать заявку
 * в Ассоциацию. В хозяйстве на пятьсот голов с наёмным оператором это
 * не гипотетическая опасность, а обычный порядок вещей — оператор
 * заводит дойки, а решения принимает руководитель. ТЗ (Приложение №3)
 * требует ровно этого разделения; мы к нему пришли своим путём.
 *
 * ## Почему три роли, а не шесть из ТЗ
 *
 * Шесть ролей ТЗ описывают всю систему: администратор, эксперт
 * Ассоциации, руководитель, зоотехник, внешний пользователь, гость.
 * Первые две у нас уже есть отдельно (`user.role`), последние две — это
 * вовсе не роли, а состояния посетителя: анонимный и получивший ссылку.
 * Внутри хозяйства остаются три, и добавлять четвёртую «на всякий
 * случай» вредно: роль, для которой никто не может назвать, чем она
 * отличается, выдаётся наугад.
 *
 * ## Граница между руководителем и зоотехником
 *
 * Она не по «важности», а по обратимости. Зоотехник вносит и правит
 * данные — ошибку видно и она чинится тем же хозяйством. Руководитель
 * делает то, чего своими силами не отменить: продажа отдаёт карточку
 * чужим рукам, ссылка уходит наружу навсегда, приглашение впускает
 * человека в стадо.
 */

export type OrgRole = 'head' | 'operator' | 'viewer'

export const ORG_ROLES = [
  {
    value: 'head',
    label: 'Руководитель',
    hint: 'Ведёт данные, приглашает сотрудников, оформляет перемещения, открывает доступ',
  },
  {
    value: 'operator',
    label: 'Зоотехник',
    hint: 'Вносит и правит данные, загружает файлы, подаёт их на проверку',
  },
  {
    value: 'viewer',
    label: 'Наблюдатель',
    hint: 'Только смотрит: ветврач на договоре, бухгалтер, консультант',
  },
] as const satisfies readonly { value: OrgRole; label: string; hint: string }[]

export const orgRoleLabel = (role: string | null | undefined): string =>
  ORG_ROLES.find((r) => r.value === role)?.label ?? 'Руководитель'

/**
 * Что можно делать.
 *
 * Возможности названы действиями, а не разделами интерфейса. Раздел
 * переедет, действие останется: «оформить перемещение» будет значить
 * то же самое, из какой бы страницы его ни вызвали, — а «доступ
 * к странице перемещений» перестанет что-либо значить в тот день,
 * когда форму встроят в карточку животного.
 */
export type Capability =
  /** Заводить и править животных, события, дойки, отёлы. */
  | 'data'
  /** Подавать данные на проверку и заявки на верификацию. */
  | 'submit'
  /** Оформлять перемещения: продажа, аренда, выбраковка. */
  | 'move'
  /** Открывать данные наружу: точечный доступ и ссылки на просмотр. */
  | 'share'
  /** Приглашать, менять роли, блокировать сотрудников. */
  | 'team'
  /** Править карточку организации и настройки хозяйства. */
  | 'org'

const MATRIX: Record<OrgRole, readonly Capability[]> = {
  head: ['data', 'submit', 'move', 'share', 'team', 'org'],
  /*
   * Подача на проверку у зоотехника есть, а перемещение и доступ — нет.
   * Подача — продолжение внесения: он же грузил файл, ему и отвечать
   * за то, что в нём. Продажа и открытый наружу доступ — обязательства
   * хозяйства перед третьими лицами, и подписывает их руководитель.
   */
  operator: ['data', 'submit'],
  viewer: [],
}

/** Роль по умолчанию — руководитель: первый человек хозяйства и есть его руководитель. */
export const DEFAULT_ORG_ROLE: OrgRole = 'head'

const roleOf = (user: { orgRole?: string | null } | null | undefined): OrgRole => {
  const r = user?.orgRole
  return r === 'operator' || r === 'viewer' || r === 'head' ? r : DEFAULT_ORG_ROLE
}

export const isBlocked = (user: { blockedAt?: string | null } | null | undefined): boolean =>
  Boolean(user?.blockedAt)

/**
 * Проверка возможности без обращения к базе.
 *
 * Годится там, где нужно решить, показывать ли кнопку. Для самого
 * действия есть `assertCan` — он ещё и смотрит на состояние хозяйства.
 */
export const can = (user: User | null | undefined, capability: Capability): boolean => {
  if (!user) return false
  if (isBlocked(user)) return false
  if (user.role === 'admin' || user.role === 'expert') return true
  return MATRIX[roleOf(user)].includes(capability)
}

/**
 * Проверка перед действием: роль, блокировка человека и состояние хозяйства.
 *
 * Обращение к базе здесь уместно, а в правилах доступа — нет. Правила
 * читаются на каждой странице книги, а действия совершаются редко: один
 * лишний запрос к таблице организаций стоит того, чтобы приостановленное
 * членство означало что-то на деле, а не только в списке Ассоциации.
 *
 * Возвращает текст отказа или `null`. Текст — не «недостаточно прав»:
 * человек должен понять, что делать дальше, а «обратитесь к руководителю»
 * это и говорит.
 */
export async function assertCan(
  payload: Payload,
  user: User | null | undefined,
  capability: Capability,
): Promise<string | null> {
  if (!user) return 'Требуется авторизация'

  if (isBlocked(user)) {
    return user.blockReason
      ? `Учётная запись заблокирована: ${user.blockReason}`
      : 'Учётная запись заблокирована'
  }

  if (user.role === 'admin' || user.role === 'expert') return null

  const org = relId(user.organization)
  if (!org) return 'У вашей учётной записи нет хозяйства'

  /*
   * Приостановленное членство останавливает обязательства перед другими,
   * а не работу хозяйства с собственными данными. Свои дойки оно ведёт
   * как вело; продать животное, открыть доступ наружу или подать заявку —
   * нет: за этими действиями стоит поручительство Ассоциации, которое
   * на время приостановлено.
   */
  if (capability === 'move' || capability === 'share' || capability === 'submit') {
    const o = await payload.findByID({
      collection: 'organizations',
      id: org,
      depth: 0,
      overrideAccess: true,
    })
    if (o?.membership === 'suspended') {
      return 'Членство хозяйства приостановлено: перемещения, доступ наружу и заявки недоступны до решения Ассоциации'
    }
  }

  if (!MATRIX[roleOf(user)].includes(capability)) {
    const what: Record<Capability, string> = {
      data: 'вносить данные',
      submit: 'подавать данные на проверку',
      move: 'оформлять перемещения',
      share: 'открывать доступ к данным',
      team: 'управлять сотрудниками',
      org: 'править карточку хозяйства',
    }
    return `${orgRoleLabel(user.orgRole)} не может ${what[capability]}. Попросите руководителя хозяйства.`
  }

  return null
}
