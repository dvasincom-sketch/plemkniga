/**
 * Попытка сделать то, чего делать нельзя, — с разбором, почему не вышло.
 *
 * ## Зачем это нужно
 *
 * Проверки прав написаны отрицаниями: «чужое хозяйство НЕ видит эту
 * запись», «наблюдатель НЕ вносит дойку», «даже Ассоциация НЕ вписывает
 * строку в журнал». Утверждение доказывается попыткой: если попытка
 * не удалась — значит нельзя.
 *
 * Так и было написано, и в этом ошибка: попытка не удаётся по десятку
 * причин. Отсутствующая колонка, непрошедшая валидация, обрыв соединения,
 * опечатка в имени поля — всё это даёт ту же «неудачу», и проверка
 * отвечает зелёным, ничего не проверив. Ровно тот случай, ради которого
 * заведено правило «прогон обязан отличать „сошлось“ от „нечего было
 * сводить“»: отказ по правам и поломка запроса выглядят одинаково, а
 * означают противоположное.
 *
 * ## Как отличается отказ по правам
 *
 * Payload отвечает на закрытую операцию `Forbidden` со статусом 403.
 * Наши хуки принадлежности бросают обычную ошибку с человеческим
 * текстом («Записать перемещение может только хозяйство-владелец»),
 * и это тоже отказ по правам — просто выраженный там, где правило
 * доступа выразить нечем (`src/access/guards.ts`).
 *
 * Поэтому признаков два: статус и текст. Текст сверяется с началом
 * известных отказов, а не с произвольным словом: «не удалось» или
 * «ошибка» в сообщении базы не должны читаться как отказ по правам.
 */

export type Attempt = {
  /** Операция прошла — значит запрет не работает. */
  allowed: boolean
  /** Операция не прошла именно по правам. */
  denied: boolean
  /** Текст ошибки — печатается в отчёте, когда причина не та. */
  error?: string
}

/** Слова, которыми отказывают наши хуки принадлежности и Payload. */
const DENIAL = [
  'forbidden',
  'not allowed',
  'unauthorized',
  'you are not allowed',
  'может только',
  'доступ',
  'нельзя',
  'не вправе',
  'только руководитель',
  'только хозяйство',
  'только ассоциация',
  'другого хозяйства',
  'своей организации',
  'своего стада',
]

export async function attempt(fn: () => Promise<unknown>): Promise<Attempt> {
  try {
    await fn()
    return { allowed: true, denied: false }
  } catch (e) {
    const status = (e as { status?: number } | null)?.status
    const name = (e as { name?: string } | null)?.name
    const text = e instanceof Error ? e.message : String(e)
    const lower = text.toLowerCase()

    const denied =
      status === 403 ||
      name === 'Forbidden' ||
      DENIAL.some((d) => lower.includes(d))

    return { allowed: false, denied, error: text }
  }
}

/**
 * Пояснение к неудачной проверке — чтобы в отчёте было видно, что
 * случилось: запрет не сработал или запрос упал не по делу.
 */
export const attemptDetail = (a: Attempt): string =>
  a.allowed ? 'операция прошла — запрет не сработал' : `отказ не по правам: ${a.error ?? '—'}`
