import { DENIED_TEXTS } from '@/access/denied'

/**
 * Попытка сделать то, чего делать нельзя, — с разбором, почему не вышло.
 *
 * ## Зачем это нужно
 *
 * Проверки прав написаны отрицаниями: «чужое хозяйство НЕ видит эту
 * запись», «наблюдатель НЕ вносит дойку», «даже Ассоциация НЕ вписывает
 * строку в журнал». Утверждение доказывается попыткой: если попытка
 * не удалась — значит нельзя.
 *
 * Так и было написано, и в этом ошибка: попытка не удаётся по десятку
 * причин. Отсутствующая колонка, непрошедшая валидация, обрыв соединения,
 * опечатка в имени поля — всё это даёт ту же «неудачу», и проверка
 * отвечает зелёным, ничего не проверив. Ровно тот случай, ради которого
 * заведено правило «прогон обязан отличать „сошлось“ от „нечего было
 * сводить“»: отказ по правам и поломка запроса выглядят одинаково, а
 * означают противоположное.
 *
 * ## Как узнаётся отказ по правам
 *
 * Первая редакция различала их по словам в сообщении, и словарь синонимов
 * немедленно отстал: «Наблюдатель не может вносить данные» в него
 * не попало, и три верных запрета отчитались как неопознанные. Словарь
 * ожидаемых фраз вообще не годится — сообщения пишут людям, они меняются,
 * и проверка, зависящая от их формулировки, ломается от правки запятой.
 *
 * Поэтому отказ заявляет о себе сам (`src/access/denied.ts`): у него свой
 * класс `AccessDenied`, а текст попадает в набор `DENIED_TEXTS` в момент
 * броска. Первое узнаётся, пока ошибка доходит целиком; второе — даже
 * когда Payload завернул её в свою и от исходного объекта остался только
 * текст. Плюс `Forbidden` со статусом 403 — так отказывают правила
 * доступа самого Payload.
 *
 * ## Чтение отказывают не 403, а «не найдено»
 *
 * И это не мелочь, а устройство Payload: правило чтения не запрещает
 * операцию, а сужает выборку. Документ, к которому нельзя, не отвергается
 * — он просто не находится, и `findByID` бросает `NotFound` со статусом
 * 404. Ревизия мультиарендности, переведённая на этот разбор, немедленно
 * покраснела на двух коллекциях с текстом «отказ не по правам:
 * Не найдено»: правила работали, а проверка объявляла их поломкой.
 *
 * Считать 404 отказом всегда нельзя: чаще всего это правда означает,
 * что записи нет. Поэтому решает вызывающий — признаком `missingIsDenial`.
 * Ставит он его там, где существование записи только что доказано
 * запросом с `overrideAccess`: тогда «не найдено» может означать
 * единственное — правило чтения скрыло документ.
 */

export type Attempt = {
  /** Операция прошла — значит запрет не работает. */
  allowed: boolean
  /** Операция не прошла именно по правам. */
  denied: boolean
  /** Текст ошибки — печатается в отчёте, когда причина не та. */
  error?: string
}

export type AttemptOptions = {
  /**
   * «Не найдено» считать отказом по правам.
   *
   * Ставится только тогда, когда запись заведомо существует — например,
   * её только что достали с `overrideAccess`. В остальных случаях 404
   * означает отсутствие записи, и выдавать его за работающий запрет
   * было бы той же неправдой, ради которой всё это писалось.
   */
  missingIsDenial?: boolean
}

export async function attempt(
  fn: () => Promise<unknown>,
  opts: AttemptOptions = {},
): Promise<Attempt> {
  try {
    await fn()
    return { allowed: true, denied: false }
  } catch (e) {
    const status = (e as { status?: number } | null)?.status
    const name = (e as { name?: string } | null)?.name
    const text = e instanceof Error ? e.message : String(e)

    /*
     * Текст сверяется целиком и по вхождению: Payload иногда добавляет
     * к сообщению хука своё обрамление, но само сообщение оставляет.
     */
    const known = [...DENIED_TEXTS].some((d) => text === d || text.includes(d))

    const hidden = opts.missingIsDenial && (status === 404 || name === 'NotFound')

    const denied =
      name === 'AccessDenied' || name === 'Forbidden' || status === 403 || known || Boolean(hidden)

    return { allowed: false, denied, error: text }
  }
}

/**
 * Пояснение к неудачной проверке — чтобы в отчёте было видно, что
 * случилось: запрет не сработал или запрос упал не по делу.
 */
export const attemptDetail = (a: Attempt): string =>
  a.allowed ? 'операция прошла — запрет не сработал' : `отказ не по правам: ${a.error ?? '—'}`
