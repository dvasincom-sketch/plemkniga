import type { Payload } from 'payload'

/**
 * На чём стоит оценка коровы.
 *
 * ## Зачем это отдельный блок
 *
 * У быка карточка честно говорит: «55 дочерей в 17 хозяйствах». Число
 * рядом с оценкой означает, сколько наблюдений за ней стоит, и без него
 * оценка не читается — прогноз по четырём дочерям выглядит так же
 * уверенно, как по тремстам.
 *
 * У коровы такого не было нигде. Надёжность 85 % стояла в колонке, а
 * откуда она взялась, карточка не сообщала: сколько лактаций учтено,
 * сколько контрольных доек, есть ли в книге родители. Зоотехник,
 * разбирающий племенную ценность, спрашивает это первым — и не находил
 * ответа.
 *
 * ## Почему именно эти четыре числа
 *
 * Они не выбраны из соображений полноты: ровно из них и складывается
 * надёжность в нашей же формуле (`reliabilityOf` в `breeding-index.ts`).
 * Собственные наблюдения дают `n·h² / (1 + (n−1)·rep)`, родители — свою
 * четверть от их надёжности. Больше лактаций и оба родителя в книге
 * означают более высокий R, и наоборот; показать одно без другого значит
 * показать вывод без основания.
 *
 * Контрольные дойки стоят рядом с лактациями, потому что лактация
 * с тремя дойками и лактация с десятью — не одно наблюдение. В формулу
 * они пока не входят, а в разговор о доверии входят: хозяйство, у которого
 * дойки раз в квартал, должно видеть это рядом со своей оценкой.
 *
 * ## Почему считается запросами, а не из карточки
 *
 * Массив лактаций в самой записи — привезённая копия; отёлы и дойки живут
 * в своих таблицах, и лента событий считает по ним. Взять здесь другое
 * значило бы показать на одной карточке два разных числа лактаций.
 */

export type CowEvidence = {
  /** Законченных лактаций по отдельной таблице отёлов. */
  lactations: number
  /** Контрольных доек, учтённых по этому животному. */
  milkTests: number
  /** Отец найден в книге — не текстом в родословной, а связью. */
  hasSire: boolean
  /** Мать найдена в книге. */
  hasDam: boolean
}

export async function cowEvidence(payload: Payload, animalId: number): Promise<CowEvidence> {
  /*
   * Три счёта одним заходом. `count` вместо `find` намеренно: нужны числа,
   * а не записи, и на корове с двенадцатью лактациями разница невелика —
   * но эта же функция зовётся с карточки, которую открывают тысячами.
   */
  const [calvings, tests, animal] = await Promise.all([
    payload.count({
      collection: 'calvings',
      where: { animal: { equals: animalId } },
      overrideAccess: true,
    }),
    payload.count({
      collection: 'milk-tests',
      where: { animal: { equals: animalId } },
      overrideAccess: true,
    }),
    payload.findByID({
      collection: 'animals',
      id: animalId,
      depth: 0,
      select: { father: true, mother: true },
      overrideAccess: true,
    }),
  ])

  return {
    lactations: calvings.totalDocs ?? 0,
    milkTests: tests.totalDocs ?? 0,
    hasSire: Boolean(animal?.father),
    hasDam: Boolean(animal?.mother),
  }
}
