/** Кодировки, в которых к нам приходят таблицы. */
export type TextEncodingName = 'utf-8' | 'windows-1251' | 'utf-16'

/**
 * Байты текстового файла — строкой, с распознанной кодировкой.
 *
 * ## Зачем это понадобилось
 *
 * Загрузка декодировала файл как UTF-8 и другого не предполагала.
 * Выгрузки российских программ учёта приходят в windows-1251 — это
 * не редкость и не небрежность, это умолчание Excel при сохранении
 * в «CSV (разделители — запятые)» на русской Windows. Такой файл
 * загружался, строки принимались, и в книгу попадали клички вида
 * «Ð—Ð¾Ñ€ÑŒÐºÐ°». Хуже всего, что принимался он молча: пятьсот записей
 * заведены, ни одной ошибки, и разбираться приходится потом и вручную.
 *
 * ## Почему распознавание, а не выбор кодировки в форме
 *
 * Человек, у которого файл в 1251, об этом не знает — Excel не спрашивал
 * его при сохранении и не показывает нигде. Список кодировок в форме
 * означал бы вопрос, на который у спрашиваемого нет ответа, и он ответил
 * бы наугад. Машина же отвечает на него уверенно, и вот почему.
 *
 * ## Почему проверка на UTF-8 надёжна
 *
 * UTF-8 — не набор байтов, а правила их сочетания: у многобайтовой
 * последовательности строго определённые старшие биты. Русский текст
 * в windows-1251 этим правилам почти никогда не удовлетворяет — каждая
 * кириллическая буква там один байт из верхней половины, а идущие
 * подряд такие байты для UTF-8 недопустимы. Поэтому вопрос ставится
 * не «похоже ли на 1251», а «является ли это правильным UTF-8»:
 * на первый вопрос отвечают гаданием по частотам букв, на второй —
 * разбором, и он либо сходится, либо нет.
 *
 * Обратная ошибка — чистый ASCII — не ошибка вовсе: в нём обе кодировки
 * дают побайтно одно и то же.
 *
 * ## UTF-16 здесь потому, что его выбирает сам Excel
 *
 * «Текст Юникод (\*.txt)» в списке форматов сохранения — это UTF-16
 * с меткой порядка байтов и табуляцией вместо точки с запятой. Файл,
 * сохранённый так, состоит наполовину из нулевых байтов, и без разбора
 * метки читается как строка, где после каждой буквы дыра.
 */
export function decodeText(bytes: Uint8Array): { text: string; encoding: TextEncodingName } {
  /*
   * Метка порядка байтов — единственный случай, когда кодировка не
   * угадывается, а прочитана: файл сам о ней сказал. Поэтому она
   * спрашивается первой, до всякого разбора.
   */
  if (bytes.length >= 2 && bytes[0] === 0xff && bytes[1] === 0xfe)
    return { text: new TextDecoder('utf-16le').decode(bytes), encoding: 'utf-16' }
  if (bytes.length >= 2 && bytes[0] === 0xfe && bytes[1] === 0xff)
    return { text: new TextDecoder('utf-16be').decode(bytes), encoding: 'utf-16' }

  try {
    /*
     * `fatal` — вся суть проверки. Обычный разбор подставляет вместо
     * непонятных байтов знак замены и возвращает строку, то есть отвечает
     * «прочитал» на файле, который прочитать не смог; строгий бросает,
     * и это единственный способ узнать ответ.
     */
    return { text: new TextDecoder('utf-8', { fatal: true }).decode(bytes), encoding: 'utf-8' }
  } catch {
    /*
     * Не UTF-8 — значит однобайтовая кодировка, а из них у нас бывает
     * ровно одна. KOI8-R и CP866 в теории возможны, на деле не приходили
     * ни разу, и различать их пришлось бы уже гаданием по частотам букв.
     * Заводить гадание ради случая, которого не было, значит завести
     * источник ошибок, которого тоже не было.
     */
    return { text: new TextDecoder('windows-1251').decode(bytes), encoding: 'windows-1251' }
  }
}

/**
 * Минимальный разбор таблицы: `;`, `,` и табуляция, кавычки и переносы
 * строк внутри кавычек.
 *
 * ## Табуляция появилась потому, что круг не сходился
 *
 * Выгрузка отдаёт формат TXT — ту же таблицу с табуляцией, «для программ
 * учёта». Загрузка табуляции не знала, и наш собственный выгруженный файл
 * обратно не принимался: строка целиком становилась одной колонкой,
 * а человек получал «не найдены обязательные колонки» на файле, который
 * система сама же и выдала. Ошибка тихая ровно в том смысле, в каком
 * тихой была история с кодировкой: ничего не падает, всё объяснимо,
 * и никому не приходит в голову проверить.
 *
 * ## Разделитель считается по первой строке, и это не небрежность
 *
 * Считать по всему файлу было бы хуже: в русских выгрузках дробная часть
 * пишется через запятую — `3,85`, — и на пяти тысячах строк запятых
 * наберётся больше, чем настоящих разделителей. В строке заголовков
 * дробей не бывает. Запятые там бывают — «Удой, кг», «Жир, %» — но их
 * заведомо меньше, чем разделителей: колонок больше, чем заголовков
 * с запятой внутри.
 */
export function parseCsv(text: string): string[][] {
  const clean = text.replace(/^﻿/, '')

  const head = clean.split('\n')[0] ?? ''
  const count = (ch: string) => head.split(ch).length - 1
  /*
   * При равенстве побеждает точка с запятой: это умолчание Excel
   * на русской раскладке, то есть самый частый у нас случай. Порядок
   * задан списком, а не цепочкой условий, — сравнение трёх величин
   * тернарными операторами и есть тот вид кода, где потом обнаруживают,
   * что один из трёх случаев недостижим.
   */
  const delimiter = ([';', ',', '\t'] as const).reduce((best, ch) =>
    count(ch) > count(best) ? ch : best,
  )

  const rows: string[][] = []
  let row: string[] = []
  let field = ''
  let inQuotes = false

  for (let i = 0; i < clean.length; i++) {
    const ch = clean[i]

    if (inQuotes) {
      if (ch === '"') {
        if (clean[i + 1] === '"') {
          field += '"'
          i++
        } else inQuotes = false
      } else field += ch
      continue
    }

    if (ch === '"') inQuotes = true
    else if (ch === delimiter) {
      row.push(field)
      field = ''
    } else if (ch === '\n') {
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else if (ch !== '\r') field += ch
  }

  if (field.length || row.length) {
    row.push(field)
    rows.push(row)
  }

  return rows.filter((r) => r.some((c) => c.trim() !== ''))
}

const escape = (v: unknown): string => {
  const s = v === null || v === undefined ? '' : String(v)
  return /[";\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

export function toCsv(headers: string[], rows: unknown[][]): string {
  const lines = [headers.map(escape).join(';'), ...rows.map((r) => r.map(escape).join(';'))]
  return '﻿' + lines.join('\r\n')
}
