/**
 * Какой наш справочник какому реестру ФГИАС ПР соответствует.
 *
 * ## Почему по системному коду, а не по uuid
 *
 * У каждого реестра есть и то, и другое. Uuid короче и надёжнее на вид,
 * но читающему код он не говорит ничего: `b0647b61-dc45-…` не проверить
 * глазами и не найти в чужой переписке. Системный код — `breeds2`,
 * `animal_line`, `animal_colour2` — читается, ищется и совпадает с тем,
 * что ФГИАС показывает в своём интерфейсе.
 *
 * Uuid при этом никуда не делся: сверка получает список реестров и берёт
 * uuid оттуда. Если код однажды поменяют, сверка скажет «реестр не найден»
 * вместо того, чтобы молча сверяться не с тем.
 *
 * ## Почему сопоставлена половина справочников
 *
 * Числа здесь не пишутся словами намеренно: они уже разъезжались
 * с длинами обоих списков — в тексте стояло «семь из пятнадцати»
 * при восьми сопоставленных, и «Типы ДНК-тестов» приводились примером
 * несопоставленного, хотя пара у них есть. Считает отчёт сверки,
 * а не абзац.
 *
 * Остальным пары в реестре нет, и придумывать её нельзя. Наши «Группы
 * крови» и «Типы гаплотипов» в реестре просто отсутствуют: ФГИАС
 * спрашивает про них иначе, отдельными колонками шаблона достоверности
 * происхождения.
 *
 * Записать их сюда «примерно» значило бы проставить чужие ключи и узнать
 * об этом от реестра, который отвергнет выгрузку целиком, — причём
 * не сказав, на какой именно колонке. Несопоставленный справочник честнее:
 * он назван ниже и виден в отчёте сверки.
 *
 * ## Про «Назначение»
 *
 * Кандидатов два, и оба неточные: «Направление продуктивности
 * (использования)» из двадцати трёх записей и «Назначения животных
 * по видам животных» из двух тысяч ста семи — второе таблица привязок,
 * а не справочник. Взято первое: наш справочник назначений — про то же,
 * про что и оно, и число записей одного порядка. Помечено как требующее
 * взгляда: если сверка найдёт пару меньше чем половине наших записей,
 * значит выбран не тот реестр.
 */

