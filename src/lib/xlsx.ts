/**
 * Книги Excel: чтение в матрицу строк и запись таблицы.
 *
 * ## Почему вся библиотека заперта в одном файле
 *
 * Две причины, и обе дороже удобства. Первая — поставщик. SheetJS
 * официально раздаётся не через npm: в реестре лежит 0.18.5 от февраля
 * 2022 года с непочиненными CVE-2023-30533 (загрязнение прототипа при
 * разборе) и CVE-2024-22363 (зависание на подготовленной строке).
 * Обе — в разборе присланного файла, то есть ровно в том, чем мы здесь
 * занимаемся. Исправления есть только в 0.20.x, а её на npm нет вовсе:
 * автор раздаёт архивом с cdn.sheetjs.com. Ставить из архива по сети
 * значит завести внешний хост в сборку образа — сборка перестаёт быть
 * воспроизводимой ровно в тот день, когда этот хост недоступен. Поэтому
 * взято зеркало `@e965/xlsx`, перепубликующее 0.20.3 в npm: версия точная,
 * без домика, хеш зафиксирован в lock-файле, а `check:xlsx` требует, чтобы
 * внутри действительно была 0.20.3 — подмена версии перестала быть тихой.
 *
 * Вторая причина — размер. Библиотека весит около восьми мегабайт, и в
 * браузер ей попадать незачем: все три места, где она нужна, серверные.
 * Пока вызов лежит в одном файле, за этим следит глаз; разбредись он по
 * компонентам — следить стало бы нечем.
 *
 * ## Почему граница именно «байты → матрица строк»
 *
 * Разбор загруженного файла в проекте уже написан: сопоставление
 * заголовков с колонками, справочники, протокол приёмки, пакет загрузки.
 * Всё это работает с `string[][]` и про формат файла не знает — CSV
 * приходил в него из `parseCsv`. Книга Excel входит туда же и тем же
 * способом, и от этого вся разница между форматами умещается в одну
 * функцию. Соблазн был обратный: дать разбору доступ к листу целиком,
 * чтобы читать типы ячеек. Тогда каждый шаг разбора пришлось бы учить
 * двум источникам значений, и расходиться они начали бы немедленно.
 */

import * as XLSX from '@e965/xlsx'
/*
 * Потолки лежат в отдельном файле, потому что их называет ещё и форма
 * загрузки, а она клиентская: импортируй она их отсюда — в браузерную
 * сборку уехала бы вся библиотека. Разбор — там же, в `table-limits`.
 */
import { XLSX_MAX_ROWS, XLSX_MAX_UNPACKED } from '@/lib/table-limits'

/** Что за файл прислали. */
export type TableKind = 'xlsx' | 'xls' | 'text'

/**
 * Вид файла определяется по первым байтам, а не по имени и не по типу
 * из браузера.
 *
 * Расширение ставит человек, и ставит как придётся: выгрузка из программы
 * учёта регулярно называется `.xls`, а внутри лежит либо настоящая книга
 * 97–2003, либо XML, либо просто таблица с табуляцией. Тип, который
 * присылает браузер, берётся из того же расширения по таблице
 * операционной системы, то есть повторяет ошибку, а не проверяет её.
 *
 * `50 4b` — обычный zip, с него начинается любой `.xlsx`.
 * `d0 cf 11 e0 a1 b1 1a e1` — контейнер OLE2, с него начинается `.xls`
 * времён Excel 97–2003. Всё остальное считаем текстом и отдаём разбору
 * CSV, который сам разберётся с разделителем.
 */
export function detectTableKind(bytes: Uint8Array): TableKind {
  if (bytes.length >= 4 && bytes[0] === 0x50 && bytes[1] === 0x4b) return 'xlsx'
  if (
    bytes.length >= 8 &&
    bytes[0] === 0xd0 &&
    bytes[1] === 0xcf &&
    bytes[2] === 0x11 &&
    bytes[3] === 0xe0
  )
    return 'xls'
  return 'text'
}

export type SheetRead = {
  rows: string[][]
  /** Имя прочитанного листа. */
  sheet: string
  /** Имена листов, которые читать не стали. */
  otherSheets: string[]
  /** Строк оказалось больше потолка — прочитано не всё. */
  truncated: boolean
}

/**
 * Суммарный размер файлов внутри zip по его оглавлению.
 *
 * Оглавление лежит в конце архива и содержит несжатый размер каждой
 * записи — то есть узнать вес распакованной книги можно, ничего
 * не распаковывая. Ради этого функция и написана: `XLSX.read` читает
 * всё в память сразу, и любая проверка после него уже опоздала.
 *
 * Возвращает `null`, когда посчитать не вышло: оглавление не нашлось
 * или размеры записаны в формате zip64. Это не отказ — `null` означает
 * «не знаем», и загрузка продолжается обычным путём. Придумать за архив
 * его размер было бы хуже, чем не знать: на этом числе стоит отказ.
 */
function unpackedSize(bytes: Uint8Array): number | null {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)

  /*
   * Хвост архива приходится искать перебором: он заканчивается записью
   * переменной длины, и её начало вычислить нельзя — только найти.
   * Комментарий к архиву не длиннее 65 535 байт, значит и искать дальше
   * этого от конца незачем.
   */
  const tail = Math.min(bytes.length, 0xffff + 22)
  let eocd = -1
  for (let i = bytes.length - 22; i >= bytes.length - tail && i >= 0; i--) {
    if (view.getUint32(i, true) === 0x06054b50) {
      eocd = i
      break
    }
  }
  if (eocd === -1) return null

  const count = view.getUint16(eocd + 10, true)
  let at = view.getUint32(eocd + 16, true)
  if (at === 0xffffffff || count === 0xffff) return null

  let total = 0
  for (let i = 0; i < count; i++) {
    if (at + 46 > bytes.length) return null
    if (view.getUint32(at, true) !== 0x02014b50) return null

    const size = view.getUint32(at + 24, true)
    // Признак zip64: настоящий размер лежит в дополнительном поле, которое
    // мы не разбираем. Считать по этому числу нельзя — оно заведомо не то.
    if (size === 0xffffffff) return null
    total += size

    const nameLen = view.getUint16(at + 28, true)
    const extraLen = view.getUint16(at + 30, true)
    const commentLen = view.getUint16(at + 32, true)
    at += 46 + nameLen + extraLen + commentLen
  }

  return total
}

/**
 * Пересчёт серийного номера Excel в дату — арифметикой, без `Date`.
 *
 * ## Почему не `cellDates` и не `Date` вообще
 *
 * Это стоило целого дня и одной опрокинутой уверенности. Excel хранит
 * дату числом дней от 30 декабря 1899 года. Библиотека умеет отдавать
 * такую ячейку готовым `Date` — параметр `cellDates` — и первый вариант
 * этого модуля так и делал, а дату из него брал через `toISOString`.
 * Правило было записано в комментарии с объяснением: библиотека строит
 * полночь по UTC, значит местные геттеры в западном поясе соврут,
 * а `toISOString` верен всегда.
 *
 * Проверка, запущенная в пяти поясах, ответила иначе:
 *
 *     UTC                    17 апреля  ✓
 *     Europe/Moscow    (+3)  16 апреля  ✗
 *     America/Los_Angeles(−7) 17 апреля ✓
 *     Pacific/Auckland (+12) 16 апреля  ✗
 *     America/Sao_Paulo(−3)  17 апреля  ✓
 *
 * То есть врал ровно противоположный случай — восточные пояса, — а до
 * того тот же опыт в другом окружении дал полночь по UTC во всех пяти.
 * Разбираться, при каких условиях библиотека строит полночь местную,
 * а при каких мировую, бессмысленно: любой ответ здесь — наблюдение
 * за поведением, которое нам никто не обещал, и держаться за него
 * значит поставить дату рождения животного в зависимость от переменной
 * окружения контейнера.
 *
 * Поэтому `Date` из этой дороги убран целиком. Число дней приходит
 * к нам числом, и в дату его превращает `SSF.parse_date_code` —
 * пересчёт из одной арифметики, в котором часовых поясов нет как
 * понятия. Проверено в тех же пяти поясах: 17 апреля везде.
 *
 * Отличить дату от числа позволяет `cellNF` — формат ячейки: `is_date`
 * отвечает на вопрос «показывает ли Excel это число как дату». Формат,
 * а не величина: `45033` в колонке удоя обязано остаться числом.
 */
type SsfApi = {
  parse_date_code: (n: number) => { y: number; m: number; d: number } | null
  is_date: (fmt: string) => boolean
}

const ssf = (XLSX as unknown as { SSF: SsfApi }).SSF

const pad = (n: number) => String(n).padStart(2, '0')

const dateCell = (serial: number): string | null => {
  const d = ssf.parse_date_code(serial)
  if (!d || !d.y) return null
  return `${d.y}-${pad(d.m)}-${pad(d.d)}`
}

/**
 * Число из ячейки — строкой, в которой нет показателя степени.
 *
 * `String(0.0000001)` даёт `1e-7`, и разбор чисел такую строку не примет:
 * колонка молча опустеет. Значения такого порядка у нас не встречаются
 * ни в удоях, ни в процентах, но встречаются в чужих выгрузках как след
 * округления, и терять из-за этого всю ячейку незачем.
 */
const numberCell = (v: number): string => {
  if (!Number.isFinite(v)) return ''
  if (v !== 0 && (Math.abs(v) < 1e-6 || Math.abs(v) >= 1e21)) return v.toFixed(10).replace(/0+$/, '')
  return String(v)
}

type RawCell = { t?: string; v?: unknown; w?: string; z?: string } | null | undefined

/**
 * Ячейка — строкой.
 *
 * Разбирается по типу, а не по виду значения: `t` библиотека проставляет
 * сама, и это единственное место, где о содержимом ячейки известно
 * достоверно.
 */
const cellText = (cell: RawCell): string => {
  if (!cell || cell.v === null || cell.v === undefined) return ''

  if (cell.t === 'n' && typeof cell.v === 'number') {
    if (cell.z && ssf.is_date(cell.z)) {
      const d = dateCell(cell.v)
      if (d) return d
    }
    return numberCell(cell.v)
  }

  /*
   * Ячейка с ошибкой формулы (`#ДЕЛ/0!`, `#ССЫЛКА!`) отдаётся текстом
   * ошибки, а не пустотой. Пустая клетка означает «не заполнено»,
   * и подменять ею сломанную формулу значит превращать поломку в файле
   * в отсутствие данных — то есть прятать её от того единственного
   * человека, который может её починить. Разбор такое значение не примет
   * и назовёт строку в протоколе приёмки.
   */
  if (cell.t === 'e') return cell.w ?? '#ОШИБКА'

  return String(cell.v)
}

/**
 * Книга Excel — матрицей строк.
 *
 * ## Почему читается первый лист, а не все
 *
 * Наборы данных у нас разведены по файлам: животные отдельно, отёлы
 * отдельно, дойки отдельно — у них нет общих колонок, кроме номера
 * животного. Склеить листы в одну матрицу значит склеить таблицы
 * с разными заголовками. Спросить, какой лист брать, — значит развести
 * загрузку на два шага и держать файл между ними.
 *
 * Поэтому берётся первый, а имена остальных возвращаются наверх и
 * попадают в протокол приёмки. Молчаливое «взяли не всё» — тот самый
 * вид ошибки, о котором система знает и молчит; сказанное вслух «прочитан
 * лист „Стадо“, лист „Легенда“ не читался» стоит одной строки и снимает
 * весь вопрос.
 *
 * ## Про `sheetRows` и `dense`
 *
 * `sheetRows` — не украшение, а единственный способ не прочитать лишнее:
 * без него библиотека раскладывает в память весь лист, и потолок,
 * проверенный после, проверяется уже по факту съеденной памяти.
 * Читается на строку больше потолка — иначе файл ровно в потолок
 * и файл длиннее потолка выглядят одинаково.
 */
export function readSpreadsheet(
  bytes: Uint8Array,
  maxRows: number = XLSX_MAX_ROWS,
): SheetRead | { error: string } {
  if (detectTableKind(bytes) === 'xlsx') {
    const size = unpackedSize(bytes)
    if (size !== null && size > XLSX_MAX_UNPACKED) {
      return {
        error:
          `Внутри файла ${Math.round(size / 1048576)} МБ данных — это больше, чем книга ` +
          'такого размера содержит при обычном заполнении. Файл не разбирался',
      }
    }
  }

  let book: XLSX.WorkBook
  try {
    book = XLSX.read(bytes, {
      type: 'buffer',
      /*
       * `cellNF` включён ради одной вещи — формата ячейки, по которому
       * число отличается от даты. Без него дата приходит числом дней
       * и молча становится числом `45033` в колонке даты рождения.
       *
       * `cellDates` намеренно выключен: разбор дат ведётся арифметикой
       * над этим же числом, и почему — сказано выше, над `dateCell`.
       */
      cellNF: true,
      cellFormula: false,
      /*
       * Оформление не читается сознательно: цвета, шрифты и объединения
       * нам не нужны ни в одной колонке, а память они занимают на каждой
       * ячейке файла.
       */
      cellStyles: false,
      sheetRows: maxRows + 1,
      /*
       * Плотный лист — не только про память. В обычном лист хранится
       * словарём с ключами вида `A1`, и обойти его по порядку можно
       * лишь собрав адреса самому; здесь ряды лежат рядами, а у каждой
       * ячейки есть её тип и формат — то самое, ради чего мы отказались
       * от `sheet_to_json`.
       */
      dense: true,
    })
  } catch (e) {
    console.error('[xlsx] книга не разобралась:', e)
    return { error: 'Файл не читается как книга Excel. Откройте его и сохраните заново' }
  }

  const [first, ...others] = book.SheetNames
  if (!first) return { error: 'В книге нет ни одного листа' }

  const sheet = book.Sheets[first]
  if (!sheet) return { error: `Лист «${first}» не читается` }

  /*
   * `sheet_to_json` здесь не годится: он отдаёт готовые значения и
   * выбрасывает формат ячейки, а без формата дата неотличима от числа.
   * Ряды берутся из плотного листа как есть.
   */
  const raw = (sheet as unknown as { '!data'?: RawCell[][] })['!data'] ?? []

  const truncated = raw.length > maxRows
  const kept = truncated ? raw.slice(0, maxRows) : raw

  /*
   * Строки выравниваются по самой длинной. Библиотека обрезает хвостовые
   * пустые ячейки, и строка, у которой не заполнены последние три колонки,
   * приходит короче заголовка. Разбор читает значения по номеру колонки
   * и на короткой строке получил бы `undefined` там, где по смыслу пусто, —
   * разница невидимая до того дня, когда по ней различают «не заполнено»
   * и «колонки нет».
   */
  const width = kept.reduce((max, r) => Math.max(max, r?.length ?? 0), 0)
  const rows = kept.map((r) => {
    const line = new Array<string>(width)
    for (let i = 0; i < width; i++) line[i] = cellText(r?.[i])
    return line
  })

  return {
    rows: rows.filter((r) => r.some((c) => c.trim() !== '')),
    sheet: first,
    otherSheets: others,
    truncated,
  }
}

/**
 * Таблица — книгой Excel.
 *
 * ## Почему всё уходит текстом, кроме чисел
 *
 * Главная колонка выгрузки — индивидуальный номер, и он не число, хотя
 * из одних цифр и состоит. Отданный числом, он теряет ведущие нули
 * при первом же открытии в Excel: `0987654321` становится `987654321`,
 * и это не отображение, а само значение — обратно такой файл загрузится
 * другим животным. Числами уходят только те колонки, по которым считают:
 * удой, проценты, килограммы, индекс. Ради этого признак задаётся
 * колонкой, а не угадывается по содержимому ячейки — угадывание сделало
 * бы номер числом ровно в тех хозяйствах, где номера записаны цифрами.
 */
export type XlsxColumn = {
  title: string
  /** Колонка с числами: сортируется и считается как число, а не как текст. */
  numeric?: boolean
  /** Ширина в знаках; без неё Excel даёт всем колонкам одинаковую. */
  width?: number
}

export function toXlsx(
  columns: XlsxColumn[],
  rows: unknown[][],
  options: { sheetName?: string } = {},
): Buffer {
  const header = columns.map((c) => ({ v: c.title, t: 's' as const }))

  const body = rows.map((row) =>
    columns.map((c, i) => {
      const v = row[i]
      if (v === null || v === undefined || v === '') return { v: '', t: 's' as const }
      if (c.numeric) {
        const n = typeof v === 'number' ? v : Number(String(v).replace(',', '.'))
        /*
         * Нечисло в числовой колонке уходит текстом, а не выбрасывается
         * и не превращается в ноль. Ноль здесь — это утверждение,
         * которого мы не делали: пустой удой и нулевой удой значат разное.
         */
        if (Number.isFinite(n)) return { v: n, t: 'n' as const }
        return { v: String(v), t: 's' as const }
      }
      return { v: String(v), t: 's' as const }
    }),
  )

  const sheet = XLSX.utils.aoa_to_sheet([header, ...body] as unknown[][])

  sheet['!cols'] = columns.map((c) => ({ wch: c.width ?? Math.max(10, c.title.length + 2) }))

  /*
   * Фильтр по заголовку, а не закрепление строки.
   *
   * Хотелось закрепить шапку — в выгрузке тысячи строк, и таблица,
   * у которой при прокрутке не видно, что за колонка, читается гаданием.
   * Но `!freeze` бесплатная сборка библиотеки молча не записывает:
   * свойство принимается, файл собирается, а в разметке листа никакого
   * `pane` нет — проверено распаковкой готового файла. Обещание в коде,
   * которого нет в файле, хуже отсутствующего обещания, поэтому его тут
   * и нет. Автофильтр записывается по-настоящему и попутно решает ту же
   * задачу: развернув список по колонке, видно, что в ней.
   */
  if (rows.length) {
    const last = XLSX.utils.encode_cell({ c: columns.length - 1, r: rows.length })
    sheet['!autofilter'] = { ref: `A1:${last}` }
  }

  const book = XLSX.utils.book_new()
  /*
   * Имя листа Excel не пускает длиннее тридцати одного знака и не пускает
   * в него `: \ / ? * [ ]`. Имя мы задаём сами и в эти границы укладываемся,
   * но обрезка стоит здесь, а не в вызывающем коде: сломанное имя листа
   * делает файл нечитаемым целиком, а помнить про это на каждом вызове
   * — способ однажды забыть.
   */
  const name = (options.sheetName ?? 'Данные').replace(/[:\\/?*[\]]/g, ' ').slice(0, 31)
  XLSX.utils.book_append_sheet(book, sheet, name)

  return XLSX.write(book, { type: 'buffer', bookType: 'xlsx', compression: true }) as Buffer
}

