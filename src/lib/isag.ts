/**
 * Панель ISAG — двенадцать локусов, которыми подтверждают происхождение.
 *
 * ## Почему двенадцать и почему все сразу
 *
 * Это стандартная панель микросателлитов ISAG для КРС, и шаблон ФГИАС
 * требует её колонка за колонкой, в этом порядке. Половина генотипа
 * не доказывает ничего: происхождение подтверждается совпадением аллелей
 * по всем локусам разом, и «мы храним шесть из двенадцати» означает
 * «мы не храним генотип».
 *
 * Поэтому заводятся все двенадцать или ни одного.
 *
 * ## Почему текст, а не число
 *
 * В локусе записана пара аллелей: `121/133`, `AB`, иногда с пометкой
 * лаборатории. Число сюда не помещается, а разложить пару на два числа
 * значило бы придумать формат, которого нет ни в шаблоне, ни
 * в лабораторных протоколах.
 *
 * ## Порядок взят из шаблона
 *
 * Он не алфавитный: BM1818, BM1824, BM2113, потом ETH3, ETH10, ETH225.
 * Внутри ETH числа идут 3, 10, 225 — то есть и не по возрастанию строки.
 * Переписывать «как ровнее» нельзя: колонки выгрузки идут в этом порядке,
 * и перестановка сдвинула бы генотип на соседний локус.
 */

export const ISAG_LOCI = [
  'BM1818',
  'BM1824',
  'BM2113',
  'ETH3',
  'ETH10',
  'ETH225',
  'INRA023',
  'SPS115',
  'TGLA53',
  'TGLA122',
  'TGLA126',
  'TGLA227',
] as const

export type IsagLocus = (typeof ISAG_LOCI)[number]

/**
 * Имя поля в карточке по имени локуса: `BM1818` → `isagBm1818`.
 *
 * ## Почему только первая буква заглавная
 *
 * Payload переводит имя поля в имя колонки, вставляя подчёркивание перед
 * каждой заглавной. `isagBM1818` превращается в `isag_b_m1818` — две
 * заглавные подряд дают лишний разделитель посередине названия локуса.
 *
 * Поймано это было не рассуждением, а прогоном: drizzle-kit увидел
 * в схеме `isag_b_m1818`, в базе `isag_bm1818` (так их создала написанная
 * руками миграция) — и спросил, не переименование ли это, предложив
 * свести все двенадцать локусов в один. Ответ «да» на любую из строк
 * склеил бы генотип в одну колонку и потерял одиннадцать.
 *
 * `isagBm1818` даёт `isag_bm1818`, `isagEth3` — `isag_eth3`,
 * `isagInra023` — `isag_inra023`. Ровно то, что в миграции.
 *
 * ## Почему не переписали миграцию под `isag_b_m1818`
 *
 * Потому что это имя — не решение, а случайность правила именования.
 * Колонка `isag_b_m1818` не значит ничего ни для человека, ни для
 * реестра; читать её в `psql` будет тот же зоотехник, что читает шаблон,
 * где локус называется `BM1818`.
 */
export const isagField = (locus: string): string =>
  `isag${locus.charAt(0).toUpperCase()}${locus.slice(1).toLowerCase()}`

