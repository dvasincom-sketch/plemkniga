/**
 * Код страны регистрации организации-оценщика в справочнике «Государства».
 *
 * ## Почему код, а не ключ
 *
 * Ключи стран лежат в справочнике `countries`, который загружается
 * однажды (`npm run sync:fgias-geo`), и брать их оттуда правильнее,
 * чем выписывать в константу: страна одна и та же, а ключ у реестра
 * свой и может смениться вместе с версией справочника.
 *
 * Код же реестр пишет английским названием — `Russia`, — и по нему
 * запись находится в нашей таблице так же, как нашлась бы по ключу.
 *
 * ## Почему страна выводится из ИНН
 *
 * Поля «страна регистрации» у организации в книге нет, и заводить его
 * ради одной колонки выгрузки значило бы просить хозяйство заполнить
 * его полутора тысячам записей. Но ИНН выдаёт Россия — организация,
 * у которой он есть, зарегистрирована в России, и это не догадка,
 * а определение.
 *
 * У организации без ИНН колонка уходит пустой. Таких среди оценщиков
 * почти нет: бонитировку проводит юридическое лицо, а не человек.
 */
export const RUSSIA_CODE = 'Russia'
