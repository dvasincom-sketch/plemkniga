/**
 * Комплексный класс — ключи реестра и правила перевода.
 *
 * ## Откуда взяты ключи
 *
 * Шаблон велит брать «справочник „Комплексный класс по видам животных“,
 * наименование „Идентификатор класса“» — то есть не сам список классов,
 * а его привязку к виду, направлению и половозрастной группе. Привязок
 * там две тысячи семьсот двадцать девять, но «Идентификатор класса»
 * у них общий: для КРС молочного направления он принимает ровно пять
 * значений, и они те же, что в плоском справочнике «Комплексный класс».
 *
 * Прочитано из открытого реестра 30 августа 2026 года перебором привязок
 * с `species_name = «Крупный рогатый скот»` и `direction_name =
 * «Молочное»`. Перебором, а не запросом с отбором: открытая ручка
 * реестра отбор по полям не поддерживает — параметр она молча
 * проглатывает и отдаёт всё подряд.
 *
 * Заодно выяснилось, что листание этой ручки повторяет нашу же беду
 * из решения №229: на соседних страницах одна и та же запись приходила
 * дважды, а между записями КРС вклинивался лесной хорёк. Сортировка
 * там по времени создания, а оно у всей партии одинаковое до микросекунд.
 * Поэтому список сверен по трём перекрывающимся окнам, а не выписан
 * с одной страницы.
 *
 * ## Почему константой, а не справочником в базе
 *
 * Как признаки взвешивания и способы подтверждения родства: список
 * закрытый, его держит государство, хозяйство пополнить его не может.
 * Заводить ради пяти строк таблицу с загрузкой значило бы дать
 * возможность их править — и однажды кто-нибудь поправит.
 */

