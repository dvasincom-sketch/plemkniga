/**
 * Вехи развития платформы и что появилось в каждой.
 *
 * Восстановлены задним числом: тегов в репозитории нет, и притворяться,
 * что были, незачем. Ценность списка не в номерах, а в том, что каждая веха
 * отвечает на вопрос «что стало можно после неё» — и отвечает не разработчику,
 * а хозяйству, Ассоциации и стороннему участнику рынка.
 *
 * В списке только то, что меняло возможности системы. Исправления ошибок,
 * правки вёрстки и внутренние работы по обслуживанию базы сюда не попадают:
 * читателю этой страницы они не говорят ничего, а список из-за них перестаёт
 * читаться. Поэтому номера изменений идут подряд, но не совпадают
 * с количеством правок в репозитории — это указатель для чтения,
 * а не история изменений кода.
 *
 * Разбиение на блоки идёт строго по хронологии, а не по темам: тематическая
 * группировка выглядит стройнее, но врёт о порядке, а порядок здесь и есть
 * главное содержание — он показывает, на чём держится следующее.
 *
 * Даты намеренно не показываются. Дата говорит, когда мы что-то сделали;
 * читателю важно другое — в каком порядке появлялись возможности.
 *
 * Язык описаний. Ни одного слова, которое понятно только разработчику:
 * страница публичная, и её читают зоотехник, специалист Ассоциации
 * и инженер сервисной компании. Название команды или библиотеки не объясняет
 * ценность никому из троих.
 */

export type Audience = 'breeding' | 'association' | 'farm' | 'service'

export type Change = {
  /** Номер вида 0.5.4 — указатель для чтения, не тег репозитория */
  version: string
  /** Заголовок человеческим языком */
  title: string
  /** Короткий хеш коммита. На странице не показывается — нужен, чтобы найти работу в репозитории */
  hash: string
  /** Что это было: два-три предложения без терминов */
  what: string
  /** Ценность по сторонам. Пустое поле честнее выдуманной пользы */
  value: Partial<Record<Audience, string>>
}

export type Milestone = {
  version: string
  title: string
  /** Одним абзацем: какую ценность блок дал участникам */
  value: string
  /** Изменения блока в хронологическом порядке */
  changes: Change[]
  /** Текущая версия — отмечается на странице */
  current?: boolean
  /** Работа идёт прямо сейчас */
  inProgress?: boolean
}

