/** Все изменения одним списком — для разбора адреса и подсчётов */
export const ALL_CHANGES: Change[] = MILESTONES.flatMap((m) => m.changes)

/** Изменение по номеру из адресной строки; неизвестный номер — не ошибка, а «панель закрыта» */
export function findChange(version: string | undefined): Change | null {
  if (!version) return null
  return ALL_CHANGES.find((c) => c.version === version) ?? null
}
