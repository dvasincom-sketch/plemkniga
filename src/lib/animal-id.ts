/**
 * Все идентификаторы стада одной выборкой: `(id, ident_number, field,
 * value, core)`. Ждёт `$1` — организацию.
 *
 * ## Почему обход строки, а не список колонок
 *
 * Видов номера у скота в России не фиксированное число: карточка несёт
 * восемь, и завтра их станет девять — таково само положение дел, ради
 * которого всё это написано. Перечисление колонок означало бы, что новое
 * поле перестаёт проверяться **молча**: проверка остаётся в каталоге,
 * продолжает ничего не находить и выглядит работающей. Обход строки
 * берёт новое поле в тот день, когда оно появилось.
 *
 * Цена — разбор строки в json на каждое животное. Дороже чтения восьми
 * колонок, но того же порядка, что остальные агрегаты по стаду, и
 * платится только по запросу.
 *
 * `not like '%\_date'` — про `alt_ids_chip_date`: дата чипирования лежит
 * рядом с номерами и состоит из цифр. Без этого условия `2019-08-08`
 * дало бы ядро `20190808` и «совпадало» бы с чем угодно.
 *
 * Один текст на два запроса — по стаду и при загрузке файла — не ради
 * экономии строк: разойдясь, они начали бы отвечать по-разному на один
 * и тот же вопрос, и хозяйство увидело бы находку, которой при загрузке
 * не было.
 */
export const IDENT_VALUES_SQL = `
  select a.id, a.ident_number, kv.key as field, kv.value as value,
         ltrim(regexp_replace(kv.value, '[^0-9]', '', 'g'), '0') as core
    from animals a
    cross join lateral jsonb_each_text(to_jsonb(a)) as kv(key, value)
   where a.owner_id = $1
     and a.archived is not true
     and (kv.key = 'ident_number' or kv.key like 'alt\\_ids\\_%')
     and kv.key not like '%\\_date'
     and kv.value is not null
     and kv.value <> ''`
