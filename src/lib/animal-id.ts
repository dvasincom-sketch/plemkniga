/**
 * Цифровое ядро идентификатора — для сопоставления, а не для хранения.
 *
 * Единого номера у скота в России нет, и одно животное приезжает то под
 * национальным номером, то под `XXRUS…`, то под инвентарным. Цифры
 * у них часто совпадают — но **не всегда**: в одних хозяйствах это
 * действительно один и тот же номер в разной записи, в других системы
 * нумерации независимы.
 *
 * Отсюда единственное допустимое употребление: совпадение ядра —
 * это **вопрос человеку**, а не основание слить записи. Автоматическое
 * слияние по цифрам однажды объединит двух разных коров, и разъединить
 * их обратно будет нечем: события, оценки и родословная уже перемешаны.
 *
 * Ведущие нули убираются: `000123456789` и `123456789` — одно и то же
 * число, записанное Excel и не Excel. Короткие ядра отбрасываются:
 * четыре цифры совпадут у кого угодно.
 */
export const IDENT_CORE_MIN = 8

export const identCore = (value?: string | null): string | null => {
  const digits = (value ?? '').replace(/\D/g, '').replace(/^0+/, '')
  return digits.length >= IDENT_CORE_MIN ? digits : null
}

