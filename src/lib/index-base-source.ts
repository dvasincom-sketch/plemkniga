/**
 * Откуда взято стандартное отклонение каждого признака базы сравнения.
 *
 * ## Зачем отдельный файл
 *
 * Само число лежит в `TRAIT_BASE` и работает в расчёте. Здесь — его
 * происхождение: как признак называется у источника, в каких единицах
 * там стоит и что мы с ним сделали. Это разные сведения, и живут они
 * порознь: расчёту происхождение не нужно, а разбору на витрине нужно
 * именно оно.
 *
 * ## Почему `Record<TraitKey, …>`, а не словарь по строкам
 *
 * Чтобы новый признак нельзя было добавить молча. Со словарём вида
 * `Record<string, …>` признак, появившийся в `TRAIT_BASE`, просто
 * не нашёлся бы здесь, и на витрине в столбце «откуда» встал бы прочерк:
 * страница, объясняющая происхождение чисел, показала бы число без
 * происхождения и не пожаловалась.
 *
 * С полным `Record` по объединению ключей это ошибка сборки. Проверку
 * делает язык, и она не может устареть — в отличие от прогона, который
 * надо не забыть запустить.
 *
 * ## Что означает «прямого соответствия нет»
 *
 * Что в источнике такого признака не существует и число взято
 * от ближайшего по смыслу. Таких два, и на витрине они помечены цветом:
 * это допущение, а не выписка.
 */

export type TraitSource = {
  /** Стандартное отклонение так, как оно стоит в источнике. */
  source: string
  /** Единица источника — вместе с его же обозначением признака. */
  unit: string
  /** Что сделано с числом по дороге к нам. */
  how: string
}

