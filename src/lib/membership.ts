import type { Payload } from 'payload'

/**
 * Что даёт членство в Ассоциации.
 *
 * До сих пор подтверждение хозяйства было отметкой без последствий:
 * `confirmed` не участвовал ни в одном правиле доступа, членство лежало
 * справочным значением. Такое подтверждение хозяйство быстро научается
 * не ждать — и правильно делает.
 *
 * Последствия очерчены узко и по одному принципу: **членство решает,
 * за что Ассоциация ручается перед другими, и не решает ничего
 * о собственных данных хозяйства.**
 *
 * | Действие | Требует членства |
 * | --- | --- |
 * | Вести, править, выгружать свои записи | нет |
 * | Загружать данные файлом | нет |
 * | Показывать животных в общей книге | **да** |
 * | Подавать заявку на верификацию | **да** |
 *
 * Загрузка данных намеренно не закрыта. Файл — это собственные данные
 * хозяйства, и запрет их вносить превратил бы проверку в заложничество:
 * «пока не примем — не работайте». Общая книга и верификация — другое
 * дело: там подпись Ассоциации, и ставить её за того, кого не приняли,
 * не за что.
 */

export type MembershipGate = { allowed: boolean; reason?: string }

const PENDING =
  'Действие доступно членам Ассоциации. Ваша заявка на рассмотрении — до решения ' +
  'вы можете вести и выгружать свои данные, но публикация в общей книге и верификация ' +
  'записей недоступны.'

/*
 * Отказ и «ещё не подавали» — разные состояния, и текст у них разный.
 *
 * Прежде оба получали строку про заявку на рассмотрении. Хозяйство,
 * которому Ассоциация отказала (`membership: 'none'` с основанием
 * в решении), читало, что его заявку рассматривают, и ждало ответа,
 * который уже дан.
 */
const NOT_MEMBER =
  'Действие доступно членам Ассоциации, а ваше хозяйство в ней не состоит. ' +
  'Вести и выгружать свои данные можно как обычно; публикация в общей книге ' +
  'и верификация записей — только членам. Если по заявке было решение, ' +
  'основание указано в профиле организации.'

const SUSPENDED =
  'Членство приостановлено, поэтому действие недоступно. Причина указана в решении ' +
  'Ассоциации — она видна в профиле организации.'

/** Состоит ли организация в Ассоциации — с человеческим объяснением отказа. */
export async function membershipGate(
  payload: Payload,
  organizationId: number | string | null | undefined,
): Promise<MembershipGate> {
  if (!organizationId) {
    return { allowed: false, reason: 'У пользователя не заполнена организация' }
  }

  const org = await payload.findByID({
    collection: 'organizations',
    id: organizationId,
    depth: 0,
    overrideAccess: true,
  })

  if (!org) return { allowed: false, reason: 'Организация не найдена' }
  if (org.membership === 'member') return { allowed: true }

  if (org.membership === 'suspended') return { allowed: false, reason: SUSPENDED }
  return { allowed: false, reason: org.membership === 'pending' ? PENDING : NOT_MEMBER }
}
