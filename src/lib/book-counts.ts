import type { Payload, Where } from 'payload'
import { NOT_ARCHIVED } from '@/lib/animal-query'

/**
 * Числа первого экрана книги: сколько их стоит и почему считаются так.
 *
 * ## Что здесь было
 *
 * Главная страница книги на каждый показ делала девять полных подсчётов:
 * страницу выдачи с её итогом, «сколько всего животных в книге» и семь
 * счётчиков быстрых отборов. PostgreSQL количество строк не хранит,
 * и дешёвым такой счёт не бывает: на книге в двести тысяч записей
 * это доли секунды каждый, а с отбором, требующим соединения, —
 * полторы секунды на один.
 *
 * Семь из девяти уходили при этом в подсказку при наведении. Сама
 * страница уже решила, что число в плашке отбора мешает — «глаз читает
 * цифру раньше слова, а выбирают здесь по слову», — и число переехало
 * в `title`. Стоило оно по-прежнему полного прохода по книге.
 *
 * ## Что стало
 *
 * Отборы спрашивают не «сколько», а «есть ли хоть одна»: плашка гаснет
 * при пустоте, и это всё, что она выражает. Пустая плашка остаётся
 * на месте с подсказкой — исчезнув, она сообщила бы, что такого отбора
 * нет вовсе, а он есть. Существование проверяется выборкой одной строки
 * без подсчёта итога (`pagination: false`), то есть индексным касанием
 * вместо прохода.
 *
 * Число «животных в книге» осталось точным: оно стоит в шапке крупно,
 * его читают и по нему судят о размере книги. Но считается оно не чаще
 * раза в минуту на посетителя: за минуту книга не меняется настолько,
 * чтобы это было видно, а разница между «точно сейчас» и «точно минуту
 * назад» здесь ничего не решает. Тот же приём и по той же причине уже
 * применён к отставанию пересчёта индекса.
 *
 * ## Чего здесь нет
 *
 * Итога самой выдачи. Он показывается как «найдено N» и разбивает список
 * на страницы, то есть должен быть точным и свежим: человек, отобравший
 * коров по стаду, сравнивает это число со своим представлением о стаде.
 * Его цена — предмет отдельного разговора, и разговор этот продуктовый,
 * а не про запросы: нужен ли книге точный итог отбора или довольно
 * «более двух тысяч». Пока — точный.
 */

type Cached = { at: number; value: number }

/**
 * Кэш живёт в `globalThis`.
 *
 * Модуль в сборке Next существует не в одном экземпляре, и переменная
 * модуля означала бы, что каждый серверный кусок считает своё. Тот же
 * приём и та же причина, что у пула соединений и набора `DENIED_TEXTS`.
 */
const store = globalThis as typeof globalThis & { __plemBookTotals?: Map<string, Cached> }
const totals: Map<string, Cached> = (store.__plemBookTotals ??= new Map<string, Cached>())

/** Минута: за это время книга не меняется настолько, чтобы это было видно. */
const TTL_MS = 60_000

/**
 * Сколько всего животных видно этому посетителю.
 *
 * Ключ кэша — сам посетитель: число считается с его правами, и общий
 * ответ на всех показал бы гостю то, что видно только Ассоциации.
 * У гостя ключ свой.
 */
export async function bookTotal(
  payload: Payload,
  user: { id?: number | string } | null | undefined,
): Promise<number> {
  const key = user?.id === undefined ? 'guest' : `user:${user.id}`
  const hit = totals.get(key)
  if (hit && Date.now() - hit.at < TTL_MS) return hit.value

  const { totalDocs } = await payload.count({
    collection: 'animals',
    where: NOT_ARCHIVED,
    overrideAccess: false,
    user: user as never,
  })

  totals.set(key, { at: Date.now(), value: totalDocs })
  return totalDocs
}

/**
 * Есть ли под отбором хоть одна запись.
 *
 * Отвечает выборкой одной строки без подсчёта итога. `pagination: false`
 * здесь не украшение: с ним Payload не делает второй запрос за общим
 * числом, а именно он и стоил дорого.
 *
 * Отказ не роняет страницу и не выдаётся за пустоту: `null` означает
 * «спросить не удалось», и плашка тогда остаётся обычной. Погасить её
 * из-за сбоя значило бы сказать «данных нет» там, где мы этого
 * не выяснили.
 */
export async function presetHasRows(
  payload: Payload,
  where: Where,
  user: { id?: number | string } | null | undefined,
): Promise<boolean | null> {
  try {
    const res = await payload.find({
      collection: 'animals',
      where: { and: [NOT_ARCHIVED, where] },
      limit: 1,
      depth: 0,
      pagination: false,
      overrideAccess: false,
      user: user as never,
    })
    return res.docs.length > 0
  } catch (e) {
    console.error(
      `[book] не удалось проверить отбор: ${e instanceof Error ? e.message : String(e)}`,
    )
    return null
  }
}
