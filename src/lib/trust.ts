import type { Payload, PayloadRequest } from 'payload'
import { relId } from '@/lib/visibility'

/**
 * Уровень достоверности: чем он становится и откуда берётся.
 *
 * ## Что было неправдой
 *
 * Шкала обещает пять ступеней, и вторая называется «Подтверждено
 * лабораторией». Дойти до неё было нельзя ничем, кроме синтетики:
 * ни формы, ни действия, ни правила — ступень существовала только
 * в подписи. Хуже пустоты: она объясняла покупателю то, чего система
 * не знала.
 *
 * ## Чем вторая ступень стала
 *
 * Фактом, а не мнением: в книге лежит протокол лаборатории — файлом,
 * с названной лабораторией, зарегистрированный Ассоциацией и привязанный
 * к этому животному. Ступень из него **выводится**, а не проставляется:
 * появился протокол — поднялась, отозвали протокол — опустилась. Поэтому
 * её нельзя ни выставить себе, ни забыть снять.
 *
 * Регистрирует протокол Ассоциация: у хозяйства нет права заполнить
 * «кто выдал» (`associationIssuesOnly`), а без этого поля протокол
 * для правила не существует. Иначе хозяйство завело бы документ через API
 * и подписало бы само себя — ровно та дыра, что закрыта у поля уровня.
 *
 * ## Чего вторая ступень не означает
 *
 * Что лаборатория настоящая, а бумага подлинная. Система хранит файл
 * и имя, а не связь с лабораторией: у лабораторий здесь нет учётных
 * записей и подписывать результат им нечем. Ассоциация ручается за то,
 * что документ ей принесли и она его приняла, — и подписи под данными
 * животного это не даёт, для неё есть третья ступень.
 *
 * Продуктивность сюда тоже не входит, хотя подпись ступени в ТЗ называет
 * и её. Контрольные дойки в книгу вносит хозяйство, лабораторного протокола
 * за ними нет, и говорить «подтверждено лабораторией» про них было бы
 * тем же обещанием сверх знания. Подпись ступени приведена к тому,
 * что система действительно проверяет (решение №198).
 */

/**
 * Тип документа, дающий вторую ступень.
 *
 * Отдельного типа «протокол лаборатории» не заводили: отчёт
 * о генотипировании и есть протокол лаборатории, а два справочных значения
 * с одним смыслом расходятся при первом же выборе из списка. Заодно
 * не понадобилось менять перечисление в базе.
 */
export const LAB_PROTOCOL_TYPE = 'genotypeReport'

/** Ступени, которые правило не трогает. */
const LOCKED: number[] = [
  -1, // отклонено экспертом: находка старше любой бумаги
  3, // подписано Ассоциацией: третья ступень включает вторую
]

/**
 * Есть ли у животного действующий протокол лаборатории.
 *
 * Четыре условия, и каждое отсекает свой способ получить ступень даром:
 * тип — чтобы договор купли-продажи не сходил за протокол; файл — чтобы
 * ступень не давала пустая карточка документа; «кто выдал» — чтобы
 * протокол зарегистрировала Ассоциация, а не хозяйство само; лаборатория —
 * чтобы у результата было имя, которое можно спросить.
 */
export async function hasLabProtocol(
  payload: Payload,
  animalId: number,
  req?: PayloadRequest,
): Promise<boolean> {
  const { totalDocs } = await payload.count({
    collection: 'documents',
    where: {
      and: [
        { animal: { equals: animalId } },
        { type: { equals: LAB_PROTOCOL_TYPE } },
        { file: { exists: true } },
        { issuedBy: { exists: true } },
        // «Есть значение» и «не пусто» — разные вопросы: пустая строка проходит первый
        { labName: { exists: true } },
        { labName: { not_equals: '' } },
        { 'revoked.at': { exists: false } },
      ],
    },
    overrideAccess: true,
    ...(req ? { req } : {}),
  })
  return totalDocs > 0
}

/**
 * Привести ступень животного в соответствие с протоколами.
 *
 * Возвращает новую ступень, если она изменилась, иначе `null` — по этому
 * значению вызывающий решает, что писать в журнал операций.
 *
 * Опускание идёт до первой ступени, а не до черновика: протокол приносят
 * на запись, которую хозяйство уже заявило своей, и отзыв бумаги
 * не отменяет этого заявления. Разницу «черновик или заявлено» правило
 * при подъёме теряет — и это осознанная плата за то, чтобы не заводить
 * второе поле памяти ради двух соседних оттенков одного «внешне
 * не подтверждено».
 */
export async function syncTrustFromLab(
  payload: Payload,
  animalId: number,
  /*
   * Запрос передаётся насквозь — и это не мелочь.
   *
   * Правило зовётся из хука документа, а хук работает внутри незавершённой
   * транзакции. Запрос без `req` идёт мимо неё и только что созданного
   * протокола не видит: ступень тихо не поднялась бы, а причину искали бы
   * в правиле, которое при ручном прогоне работает.
   */
  req?: PayloadRequest,
): Promise<number | null> {
  const animal = await payload.findByID({
    collection: 'animals',
    id: animalId,
    depth: 0,
    overrideAccess: true,
    ...(req ? { req } : {}),
  })

  const level = Number((animal as { trustLevel?: unknown })?.trustLevel ?? 0)
  if (LOCKED.includes(level)) return null

  const found = await hasLabProtocol(payload, animalId, req)
  const next = found ? 2 : level === 2 ? 1 : level
  if (next === level) return null

  await payload.update({
    collection: 'animals',
    id: animalId,
    // Поле закрыто на запись всем: законный путь идёт мимо правил поля
    overrideAccess: true,
    data: {
      trustLevel: next,
      trustCheckedAt: next === 2 ? new Date().toISOString() : null,
    },
    ...(req ? { req } : {}),
  })

  return next
}

/** Ступень «Отклонено»: эксперт нашёл расхождение. */
export const TRUST_REJECTED = -1

/**
 * Поставить записям заявки ступень «Отклонено».
 *
 * ## Почему ступень вообще понадобилась завести заново
 *
 * Она была в шкале с самого начала: значение −1, подпись «Отклонено»,
 * пояснение «эксперт нашёл расхождение: документы не выпускаются».
 * Её защищал `LOCKED`, под неё было раздвинуто ограничение базы,
 * её показывал справочник. Поставить её при этом не мог никто: отказ
 * по заявке менял статус самой заявки и не трогал записи, а поле
 * `trustLevel` закрыто на запись и через форму, и через API. Оставался
 * ручной `UPDATE`.
 *
 * То есть шкала обещала состояние, которого система не производила.
 * Хозяйство, получившее отказ, видело у своих записей прежний уровень —
 * и «Заявлено хозяйством» рядом с отказом читается как «Ассоциация
 * ошиблась», а не как «данные противоречивы».
 *
 * ## Почему отклоняются и подтверждённые прежде
 *
 * Соблазн пощадить ступень 3 велик: её ставил такой же эксперт, и она
 * означает выданное свидетельство. Но `LOCKED` про −1 говорит прямо —
 * «находка старше любой бумаги», — и это верно по существу: если сегодня
 * в родословной найдено противоречие, вчерашняя подпись его не отменяет,
 * она его не заметила. Оставить 3 значило бы продолжать выпускать
 * свидетельства по записи, о которой уже известно, что она неверна.
 *
 * ## Чего эта функция не делает
 *
 * Не трогает чужих. Заявка живёт долго, и животное за это время могли
 * продать; ставить отметку на карточку, которая теперь ведётся другим
 * хозяйством, значило бы наказать покупателя за спор продавца. Список
 * своих отбирает вызывающий — тем же запросом, которым проверяет
 * принадлежность при подтверждении.
 */
export async function markRejected(
  payload: Payload,
  animalIds: number[],
  at: string,
): Promise<number> {
  if (!animalIds.length) return 0

  await payload.update({
    collection: 'animals',
    where: { id: { in: animalIds } },
    // Поле закрыто на запись всем: законный путь идёт мимо правил поля
    overrideAccess: true,
    data: { trustLevel: TRUST_REJECTED, trustCheckedAt: at },
    /*
     * Не журналим как ручную правку: это решение Ассоциации, и его след —
     * сама заявка с заключением. Тот же довод, что у подтверждения.
     */
    context: { skipJournal: true },
  })

  return animalIds.length
}

/**
 * Снять «Отклонено» при новой заявке.
 *
 * ## Почему снимает именно подача заявки
 *
 * Отказ не приговор, а состояние на сегодня, и выход из него должен быть.
 * Рассматривались три двери. Снимать решением Ассоциации — строго,
 * но требует отдельного действия, о котором забудут, и хозяйство
 * застрянет. Снимать любой правкой карточки — просто, но тогда отметку
 * стирает случайная правка клички, и след теряется. Осталась подача новой
 * заявки: это ровно то действие, которым хозяйство говорит «я исправил
 * и снова ручаюсь», и оно уже описано, ограничено ролью и членством.
 *
 * ## Почему возврат на ступень «Заявлено хозяйством», а не на «Черновик»
 *
 * Подача заявки и есть заявление хозяйства своим именем — это дословно
 * определение первой ступени. Ноль означал бы «внесено, но готовым
 * не заявлено», то есть неправду о происходящем.
 *
 * Вторую ступень возвращает не эта функция, а обычное правило
 * (`syncTrustFromLab`): пока запись была отклонена, правило её не трогало
 * — `LOCKED` включает −1, — и накопившийся протокол лаборатории не мог
 * поднять ступень. Сняв отметку, мы даём правилу пересчитать: у кого
 * протокол есть, тот получит свою вторую ступень тут же и не будет ждать
 * следующей правки документа.
 *
 * ## Почему возврат, а не память о прежнем уровне
 *
 * Хранить «какая ступень была до отказа» значило бы завести второе поле
 * ради одного случая — и отвечать на вопрос, что с ним делать, если
 * между отказом и новой заявкой запись изменилась. Ступени 1 и 2
 * восстанавливаются из того, что в книге есть на самом деле; ступень 3
 * не восстанавливается сознательно: её ставит эксперт, и вернуть её
 * должен он же.
 */
export async function clearRejection(payload: Payload, animalIds: number[]): Promise<number[]> {
  if (!animalIds.length) return []

  const { docs } = await payload.find({
    collection: 'animals',
    where: { and: [{ id: { in: animalIds } }, { trustLevel: { equals: TRUST_REJECTED } }] },
    limit: animalIds.length,
    depth: 0,
    overrideAccess: true,
  })

  const cleared = docs.map((d) => Number(d.id))
  if (!cleared.length) return []

  await payload.update({
    collection: 'animals',
    where: { id: { in: cleared } },
    overrideAccess: true,
    data: { trustLevel: 1, trustCheckedAt: null },
    context: { skipJournal: true },
  })

  /*
   * Пересчёт по протоколам — по одному животному: правило спрашивает
   * документы каждого. Заявка ограничена сотней записей, и сотня коротких
   * запросов здесь дешевле второго правила, написанного пакетом.
   */
  for (const id of cleared) {
    await syncTrustFromLab(payload, id).catch((e: unknown) => {
      /*
       * Отказ пересчёта не отменяет снятия отметки: без второй ступени
       * хозяйство работает, с несмываемым «Отклонено» — нет.
       */
      console.error(
        `[trust] ступень по протоколу не пересчиталась у животного ${id}:`,
        e instanceof Error ? e.message : e,
      )
    })
  }

  return cleared
}

/** Достать номер животного из связи документа — для хука, где depth не задан. */
export const animalIdOf = (v: unknown): number | null => {
  const id = relId(v)
  return typeof id === 'number' ? id : null
}
