/**
 * Дорожная карта платформы.
 *
 * Зачем она публичная. Партнёр, который прикидывает интеграцию, и хозяйство,
 * которое решает, вести ли здесь учёт, задают один и тот же вопрос: «а это
 * будет?» Ответ «конечно, скоро» ничего не стоит. Карта отвечает иначе:
 * называет работу, горизонт и состояние — и отдельно то, что заблокировано
 * не нами.
 *
 * Сроки — намерения, а не обязательства, и это сказано на самой странице.
 * Карта без такой оговорки читается как договор, а договор о сроках
 * разработки прототипа никто выполнить не может.
 *
 * Порядок горизонтов прямой: ближайшее сверху. В отличие от списка версий,
 * где сверху последнее сделанное, здесь читателя интересует ближайшее
 * будущее, а не самое дальнее.
 *
 * Заблокированное вынесено в собственное состояние, а не спрятано
 * в «планах». «ФГИАС ПР — план» и «ФГИАС ПР — ждём спецификации, которых
 * нет в открытом доступе» это разные сообщения, и второе честнее.
 */

export type RoadmapState = 'inProgress' | 'designed' | 'planned' | 'blocked'

export type RoadmapItem = {
  title: string
  /** Что именно нужно сделать */
  what: string
  /** Зачем это участникам — одним предложением */
  why: string
  state: RoadmapState
  /** Направление: чтобы в длинном горизонте было видно, о чём речь */
  area: string
}

export type Horizon = {
  id: string
  /** Срок в том виде, в каком он честен: «сейчас», «2027» */
  when: string
  title: string
  /** Что должно стать правдой к концу горизонта */
  goal: string
  items: RoadmapItem[]
}

