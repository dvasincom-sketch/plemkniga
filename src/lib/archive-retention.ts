import type { Payload } from 'payload'

/**
 * Срок хранения архива: сколько живёт карточка после отправки в архив.
 *
 * ## Что здесь за правило
 *
 * Архив в этой книге не «корзина, которую однажды разберут». Через
 * тридцать дней карточка уходит из книги совсем, вместе с отёлами,
 * дойками, осеменениями и оценками; в реестре удалённых записей остаётся
 * строка о том, что она была. Это отменяет прежнее «данные животных
 * никогда не удаляются» (ТЗ, стр. 43) — отменяет сознательно, решением
 * заказчика, и разбор записан в docs/reshenya.md, №90.
 *
 * ## Почему правило живёт отдельным модулем
 *
 * Его спрашивают трое, и ответы обязаны совпасть: кнопка «Отправить
 * в архив» (что скажет хозяйству перед нажатием), список архива (какую
 * дату показать) и сценарий очистки (что удалить сегодня ночью). Разведи
 * их по трём файлам — и хозяйство увидит одну дату, а исчезнет запись
 * в другую.
 *
 * ## Чего это правило не делает
 *
 * Не удаляет ничего само. Пока никто не запустил `npm run archive:purge`,
 * в базе не меняется ничего: срок — это обещание удалить, а не удаление.
 * Так и задумано. Сервер приложения не должен ничего стирать в фоне
 * от того, что кто-то открыл страницу.
 */

export const ARCHIVE_RETENTION_DAYS = 30

const DAY_MS = 86_400_000

const asDate = (v: unknown): Date | null => {
  if (!v) return null
  const d = v instanceof Date ? v : new Date(String(v))
  return Number.isNaN(d.getTime()) ? null : d
}

/**
 * Когда запись уйдёт из книги.
 *
 * `null` значит «срок не начинался»: запись не в архиве, или дата
 * архивации не проставлена. Пустую дату нельзя читать как ноль — так
 * запись, попавшая в архив до появления срока, была бы удалена первым же
 * запуском очистки. Миграция проставляет её всем прежним архивным
 * записям, но защита от пустоты остаётся: чинить данные должна миграция,
 * а не расчёт, который об этом молчит.
 */
export const removalDueAt = (archivedAt: unknown): Date | null => {
  const from = asDate(archivedAt)
  return from ? new Date(from.getTime() + ARCHIVE_RETENTION_DAYS * DAY_MS) : null
}

/** Сколько дней осталось. Отрицательное — срок вышел, ждём очистки. */
export const daysLeft = (archivedAt: unknown, now: Date = new Date()): number | null => {
  const due = removalDueAt(archivedAt)
  return due === null ? null : Math.ceil((due.getTime() - now.getTime()) / DAY_MS)
}

export type RemovalBlocker = { code: string; text: string }

/**
 * Почему эту запись нельзя убрать из книги даже по сроку.
 *
 * ## Откуда взялись запреты
 *
 * Их не просили. Решение звучало «через тридцать дней удалять», и буквальное
 * исполнение выглядело бы так: у чужой коровы в родословной на тридцатый
 * день пропадает мать, а хозяйство этой коровы ничего не делало и ни о чём
 * не просило. Удаление своей записи не должно портить чужую — это не
 * смягчение решения, а его граница.
 *
 * Три запрета, и каждый — про чужой ущерб, а не про ценность самой записи:
 *
 *  - **родитель живых записей**: потомки останутся с дырой в родословной,
 *    а расчёт инбридинга и происхождения — без опоры;
 *  - **выданные документы**: свидетельство ссылается на номер, по которому
 *    в книге не окажется ничего; бумага на руках переживёт запись;
 *  - **открытая заявка на верификацию**: эксперт разбирает пакет, и запись
 *    не должна исчезать у него из-под рук.
 *
 * Запреты не вечные: хозяйство может отвязать потомков или дождаться
 * закрытия заявки. Поэтому очистка их не «пропускает молча», а называет —
 * иначе запись просто не исчезнет, и никто не поймёт почему.
 */
export async function removalBlockers(
  payload: Payload,
  animalId: number,
): Promise<RemovalBlocker[]> {
  const out: RemovalBlocker[] = []

  const children = await payload.count({
    collection: 'animals',
    where: {
      and: [
        { or: [{ father: { equals: animalId } }, { mother: { equals: animalId } }] },
        { or: [{ archived: { equals: false } }, { archived: { exists: false } }] },
      ],
    },
    overrideAccess: true,
  })
  if (children.totalDocs > 0) {
    out.push({
      code: 'has-children',
      text: `Запись — родитель ${children.totalDocs} ${
        children.totalDocs === 1 ? 'записи' : 'записей'
      } в книге. Удаление оставит потомков без происхождения`,
    })
  }

  const docs = await payload.count({
    collection: 'documents',
    where: { animal: { equals: animalId } },
    overrideAccess: true,
  })
  if (docs.totalDocs > 0) {
    out.push({
      code: 'has-documents',
      text: `По записи выдано документов: ${docs.totalDocs}. Бумага на руках ссылается на номер, которого не станет`,
    })
  }

  const requests = await payload.count({
    collection: 'verification-requests',
    where: {
      and: [{ animals: { equals: animalId } }, { status: { in: ['new', 'checking'] } }],
    },
    overrideAccess: true,
  })
  if (requests.totalDocs > 0) {
    out.push({
      code: 'in-verification',
      text: 'Запись входит в заявку на верификацию, которую Ассоциация ещё разбирает',
    })
  }

  return out
}

