export type IcarState = 'full' | 'partial' | 'out'

/**
 * Подписи состояний по-русски; остальные пять языков — в словарях.
 *
 * `Record` по состоянию, а не список: новое состояние не соберётся, пока
 * ему не найдено слово, — и это верно теперь про все шесть языков сразу,
 * потому что словарь набора тоже полон по типу.
 *
 * ## Почему «Учтено», а не «Выполнено»
 *
 * Рядом живёт шкала соответствия (`lib/compliance.ts`), и её верхняя
 * ступень называется «Выполнено». Совпадение слов было бы ошибкой: там
 * состояние работы — требование сделано, и это подтверждается прогоном
 * или страницей. Здесь состояние **раздела чужого стандарта**: ICAR
 * описывает область, а мы отвечаем, попадает ли она в книгу. Раздел
 * нельзя выполнить, его можно учесть или не учесть.
 *
 * Что различие не случайное, видно по остальным ступеням: «Частично»
 * и «Вне области» у двух шкал совпадают дословно и переведены одинаково
 * на все шесть языков, а верхняя расходится в каждом из шести
 * (Covered против Done). Сводить их в одно слово — потерять смысл,
 * который переводчики держали в шести языках подряд.
 */
