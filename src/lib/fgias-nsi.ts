/**
 * Справочники ФГИАС ПР — открытый доступ на чтение.
 *
 * ## Что это и почему оно бесплатно
 *
 * Двадцать шаблонов ФГИАС заполняются не словами, а ключами: порода —
 * это `1bd6b3f1-648a-453b-8529-f2907442d487`, а не «Голштинская». Разбор
 * шаблонов объявил это вторым по тяжести заслоном — тринадцать реестров,
 * значений которых у нас нет. Утверждение было предположением, и оно
 * оказалось неверным.
 *
 * Реестры открыты. Гостю, без авторизации, снаружи, обычным REST
 * с постраничной выдачей; в самом интерфейсе рядом стоит кнопка «Экспорт
 * машиночитаемый CSV» — то есть выгрузка предусмотрена намеренно,
 * а не подсмотрена.
 *
 *     GET /public/public/api/v1/nsi/                     список справочников
 *     GET /public/public/api/v1/nsi/{uuid}/meta/         описание полей
 *     GET /public/public/api/v1/nsi/{uuid}/?offset&limit записи
 *
 * Заслон превратился в работу: суточная сверка и поле `fgiasUuid`
 * в наших справочниках.
 *
 * ## Почему модуль ничего не знает про наши коллекции
 *
 * Здесь только чтение чужого API — ни Payload, ни базы. Так его можно
 * позвать из проверки, из скрипта сверки и однажды из выгрузки, не таща
 * за собой подключение к базе; и так же его можно прогнать на машине,
 * где базы нет вовсе.
 *
 * ## Про постраничность
 *
 * Выдача устроена как у Django REST: `count`, `next`, `results`. Мы ходим
 * по `offset`, а не по `next`, и это не упрямство: в `next` приезжает
 * полный адрес, и следовать ему значит ходить туда, куда скажет чужой
 * сервер. Для открытого справочника разница невелика, но правило дешевле
 * держать одинаковым везде.
 */

const BASE = 'https://fgias-pr.mcx.ru/public/public/api/v1/nsi'

/** Сколько записей просить за раз. Реестр линий — десять с половиной тысяч. */
const PAGE = 500

export type NsiRegistry = {
  uuid: string
  name: string
  /** Системный код вида `animal_line` — устойчивее названия. */
  code: string | null
  statusActive: boolean
}

/**
 * Запись справочника ФГИАС.
 *
 * Три поля названы, потому что они есть у всех реестров и на них
 * держится сверка. Остальные приходят как есть: у пород это
 * `direction_name` и `species_name`, у линий своё, и перечислять
 * их здесь значило бы держать копию чужой схемы, которая меняется
 * без нас.
 */
export type NsiRecord = {
  uuid: string
  name: string
  code: string | null
  [field: string]: unknown
}

/**
 * Запрос с внятным отказом.
 *
 * Чужой сервер отвечает и `502`, и страницей входа вместо JSON. Разбирать
 * такой ответ как записи значило бы завести в книгу справочник из одной
 * строки «Ошибка», поэтому и код ответа, и разбор проверяются здесь,
 * а не там, где результат пригодился.
 */
async function get(url: string): Promise<unknown> {
  const res = await fetch(url, { headers: { accept: 'application/json' } })

  if (!res.ok) {
    throw new Error(`ФГИАС ответил ${res.status} на ${url}`)
  }

  const text = await res.text()

  try {
    return JSON.parse(text)
  } catch {
    throw new Error(
      `ФГИАС вернул не JSON на ${url} — первые сто знаков: ${text.slice(0, 100)}`,
    )
  }
}

const asString = (v: unknown): string | null => (typeof v === 'string' && v ? v : null)

/** Список всех справочников реестра. */
export async function listRegistries(): Promise<NsiRegistry[]> {
  const data = (await get(`${BASE}/?offset=0&limit=200`)) as {
    results?: unknown[]
  }

  return (data.results ?? []).flatMap((r) => {
    const row = r as Record<string, unknown>
    const uuid = asString(row.uuid)
    const name = asString(row.name)
    if (!uuid || !name) return []
    return [
      {
        uuid,
        name,
        code: asString(row.code),
        statusActive: row.status_active !== false,
      },
    ]
  })
}

/**
 * Все записи одного справочника.
 *
 * Идём страницами до тех пор, пока не наберём объявленное сервером
 * `count`. Останов по пустой странице, а не по счётчику, был бы короче
 * и опаснее: сервер, отдавший пустую страницу посередине, оборвал бы
 * обход молча, и справочник приехал бы неполным — а неполный справочник
 * означает, что часть пород объявится «отсутствующими во ФГИАС».
 */
export async function fetchRegistry(uuid: string): Promise<NsiRecord[]> {
  const out: NsiRecord[] = []
  let offset = 0
  let total: number | null = null

  for (;;) {
    const data = (await get(`${BASE}/${uuid}/?offset=${offset}&limit=${PAGE}`)) as {
      count?: number
      results?: unknown[]
    }

    if (total === null) total = typeof data.count === 'number' ? data.count : 0

    const page = data.results ?? []
    for (const r of page) {
      const row = r as Record<string, unknown>
      const id = asString(row.uuid)
      const name = asString(row.name)
      /*
       * Строка кладётся целиком, а не тремя полями.
       *
       * Прежде здесь собирался новый объект `{ uuid, name, code }`,
       * и всё остальное молча терялось. Сверке справочников хватало,
       * а выборке молочных пород — нет: у породы в реестре есть
       * `direction_name` и `species_name`, и именно они отвечают
       * на вопрос «молочная ли». Приведение типа на стороне вызывающего
       * тут не спасает: приведение не создаёт данных, которых нет,
       * и выборка молча возвращала ноль пород из пятисот пятидесяти
       * шести.
       *
       * Именованные поля идут после развёртывания: они разобраны
       * и проверены, а `row` кладёт их сырыми.
       */
      if (id && name) out.push({ ...row, uuid: id, name, code: asString(row.code) })
    }

    offset += PAGE
    if (out.length >= total || page.length === 0) break
  }

  if (total !== null && out.length < total) {
    throw new Error(
      `Справочник ${uuid} приехал неполным: ${out.length} записей из ${total}. ` +
        'Сверять по неполному нельзя — часть наших значений объявится отсутствующими',
    )
  }

  return out
}

/**
 * Наименование к сравнимому виду.
 *
 * Сверка идёт по названию, потому что общего кода у нас с реестром нет:
 * наш `code` — из «Селэкса», их `code` — свой. Названия же расходятся
 * мелочами: регистр, «ё», лишние пробелы, дефис вместо тире.
 *
 * Приведение нарочно осторожное. Убрать, скажем, слово «порода» было бы
 * заманчиво («Голштинская» против «Голштинская порода»), но тогда
 * «Русская порода» и «Русская» слились бы в одно, а это разные записи
 * в реестрах, где такое встречается. Сомнительное сближение здесь дороже
 * несовпадения: несовпадение человек увидит в отчёте и разберёт,
 * а ложное совпадение проставит чужой ключ и промолчит.
 */
export const nsiKey = (name: string): string =>
  name
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[‑–—]/g, '-')
    .replace(/\s+/g, ' ')

/**
 * Похожие названия — подсказка человеку, а не второй круг угадывания.
 *
 * ## Зачем
 *
 * Отчёт, который говорит «двадцати восьми пород в реестре нет», оставляет
 * работу целиком человеку: ему предстоит открыть реестр и искать каждую
 * глазами. Между тем половина этих двадцати восьми там есть — под другим
 * написанием: «Голштинская» против «Голштинская чёрно-пёстрая», «Симментал»
 * против «Симментальская».
 *
 * Разница между «нет в реестре» и «называется иначе» — это разница между
 * «завести признак» и «переименовать строку», то есть между работой
 * на неделю и работой на минуту. Отчёт, который их не различает, отправляет
 * человека делать первое там, где хватило бы второго.
 *
 * ## Почему подсказка, а не сопоставление
 *
 * Найденное здесь **не** проставляется ключом ни при каких условиях.
 * Вхождение одной строки в другую — довод, а не доказательство: «Русская»
 * входит в «Русская комолая», а это разные породы. Ошибка стоила бы чужого
 * ключа в карточке и отказа реестра на выгрузке, причём без указания
 * колонки.
 *
 * Поэтому итог — строка «похоже на», которую читает человек и решает сам.
 *
 * ## Почему по вхождению, а не по расстоянию Левенштейна
 *
 * Расстояние ловит опечатки, а у нас не опечатки: у нас уточняющие слова.
 * «Голштинская» и «Голштинская чёрно-пёстрая» отличаются на четырнадцать
 * знаков — для расстояния это чужие строки, а для человека очевидная пара.
 * Вхождение ловит ровно этот случай и не ловит опечаток; заводить второй
 * способ ради опечаток, которых в справочниках почти не бывает, значит
 * удвоить число ложных подсказок.
 *
 * Порог в четыре знака отсекает мелочь: «як» входит в добрую половину
 * названий, и подсказка «похоже на» после такого перестаёт читаться.
 */
export const looksLike = (ourName: string, theirName: string): boolean => {
  const a = nsiKey(ourName)
  const b = nsiKey(theirName)
  if (a.length < 4 || b.length < 4) return false
  if (a === b) return false
  return a.includes(b) || b.includes(a)
}
