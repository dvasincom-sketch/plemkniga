export const nf = (value: number | null | undefined, digits = 1): string => {
  if (value === null || value === undefined || Number.isNaN(value)) return '—'
  return value.toLocaleString('ru-RU', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })
}

export const signed = (value: number | null | undefined, digits = 1): string => {
  if (value === null || value === undefined || Number.isNaN(value)) return '—'
  const s = nf(Math.abs(value), digits)
  return `${value < 0 ? '−' : '+'}${s}`
}

/**
 * Пояс, в котором показывается время, пока не известен пояс читателя.
 *
 * Нужен потому, что страницу сначала рисует сервер, а он про читателя
 * ничего не знает. Раньше пояс не задавался вовсе — и это была не мелочь:
 * без него разбор берёт пояс процесса, то есть на сервере UTC контейнера,
 * а в браузере пояс читателя. Одна и та же метка показывалась по-разному
 * в зависимости от того, отрисовалась страница на сервере или обновилась
 * на клиенте, и никакая подпись не могла быть верной, потому что верного
 * ответа не было.
 *
 * Москва выбрана не как «главный город», а как пояс, в котором работает
 * Ассоциация: если читателя мы ещё не знаем, время показывается тем,
 * с кем читатель по этому поводу будет разговаривать.
 */
export const FALLBACK_TIME_ZONE = 'Europe/Moscow'

/**
 * Календарная дата — всегда в UTC, и это не выбор пояса, а отказ
 * от пояса.
 *
 * Дата рождения, дата отёла, дата осеменения — не моменты времени,
 * а клетки календаря. Payload хранит их полуночью по UTC, и стоит
 * показать такую полночь в местном поясе, как она уезжает на сутки:
 * `dateRu('2023-04-17')` в поясе −7 давало **16.04.2023** — проверено.
 * Животное рождается в один день во всех странах сразу, и показывать
 * эту дату по-разному разным читателям было бы не удобством,
 * а искажением записи.
 *
 * Ровно та же ловушка встретилась в разборе книг Excel и разобрана
 * там же (`src/lib/xlsx.ts`, над `dateCell`): дату нельзя пропускать
 * через часовой пояс, если она не про часы.
 */
export const dateRu = (value?: string | null): string => {
  if (!value) return '—'
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return '—'
  return d.toLocaleDateString('ru-RU', {
    timeZone: 'UTC',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  })
}

/**
 * Момент времени — с подписью пояса, в котором он показан.
 *
 * ## Почему подпись обязательна
 *
 * «25.08.2026, 07:11» не отвечает на вопрос, чьи это семь утра.
 * Пока пояс не назван, читатель достраивает его сам — своим, — и время
 * записи расходится с тем, что он помнит о собственных действиях,
 * причём молча. Подпись стоит у каждой метки, а не один раз на таблицу:
 * строку копируют в письмо, и уходит она без шапки.
 *
 * ## Почему пояс приходит снаружи
 *
 * Функция не спрашивает пояс у окружения намеренно: окружение у сервера
 * и у браузера разное, и функция, читающая его сама, возвращала бы разное
 * в двух местах, где вызвана. Пояс называет тот, кто знает, — компонент
 * `Moment`, у которого есть браузер.
 */
export const dateTimeRu = (value?: string | null, timeZone = FALLBACK_TIME_ZONE): string => {
  if (!value) return '—'
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return '—'
  return d.toLocaleString('ru-RU', {
    timeZone,
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    /*
     * `short` даёт «GMT+3», «GMT+10», «GMT-7» — короче и однозначнее,
     * чем `shortGeneric` с его «Москва» и «Владивосток»: названия
     * длиннее, а для городов вне России по-русски читаются странно.
     * Смещение же одинаково понятно везде и складывается в уме.
     */
    timeZoneName: 'short',
  })
}

export const dash = <T,>(v: T | null | undefined): T | '—' =>
  v === null || v === undefined || v === '' ? '—' : v

/**
 * Форма слова при числе: «1 запись», «2 записи», «5 записей».
 *
 * Заводится потому, что в кабинете стояло «2 записей неполны» — родительный
 * падеж там, где нужен именительный. Правило русского счёта не сводится
 * к «один или много», и написанное на глаз условие `n === 1 ? … : …`
 * ошибается на каждом числе от двух до четырёх — то есть на самых частых.
 *
 * Формы передаются как есть: `['запись', 'записи', 'записей']`.
 */
export const plural = (n: number, forms: [string, string, string]): string => {
  const abs = Math.abs(n) % 100
  const last = abs % 10
  if (abs > 10 && abs < 20) return forms[2]
  if (last > 1 && last < 5) return forms[1]
  if (last === 1) return forms[0]
  return forms[2]
}
