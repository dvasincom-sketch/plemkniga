/**
 * Словарь терминов: что слово значит здесь.
 *
 * ## Зачем он, если есть разборы
 *
 * Разбор отвечает на вопрос «как это устроено» и читается сорок минут.
 * Человек, встретивший в отчёте слово «сервис-период», спрашивает другое
 * и короче: что это и почему у меня сто дней. Отправлять его в разбор
 * значит не ответить: он уйдёт искать ответ туда, где короче, и найдёт
 * определение без чисел, одинаковое на десяти сайтах.
 *
 * ## Почему два уровня, а не восемьдесят семь страниц
 *
 * Терминов, употребляемых системой как термины, набралось восемьдесят
 * семь. Соблазн — дать каждому свой адрес; так делают все словари,
 * и так делать нельзя. Страница на сто тридцать слов считается тонкой:
 * её либо не показывают, либо показывают так, что она тянет вниз соседей.
 * Полсотни тонких страниц вредят домену целиком.
 *
 * Поэтому адрес получают только те термины, о которых нам есть что
 * сказать на четыреста-семьсот слов — то есть те, где у нас есть свои
 * числа и своя оговорка. Остальные живут строкой на указателе: тот же
 * ответ, та же ссылка дальше, но на странице, которая толстая.
 *
 * Признак здесь не «важность», а `body`: есть развёрнутая статья —
 * есть адрес. Тип это и выражает, и потому вопрос «а не завести ли
 * страницу и этому» решается написанием текста, а не правкой списка.
 *
 * ## Правила жанра
 *
 * У статьи три части, и порядок их не переставляется.
 *
 * **Что это** — первые сорок слов, потому что ровно их показывает
 * выдача и ровно их читает пришедший с вопроса. Определение целиком
 * в первой фразе, без разгона.
 *
 * **Как это считает книга** — с настоящим числом из кода: порог,
 * граница, формула. Это то, чего нет ни в одном другом словаре: там
 * «коэффициент инбридинга показывает степень родства», здесь «порог
 * внимания 6,25 %, глубина обхода шесть колен, пустой предок принимается
 * нулём — и коэффициент выходит заниженным».
 *
 * **Чего это не означает** — ловушка. Их в системе тридцать, и почти
 * все уже описаны в коде и разборах; словарь их не придумывает,
 * а вытаскивает на свет.
 *
 * ## Почему только по-русски
 *
 * Тот же довод, что у разборов и страниц пород: восемьдесят семь
 * определений на шесть языков — это пятьсот машинных переводов
 * зоотехнической терминологии, то есть ровно то, против чего
 * `docs/lokalizatsiya.md`.
 */

