/** Термины со своим адресом. */
export const TERM_PAGES = TERMS.filter((t) => t.body)

export const termBySlug = (slug: string): Term | undefined =>
  TERMS.find((t) => t.slug === slug)

/**
 * Куда ведёт ссылка на термин.
 *
 * У термина со статьёй — свой адрес. У термина без статьи адреса нет,
 * и ссылка на него отдала бы «страница не найдена»: так и вышло, когда
 * словарь наполняли — десять ссылок «читать дальше» вели на определения,
 * живущие строкой на указателе.
 *
 * Чинить это перечислением было бы бесполезно: следующий, кто допишет
 * термин, поставит одиннадцатую такую ссылку и не узнает об этом,
 * потому что на странице она выглядит рабочей. Поэтому адрес не пишется
 * руками, а считается: есть статья — путь, нет — якорь на строку
 * указателя. Ссылка ведёт к ответу в обоих случаях, а разница между
 * ними перестаёт быть заботой пишущего.
 */
export const termHref = (slug: string): string => {
  const term = termBySlug(slug)
  return term?.body ? `/ru/slovar/${slug}` : `/ru/slovar#${slug}`
}

/**
 * Термины группы, по алфавиту.
 *
 * Порядок внутри группы алфавитный, а сами группы — по смыслу: по алфавиту
 * ищет тот, кто слово уже знает, а пришедший с отчётом ищет глазами
 * в разделе, к которому относится его вопрос.
 */
export const termsIn = (group: TermGroup): Term[] =>
  TERMS.filter((t) => t.group === group).sort((a, b) => a.title.localeCompare(b.title, 'ru'))
