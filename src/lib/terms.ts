export type TermSource = {
  /** Название так, чтобы источник можно было найти и без ссылки. */
  title: string
  url?: string
}

export type TermBody = {
  /** Что это. Первый абзац — определение целиком, без разгона. */
  what: string[]
  /** Как считает книга: с числом, которое стоит в коде. */
  how: string[]
  /** Чего это не означает. Без этой части статья становится рекламой. */
  not: string[]
}

export type Term = {
  slug: string
  title: string
  /**
   * Определение одной фразой.
   *
   * Оно же уезжает в описание страницы и в указатель, поэтому длиной
   * ограничено: то, что не поместилось в строку, читатель всё равно
   * не увидит ни там, ни там.
   */
  short: string
  group: TermGroup
  /** Иные написания и синонимы — по ним термин ищут на указателе. */
  also?: string[]
  /**
   * Развёрнутая статья. Есть она — у термина свой адрес, нет —
   * термин стоит строкой на указателе.
   */
  body?: TermBody
  /** Куда идти за подробностями: разбор, раздел книги, страница витрины. */
  see?: { label: string; href: string }[]
  sources?: TermSource[]
}

