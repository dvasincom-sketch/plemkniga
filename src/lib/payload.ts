import { getPayload } from 'payload'
import config from '@payload-config'
import type { User } from '@/payload-types'

/**
 * Обрыв простаивающего соединения не должен ронять процесс.
 *
 * Пул `pg` держит открытые соединения между запросами. Если такое соединение
 * оборвётся — база ушла в перезагрузку, сеть моргнула, файрвол закрылся, —
 * пул сообщает об этом событием `error`. Слушателя у события нет, и Node
 * поступает по общему правилу: необработанный `error` у EventEmitter
 * превращается в `uncaughtException` и убивает процесс.
 *
 * На проде это выглядело так: база перестала отвечать, в логе появилось
 * `⨯ uncaughtException: Error: read ETIMEDOUT`, контейнер умер и поднялся
 * заново — и так по кругу. Перезапуск ничего не чинил (база как была
 * недоступна, так и осталась), но сбивал диагностику: `uptimeSec` на пробе
 * показывал минуты, и казалось, что дело в свежем деплое.
 *
 * Слушатель ничего не восстанавливает: пул откроет новое соединение при
 * следующем запросе сам. Он только не даёт обрыву одного соединения решать
 * судьбу всего приложения — и оставляет строку в логе, по которой видно,
 * что именно оборвалось.
 */
/**
 * Отметка «пул уже под присмотром» стоит на самом пуле, а не в переменной
 * модуля.
 *
 * Сначала это был обычный `let poolGuarded = false`, и в проде он работал:
 * модуль вычисляется один раз, слушатели вешаются один раз. В `next dev`
 * то же самое разваливается. Пул живёт в `globalThis` — его кладёт туда сам
 * Payload, чтобы пережить горячую замену модулей, — а вот наш модуль после
 * каждой пересборки вычисляется заново, и `poolGuarded` снова становится
 * `false`. Пул один, охранников всё больше: на одиннадцатой пересборке Node
 * сообщает `MaxListenersExceededWarning: 11 error listeners added to
 * [Client]`. Предупреждение не про утечку памяти в буквальном смысле — оно
 * про то, что каждое соединение теперь пишет в лог одиннадцать одинаковых
 * строк об одном обрыве.
 *
 * Отметка на пуле переживает пересборку ровно потому, что переживает её
 * сам пул: это одно и то же место жизни. `Symbol.for` берёт символ
 * из общего для процесса реестра, а не заводит новый — важно, потому что
 * серверные компоненты, обработчики маршрутов и серверные действия
 * собираются в разные пакеты, и `Symbol()` дал бы каждому свой ключ,
 * то есть ту же болезнь с другой стороны.
 *
 * Поднять `setMaxListeners` было бы проще всего и означало бы заглушить
 * счётчик, оставив саму очередь охранников на месте.
 */
const GUARDED: unique symbol = Symbol.for('plemkniga.pool-guarded')

type Guarded = { [GUARDED]?: true }

type ClientLike = { on?: (event: 'error', listener: (err: Error) => void) => void }
type PoolLike = {
  on?: (event: 'error' | 'acquire', listener: (arg: never, client?: ClientLike) => void) => void
  query?: (...args: unknown[]) => Promise<unknown>
}

/**
 * Отдельная отметка для перехвата запросов — не та же, что у слушателей.
 *
 * Обёртку и слушателей ставит один и тот же `guardPool`, но проверять
 * их одним флагом нельзя: тогда порядок «поставили слушателей, потом
 * добавили обёртку» дал бы пул, на котором флаг уже стоит, а обёртки нет,
 * — и она не появилась бы никогда.
 */
const QUERY_LOGGED: unique symbol = Symbol.for('plemkniga.pool-query-logged')
type QueryLogged = { [QUERY_LOGGED]?: true }

/**
 * Ошибка PostgreSQL с текстом запроса, который её вызвал.
 *
 * ## Зачем
 *
 * В логе прода третий день висят четырнадцать `division by zero`.
 * Всё, что о них известно: `numeric.c`, `div_var`, минифицированный стек
 * вида `chunks/ssr/src_0ry4r9p.js:1:840`. Ни пути страницы, ни таблицы,
 * ни запроса. Я дважды прошёл все деления в коде и не нашёл ни одного
 * незакрытого — и это ровно то положение, в котором дальше можно только
 * гадать.
 *
 * Причина потери простая: текст запроса есть у ошибки drizzle
 * (`DrizzleQueryError` несёт `query` и `params` — их видно в выводе
 * скриптов), но до лога Next доходит не он, а внутреннее исключение `pg`,
 * у которого этих полей нет. Поймать надо там, где запрос ещё известен,
 * то есть в самом пуле.
 *
 * ## Почему обёртка над `pool.query`, а не над нашими вызовами
 *
 * Через `pool.query` идут все запросы — и наши прямые, и те, что строит
 * drizzle для Payload. Обернув свои вызовы, мы получили бы диагностику
 * ровно там, где она и так есть: у собственных запросов текст известен
 * и в месте написания.
 *
 * ## Что попадает в лог, а что нет
 *
 * Запрос обрезается до полутора тысяч знаков: полный `select` карточки
 * животного — это пять экранов перечисления колонок, и в логе он вытеснит
 * всё остальное. Первых полутора тысяч хватает, чтобы узнать запрос.
 *
 * Параметры логируются, но длинные значения заменяются длиной. В них
 * попадают клички, номера и адреса — данные хозяйств, и класть их в лог
 * целиком незачем: для поиска причины хватает вида «строка, 42 знака».
 * Числа и короткие строки остаются как есть — по ним и ищут.
 */
const MAX_QUERY_IN_LOG = 1500
const MAX_PARAM_IN_LOG = 40

const shortParam = (v: unknown): unknown => {
  if (typeof v === 'string' && v.length > MAX_PARAM_IN_LOG) return `строка, ${v.length} знаков`
  if (v instanceof Date) return v.toISOString()
  if (v && typeof v === 'object') return `объект ${Object.prototype.toString.call(v)}`
  return v
}

const logQueryFailure = (err: unknown, args: unknown[]): void => {
  const e = err as { code?: string; routine?: string; message?: string }

  /*
   * Логируются только отказы самой базы — у них есть пятизначный код
   * SQLSTATE. Обрыв соединения сюда не попадает: о нём уже сообщает
   * `note`, и второй строкой об одном событии лог не улучшить.
   */
  if (!e?.code || !/^[0-9A-Z]{5}$/.test(e.code)) return

  const first = args[0]
  const text =
    typeof first === 'string'
      ? first
      : typeof (first as { text?: string })?.text === 'string'
        ? (first as { text: string }).text
        : '(запрос не в текстовом виде)'

  const params = Array.isArray(args[1])
    ? (args[1] as unknown[]).map(shortParam)
    : Array.isArray((first as { values?: unknown[] })?.values)
      ? ((first as { values: unknown[] }).values ?? []).map(shortParam)
      : []

  console.error(
    `[plemkniga] Отказ базы ${e.code}${e.routine ? ` (${e.routine})` : ''}: ${e.message ?? ''}\n` +
      `  запрос: ${text.slice(0, MAX_QUERY_IN_LOG)}${text.length > MAX_QUERY_IN_LOG ? ' …' : ''}\n` +
      `  параметры: ${JSON.stringify(params)}`,
  )
}

const note = (what: string, err: Error): void => {
  console.error(
    `[plemkniga] ${what}: ${err.message}. ` +
      'Пул откроет новое соединение при следующем запросе; состояние базы — на /healthz',
  )
}

export const guardPool = (client: unknown): void => {
  const pool = (client as { db?: { pool?: PoolLike } })?.db?.pool
  if (typeof pool?.on !== 'function') return

  /*
   * Перехват запросов ставится до слушателей и своей отметкой: ниже
   * стоит ранний выход, и с общим флагом обёртка не появилась бы вовсе
   * на пуле, у которого слушатели уже есть.
   *
   * Обёртка не глотает и не меняет поведения: она пишет строку в лог
   * и отдаёт тот же отказ дальше. Ошибка доходит до страницы ровно такой,
   * какой была.
   */
  const q = pool as PoolLike & QueryLogged
  if (typeof q.query === 'function' && !q[QUERY_LOGGED]) {
    q[QUERY_LOGGED] = true
    const original = q.query.bind(pool)
    q.query = (...args: unknown[]) => {
      /*
       * `pool.query` умеет и обратный вызов вместо обещания. В нашем коде
       * так никто не пишет, но Payload и drizzle — чужой код, и подменять
       * им способ вызова нельзя. Такие вызовы пропускаются мимо перехвата
       * целиком: лучше не залогировать, чем сломать.
       */
      if (typeof args[args.length - 1] === 'function') return original(...args)

      return original(...args).catch((err: unknown) => {
        logQueryFailure(err, args)
        throw err
      })
    }
  }

  const marked = pool as PoolLike & Guarded
  if (marked[GUARDED]) return
  marked[GUARDED] = true

  // Соединение, лежавшее в пуле без дела
  pool.on('error', ((err: Error) => note('Простаивающее соединение с базой оборвалось', err)) as never)

  /*
   * И то, что сейчас на руках у запроса.
   *
   * Событие `error` пул поднимает у себя только для простаивающих
   * соединений. У выданного клиента обрыв приходит на него самого,
   * и если слушателя нет, Node превращает его в `uncaughtException`
   * и убивает процесс. На проде это выглядело так: база на другом хосте
   * перестала отвечать, в логе `⨯ uncaughtException: Error: read ETIMEDOUT`,
   * контейнер умер и поднялся заново — и так по кругу, пока сеть
   * не вернулась.
   *
   * Слушатель ничего не чинит: запрос всё равно завершится отказом,
   * и страница покажет ошибку. Он лишь не даёт обрыву одного соединения
   * решать судьбу всего приложения.
   *
   * **Слушать нужно `acquire`, а не `connect`.** Сначала здесь стояло
   * `connect` — событие открытия нового соединения, и по смыслу это верное
   * место: соединение только что появилось, вешаем на него слушателя.
   * Не покрыт при этом остаётся ровно тот случай, ради которого всё
   * затевалось. `getPayload` открывает соединение сам, при разборе
   * конфигурации, — то есть раньше, чем доходит очередь до `guardPool`.
   * Соединение уже открыто, `connect` по нему больше не наступит никогда,
   * и до конца жизни процесса оно живёт без присмотра. А поскольку пул
   * отдаёт запросам свободное соединение, а не свежее, именно это первое
   * и достаётся почти всем запросам. Защита стояла на всех соединениях,
   * кроме главного.
   *
   * `acquire` наступает при каждой выдаче соединения запросу, включая
   * первую выдачу давно открытого. Оно шире `connect` и покрывает его
   * целиком: пул поднимает `acquire` в том числе сразу после `connect`.
   * Ценой того, что обработчик зовётся на каждый запрос, — поэтому
   * отметка на клиенте здесь не подстраховка, как было при `connect`,
   * а необходимость: без неё слушатель добавлялся бы к соединению
   * при каждой его выдаче, и мы получили бы ту же очередь охранников,
   * от которой ушли выше, только на соединении вместо пула.
   *
   * Нашла это проверка, а не глаз: прежняя утверждала, что слушатель есть,
   * и не утверждала, на чём именно он есть.
   */
  pool.on('acquire', ((c: ClientLike & Guarded) => {
    if (typeof c?.on !== 'function' || c[GUARDED]) return
    c[GUARDED] = true
    c.on('error', (err) => note('Соединение с базой оборвалось во время запроса', err))
  }) as never)
}

export const getClient = async () => {
  const client = await getPayload({ config })
  guardPool(client)
  return client
}

export const AUTH_COOKIE = 'payload-token'

/**
 * Текущий пользователь.
 *
 * Токен читается из cookie напрямую и передаётся в Payload заголовком
 * `Authorization: JWT …`. Через `headers()` это не всегда работает:
 * в server actions заголовки исходного запроса до обработчика не доходят,
 * и пользователь определялся как анонимный.
 */
export const getCurrentUser = async (): Promise<User | null> => {
  try {
    /*
     * `next/headers` подгружается здесь, а не импортом наверху файла,
     * и это не стилистика.
     *
     * Модуль нужен внутри запроса и только там, а сам файл — библиотечный:
     * из него берут `getClient` серверные скрипты, которые ни к какому
     * запросу не относятся. Пока импорт стоял наверху, любой такой скрипт
     * тянул за собой контекст Next целиком — и замер, собранный отдельным
     * файлом для запуска в боевом контейнере, падал на резолве
     * `next/headers` ещё до первой строки работы.
     *
     * Ленивая загрузка стоит одного `await` на запрос и снимает
     * зависимость библиотеки от среды, в которой её позвали.
     */
    const { cookies } = await import('next/headers')
    const jar = await cookies()
    const token = jar.get(AUTH_COOKIE)?.value
    if (!token) return null

    const payload = await getClient()
    const headers = new Headers({
      Authorization: `JWT ${token}`,
      cookie: `${AUTH_COOKIE}=${token}`,
    })

    const { user } = await payload.auth({ headers })
    if (!user) return null

    /*
     * Заблокированный — не пользователь.
     *
     * Единственная точка, где это можно решить раз и навсегда: страницы
     * и серверные действия спрашивают «кто вошёл» только здесь, и ответ
     * «никто» закрывает их все сразу. Проверять блокировку в каждом
     * действии по отдельности значило бы забыть о ней в том, которое
     * напишут завтра.
     *
     * Токен при этом остаётся действительным, и это не оплошность:
     * отозвать выданный JWT нечем, поэтому решение принимается на каждом
     * запросе по состоянию записи, а не по факту выдачи. Правила доступа
     * коллекций проверяют то же самое (`notBlocked` в `src/access`) —
     * они защищают прямые обращения к API, минующие эту функцию.
     */
    if ((user as User).blockedAt) return null

    return user as User
  } catch {
    return null
  }
}
