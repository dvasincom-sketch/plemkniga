import type { Payload } from 'payload'

/**
 * Прямой доступ к PostgreSQL: одно объявление на всё приложение.
 *
 * ## Зачем это вообще есть
 *
 * Отчёты по стаду, качество книги, подбор пар и расчёт индексов считаются
 * запросами, а не перебором записей через Payload: там оконные функции,
 * рекурсивные обходы родословной и агрегаты по сотням тысяч строк.
 * Payload такого не умеет и уметь не должен — у него другая работа.
 *
 * ## Почему тип свой, а не из драйвера
 *
 * `payload.db` типизирован адаптером, и `pool` в этом типе не объявлен:
 * он есть у постгресового адаптера и отсутствует у остальных. Свой узкий
 * тип описывает ровно то, чем мы пользуемся, и заодно честно говорит,
 * что пула может не быть: `poolOf` возвращает `null`, а вызывающий решает,
 * отказать или обойтись.
 *
 * Соблазн написать `payload.db.pool as Pool` был, и он хуже: тип из `pg`
 * обещает сотню методов, которых мы не трогаем, и превращает подмену
 * адаптера в молчаливую поломку вместо ошибки типов.
 *
 * ## Почему это вынесено
 *
 * Двадцать модулей объявляли этот тип и эту функцию у себя — посимвольно
 * одинаково, но с расхождениями в мелочах: где-то в результате запроса
 * объявлен `rowCount`, где-то нет, и добавить его приходилось в том файле,
 * где понадобился. Двадцать копий одного объявления — это двадцать мест,
 * где нужно вспомнить про правку.
 */

/** Ряд результата: имена колонок известны только запросу, который их просил. */
export type SqlRow = Record<string, unknown>

export type SqlResult = { rows?: SqlRow[]; rowCount?: number | null }

export type SqlPool = {
  query: (q: string, p?: unknown[]) => Promise<SqlResult>
  /**
   * Отдельное соединение — нужно там, где важна последовательность
   * (например `set local statement_timeout` перед тяжёлым запросом).
   * У пула он есть не всегда, поэтому необязательный.
   */
  connect?: () => Promise<{
    query: (q: string, p?: unknown[]) => Promise<SqlResult>
    release: () => void
  }>
}

/** Пул, если адаптер его даёт. `null` — не ошибка, а состояние. */
export const poolOf = (payload: Payload): SqlPool | null =>
  (payload.db as unknown as { pool?: SqlPool }).pool ?? null

/**
 * Число из ряда результата.
 *
 * PostgreSQL отдаёт `numeric` и `bigint` строками — драйвер не приводит
 * их к `number` намеренно, чтобы не терять точность на больших значениях.
 * Для наших сумм и счётчиков потеря невозможна, а `Number(...)` в каждой
 * строке разбора — шум.
 */
export const numOf = (v: unknown): number => Number(v ?? 0)

/**
 * То же, но пропуск остаётся пропуском.
 *
 * `numOf` превращает `null` в ноль, и это верно для счётчиков: «ни одной»
 * и есть ноль. Для среднего удоя неверно: ноль там означает «корова
 * не доится», а пусто — «не измеряли». Разные вопросы, разные ответы.
 */
export const numOrNull = (v: unknown): number | null => {
  if (v === null || v === undefined) return null
  const x = Number(v)
  return Number.isFinite(x) ? x : null
}
