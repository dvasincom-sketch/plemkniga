import { BOOK_URL } from '@/lib/hosts'
import { TENANTS } from '@/lib/tenant'
import registry from '@/data/fgias-dairy-breeds.json'
import { buildCatalog, type BreedRow, type RegistryBreed } from '@/lib/breeds-catalog'

/**
 * Каталог пород — из справочников, без похода в базу.
 *
 * ## Почему без базы
 *
 * Первая редакция дополняла выписку реестра тем, что заведено у нас:
 * код ICAR брался из справочника пород в базе, если он там стоял.
 * Выигрыш был в одну породу, а цена оказалась несоразмерной — главная
 * страница витрины начала ходить в базу за справочником и **упала**
 * на боевой книге, где новая колонка ещё не появилась: миграции там
 * применяются отдельно, а настройки Payload уже спрашивали её у базы.
 *
 * Витрина не должна падать из-за справочника. Оба её источника —
 * выписка реестра и копия списка Interbull — лежат в дереве, читаются
 * без сети и без базы, и меняются отдельными командами. Число на витрине
 * и число в каталоге при этом совпадают всегда, потому что считаются
 * из одного и того же файла.
 *
 * Породы, у которых код ICAR известен нам, но отсутствует в мосте,
 * попадают в «в справочнике». Это не потеря: мост правится руками
 * и именно там, где решение о коде принимает человек.
 *
 * ## Почему функция, а не константа
 *
 * Действующие книги берутся из настройки арендаторов, а та читает
 * переменные среды. Константа, вычисленная при сборке, застыла бы
 * с тем адресом, который был на машине сборщика.
 */
export function breedCatalog(): BreedRow[] {
  const books: Record<string, string> = TENANTS.holstein.breed
    ? { [TENANTS.holstein.breed.name]: BOOK_URL }
    : {}

  return buildCatalog(registry.breeds as RegistryBreed[], [], books)
}
