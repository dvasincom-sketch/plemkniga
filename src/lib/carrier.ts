/**
 * Носительство генетического дефекта: три состояния и их подписи.
 *
 * ## Почему отдельным файлом
 *
 * Подписи жили внутри коллекции животных, и потому в племенном
 * свидетельстве печаталось не то. Свидетельство собирается в `lib`,
 * до коллекции ему не дотянуться, и строка маркеров набиралась
 * подстановкой самого значения: в документ, который предъявляют
 * покупателю, уходило `CVM: carrier` — машинное слово вместо ответа.
 *
 * На экране при этом всё было правильно, и в этом вся беда: карточку
 * смотрят каждый день, а свидетельство печатают раз в год и читают
 * глазами человека, который английского слова не знает и решит, что
 * система сломана.
 *
 * ## Почему «не тестировано», а не «свободен»
 *
 * Отсутствие теста — не отрицательный результат. Животное без теста
 * может оказаться носителем, и подпись обязана это различать: покупатель,
 * прочитавший «свободен» там, где никто не проверял, принимает решение
 * на основании нашего умолчания.
 */

export type Carrier = 'unknown' | 'free' | 'carrier'

export const CARRIER_LABEL: Record<Carrier, string> = {
  unknown: 'Не тестировано',
  free: 'Свободен (не носитель)',
  carrier: 'Носитель',
}

export const CARRIER_OPTIONS = (Object.keys(CARRIER_LABEL) as Carrier[]).map((value) => ({
  value,
  label: CARRIER_LABEL[value],
}))

/**
 * Подпись для документа.
 *
 * Незнакомое значение отдаётся как есть, а не подменяется прочерком:
 * в базе может лежать то, чего в перечислении уже нет, и молча стереть
 * это из свидетельства значило бы напечатать документ, отличающийся
 * от записи в книге.
 */
export const carrierLabel = (value: string | null | undefined): string | null => {
  if (!value) return null
  return CARRIER_LABEL[value as Carrier] ?? value
}
