/**
 * Кто есть кто в стаде — предикатами запроса.
 *
 * ## Зачем именованные куски
 *
 * Тот же довод, что у `sql-lactation.ts`, и та же цена ошибки. «Живая
 * корова», «тёлка», «возраст в месяцах», «выбыла за год» стояли копиями
 * в отчётах по стаду и в разборах за числами. Копии совпадали, и это была
 * не заслуга, а везение: в `herd-drilldown.ts` над каждой стоял комментарий
 * «тем же выражением, что в `heiferAges`» — обещание, которое ничто
 * не проверяло.
 *
 * Теперь копий стало на одну больше: те же числа считаются ещё и разом
 * по всем хозяйствам, для кабинета Ассоциации (`herd-condition.ts`).
 * Третья копия правила — это уже не риск, а вопрос времени, а расхождение
 * здесь означает, что Ассоциация звонит хозяйству про передержку, которой
 * то у себя не видит.
 *
 * ## Что сюда попадает, а что нет
 *
 * Только определения — то, о чём можно спорить и что будут уточнять:
 * кого считать живой самкой, кого тёлкой, за какой срок считать выбытие.
 * Расхождение в них означает, что два экрана отвечают на один вопрос
 * по-разному, и стоит это доверия ко всей книге.
 *
 * Голое `archived is not true` осталось литералом, и это решение,
 * а не недоделка. Это не правило, а технический признак, и переписать
 * его иначе нельзя — расходиться нечему. Обернуть все сорок восемь
 * вхождений значило бы перевести десяток файлов с обычных строк
 * на шаблонные ради предиката, текст которого никогда не изменится,
 * — а именно на этом переводе проект уже четырежды ловил обратную
 * кавычку внутри SQL. Цена правки должна быть меньше цены беды,
 * от которой она защищает.
 *
 * Настоящая беда с архивом другая — про него **забывают**, — и общее
 * объявление от этого не спасает: забыть `${notArchived()}` ровно так же
 * легко, как `archived is not true`. Ловить это надо прогоном, а не
 * именем.
 *
 * ## Почему строки, а не построитель запросов
 *
 * Запросы здесь пишутся руками — с боковыми соединениями, `distinct on`
 * и фильтрами агрегатов, — и построитель на них не годится. Общими
 * получается сделать только куски текста, а кусок текста хуже функции:
 * его не проверить типами и в него не подставить значение. Поэтому здесь
 * только предикаты и выражения без параметров, а псевдоним таблицы
 * приходит доводом — иначе кусок молча привяжется к чужому.
 */

/** Не в архиве. Архив — это убранное из работы, а не удалённое. */
export const notArchived = (a = 'a') => `${a}.archived is not true`

/**
 * Живая самка.
 *
 * `state = 'alive'` и `archived is not true` — разные вещи, и нужны обе:
 * первое про животное, второе про запись. Выбывшая корова может годами
 * лежать в работе, а живая — быть убранной в архив по ошибке.
 */
export const liveFemale = (a = 'a') => `(${a}.sex = 'female' and ${a}.state = 'alive')`

/** Возраст в месяцах. */
export const ageMonths = (a = 'a') =>
  `(extract(year from age(now(), ${a}.birth_date)) * 12` +
  ` + extract(month from age(now(), ${a}.birth_date)))`

/** Сколько отёлов записано. */
export const calvingsCount = (a = 'a') =>
  `(select count(*) from calvings k where k.animal_id = ${a}.id)`

/** Дата последнего отёла. */
export const lastCalvingDate = (a = 'a') =>
  `(select max(k."date") from calvings k where k.animal_id = ${a}.id)`

/**
 * Отелилась хотя бы раз.
 *
 * Это одно из трёх определений коровы, которые ходят по книге: есть ещё
 * вид животного (`kind`) и возрастная группа (`age_group`). Здесь названо
 * ровно то, что проверяется, — факт отёла, — и объединять три определения
 * в одно `isCow` намеренно не стали: пока не решено, какое из них главное,
 * общее имя закрепило бы путаницу вместо того, чтобы её убрать.
 */
export const hasCalved = (a = 'a') =>
  `exists (select 1 from calvings k where k.animal_id = ${a}.id)`

/**
 * Тёлка: живая самка с известной датой рождения и без единого отёла.
 *
 * «Без отёла», а не «возрастная группа тёлка», и это решение, а не мелочь:
 * группу заполняет человек и забывает обновить после отёла, а отёл есть
 * событие с датой. Запись, где в группе «Корова», а отёлов нет, — находка,
 * а не сбой, и попадает она в списки именно поэтому.
 */
export const isHeifer = (a = 'a') =>
  `(${notArchived(a)} and ${liveFemale(a)} and ${a}.birth_date is not null` +
  ` and not exists (select 1 from calvings k where k.animal_id = ${a}.id))`

/**
 * Выбыла за последние двенадцать месяцев.
 *
 * Ни архив, ни пол здесь не проверяются, и это не упущение: выбывшую
 * корову обычно и убирают в архив, а отчёт про то, скольких хозяйство
 * потеряло, а не скольких оно показывает.
 */
export const culledYear = (a = 'a') =>
  `(${a}.disposal_date is not null and ${a}.disposal_date > now() - interval '12 months')`
