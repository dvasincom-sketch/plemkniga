/**
 * Кто есть кто в стаде — предикатами запроса.
 *
 * ## Зачем именованные куски
 *
 * Тот же довод, что у `sql-lactation.ts`, и та же цена ошибки. «Живая
 * корова», «тёлка», «возраст в месяцах», «выбыла за год» стояли копиями
 * в отчётах по стаду и в разборах за числами. Копии совпадали, и это была
 * не заслуга, а везение: в `herd-drilldown.ts` над каждой стоял комментарий
 * «тем же выражением, что в `heiferAges`» — обещание, которое ничто
 * не проверяло.
 *
 * Теперь копий стало на одну больше: те же числа считаются ещё и разом
 * по всем хозяйствам, для кабинета Ассоциации (`herd-condition.ts`).
 * Третья копия правила — это уже не риск, а вопрос времени, а расхождение
 * здесь означает, что Ассоциация звонит хозяйству про передержку, которой
 * то у себя не видит.
 *
 * ## Что сюда попадает, а что нет
 *
 * Только определения — то, о чём можно спорить и что будут уточнять:
 * кого считать живой самкой, кого тёлкой, за какой срок считать выбытие.
 * Расхождение в них означает, что два экрана отвечают на один вопрос
 * по-разному, и стоит это доверия ко всей книге.
 *
 * Голое `archived is not true` осталось литералом, и это решение,
 * а не недоделка. Это не правило, а технический признак, и переписать
 * его иначе нельзя — расходиться нечему. Обернуть все сорок восемь
 * вхождений значило бы перевести десяток файлов с обычных строк
 * на шаблонные ради предиката, текст которого никогда не изменится,
 * — а именно на этом переводе проект уже четырежды ловил обратную
 * кавычку внутри SQL. Цена правки должна быть меньше цены беды,
 * от которой она защищает.
 *
 * Настоящая беда с архивом другая — про него **забывают**, — и общее
 * объявление от этого не спасает: забыть `${notArchived()}` ровно так же
 * легко, как `archived is not true`. Ловить это надо прогоном, а не
 * именем.
 *
 * ## Почему строки, а не построитель запросов
 *
 * Запросы здесь пишутся руками — с боковыми соединениями, `distinct on`
 * и фильтрами агрегатов, — и построитель на них не годится. Общими
 * получается сделать только куски текста, а кусок текста хуже функции:
 * его не проверить типами и в него не подставить значение. Поэтому здесь
 * только предикаты и выражения без параметров, а псевдоним таблицы
 * приходит доводом — иначе кусок молча привяжется к чужому.
 */

/** Не в архиве. Архив — это убранное из работы, а не удалённое. */
export const notArchived = (a = 'a') => `${a}.archived is not true`

/**
 * Живая самка.
 *
 * `state = 'alive'` и `archived is not true` — разные вещи, и нужны обе:
 * первое про животное, второе про запись. Выбывшая корова может годами
 * лежать в работе, а живая — быть убранной в архив по ошибке.
 */
export const liveFemale = (a = 'a') => `(${a}.sex = 'female' and ${a}.state = 'alive')`

/** Возраст в месяцах. */
export const ageMonths = (a = 'a') =>
  `(extract(year from age(now(), ${a}.birth_date)) * 12` +
  ` + extract(month from age(now(), ${a}.birth_date)))`

/**
 * Запись в `calvings` — отёл, а не аборт и не запуск.
 *
 * В таблице отёлов лежат три события, различаемые типом; пустой тип —
 * старый отёл, записанный до появления типа (`lib/calving.ts`,
 * `isCalvingEvent`). Всё, что считает отёлы, обязано ставить это условие,
 * и предикаты ниже ставят его сами. Появилось оно здесь поздно: тип
 * события завёлся, проверки, сервис-период и межотельный за ним пошли,
 * а общие предикаты стада — нет. У хозяйства, ведущего аборты записями,
 * тёлка с абортом переставала быть тёлкой во всех списках молодняка,
 * аборт прибавлял лактацию в структуре стада, выбраковке, рейтинге
 * и подборе, а календарь считал «дней после отёла» от запуска.
 * `check:condition` этого не видел: он сверял два расчёта с одной
 * и той же ошибкой.
 */
export const calvingEvent = (k = 'k') =>
  `(${k}.event_type is null or ${k}.event_type = 'calving')`

/** Сколько отёлов записано. */
export const calvingsCount = (a = 'a') =>
  `(select count(*) from calvings k where k.animal_id = ${a}.id and ${calvingEvent()})`

/** Дата последнего отёла. */
export const lastCalvingDate = (a = 'a') =>
  `(select max(k."date") from calvings k where k.animal_id = ${a}.id and ${calvingEvent()})`

/**
 * Отелилась хотя бы раз.
 *
 * Это одно из двух определений коровы, которые ходят по книге: есть ещё
 * возрастная группа (`age_group`); третье — вид животного `kind` —
 * убрано миграцией групп. Здесь названо ровно то, что проверяется, —
 * факт отёла, — и объединять определения в одно `isCow` намеренно
 * не стали: пока не решено, какое из них главное, общее имя закрепило бы
 * путаницу вместо того, чтобы её убрать.
 */
export const hasCalved = (a = 'a') =>
  `exists (select 1 from calvings k where k.animal_id = ${a}.id and ${calvingEvent()})`

/**
 * Тёлка: живая самка с известной датой рождения и без единого отёла.
 *
 * «Без отёла», а не «возрастная группа тёлка», и это решение, а не мелочь:
 * группу заполняет человек и забывает обновить после отёла, а отёл есть
 * событие с датой. Запись, где в группе «Корова», а отёлов нет, — находка,
 * а не сбой, и попадает она в списки именно поэтому.
 *
 * ## Почему факт отёла — довод, а не часть выражения
 *
 * По умолчанию он устанавливается подзапросом: у одного животного это
 * один поиск по индексу, дёшево и читается прямо. Но сводка по всем
 * хозяйствам разом проходит по трёмстам тысячам записей, и триста тысяч
 * подзапросов — уже не мелочь. Там отёлы сосчитаны один раз соединением,
 * и факт устанавливается им.
 *
 * Правило при этом остаётся одним: меняется не «кого считать тёлкой»,
 * а способ узнать, телилась ли она. Совпадение двух способов проверяет
 * `npm run check:condition` на живых данных — тем же прогоном, что сверяет
 * сводку Ассоциации с кабинетом хозяйства.
 */
export const isHeifer = (
  a = 'a',
  calved = hasCalved(a),
) =>
  /*
   * Скобки вокруг довода обязательны. Без них `not k.animal_id is not
   * null` разбирается верно, но читается как ошибка, а следующая
   * подстановка со словом `or` внутри сломалась бы молча.
   */
  `(${notArchived(a)} and ${liveFemale(a)} and ${a}.birth_date is not null` +
  ` and not (${calved}))`

/**
 * Выбыла за последние двенадцать месяцев.
 *
 * Ни архив, ни пол здесь не проверяются, и это не упущение: выбывшую
 * корову обычно и убирают в архив, а отчёт про то, скольких хозяйство
 * потеряло, а не скольких оно показывает.
 */
export const culledYear = (a = 'a') =>
  `(${a}.disposal_date is not null and ${a}.disposal_date > now() - interval '12 months')`

/* ------------------------------------------------------------------ *
 *  Стельность                                                        *
 * ------------------------------------------------------------------ */

/**
 * Последнее осеменение после последнего отёла — вместе с результатом.
 *
 * Боковым запросом, а не подзапросом на каждое поле: спрашивают о нём
 * сразу три вещи — когда, чем кончилось и проверяли ли стельность, —
 * и три подзапроса по одной таблице означали бы три прохода и три случая
 * забыть условие.
 */
export const lastInsemination = (a = 'a', lastCalving = lastCalvingDate(a)) => `(
    select i."date"                                as at,
           r.code                                  as result_code,
           i.pregnancy_check_date is not null      as checked
      from inseminations i
      left join insemination_results r on r.id = i.result_id
     where i.animal_id = ${a}.id
       and (${lastCalving} is null or i."date" > ${lastCalving})
     order by i."date" desc
     limit 1
  )`

/**
 * Стельная сейчас: **последнее** осеменение после отёла оказалось
 * плодотворным.
 *
 * Слово «последнее» здесь и есть всё правило. Определений было три,
 * и они расходились ровно на той корове, ради которой их и смотрят:
 * календарь брал последнее осеменение, а список выбраковки и подбор пар —
 * «есть хоть одно плодотворное после отёла». Корова, у которой стельность
 * подтвердили, а потом осеменили снова (перегуляла, потеряла), для одного
 * экрана оставалась стельной, для другого нет: подбор исключал её как
 * стельную, а календарь тем же утром звал переосеменять.
 *
 * Осеменение без результата стельной не делает: пустой результат — это
 * «не знаем», а не «нет». Такую корову зовёт к себе список проверки
 * стельности, и это верно.
 *
 * ## Почему `coalesce`, а не голое сравнение
 *
 * Без него предикат отвечает NULL там, где осеменений нет вовсе или
 * результат не проставлен, и `not (…)` тоже даёт NULL — то есть строка
 * не проходит `where` ни при каком раскладе. В подборе пар это выкосило
 * из плана всех коров без осеменений, а `check:mating` показал минус
 * единицу вместо коэффициента: пар в ответе не оказалось совсем.
 * Трёхзначная логика ошибается молча и в обе стороны, поэтому ответ
 * здесь двузначный: «не знаем» — это «не стельная».
 */
export const isPregnant = (a = 'a', lastCalving = lastCalvingDate(a)) =>
  `coalesce((select r.code
       from inseminations i
       left join insemination_results r on r.id = i.result_id
      where i.animal_id = ${a}.id
        and (${lastCalving} is null or i."date" > ${lastCalving})
      order by i."date" desc
      limit 1) = '1', false)`
