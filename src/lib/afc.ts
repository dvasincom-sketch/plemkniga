/**
 * Возраст первого отёла (AFC) и возраст животного на момент события.
 *
 * ## Почему это отдельный модуль, а не пара строк по месту
 *
 * Возраст первого отёла считается по двум полям, которые хозяйство и так
 * заполняет: дата рождения животного и дата отёла с номером 1. Ни одного
 * нового поля вводить не нужно — и именно поэтому величина до сих пор
 * нигде не показывалась: она есть в данных, но её никто не доставал.
 *
 * Доставать стоит. AFC — не зоотехническая мелочь, а признак с наследуемой
 * составляющей: у CDCB под него есть отдельная племенная оценка EFC
 * (Early First Calving). То есть вопрос «в каком возрасте телятся дочери
 * этого быка» — вопрос племенной книги, а не системы управления стадом.
 *
 * Связи с продуктивностью и выбытием разобраны у Истхэма и соавторов
 * (PLOS ONE, 2018, doi:10.1371/journal.pone.0197764; 396 534 первотёлки,
 * 6 985 хозяйств Великобритании). Кратко: чем позже первый отёл, тем выше
 * надой за первую лактацию — и тем ниже пожизненный суточный удой, выше
 * соматика, длиннее межотельный период и меньше шансов дожить до второй
 * лактации. Справочные кривые сюда не зашиты намеренно: выборка британская
 * и отёлы 2006–2008 годов, переносить её на российское стадо как истину
 * нельзя (решение №49). Кривые появятся отдельной версионированной базой,
 * посчитанной по исходному набору, а не переписанной из статьи.
 *
 * ## Чего этот модуль не делает
 *
 * Не советует. «Отелить в 24 месяца» — управленческое решение хозяйства,
 * принимаемое с учётом кормов, помещений и цены нетели, и книга его
 * за хозяйство не принимает. Модуль отвечает на вопрос «сколько было»,
 * а не «сколько надо».
 */

/** Дата в любом виде, в каком её отдаёт Payload. */
type DateLike = string | Date | null | undefined

const asDate = (v: DateLike): Date | null => {
  if (!v) return null
  const d = v instanceof Date ? v : new Date(v)
  return Number.isNaN(d.getTime()) ? null : d
}

/**
 * Полных месяцев между датами.
 *
 * Считается по календарю, а не делением миллисекунд на 30,44 дня.
 * Разница не косметическая: зоотехник называет возраст в месяцах так же,
 * как возраст ребёнка, — «27 месяцев» значит «двадцать седьмой месяц
 * прошёл целиком». Деление на среднюю длину месяца даёт 26 или 28
 * в зависимости от того, на какие месяцы пришёлся отрезок, и объяснить
 * это человеку, который вычитает даты в уме, невозможно.
 */
export function monthsBetween(from: DateLike, to: DateLike): number | null {
  const a = asDate(from)
  const b = asDate(to)
  if (!a || !b) return null

  let months = (b.getFullYear() - a.getFullYear()) * 12 + (b.getMonth() - a.getMonth())

  // Месяц ещё не дожит: 15 марта → 10 апреля — это ноль полных месяцев
  if (b.getDate() < a.getDate()) months -= 1

  return months
}

/**
 * Рамки правдоподобия для возраста первого отёла.
 *
 * Это не нормативы и не цели. Нижняя граница — биология: стельность
 * у крупного рогатого скота длится около 279 дней, то есть первый отёл
 * раньше девятнадцатого месяца жизни означал бы оплодотворение до полового
 * созревания. Такого не бывает, и запись с таким AFC — ошибка в дате,
 * а не рекорд.
 *
 * Верхняя граница мягче и означает другое. Отёл в четыре года сам по себе
 * возможен, просто дорог. Но чаще число за 48 говорит не о позднем отёле,
 * а о неполных данных: хозяйство завело карточку с середины жизни коровы,
 * и отёл, записанный первым, на деле третий. Поэтому находка помечается
 * как «на усмотрение», а текст замечания называет обе причины — эксперт
 * должен знать, куда смотреть.
 *
 * Для сравнения: у Истхэма средний AFC по Великобритании 29,1 месяца,
 * медиана 28, разбор ограничен диапазоном 21–42 месяца. Этот диапазон —
 * условие отбора в исследование, а не граница возможного, и брать его
 * рамкой правдоподобия было бы подменой.
 */
export const AFC_PLAUSIBLE = {
  /** Ниже — физически невозможно. */
  min: 19,
  /** Выше — почти наверняка неполные данные, а не поздний отёл. */
  max: 48,
} as const

/** Ориентиры для подписи, откуда они взяты — в `docs/vneshnie-dannye.md`. */
export const AFC_REFERENCE = {
  ukMean: 29.1,
  ukMedian: 28,
  source: 'Eastham et al., PLOS ONE 2018, doi:10.1371/journal.pone.0197764',
} as const

export type AfcVerdict = 'ok' | 'tooYoung' | 'tooOld'

/**
 * Границы можно передать снаружи — их настраивает Ассоциация.
 *
 * Умолчание оставлено намеренно: функцию зовут и там, где настроек нет
 * под рукой (карточка животного, лента событий), и заставлять каждое такое
 * место ходить в базу за двумя числами значило бы сделать подпись
 * в интерфейсе дороже самого расчёта. Расхождение возможно только пока
 * порог отличается от заложенного, и видно оно в каталоге проверок,
 * где значения показываются действующие.
 */
export const afcVerdict = (
  months: number,
  bounds: { min: number; max: number } = AFC_PLAUSIBLE,
): AfcVerdict => {
  if (months < bounds.min) return 'tooYoung'
  if (months > bounds.max) return 'tooOld'
  return 'ok'
}

/**
 * Возраст первого отёла в месяцах.
 *
 * Второй аргумент — дата отёла, который в базе числится первым. Слово
 * «числится» здесь существенно: номер отёла проставляет хозяйство, и если
 * учёт начали вести с середины жизни коровы, единица будет стоять
 * не на первом отёле. Отличить эти два случая по одной записи нельзя,
 * поэтому модуль честно считает то, что записано, а сомнительный результат
 * ловится рамкой правдоподобия выше.
 */
export const afcMonths = (birthDate: DateLike, firstCalvingDate: DateLike): number | null =>
  monthsBetween(birthDate, firstCalvingDate)

/** Склонение месяцев: 1 месяц, 2 месяца, 5 месяцев. */
const monthWord = (n: number): string => {
  const n10 = n % 10
  const n100 = n % 100
  if (n10 === 1 && n100 !== 11) return 'месяц'
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return 'месяца'
  return 'месяцев'
}

/** «27 месяцев» — полная подпись, для мест, где число одно и места хватает. */
export const monthsLabel = (months: number): string => `${months} ${monthWord(months)}`

/**
 * Возраст короткой строкой для ленты событий: «27 мес.» либо «4 г. 3 мес.».
 *
 * Порог в три года выбран не ради круглого числа. До него возраст читают
 * в месяцах, потому что в этом промежутке умещается всё, что решает судьбу
 * животного: осеменение тёлки, первый отёл, первая лактация. После —
 * месяцы становятся шумом, и «4 г. 3 мес.» читается быстрее, чем «51 мес.».
 */
export function ageLabel(months: number | null): string | null {
  if (months === null || months < 0) return null
  if (months < 36) return `${months} мес.`
  const years = Math.floor(months / 12)
  const rest = months % 12
  return rest ? `${years} г. ${rest} мес.` : `${years} г.`
}

/** Возраст животного на момент события, в месяцах. */
export const ageAtMonths = (birthDate: DateLike, at: DateLike): number | null =>
  monthsBetween(birthDate, at)
