import type { Payload, PayloadRequest } from 'payload'

/**
 * Следствия записи, наступающие после коммита, а не внутри него.
 *
 * ## Из-за чего появилось
 *
 * У трёх хуков стоял комментарий примерно одного содержания: «отказ
 * не роняет сохранение — сама запись уже сделана, а следствие важнее
 * не бывает». Написано это было про журнал правок животного, про
 * согласование видимости фотографии, про пересчёт индекса, про подъём
 * возрастной группы после отёла и про перенос класса из бонитировки
 * в карточку. Все они обёрнуты в `try/catch` и все зовут Payload
 * с `req`.
 *
 * Обещание было неправдой. `req` означает «в той же транзакции», а хуки
 * `afterChange` выполняются до коммита. В PostgreSQL первый же упавший
 * запрос переводит транзакцию в состояние `aborted`: дальше в ней нельзя
 * ничего, кроме отката, и `catch` тут не помогает — он перехватит ошибку,
 * хук вернёт документ, а `commit` откатит всё, включая саму запись.
 * В журнал при этом ляжет «не удалось записать правки животного» — то
 * есть сообщение, которое прямо говорит, что правка сохранена, а следа
 * нет. Человек прочитает его и не пойдёт искать пропавшую правку.
 *
 * Особенно скверно то, что неправда эта перемежающаяся. Отказ валидации
 * Payload происходит до всякого SQL и транзакцию не портит — тогда
 * комментарий верен. Отказ базы (нет колонки, нарушено ограничение,
 * оборвалось соединение) её портит — тогда комментарий лжёт. В разработке
 * чаще первое, на проде чаще второе.
 *
 * ## Почему не «убрать req»
 *
 * Соблазнительно и неверно. Отдельное подключение внутри открытой
 * транзакции даёт не ошибку, а зависание: вставка отёла держит на строке
 * животного блокировку по внешнему ключу, а правка карточки со стороны
 * ждёт её снятия — которое случится только после хука. Это решение №20,
 * и оно уже стоило пятнадцати минут висящего сида.
 *
 * ## Почему не «оставить как есть и переписать комментарии»
 *
 * Это был второй рассматривавшийся вариант, и он честнее нынешнего
 * состояния, но хуже по существу. Он оставляет систему, в которой
 * неудавшаяся запись в журнал отменяет принятую правку карточки —
 * то есть производная роняет первичное. Ради одного абзаца текста
 * мы согласились бы с устройством, которое сами же называем неверным.
 *
 * ## Как устроено
 *
 * Следствие не выполняется в хуке, а откладывается до коммита той
 * транзакции, внутри которой хук работает. Очередь заведена на
 * идентификатор транзакции; опустошает её обёртка над
 * `payload.db.commitTransaction`, поставленная при старте
 * (`installAfterCommit`, зовётся из `onInit` в `payload.config.ts`).
 * Откат (`rollbackTransaction`) очередь выбрасывает: следствия у отменённой
 * записи нет.
 *
 * К моменту опустошения транзакция уже закрыта, блокировки сняты,
 * и отдельное подключение перестаёт быть ловушкой — то самое препятствие,
 * ради которого стоял `req`, исчезает вместе с транзакцией. Поэтому
 * отложенная работа зовёт Payload без `req`, и её отказ не может тронуть
 * уже сохранённое. Ровно то, что обещали комментарии.
 *
 * ## Чего это не делает
 *
 * Не превращает следствие в фоновую задачу. Очередь опустошается внутри
 * `commitTransaction`, то есть до того, как `payload.update` вернёт ответ
 * вызывающему: страница, перерисованная после сохранения, увидит
 * последствия, а не застанет их на полпути. Отложено здесь не время,
 * а транзакция.
 *
 * Не даёт гарантии выполнения. Если процесс умрёт между коммитом
 * и следствием, следствие не наступит — и это осознанный размен: ровно
 * так же ведёт себя нынешний `catch`, а очередь с гарантией доставки
 * означала бы таблицу заданий и работника, то есть отдельную подсистему
 * ради журнала правок.
 */

type Job = { what: string; run: (payload: Payload) => Promise<void> }

/**
 * Очереди по идентификатору транзакции — в `globalThis`.
 *
 * Модуль загружается не один раз: сборка Next разводит серверные куски
 * по разным связкам, а настройка Payload зовёт его отдельным динамическим
 * импортом. У двух копий было бы две разные `Map`: хук положил бы работу
 * в свою, обёртка опустошала бы чужую, и следствие не наступило бы никогда
 * — молча, потому что и хук, и обёртка отчитались бы об успехе.
 *
 * Это уже случалось с набором `DENIED_TEXTS` (`src/access/denied.ts`)
 * и стоило трёх ложных строк в прогоне прав. `globalThis` — единственное,
 * что у копий общее; по той же причине в нём живут пул соединений
 * и клиент Payload.
 */
const store = globalThis as typeof globalThis & { __plemAfterCommit?: Map<string, Job[]> }
const queues: Map<string, Job[]> = (store.__plemAfterCommit ??= new Map<string, Job[]>())

const runSafely = async (payload: Payload, job: Job): Promise<void> => {
  try {
    await job.run(payload)
  } catch (e) {
    payload.logger.error(
      `Следствие «${job.what}» не выполнилось после коммита: ${
        e instanceof Error ? e.message : String(e)
      }. Сама запись сохранена.`,
    )
  }
}

/**
 * Отложить работу до коммита транзакции запроса.
 *
 * Если транзакции нет (серверный скрипт, вызов без `req`), работа
 * выполняется сразу: откладывать не до чего, а незаметно её потерять
 * было бы хуже всего.
 *
 * Обработчику передаётся `payload`, а не `req`, и это не мелочь:
 * к моменту вызова транзакция запроса закрыта, и `req` означал бы
 * ссылку на то, чего уже нет.
 */
export async function afterCommit(
  req: PayloadRequest | undefined,
  what: string,
  run: (payload: Payload) => Promise<void>,
): Promise<void> {
  const raw = req?.transactionID
  const id = raw instanceof Promise ? await raw : raw

  if (id === undefined || id === null) {
    if (req?.payload) await runSafely(req.payload, { what, run })
    return
  }

  /*
   * Обёртка над коммитом должна стоять, иначе очередь никто не опустошит
   * и следствие пропадёт бесследно. Признак спрашивается у живого объекта
   * адаптера, а не у переменной модуля: копий модуля бывает несколько,
   * а адаптер в процессе один.
   *
   * Отказ здесь — единственный честный ответ, и выбран он не сгоряча.
   * Тихо потерять работу нельзя: это ровно та беда, ради которой всё
   * и затевалось. Выполнить её на месте тоже нельзя: транзакция открыта,
   * работа зовёт Payload без `req`, и отдельное подключение встанет
   * на блокировке строки животного — не ошибка, а зависание до таймаута
   * (решение №20). Между понятным отказом и повисшим запросом выбран
   * отказ.
   *
   * Случиться это может только от неверной сборки: `onInit` выполняется
   * при любом создании клиента. Поэтому цена ложного срабатывания нулевая,
   * а цена молчания — все следствия записи разом.
   */
  const installed = (req?.payload?.db as { __plemAfterCommit?: boolean } | undefined)
    ?.__plemAfterCommit
  if (!installed) {
    throw new Error(
      `Следствие «${what}» некуда отложить: обёртка afterCommit не установлена. ` +
        'Проверьте onInit в src/payload.config.ts.',
    )
  }

  const key = String(id)
  const list = queues.get(key)
  if (list) list.push({ what, run })
  else queues.set(key, [{ what, run }])
}

/** Сколько следствий ждёт этой транзакции. Нужно прогонам. */
export const pendingAfterCommit = (id: unknown): number =>
  queues.get(String(id))?.length ?? 0

/**
 * Обёртки над коммитом и откатом.
 *
 * Ставятся на живой объект адаптера, а не на его класс: адаптеров
 * в процессе один, а подмена класса задела бы и то, что мы не писали.
 * Повторная установка не страшна — признак `__plemAfterCommit` её
 * останавливает; при горячей перезагрузке `next dev` модуль перечитывается,
 * а объект `payload.db` остаётся прежним, и без признака обёртки легли бы
 * одна на другую.
 */
export function installAfterCommit(payload: Payload): void {
  const db = payload.db as unknown as {
    /* Признак стоит на объекте адаптера, а не в переменной модуля: его
     * спрашивает `afterCommit`, а копий модуля в сборке бывает несколько. */
    __plemAfterCommit?: boolean
    commitTransaction: (id?: unknown) => Promise<void>
    rollbackTransaction: (id?: unknown) => Promise<void>
  }
  if (db.__plemAfterCommit) return
  db.__plemAfterCommit = true

  const commit = db.commitTransaction.bind(db)
  const rollback = db.rollbackTransaction.bind(db)

  db.commitTransaction = async (id?: unknown) => {
    await commit(id)
    const key = String(id ?? '')
    const jobs = queues.get(key)
    if (!jobs) return
    queues.delete(key)
    for (const job of jobs) await runSafely(payload, job)
  }

  db.rollbackTransaction = async (id?: unknown) => {
    /*
     * Очередь выбрасывается до отката, а не после: откат может и сам
     * не удаться, а следствия отменённой записи не должны наступить
     * ни при каком исходе.
     */
    queues.delete(String(id ?? ''))
    await rollback(id)
  }
}
