/**
 * Отёл ли это.
 *
 * ## Зачем отдельная функция на одно сравнение
 *
 * Затем, что забыть это сравнение легко, а последствия тихие. В таблице
 * `calvings` теперь лежат три разных события, и всё, что считает отёлы —
 * возрастная группа, возраст первого отёла, межотельный период, порядок
 * номеров, — обязано считать только их. Аборт, посчитанный отёлом, даёт
 * ложное «слишком короткий межотельный период», а запуск, ставший
 * первым отёлом, портит возраст первого отёла.
 *
 * Ровно это и случилось: тип события завёлся, а проверки за ним
 * не пошли и неделю считали отёлом всё подряд.
 *
 * ## Пустое читается как отёл
 *
 * До появления типа других записей в книге не было, а миграция
 * проставила «Аборт» ровно тем, у кого он стоял в результате. Пустой
 * тип — это старый отёл, а не неизвестность.
 */
export const isCalvingEvent = (eventType?: string | null): boolean =>
  !eventType || eventType === 'calving'

export const calvingEventLabel = (value?: string | null): string =>
  CALVING_EVENTS.find((e) => e.value === value)?.label ?? '—'

