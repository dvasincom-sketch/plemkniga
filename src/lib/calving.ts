/**
 * Отёл, аборт и запуск — три события, которые книга звала одним словом.
 *
 * ## Что здесь исправляется
 *
 * Поле «Результат» отвечало сразу на три вопроса: что за событие
 * (отёл или аборт), сколько родилось (один или двойня) и какого пола
 * (тёлка или бычок). Пять значений — «Тёлка», «Бычок», «Двойня»,
 * «Мертворождение», «Аборт» — лежали в одном списке, хотя это ответы
 * на разные вопросы, и складывать их в одну колонку значит не уметь
 * ответить ни на один: у двойни пол не записан вовсе, а у аборта
 * «результат» — это не про приплод.
 *
 * Реестр спрашивает по-человечески: тип события отдельно, тип рождения
 * отдельно, числа живых тёлочек, бычков и мертворождённых — тремя
 * колонками. Здесь то же разделение.
 *
 * ## Почему списки лежат отдельно от коллекции
 *
 * Их читает не только форма Payload, но и разбор загружаемого файла,
 * и форма ручного ввода в кабинете, которая собирается для браузера.
 * Пока они жили в `collections/Calvings.ts`, клиентская форма тащила
 * бы за собой правила доступа и хуки — то есть серверный код, — и
 * поэтому держала у себя переписанную от руки копию. Копия и оригинал
 * разошлись бы молча в первый же день.
 */

