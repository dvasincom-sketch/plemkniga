/**
 * Откуда берётся каждое посчитанное книгой число.
 *
 * ## Зачем реестр
 *
 * В карточке рядом стоят числа двух пород: привезённые и посчитанные.
 * Привезённое можно только показать — за него отвечает тот, кто прислал.
 * Посчитанное книга обязана уметь объяснить, потому что за него отвечает
 * она сама, а человек по нему принимает решение о спаривании, покупке
 * или выбраковке.
 *
 * До сих пор разница между ними была видна только автору кода. Теперь
 * посчитанное подчёркнуто пунктиром, и под подчёркиванием — формула
 * с расшифровкой обозначений. Это не справка «для любознательных»:
 * зоотехник, который не может проверить, откуда взялся индекс, обязан
 * ему не верить, и правильно делает.
 *
 * ## Почему формулы здесь, а не рядом с расчётом
 *
 * Соблазн был писать пояснение прямо в компоненте показа. Тогда одна
 * и та же величина объяснялась бы по-разному в трёх местах — и разошлась
 * бы при первой правке. Здесь она одна, и всякий показ ссылается на неё
 * ключом.
 *
 * Обратный соблазн — генерировать текст из кода расчёта — не работает:
 * код отвечает на вопрос «как посчитать», а человеку нужен ответ
 * на вопрос «почему так считается», и второго в коде нет.
 *
 * ## Правило пополнения
 *
 * Появилось на экране число, которого не было, — сюда добавляется запись.
 * Показывать посчитанное без объяснения нельзя: непрозрачное число хуже
 * отсутствующего, потому что выглядит достоверным.
 */

