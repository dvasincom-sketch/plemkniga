import type { Payload } from 'payload'
import { poolOf } from '@/lib/sql'

/**
 * Хозяйство с наибольшим стадом.
 *
 * ## Зачем это вообще нужно
 *
 * Проверкам и замерам нужно стадо, на котором есть что считать. Взять
 * первое попавшееся — значит однажды попасть на хозяйство с одной
 * коровой: все отчёты честно вернут пустоту, проверка станет зелёной,
 * ничего не проверив, а замер покажет не скорость запроса, а скорость
 * ответа «ничего нет». Зелёный цвет тогда означает не «сошлось»,
 * а «не смотрели».
 *
 * Именно так и было в трёх местах сразу: подпись обещала наибольшее
 * стадо, а код брал владельца самого свежего животного
 * (`sort: -createdAt, limit: 1`). Подпись и код разошлись молча,
 * и разошлись одинаково — потому что копировались.
 *
 * ## Почему отдельным модулем
 *
 * Пользуются им проба сходимости, прогон отчётов и замер. Замер
 * собирается отдельным бандлом, и если бы функция жила в `probes.ts`,
 * в этот бандл приехала бы вся обвязка проверок вместе с осмотром базы.
 * Один модуль на одну задачу дешевле любой экономии на файлах.
 *
 * ## Почему запросом, а не перебором
 *
 * Через Payload пришлось бы поднять сотни тысяч документов ради одного
 * `max(count)`. Группировка на стороне базы отвечает за миллисекунды.
 */
export async function biggestHerd(payload: Payload): Promise<number | null> {
  const pool = poolOf(payload)
  if (!pool) return null

  const { rows } = await pool.query(
    `select owner_id
       from animals
      where owner_id is not null and archived is not true
      group by owner_id
      order by count(*) desc
      limit 1`,
  )

  const id = (rows ?? [])[0]?.owner_id
  return typeof id === 'number' ? id : id != null ? Number(id) : null
}
