import { INBREEDING_LABEL, SCC_LABEL } from '@/lib/herd-analytics'
import type { Culling, GeneticTrend, HeiferAges, UdderHealth } from '@/lib/herd-analytics'
import { plural } from '@/lib/format'

/**
 * Сигналы по стаду: числа, которые требуют решения сегодня.
 *
 * ## Зачем отдельная сущность
 *
 * Отчёты переехали с «Обзора» в «Отчёты» — там их и ищут. Но у отчётов
 * было одно свойство, которое терять нельзя: их видели каждый день, потому
 * что «Обзор» открывают каждый день. Раздел, куда надо зайти, читают раз
 * в квартал, а передержанная тёлка стоит денег ежедневно.
 *
 * Поэтому на «Обзоре» осталось не всё, а только тревожное. Полоса
 * не показывает состояние стада — для этого есть «Стадо в числах» рядом
 * — она показывает то, с чем нужно что-то делать.
 *
 * ## Почему сигнал появляется только при беде
 *
 * «Передержки нет — 0» занимает столько же места, сколько «передержка —
 * четыре», и приучает пробегать полосу глазами не читая. Полоса, в которой
 * каждая строка означает работу, читается вся; полоса, в которой половина
 * строк означает «всё хорошо», не читается вовсе. Когда сигналов нет,
 * нет и полосы — молчание здесь и есть сообщение «беды нет».
 *
 * ## Почему числа не считаются заново
 *
 * Берутся из тех же семи отчётов, что и на странице «Отчёты». Посчитать
 * их своим запросом было бы быстрее на «Обзоре», но однажды два запроса
 * разошлись бы — и «Обзор» тревожил бы о том, чего в отчёте нет. Ровно
 * так уже расходились числа стада.
 *
 * ## Почему рядом с числом стоит база
 *
 * «4033 коровы выше порога соматики» — само по себе не сообщение.
 * Четыре тысячи из сорока это работа на неделю; четыре тысячи
 * из четырёх тысяч восьмисот — совсем другой разговор. Доля меняет
 * не масштаб беды, а её природу, и без базы число вводит в заблуждение
 * ровно того, кто на него смотрит первым.
 *
 * ## Почему при большой доле меняется совет
 *
 * «Разберите 4033 коровы» — указание, которое никто не выполнит,
 * и потому оно хуже молчания: полоса приучает к тому, что её советы
 * невыполнимы. Когда за порогом больше половины стада, дело почти
 * никогда не в животных: не приехала часть замеров, замеры пришли
 * из лаборатории с другой методикой, порог настроен не под это
 * хозяйство. Про это и надо говорить — проверить причину, а не лечить
 * следствие.
 *
 * Порог в половину взят не из статистики, а из смысла: пока беда
 * у меньшинства, это выборка, с которой работают поголовно; когда
 * у большинства — это уже свойство всего стада или всех данных.
 */

/** Доля, начиная с которой сигнал говорит не о животных, а о данных. */
const MASS_SHARE = 0.5

export type Signal = {
  key: string
  /** Число — оно и есть повод. */
  count: number
  label: string
  /**
   * Из скольких. `null` — база неизвестна, и тогда её не показывают:
   * выдуманный знаменатель хуже отсутствующего.
   */
  of: number | null
  /** Чем является база, если это не «столько же, сколько в числе». */
  ofLabel?: string
  /** Доля от базы, 0…1. */
  share: number | null
  /** Чем это грозит, одной строкой. */
  hint: string
  href: string
  /** Красным — то, что уже стоит денег; обычным — то, что просит внимания. */
  urgent: boolean
  /**
   * Беда охватила большинство — совет сменился с разбора животных
   * на проверку данных. Полоса рисует такие иначе: это не список задач,
   * а повод остановиться.
   */
  mass: boolean
}

/**
 * Подпись базы: из чего именно эти столько-то.
 *
 * Обычно база — само стадо, и слово в подписи повторяет слово в числе:
 * «6 тёлок в передержке из 22». У соматики иначе: знаменатель — коровы
 * **с замером**, а не все коровы. Разница видна сразу («из 25» при 28
 * в стаде) и без объяснения читается как ошибка счёта. Объяснение стоит
 * одного слова.
 */

/**
 * Собрать сигнал, посчитав долю и подменив совет при большой доле.
 *
 * Подмена живёт здесь, а не в вёрстке: это решение о смысле, а не о виде.
 * Вынеси его на страницу — и второй показ сигналов (письмо, выгрузка,
 * кабинет Ассоциации) отправит человека разбирать четыре тысячи коров.
 */
const signal = (
  s: Omit<Signal, 'share' | 'mass'> & { massHint?: string },
): Signal => {
  const share = s.of && s.of > 0 ? s.count / s.of : null
  const mass = share !== null && share >= MASS_SHARE
  return {
    key: s.key,
    count: s.count,
    label: s.label,
    of: s.of,
    ofLabel: s.ofLabel,
    share,
    hint: mass && s.massHint ? s.massHint : s.hint,
    href: s.href,
    urgent: s.urgent,
    mass,
  }
}

/**
 * Что нужно сигналам от отчётов — и ничего сверх.
 *
 * Просились сами `HeiferAges`, `GeneticTrend`, `UdderHealth` и `Culling`:
 * так оно и было, пока считал их один вызов на одно хозяйство. Но те же
 * числа теперь считаются ещё и разом по всем хозяйствам, для кабинета
 * Ассоциации, и там нет ни ряда по годам рождения, ни разбивки выбытия
 * по причинам — они не нужны ни одному сигналу, а стоят полного прохода
 * по книге.
 *
 * Требовать их значило бы заставить групповой запрос считать лишнее
 * или, что хуже, подставить пустой ряд — то есть соврать типом ради того,
 * чтобы он сошёлся. Поэтому здесь перечислено ровно то, что читается
 * ниже; полные отчёты подходят под это как есть.
 */
export type SignalInput = {
  heifers: Pick<HeiferAges, 'overdue' | 'ready' | 'total'> | null
  trend: Pick<GeneticTrend, 'aboveThreshold' | 'withInbreeding'> | null
  udder: Pick<UdderHealth, 'above' | 'measured'> | null
  cull: Pick<Culling, 'firstLactation' | 'total'> | null
}

export function herdSignals({ heifers, trend, udder, cull }: SignalInput): Signal[] {
  const out: Signal[] = []

  /*
   * Передержка — единственный сигнал, который прямо каждый день стоит
   * корма. Остальные говорят о том, что уже случилось или случится
   * через поколение.
   */
  if (heifers && heifers.overdue > 0) {
    out.push(
      signal({
        key: 'heifers-overdue',
        count: heifers.overdue,
        of: heifers.total,
        label: `${plural(heifers.overdue, 'тёлка', 'тёлки', 'тёлок')} в передержке`,
        hint: 'старше 15 месяцев без отёла — корм без отдачи',
        massHint:
          'передержан почти весь молодняк — похоже, отёлы вносят не все ' +
          'или даты рождения приехали неверными',
        href: '/account/reports/heifers-overdue',
        urgent: true,
      }),
    )
  }

  if (udder && udder.above > 0) {
    out.push(
      signal({
        key: 'scc-above',
        count: udder.above,
        of: udder.measured,
        label: `${plural(udder.above, 'корова', 'коровы', 'коров')} выше ${SCC_LABEL} соматики`,
        ofLabel: 'коров с замером',
        hint: 'скрытый мастит: удой, сортность и выбраковка сразу',
        massHint:
          'выше порога больше половины стада — сперва проверьте, все ли ' +
          'замеры приехали и той ли лабораторией сделаны',
        href: '/account/reports/scc-above',
        urgent: true,
      }),
    )
  }

  if (trend && trend.aboveThreshold > 0) {
    out.push(
      signal({
        key: 'inbreeding-above',
        count: trend.aboveThreshold,
        of: trend.withInbreeding,
        label:
          `${plural(trend.aboveThreshold, 'животное', 'животных', 'животных')} ` +
          `с инбридингом выше ${INBREEDING_LABEL}`,
        ofLabel: 'с посчитанным коэффициентом',
        hint: 'решается подбором быка, а не лечением',
        massHint:
          'инбридинг выше порога у большинства — стадо давно закрыто ' +
          'по завозу, и подбором внутри него это уже не решается',
        href: '/account/reports/inbreeding-above',
        urgent: false,
      }),
    )
  }

  /*
   * Первотёлки в выбытии, а не выбытие целиком: выбытие бывает плановым,
   * а первотёлка не окупает даже выращивания. Сигналом должно быть
   * то, чего быть не должно, — иначе это просто ещё одно число.
   */
  if (cull && cull.firstLactation > 0) {
    out.push(
      signal({
        key: 'culled-first',
        count: cull.firstLactation,
        of: cull.total,
        label:
          `${plural(cull.firstLactation, 'первотёлка', 'первотёлки', 'первотёлок')} ` +
          `${plural(cull.firstLactation, 'выбыла', 'выбыли', 'выбыло')} за год`,
        ofLabel: 'от всего выбытия',
        hint: 'выращивание не окупилось — самая дорогая потеря',
        massHint:
          'больше половины выбытия — первотёлки: беда не в отдельных ' +
          'коровах, а в выращивании или в раздое',
        href: '/account/reports/culled-first',
        urgent: false,
      }),
    )
  }

  /*
   * Тёлки, готовые к осеменению, — не беда, а работа, и по значимости
   * они ниже всего перечисленного. Но не показать их нельзя: пропущенная
   * охота становится передержкой через месяц.
   */
  if (heifers && heifers.ready > 0) {
    out.push(
      signal({
        key: 'heifers-ready',
        count: heifers.ready,
        of: heifers.total,
        label: `${plural(heifers.ready, 'тёлку', 'тёлок', 'тёлок')} пора осеменять`,
        hint: '13–15 месяцев — возраст осеменения голштинки',
        href: '/account/reports/heifers-ready',
        urgent: false,
      }),
    )
  }

  return out
}
