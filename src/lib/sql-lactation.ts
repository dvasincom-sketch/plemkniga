/**
 * Лактация в SQL: что считать законченной и как делить на группы.
 *
 * ## Зачем именованные куски запроса
 *
 * Условие «лактация закончена» стояло тремя копиями — в списке
 * на выбраковку, в отчёте по удою и в сравнении дочерей быка. Копии
 * пока совпадали, и это не заслуга, а везение: правило зоотехническое,
 * его будут уточнять, и уточнят в том файле, где заметили.
 *
 * Расхождение здесь стоит дорого и обнаружится поздно. Средний удой
 * по стаду и средний удой дочерей быка — числа, которые смотрят рядом
 * и вычитают одно из другого; разойдись у них определение законченной
 * лактации, и разница по быку окажется на пустом месте, а объяснить
 * её будет нечем.
 *
 * ## Почему строки, а не построитель запросов
 *
 * Запросы здесь пишутся руками — с оконными функциями, боковыми
 * соединениями и рекурсией, — и построитель на них не годится. Значит
 * общими можно сделать только куски текста. Кусок текста хуже функции:
 * его нельзя проверить типами, и подставлять в него значения нельзя.
 * Поэтому здесь только предикаты и выражения без параметров, а имя
 * таблицы приходит доводом — иначе кусок молча привяжется к чужому
 * псевдониму.
 */

/**
 * Лактация закончена.
 *
 * Два признака через «или», и второй не запасной. Дату окончания
 * заполняют не все — она нужна для запуска, а не для отчёта, — зато
 * дойные дни приезжают из программы доения сами. Лактация в 320 дней
 * заведомо не в ходу, даже если конец не проставлен.
 *
 * Обратное неверно: 305 дней ровно бывает и у идущей лактации,
 * но такая корова уже додоила норму, и в среднее её брать честно.
 */
export const finishedLactation = (l = 'l') =>
  `(${l}.end_date is not null or coalesce(${l}.dd, 0) >= 305)`

/** У лактации есть удой за 305 дней — без него сравнивать нечего. */
export const hasMilk305 = (l = 'l') => `(${l}.milk305 is not null and ${l}.milk305 > 0)`

/**
 * Группа лактаций: первая, вторая, третья и старше.
 *
 * Три группы, а не пять и не «каждая своя», потому что так делят
 * в племенных отчётах: первотёлка ещё растёт и доит меньше взрослой,
 * вторая лактация — переход, с третьей корова выходит на свой уровень.
 * Дальше различия меньше разброса внутри группы.
 *
 * Ноль и единица попадают в первую вместе: ноль означает, что номер
 * лактации не проставлен, а такая запись почти всегда первотёлка —
 * у коровы постарше номер обычно есть.
 */
export const lactationGroup = (expr: string) =>
  `case when ${expr} <= 1 then 1 when ${expr} = 2 then 2 else 3 end`

/** Подписи групп — рядом с делением, чтобы не разошлись. */
export const LACTATION_GROUP_LABEL: Record<number, string> = {
  1: 'Первотёлки',
  2: 'Вторая лактация',
  3: 'Третья и старше',
}
