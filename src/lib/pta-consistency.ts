/**
 * Согласие оценок между собой: килограммы против удоя и процентов.
 *
 * ## Что здесь считается
 *
 * Оценка племенной ценности по молочным признакам — это не пять
 * независимых чисел, а два независимых и три производных. Независимы удой
 * и проценты жира и белка; килограммы выводятся из них:
 *
 *     ПЦ жир, кг = ПЦ удой · базовый жир % / 100  +  ПЦ жир % · базовый удой / 100
 *
 * Первое слагаемое — то, что даст лишнее молоко при неизменной жирности;
 * второе — то, что даст возросшая жирность при базовом удое. С белком
 * так же.
 *
 * ## Зачем это проверять
 *
 * Потому что нарушение выглядит совершенно обычно. На живой карточке
 * стояло: удой −320 кг, белок 0,00 %, белок 29,6 кг. Каждое число само
 * по себе правдоподобно, все три вместе невозможны — при нулевом проценте
 * килограммы обязаны идти за удоем, то есть быть около −10. Разница
 * в сорок килограммов, и она уходит в индекс: белок весит в профиле
 * Ассоциации четырнадцать процентов, а отклонение почти в шесть сигм
 * (σ белка 6,93 кг) вытаскивает животное в первый процент книги. Дальше это число попадает
 * в свидетельство.
 *
 * Ни одна из прежних проверок такое не ловила: границы правдоподобия
 * смотрят на числа поодиночке, а здесь каждое в границах.
 *
 * ## Почему допуск в килограммах, а не в долях
 *
 * Оценки колеблются около нуля, и относительный допуск от нуля
 * бессмысленен: при ожидаемых −0,3 кг любое расхождение — тысячи
 * процентов. Поэтому допуск абсолютный и взят от разброса самого
 * признака: одно стандартное отклонение по книге. Расхождение меньше
 * сигмы объясняется тем, что базовые удой и жирность у каждого хозяйства
 * свои; больше сигмы — тем, что числа взяты из разных источников.
 *
 * ## Откуда базовые значения
 *
 * Средние по голштинской породе, те же, что в эталонном сиде:
 * девять тысяч килограммов при 3,8 % жира и 3,2 % белка. Точность здесь
 * не критична — она влияет на второе слагаемое, а допуск в сигму её
 * покрывает; критично, чтобы сид и проверка пользовались одними
 * значениями. Иначе наш собственный эталонный бык не прошёл бы
 * собственную проверку, и разбираться в этом пришлось бы с нуля.
 */

/** Базовый удой породы, кг за лактацию. */
export const BASE_MILK = 9000

/** Базовая массовая доля жира, %. */
export const BASE_FAT_PERCENT = 3.8

/** Базовая массовая доля белка, %. */
export const BASE_PROTEIN_PERCENT = 3.2

/**
 * Сколько килограммов даёт один процентный пункт жирности при базовом удое.
 * Девять тысяч килограммов на сто процентных пунктов — девяносто.
 */
export const KG_PER_PERCENT_POINT = BASE_MILK / 100

/** Ожидаемая оценка по жиру в килограммах из оценок удоя и процента. */
export const expectedFatKg = (milk: number, fatPercent: number): number =>
  (milk * BASE_FAT_PERCENT) / 100 + fatPercent * KG_PER_PERCENT_POINT

/** Ожидаемая оценка по белку в килограммах из оценок удоя и процента. */
export const expectedProteinKg = (milk: number, proteinPercent: number): number =>
  (milk * BASE_PROTEIN_PERCENT) / 100 + proteinPercent * KG_PER_PERCENT_POINT

/**
 * Допуски — по стандартному отклонению признака в базе сравнения.
 *
 * Числа продублированы отсюда, а не взяты из `TRAIT_BASE`, и это
 * осознанно: база сравнения меняется вместе с породой и годом
 * (`BASE_VERSION`), а допуск проверки — свойство самой проверки,
 * и ему незачем ездить следом. Смена базы не должна тихо менять то,
 * какие записи считаются противоречивыми.
 */
export const KG_TOLERANCE = { fat: 11.3, protein: 6.9 } as const
