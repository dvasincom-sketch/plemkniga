/**
 * Потолки на файлы обмена — отдельным файлом, и это не мелочность.
 *
 * Числа нужны в двух местах сразу: на сервере, где по ним отказывают,
 * и в форме загрузки, где их называют до нажатия. Форма — клиентский
 * компонент, и импорт из `@/lib/xlsx`, где потолки жили бы по соседству
 * с разбором, потащил бы в браузерную сборку саму библиотеку: восемь
 * мегабайт ради двух чисел. Расчёт на то, что сборщик их выбросит,
 * не оправдан — библиотека собрана по-старому и объявляет побочные
 * действия, то есть выбрасывать её нельзя.
 *
 * Обратный ход — написать числа в форме руками — стоит дешевле ровно
 * до дня, когда потолок поменяют в одном месте из двух. Тогда форма
 * обещает пятьдесят тысяч, сервер принимает двадцать, и разошлись они
 * молча.
 */

/**
 * Строк данных в загружаемой книге.
 *
 * Выше выгрузочного потолка намеренно: выгружаем мы своё стадо,
 * а принимаем чужую историю, которая законно бывает длиннее.
 */
export const XLSX_MAX_ROWS = 50_000

/**
 * Распакованный размер книги.
 *
 * Проверяется по оглавлению архива до разбора, а не по факту съеденной
 * памяти после: восьмимегабайтный zip разворачивается во что угодно,
 * и узнавать об этом из упавшего контейнера — худший способ.
 */
export const XLSX_MAX_UNPACKED = 256 * 1024 * 1024
