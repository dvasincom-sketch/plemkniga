/**
 * Строки, которые есть только у витрины.
 *
 * ## Почему отдельный маленький набор, а не большой общий
 *
 * Основное описание продукта — что за система, какие задачи закрывает,
 * на чём построена, кому это — лежит в `product-messages.ts` и одно
 * на всё. Здесь то, чего там быть не может: надзаголовок, числа, схемы,
 * карточка со ссылкой на действующую книгу.
 *
 * Свести всё в один файл было бы проще, но тогда описание продукта
 * оказалось бы привязано к витрине, и вынести его обратно — на страницу
 * книги, в письмо, в презентацию — пришлось бы копированием.
 *
 * ## Почему витрина сделана на числах и схемах, а не на тексте
 *
 * Каждая строка здесь умножается на шесть языков, и четыре из шести
 * переведены без носителя. Абзац, написанный по-русски и переведённый
 * машинально, опознаётся специалистом с первой фразы; короткая подпись
 * из двух слов — почти нет.
 *
 * Это не только про перевод. Продающая страница, набранная сплошным
 * текстом, требует, чтобы её читали; схема и число работают на том,
 * кто пролистывает. А пролистывают почти все.
 *
 * Поэтому вес несут четыре числа наверху, три схемы и подписи к ним,
 * а прозы ровно столько, сколько нужно, чтобы схемы не пришлось
 * разгадывать.
 *
 * ## Числа обязаны быть правдой
 *
 * «20 из 20» — все шаблоны государственного реестра, проверяется
 * `check:fgias-export`. «7» — коллекции ADE, `check:ade`. «50+» —
 * правила проверки данных, реестр в `checks-registry.ts`. Дата
 * обязательной регистрации — из постановления, а не из головы.
 *
 * Круглое число, которое нельзя проверить, на витрине хуже отсутствия
 * числа: первый же специалист попросит показать, и показывать будет
 * нечего.
 *
 * ## Оговорка про качество перевода
 *
 * Казахский, армянский, белорусский и киргизский помечены
 * `reviewed: false` в `locales.ts`. Строка об этом показывается внизу
 * страницы.
 */

