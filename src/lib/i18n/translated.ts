import { DEFAULT_LOCALE, localeInfo, type Locale } from '@/lib/i18n/locales'
import { PAGE_MESSAGES } from '@/lib/i18n/page-messages'

/**
 * Длинные тексты, переведённые не на все языки сразу.
 *
 * ## Почему понадобился отдельный слой
 *
 * Наборы строк (`site-messages`, `page-messages`) устроены как
 * `Record<Locale, …>`: язык нельзя забыть, потому что без него не
 * соберётся. Для подписей на кнопках это верно — их полсотни, и перевести
 * их разом можно.
 *
 * Разбор раздела книги — другое дело: четыре абзаца с оговорками, где
 * ценность в точности формулировок. Требование «все шесть сразу» на таком
 * тексте даёт один из двух исходов, и оба плохи. Либо не переводится
 * ничего — ровно то, что и было: двенадцать страниц по-русски на всех
 * шести языках. Либо появляются четыре машинных перевода зоотехнической
 * прозы, которые выглядят достоверно для того, кто языка не знает, то есть
 * для нас (`docs/lokalizatsiya.md`).
 *
 * Поэтому здесь `Partial<Record<Locale, …>>` и явный откат на русский.
 * Английский идёт первым, остальные добавляются по мере того, как их
 * кто-то напишет.
 *
 * ## Почему откат обязан быть виден
 *
 * Молчаливый откат — та самая беда, ради которой всё и затевалось:
 * страница на английском с русскими абзацами читается как небрежность,
 * а не как «перевода пока нет». Поэтому `pick` возвращает не значение,
 * а пару «значение и был ли откат», и страница обязана сказать об откате
 * читателю. Функция, возвращающая просто текст, позволила бы забыть
 * об этом — и о ней забыли бы.
 *
 * ## Почему объявление об откате не переводится на язык читателя
 *
 * Потому что переводить его было бы некому — это ровно тот язык, для
 * которого перевода нет. Объявление идёт по-английски: человек, открывший
 * страницу на киргизском и увидевший русский текст, английскую строку
 * поймёт скорее, чем догадается сам.
 */

export type Translated<T> = Partial<Record<Locale, T>>

export type Picked<T> = {
  value: T
  /** Показан не тот язык, который просили. */
  fallback: boolean
  /** На каком языке показано на самом деле. */
  shown: Locale
}

export function pick<T>(map: Translated<T>, locale: Locale): Picked<T> {
  const exact = map[locale]
  if (exact !== undefined) return { value: exact, fallback: false, shown: locale }

  const base = map[DEFAULT_LOCALE]
  if (base === undefined) {
    throw new Error('Перевод отсутствует даже на русском: тексту неоткуда взяться')
  }
  return { value: base, fallback: true, shown: DEFAULT_LOCALE }
}

/** Языки, на которые текст действительно переведён. */
export const translatedLocales = <T,>(map: Translated<T>): Locale[] =>
  (Object.keys(map) as Locale[]).filter((l) => map[l] !== undefined)

/**
 * Строка, которую страница показывает при откате.
 *
 * Коротко и по делу: чего нет, что показано вместо и что делать. Ссылка
 * на почту не ставится намеренно — предложение «напишите нам, и мы
 * переведём» без сроков это обещание, за которое никто не отвечает.
 */
export const FALLBACK_NOTICE =
  'This page has not been translated into your language yet, so the Russian original is shown. ' +
  'The English version is available where the section has already been translated.'


/**
 * Какую оговорку показать над текстом страницы.
 *
 * Их две, и путать их нельзя.
 *
 * **Перевода нет вовсе** — показан русский текст. Об этом говорит
 * английская строка `FALLBACK_NOTICE`: перевести её на язык, для которого
 * перевода нет, некому.
 *
 * **Перевод есть, но его не читал носитель языка.** Тогда стоит оговорка
 * из общего набора на языке самой страницы: она признаёт неточность
 * терминов и тут же говорит, что числа и источники под ними одинаковы
 * на всех языках.
 *
 * Признак вычитки живёт в `locales.ts` рядом с самим языком, и снимается
 * он ровно тогда, когда текст прочёл человек, знающий, как эти вещи
 * называются в отрасли. Пока признак не снят, оговорка стоит — и это
 * дешевле, чем молчаливый машинный перевод зоотехнической прозы.
 */
export function noticeFor(locale: Locale, fallback: boolean): string | null {
  if (fallback) return FALLBACK_NOTICE
  return localeInfo(locale).reviewed ? null : PAGE_MESSAGES[locale].notice
}
