import { DEFAULT_LOCALE, LOCALE_CODES, type Locale } from '@/lib/i18n/locales'

/**
 * Переводы данных: не текста страницы, а записей под ним.
 *
 * ## Чем это отличается от двух уже существующих способов
 *
 * Коротких подписей (`site-messages`, `page-messages`) — полсотни, они
 * лежат в `Record<Locale, …>`, и язык там забыть нельзя: не соберётся.
 * Длинные тексты страниц лежат в `Translated<T>` (`i18n/translated.ts`),
 * где неполнота законна и видна читателю оговоркой.
 *
 * Данные — третий случай, и он не сводится ни к первому, ни ко второму.
 * Пятьдесят пять правил проверки, двадцать три пункта соответствия,
 * шестнадцать пробелов карты ICAR — это не подписи и не абзацы, а записи,
 * у каждой из которых есть ключ и четыре-шесть строк прозы. Их две
 * особенности: перевод нужен целиком (страница правил без правил — рамка
 * вокруг пустоты), а сами записи должны остаться читаемыми на русском,
 * потому что рядом с ними живут пороги, коды и рассуждения о том, почему
 * порог такой.
 *
 * ## Почему не пары полей рядом с записью
 *
 * Так и было: `label` и `labelEn` обязательной парой, и правило нельзя
 * было завести, не написав английского. Приём хороший, и на двух языках
 * он работал. На шести он ломается дважды.
 *
 * Во-первых, запись разбухает: четыре поля прозы на шесть языков — это
 * двадцать четыре строки на правило, и русское рассуждение о том, почему
 * граница в 270 дней, тонет между казахским и армянским переводами
 * подписи. Файл перестаёт быть местом, куда заходят думать о правилах.
 *
 * Во-вторых, страница вынуждена выбирать язык руками. Пока языков было
 * два, это была одна тернарная строка `english ? r.labelEn : r.label` —
 * и она же оказалась ловушкой: признак `english` ложен на казахском, так
 * что казахская страница брала русскую половину пары. Тело страницы
 * оставалось русским под переведённой рамкой, и никто этого не замечал,
 * потому что отката (`pick`) здесь не происходило — данные молча отдавали
 * запасной язык, не сказав об этом ни строкой.
 *
 * ## Как устроено вместо
 *
 * Русский остаётся в самой записи: это источник, и он там, где пороги.
 * Каждый другой язык — отдельный файл-словарь `i18n/data/<набор>.<язык>.ts`
 * вида `Record<Ключ, Поля>`, полный по типу. Полнота по типу и есть то,
 * ради чего затевались пары полей: запись, добавленная без перевода,
 * не соберётся — только теперь это верно про все пять языков, а не про
 * один английский.
 *
 * Отдельный файл на язык — не аккуратность, а условие работы: словарь
 * отдают носителю языка целиком и целиком же принимают обратно. Пары
 * полей отдать было нельзя — пришлось бы вычитывать казахский внутри
 * файла, где рядом стоит русская проза и код.
 *
 * ## Что делает `pickText`
 *
 * Возвращает функцию «ключ → поля» на нужном языке. Русский и язык,
 * словаря для которого нет вовсе, отдают запись как есть.
 *
 * Отсутствие словаря целиком — законное состояние: язык, добавленный
 * в `locales.ts` сегодня, переводится не в тот же час. Видимым это
 * состояние делает не тип, а `check:languages`: он перечисляет наборы,
 * где языка нет, и падает, если язык объявлен вычитанным
 * (`reviewed: true`), а словаря под ним нет. Тип поймать это не может —
 * он проверяет полноту словаря, а не его существование.
 */

export type TextTable<K extends string, T> = Record<K, T>

export type TextTables<K extends string, T> = Partial<Record<Locale, TextTable<K, T>>>

export function pickText<K extends string, T>(
  tables: TextTables<K, T>,
  locale: Locale,
  russian: (key: K) => T,
): (key: K) => T {
  if (locale === DEFAULT_LOCALE) return russian

  const table = tables[locale]
  if (!table) return russian

  /*
   * `??` здесь не мёртвый код, хотя тип словаря полон.
   *
   * Полон он относительно ключей, известных при сборке. У каталога пород
   * ключ — имя из выписки реестра, то есть строка, приехавшая снаружи:
   * завтра в реестре появится порода, которой в словаре нет. Русское имя
   * посреди казахской таблицы — плохо, но пустая ячейка хуже: по ней
   * не видно даже того, о какой породе речь.
   */
  return (key) => table[key] ?? russian(key)
}

/** Языки, для которых словаря в наборе нет. Нужно `check:languages`. */
export const missingLocales = <K extends string, T>(tables: TextTables<K, T>): Locale[] =>
  LOCALE_CODES.filter((l) => l !== DEFAULT_LOCALE && tables[l] === undefined)
