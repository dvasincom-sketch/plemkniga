/**
 * Тексты витрины продукта — все шесть языков в одном файле.
 *
 * ## Почему файл переименован
 *
 * Набор появился для страницы `/eaeu` внутри книги и назывался
 * по ней. Страницы больше нет: предложение продукта переехало
 * на `plem.online`, а держать его копию на домене голштинской
 * ассоциации значило показывать чужому хозяйству чужие реквизиты.
 *
 * Имя, пережившее свою причину, — обычный способ завести в коде
 * ложь без единой ошибки: следующий читатель ищет страницу ЕАЭС
 * и не находит её.
 *
 * ## Почему в одном файле, а не по файлу на язык
 *
 * Обычно делают наоборот, и для большого приложения это правильно.
 * Здесь набор маленький — около сорока строк, — и главная опасность
 * не в размере файла, а в том, что при правке русского текста забудут
 * пять остальных. В отдельных файлах пропуск не виден вовсе: страница
 * покажет старую фразу и не пожалуется. Рядом друг с другом пропуск
 * виден глазами, а тип `Record<Locale, Messages>` не даст забыть язык
 * целиком.
 *
 * Когда переводиться начнёт вся система, это разъедется по файлам
 * и, скорее всего, уедет во внешний сервис. Пока — так.
 *
 * ## Что делать при правке
 *
 * Правится русский — правятся все шесть. Если перевода нет, ставится
 * русская или английская строка, а язык помечается непроверенным
 * в `locales.ts`. Оставить пустую строку нельзя: пустое место на странице
 * читается как поломка, а не как отсутствие перевода.
 *
 * ## Оговорка про качество
 *
 * Казахский, армянский, белорусский и киргизский переводы сделаны без
 * носителя языка и помечены `reviewed: false`. Зоотехнические термины —
 * «сервис-период», «комплексный класс», «контрольное доение» — самая
 * вероятная часть, где перевод окажется формально верным и профессионально
 * неверным. Список того, что нужно вычитать, — в `docs/lokalizatsiya.md`.
 */

