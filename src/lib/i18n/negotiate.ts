import { DEFAULT_LOCALE, LOCALE_CODES, isLocale, type Locale } from '@/lib/i18n/locales'

/**
 * Какой язык показать пришедшему.
 *
 * ## Почему не по стране, хотя просили именно так
 *
 * Определение по IP-адресу отвечает на вопрос «где сейчас находится
 * устройство», а нужен ответ на вопрос «какой язык человек понимает».
 * Это разные вопросы, и расходятся они не в редких случаях:
 *
 * Казахский зоотехник в командировке в Ереване получит армянский.
 * Русскоязычный специалист из Минска, работающий через корпоративный
 * VPN с выходом во Франкфурте, получит английский. Армянская диаспора
 * в России получит русский, что как раз верно, но случайно. А любой,
 * кто пользуется VPN — а в этих странах это обычное дело, — получит
 * язык страны выхода.
 *
 * Заголовок `Accept-Language` отвечает ровно на нужный вопрос: это язык,
 * который человек однажды выбрал в настройках своего устройства. Он
 * не всегда точен — у многих там стоит русский по умолчанию из коробки, —
 * но он ошибается реже и, главное, ошибается предсказуемо.
 *
 * ## Почему выбор человека сильнее всего
 *
 * Порядок такой: cookie с явным выбором, потом заголовок браузера, потом
 * запасной язык. Никакая догадка не должна переспорить того, кто уже
 * нажал на переключатель, — иначе человек нажимает второй раз, третий,
 * и уходит.
 *
 * ## Почему язык стоит в адресе
 *
 * `/eaeu/kk` вместо `/eaeu` с невидимым состоянием. Ссылку на страницу
 * пересылают коллеге, и она обязана открыться на том языке, на котором
 * её прислали. Адрес без языка этого не гарантирует: у коллеги другой
 * браузер и другая cookie.
 */

type Candidate = { tag: string; q: number }

/**
 * Разбор заголовка `Accept-Language`.
 *
 * Формат: `kk,ru;q=0.9,en-US;q=0.8,en;q=0.7`. Вес по умолчанию — единица.
 * Строки без веса идут первыми, и это по стандарту, а не по совпадению.
 */
function parseAcceptLanguage(header: string): Candidate[] {
  return header
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';')
      if (!tag) return null

      const qParam = params.find((p) => p.trim().startsWith('q='))
      const q = qParam ? Number.parseFloat(qParam.trim().slice(2)) : 1

      return { tag: tag.trim().toLowerCase(), q: Number.isFinite(q) ? q : 0 }
    })
    .filter((c): c is Candidate => c !== null && c.q > 0)
    .sort((a, b) => b.q - a.q)
}

/**
 * Выбрать язык по заголовку.
 *
 * Сравнение идёт по основному тегу: `ru-BY`, `ru-KZ` и `ru` — один
 * и тот же русский. Отделять их значило бы поддерживать шесть языков
 * в двадцати вариантах ради различий, которых на этой странице нет.
 *
 * Совпадение `*` игнорируется намеренно: браузеры ставят его в конец
 * как «сойдёт любой», и толковать это как согласие на киргизский было бы
 * буквоедством.
 */
export function negotiateLocale(acceptLanguage: string | null | undefined): Locale {
  if (!acceptLanguage) return DEFAULT_LOCALE

  for (const { tag } of parseAcceptLanguage(acceptLanguage)) {
    const base = tag.split('-')[0]
    if (base && (LOCALE_CODES as string[]).includes(base)) return base as Locale
  }

  return DEFAULT_LOCALE
}

/**
 * Полное решение: cookie сильнее заголовка, заголовок сильнее умолчания.
 *
 * Значение cookie проверяется, а не берётся на веру: в неё может попасть
 * что угодно — устаревший код языка после переименования, правка руками,
 * мусор от чужого расширения. Неизвестный код здесь не ошибка,
 * а повод спросить браузер.
 */
export function resolveLocale(opts: {
  cookie?: string | null
  acceptLanguage?: string | null
}): Locale {
  if (isLocale(opts.cookie)) return opts.cookie
  return negotiateLocale(opts.acceptLanguage)
}
