/**
 * Разделы витрины, написанные по-русски намеренно.
 *
 * ## Почему они объявлены, а не подразумеваются
 *
 * Русский раздел на многоязычной витрине — решение, а не недоделка,
 * и у него два следствия, которые до сих пор жили порознь. Первое: ссылку
 * на такой раздел показывают только русскому читателю, иначе казахский
 * подвал обещает казахский текст и отдаёт русский. Второе: прогон
 * `check:english`, который ищет русский текст в разметке витрины,
 * обязан такие разделы пропускать.
 *
 * Порознь это разъезжалось: словарь, исследования и страницы шаблонов
 * реестра завели после прогона, ссылки на них закрыли условием `lang ===
 * 'ru'` руками, а прогон о них не узнал — и стал красным на десяти файлах.
 * Красная проверка, которую терпят, перестаёт быть проверкой: следующее
 * настоящее непереведённое место утонет среди привычных строк.
 *
 * Поэтому список один и здесь. Раздел, объявленный русским, автоматически
 * получает и ссылку только на русском, и пропуск в прогоне.
 *
 * ## Чего здесь нет
 *
 * «Эволюции продукта» здесь нет намеренно: её ссылка стоит на всех
 * языках, и это её долг, а не образец (разбор — в подвале `ProductShell`).
 * Нет и страниц пород: у них русская только статья о породе, а каталог
 * переведён, и раздел целиком русским назвать нельзя — исключение
 * прогона у них точечное, по адресу статьи.
 */

/** Раздел витрины, который читается только по-русски. */
export type RuOnlySection = {
  /** Адрес с языком — он всегда `/ru`. */
  href: string
  /** Подпись в шапке и подвале. */
  label: string
  /**
   * Где живут его страницы — куском пути, как их видит прогон.
   * Пустая строка означает, что своих страниц у раздела нет.
   */
  dir: string
  /** Почему русский. Читают это в отчёте прогона. */
  why: string
}

export const RU_ONLY_SECTIONS: RuOnlySection[] = [
  {
    href: '/ru/razbory',
    label: 'Разборы',
    dir: 'site/[locale]/razbory',
    why: 'разбор ценен точностью формулировок; на шести языках это пять машинных переводов',
  },
  {
    href: '/ru/issledovaniya',
    label: 'Исследования',
    dir: 'site/[locale]/issledovaniya',
    why: 'то же, что у разборов: текст научный, и машинный перевод выглядел бы достоверно',
  },
  {
    href: '/ru/slovar',
    label: 'Словарь',
    dir: 'site/[locale]/slovar',
    why: 'восемь десятков определений на шесть языков — пять сотен переводов терминологии',
  },
]

/**
 * Отдельные файлы, русские по той же причине, но разделом не являющиеся:
 * рамки перечисленных выше разделов и страницы шаблонов реестра.
 *
 * Страницы шаблонов ФГИАС ПР стоят здесь, а не в разделах: сам раздел
 * `/fgias` переведён на все шесть языков, а разбор отдельного шаблона —
 * нет. Он про российский реестр и написан для тех, кто в него сдаёт.
 */
export const RU_ONLY_FILES: string[] = [
  'site/[locale]/fgias/[slug]',
  'site/[locale]/breeds/[slug]',
  'components/site/NoteFrame.tsx',
  'components/site/StudyFrame.tsx',
  'components/site/TermFrame.tsx',
  'components/site/TermIndex.tsx',
  'components/site/TermsSeen.tsx',
]

/**
 * Пункт меню русского раздела — по его адресу.
 *
 * Функция, а не поиск на месте, и живёт она здесь, а не в разметке:
 * подпись, набранная в компоненте, непереводима по построению, и прогон
 * `check:english` считает её непереведённой — справедливо, потому что
 * отличить «русское по решению» от «забыли перевести» в разметке нельзя.
 *
 * Отсутствие раздела в списке — ошибка сборки страницы, а не пустая
 * ссылка: пункт меню, ведущий в никуда, читатель находит раньше нас.
 */
export const ruOnlySection = (href: string): { href: string; label: string } => {
  const found = RU_ONLY_SECTIONS.find((s) => s.href === href)
  if (!found) throw new Error(`Раздел ${href} не объявлен в lib/i18n/ru-only.ts`)
  return { href: found.href, label: found.label }
}
