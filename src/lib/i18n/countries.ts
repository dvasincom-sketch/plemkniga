import { DEFAULT_LOCALE, type Locale } from '@/lib/i18n/locales'

/**
 * Страна читателя — ось, отдельная от языка.
 *
 * ## Из-за чего понадобилось
 *
 * Долгое время язык и страна были у нас одним и тем же: русская
 * страница — про Россию, казахская — про Казахстан. Разбор четырёх
 * стран союза (`docs/strany-eaes.md`) сделан, страновые доводы
 * на страницы попали, — и всё равно почти никто из тех, ради кого
 * это писалось, их не прочтёт.
 *
 * Причина в нашем же разборе, раздел «Язык» по Беларуси: «фактически
 * в АПК и племенном деле безусловно доминирует русский… русскоязычный
 * интерфейс обязателен и достаточен, белорусская локализация —
 * не требование, а имиджевая опция». То есть белорусское хозяйство
 * почти наверняка откроет русскую страницу — и прочтёт там про ФГИАС ПР
 * и срок 1 марта 2026 года, который его не касается.
 *
 * В Казахстане двуязычие с креном в казахский, но русский в обиходе;
 * в Киргизии русский — официальный язык. Из четырёх стран три
 * с высокой вероятностью приходят на русскую страницу.
 *
 * Мы уже чинили зеркальную беду — «на нерусских языках не должно быть
 * отсылок к России». Оказалось, что дыра пошире с другой стороны:
 * на русской странице отсылки к России есть, а читатель может быть
 * из Гродно.
 *
 * ## Почему не по адресу сети
 *
 * Соблазн был определять страну по адресу подключения. Так нельзя:
 * зоотехник в командировке, хозяйство за общим выходом в сеть,
 * посредник, смотрящий из третьей страны, — все получат чужую версию,
 * и исправить её будет нечем, потому что выбор нигде не показан.
 *
 * Страна определяется по языковым предпочтениям браузера (там бывает
 * область: `ru-KZ`, `be-BY`), помнится в cookie и переключается руками —
 * ровно так же, как язык. Угадывание, которое можно отменить одним
 * движением, лучше точного угадывания, которое отменить нельзя.
 *
 * ## Почему пары «страна + язык», а не решётка
 *
 * Шесть стран на шесть языков дали бы тридцать шесть наборов, из которых
 * тридцать не понадобятся никогда: армянская страница по-киргизски
 * не нужна никому. Каждая страна называет языки, на которых её читают,
 * и содержимое пишется только для этих пар.
 */

export type Country = 'ru' | 'kz' | 'by' | 'am' | 'kg' | 'int'

export type CountryInfo = {
  code: Country
  /**
   * Языки, на которых страну читают, — в порядке вероятности.
   *
   * Первый служит запасным, когда язык читателя стране незнаком:
   * человек с армянским браузером, попавший на белорусскую страницу,
   * получит русскую версию, а не пустоту.
   */
  locales: Locale[]
  /**
   * Метки области в языковых предпочтениях браузера, по которым
   * страна узнаётся: `ru-KZ`, `kk`, `kk-KZ`.
   *
   * Голый код языка сюда входит только там, где он однозначен:
   * `kk` — это Казахстан, `be` — Беларусь. Голый `ru` не входит
   * никуда: он значит «русский язык», а не «Россия», и именно
   * из-за этого смешения всё и затевалось.
   */
  tags: string[]
}

export const COUNTRIES: CountryInfo[] = [
  { code: 'ru', locales: ['ru'], tags: ['ru-ru'] },
  { code: 'kz', locales: ['kk', 'ru'], tags: ['kk', 'kk-kz', 'ru-kz'] },
  { code: 'by', locales: ['ru', 'be'], tags: ['be', 'be-by', 'ru-by'] },
  { code: 'am', locales: ['hy', 'ru'], tags: ['hy', 'hy-am', 'ru-am'] },
  { code: 'kg', locales: ['ky', 'ru'], tags: ['ky', 'ky-kg', 'ru-kg'] },
  /**
   * Международная версия. Не «страна по умолчанию для всех прочих»,
   * а честное «страна неизвестна»: доводы в ней международные,
   * государственных сроков нет ни одного.
   */
  { code: 'int', locales: ['en', 'ru'], tags: ['en'] },
]

export const COUNTRY_CODES = COUNTRIES.map((c) => c.code)

/**
 * Страна по умолчанию — международная, а не Россия.
 *
 * Соблазн был поставить Россию: книга русская, разработчик русский,
 * большинство первых читателей будут оттуда. Так нельзя ровно по той
 * причине, из-за которой всё это заводится: непонятно откуда пришедший
 * получил бы российские сроки как свои. Международная версия
 * не утверждает о читателе ничего.
 */
export const DEFAULT_COUNTRY: Country = 'int'

export const isCountry = (v: unknown): v is Country =>
  typeof v === 'string' && (COUNTRY_CODES as string[]).includes(v)

export const countryInfo = (code: Country): CountryInfo =>
  COUNTRIES.find((c) => c.code === code) ?? COUNTRIES[COUNTRIES.length - 1]!

/** Читают ли эту страну на этом языке. */
export const countrySpeaks = (country: Country, locale: Locale): boolean =>
  countryInfo(country).locales.includes(locale)

/**
 * Язык страны, ближайший к желаемому.
 *
 * Возвращает сам желаемый, если страна его знает, иначе первый из её
 * списка. Пустоты не бывает: у каждой страны есть хотя бы один язык.
 */
export const localeFor = (country: Country, wanted: Locale): Locale =>
  countrySpeaks(country, wanted) ? wanted : (countryInfo(country).locales[0] ?? DEFAULT_LOCALE)

/**
 * Страна по заголовку `Accept-Language`.
 *
 * Разбор нарочно грубый: берётся первая метка, которую мы узнаём.
 * Тонкость здесь не нужна — важнее, чтобы результат был предсказуем
 * и чтобы его можно было отменить.
 *
 * Голый `ru` не даёт России. Это единственное место, где решение
 * противоречит здравому смыслу на первый взгляд, и оно намеренное:
 * `ru` без области значит «мне удобно по-русски», а не «я из России», —
 * и именно на этом смешении белорусское хозяйство получало российский
 * срок как свой. Русскоязычный читатель без области попадает
 * на международную версию по-русски и выбирает страну сам.
 */
export function negotiateCountry(acceptLanguage: string | null | undefined): Country {
  if (!acceptLanguage) return DEFAULT_COUNTRY

  const wanted = acceptLanguage
    .split(',')
    .map((part) => part.split(';')[0]?.trim().toLowerCase() ?? '')
    .filter(Boolean)

  for (const tag of wanted) {
    const hit = COUNTRIES.find((c) => c.tags.includes(tag))
    if (hit) return hit.code
  }

  return DEFAULT_COUNTRY
}

/** Cookie выбора страны — рядом с cookie языка и с тем же сроком. */
export const COUNTRY_COOKIE = 'plemkniga_country'

/**
 * Пары «страна + язык», для которых существует содержимое.
 *
 * Из них собираются адреса и по ним же проверяется полнота наборов:
 * пара, для которой текста нет, обязана падать прогоном, а не пустой
 * страницей у читателя.
 */
export const COUNTRY_LOCALES: [country: Country, locale: Locale][] = COUNTRIES.flatMap((c) =>
  c.locales.map((l) => [c.code, l] as [Country, Locale]),
)
