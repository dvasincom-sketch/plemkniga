/**
 * Языки союза.
 *
 * ## Почему шесть и почему именно эти
 *
 * Пять государственных языков стран-членов ЕАЭС плюс английский как
 * международный. Русский среди них не «главный», а один из шести, хотя
 * фактически он рабочий язык органов союза и язык, на котором зоотехники
 * пяти стран разговаривают друг с другом. Ставить его первым в списке —
 * практика, а не иерархия: он же и запасной, когда перевода нет.
 *
 * ## Почему у языка есть признак «проверен»
 *
 * Перевод зоотехнической терминологии — работа не переводчика вообще,
 * а человека, который знает, как в этой стране называют сервис-период
 * и комплексный класс. Машинный перевод такие слова выдаёт мгновенно
 * и опознаётся специалистом с первой строки; хуже того, он выглядит
 * достоверно для того, кто языка не знает, — то есть для нас.
 *
 * Выложить непроверенный перевод молча значило бы сделать ровно то,
 * против чего в этом проекте написано полтора десятка решений: показать
 * читателю число, не сказав, откуда оно взялось. Поэтому признак есть
 * в коде, страница о нём говорит одной строкой, а список того, что
 * требует вычитки, лежит в `docs/lokalizatsiya.md`.
 *
 * Убрать оговорку можно только вместе со сменой признака на `true`,
 * то есть после того, как перевод действительно прочёл носитель языка.
 */

export type Locale = 'ru' | 'en' | 'kk' | 'hy' | 'be' | 'ky'

export type LocaleInfo = {
  code: Locale
  /** Самоназвание: в переключателе языков человек ищет своё слово, а не чужое. */
  native: string
  /** Название по-русски — для внутренних списков и документации. */
  ru: string
  /** Перевод прочитан носителем языка. */
  reviewed: boolean
}

export const LOCALES: LocaleInfo[] = [
  { code: 'ru', native: 'Русский', ru: 'Русский', reviewed: true },
  { code: 'en', native: 'English', ru: 'Английский', reviewed: true },
  { code: 'kk', native: 'Қазақша', ru: 'Казахский', reviewed: false },
  { code: 'hy', native: 'Հայերեն', ru: 'Армянский', reviewed: false },
  { code: 'be', native: 'Беларуская', ru: 'Белорусский', reviewed: false },
  { code: 'ky', native: 'Кыргызча', ru: 'Киргизский', reviewed: false },
]

/**
 * Запасной язык.
 *
 * Русский, а не английский, и это не самоочевидно. Английский был бы
 * логичнее для международного продукта, но читатель этой страницы —
 * зоотехник или руководитель ассоциации в стране союза, и вероятность,
 * что он читает по-русски, выше, чем что он читает по-английски.
 * Запасной язык должен быть тем, который поймут, а не тем, который
 * приличнее выглядит.
 */
export const DEFAULT_LOCALE: Locale = 'ru'

export const LOCALE_CODES = LOCALES.map((l) => l.code)

export const isLocale = (v: unknown): v is Locale =>
  typeof v === 'string' && (LOCALE_CODES as string[]).includes(v)

export const localeInfo = (code: Locale): LocaleInfo =>
  LOCALES.find((l) => l.code === code) ?? LOCALES[0]!

/** Имя cookie с выбранным языком. Выбор человека сильнее заголовка браузера. */
export const LOCALE_COOKIE = 'plemkniga_locale'

/** Год: язык — не сессионное решение, его меняют раз и надолго. */
export const LOCALE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365
