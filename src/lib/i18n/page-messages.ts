/**
 * Рамка внутренних страниц витрины на шести языках.
 *
 * ## Что здесь есть и чего здесь нет
 *
 * Здесь **рамка**: надзаголовок, заголовок, вводный абзац и пометка
 * о языке. Здесь **нет** содержания: разборов соответствия, карты
 * руководств ICAR, описания схем обмена. Разделение не техническое,
 * а честное.
 *
 * Содержание этих страниц — плотная проза про регуляторику и стандарты:
 * четыре десятка разборов, где каждая формулировка стоит рядом
 * с требованием чужого документа. Прогнать её через машинный перевод
 * на казахский, армянский, белорусский и киргизский значит выпустить
 * текст, в котором первая же неточность бьёт по доверию сильнее, чем
 * русская страница с честной пометкой: специалист читает такой перевод
 * и понимает, что проверять его никто не станет.
 *
 * Поэтому: рамка переведена целиком, разборы остаются на русском,
 * и об этом сказано на самой странице — а не выяснится при чтении.
 *
 * ## Почему заголовки короткие
 *
 * Их переводит тот же, кто пишет, и без носителя языка. Короткая фраза
 * из четырёх слов переживает такой перевод, абзац — нет. Это то же
 * правило, по которому построена главная (`site-messages.ts`).
 */

export type PageKey = 'compliance' | 'icar' | 'ade' | 'breeds' | 'api'

export type PageFrame = { eyebrow: string; title: string; lead: string }

export type PageMessages = {
  /** Подписи разделов продукта — в шапке и подвале. */
  nav: { about: string; breeds: string; compliance: string; api: string; language: string }
  /** Пометка о языке разбора. У русского её нет. */
  notice: string | null
  /**
   * На чём держится доверие, когда заверить документ некому.
   *
   * Стоит на странице соответствия, потому что именно там читатель
   * ищет печать и не находит её. Сказать это самим — единственный
   * способ не оставить вопрос без ответа: неназванная слабость
   * додумывается читателем в худшую сторону.
   */
  trust: { title: string; body: string }
  pages: Record<PageKey, PageFrame>
}

