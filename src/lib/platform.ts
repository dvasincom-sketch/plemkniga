/**
 * Кто содержит платформу.
 *
 * ## Зачем понадобилось
 *
 * В подвале книги стояла подпись разработчика со ссылкой на личный
 * Telegram. Пока платформа была работой одного человека, это было
 * честно. Теперь у неё есть юридическое лицо, и подпись физического
 * лица в том же месте стала говорить неправду дважды: она называет
 * не того, кто отвечает за платформу, и предлагает писать в личку
 * там, где должен стоять адрес организации.
 *
 * Хуже вида здесь смысл. Книга торгует доверием: она утверждает, что
 * записи в ней прослеживаемы и что документ, выпущенный сегодня,
 * не перепишут завтра. Такое утверждение делает лицо, а не автор кода.
 *
 * ## Почему это здесь, а не в `tenant.ts`
 *
 * Соседний файл отвечает на вопрос «чья это книга»: Ассоциация,
 * показательная книга, завтра кто-то ещё. Этот отвечает на другой
 * вопрос — «кто содержит систему», — и ответ на него один для всех
 * книг сразу. Смешать их значило бы завести у каждой книги своего
 * оператора платформы и потерять разницу между владельцем данных
 * и владельцем системы; а разница эта — ровно то, что мы объясняем
 * на витрине.
 *
 * ## Почему форма названа, а реквизиты пока пусты
 *
 * Организационно-правовая форма — утверждение о состоявшемся факте,
 * и ставить её до записи в реестр нельзя. ИНН и ОГРН лежат отдельными
 * полями и по умолчанию пусты: незаполненный реквизит просто
 * не показывается, а выдуманный превратил бы страницу о прослеживаемости
 * в её опровержение. Когда номера придут — они вписываются сюда,
 * и подвал с страницей об организации подхватят их сами.
 */

