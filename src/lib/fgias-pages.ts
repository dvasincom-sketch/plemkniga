import { FGIAS_TEMPLATES, type FgiasTemplate } from '@/lib/fgias-templates'
import { FGIAS_PAGES_A } from '@/lib/fgias/group-a'
import { FGIAS_PAGES_B } from '@/lib/fgias/group-b'
import { FGIAS_PAGES_C } from '@/lib/fgias/group-c'
import { FGIAS_PAGES_D } from '@/lib/fgias/group-d'

/**
 * Двадцать шаблонов ФГИАС ПР — по странице на каждый.
 *
 * ## Зачем это отдельные страницы, а не один разбор
 *
 * Обзорная страница отвечает на вопрос «сколько шаблонов книга умеет».
 * Зоотехник в марте спрашивает другое и по одному шаблону за раз: почему
 * реестр отказал по «Живой массе», какие колонки обязательны в «Отёле»,
 * что писать в «Признаке» контрольного доения. Это двадцать разных
 * вопросов, и каждый задают отдельно — от одной страницы на все двадцать
 * человек уходит, не найдя своего.
 *
 * У этого раздела есть и вторая, не менее честная причина. Обязанность
 * сдавать данные в реестр наступила для всех, а внятного описания того,
 * как заполнять шаблоны, нет нигде: есть сами файлы, есть отказы
 * при загрузке и есть чаты, где зоотехники пересказывают друг другу,
 * что у кого прошло. Мы разобрали все двадцать до колонки — потому что
 * иначе не смогли бы их выгружать, — и не показать этот разбор было бы
 * жадностью до знания, которое всё равно у нас в коде.
 *
 * ## Правило жанра
 *
 * Страница отвечает тому, кто уже открыл файл и не понимает, что писать.
 * Отсюда шесть частей, и порядок их не переставляется.
 *
 * **Что это за шаблон** — что реестр хочет узнать и о каком событии.
 * **Обязательные колонки** — какие без ответа не примут.
 * **Что кладёт книга** — поимённо, из кода выгрузки: это и есть то, чего
 * нет ни в одном чате.
 * **Где спотыкаются** — отказы, которые видели мы и хозяйства.
 * **Чего книга не кладёт и почему** — из `FGIAS_TEMPLATES.gap`, честно.
 * **Чего этот шаблон не закрывает** — чтобы не решили, что сдав его,
 * закрыли обязанность целиком.
 *
 * ## Почему имя шаблона не пишется руками
 *
 * Оно есть в `FGIAS_TEMPLATES`, и оттуда же берутся числа колонок
 * и заполнения. Написанное второй раз, оно разойдётся с реестром
 * шаблонов на первой же правке — и разойдётся молча, потому что читатель
 * видит одну страницу, а число на обзорной странице другую. Поэтому
 * страница называет шаблон по имени, а всё остальное о нём получает
 * связью (`templateOf`).
 */

export type FgiasSection = {
  title: string
  /** Абзацы. Пустой раздел на странице не рисуется. */
  body: string[]
}

export type FgiasPage = {
  slug: string
  /**
   * Имя шаблона в реестре. Совпадает с `FGIAS_TEMPLATES[].name` —
   * по нему страница берёт число колонок, заполнение и состояние.
   */
  template: string
  /** Заголовок страницы: не имя шаблона, а вопрос, с которым приходят. */
  title: string
  /** Одна строка, ради которой страницу открыли. */
  lead: string

  /** 1. Что это за шаблон. */
  what: string[]
  /**
   * 2. Обязательные колонки.
   *
   * `kind` различает две разные вещи, и различать их обязательно.
   * `column` — имя колонки контракта дословно, и прогон сверяет его
   * с шаблоном: приблизительное имя бесполезно, по нему ищут строку
   * в своём файле. `condition` — требование, которое одной колонкой
   * не выражается: «хотя бы один признак в шкале 1…9». Сверять такое
   * с именами колонок нельзя, и первая редакция прогона на этом
   * и споткнулась, назвав пять честных требований несуществующими
   * колонками.
   */
  required: { name: string; note: string; kind?: 'column' | 'condition' }[]
  /** 3. Что кладёт книга — поимённо. */
  ours: string[]
  /** 4. Где спотыкаются: отказ и что он значит. */
  errors: { error: string; means: string }[]
  /** 5. Чего книга не кладёт и почему. */
  gaps: string[]
  /** 6. Чего этот шаблон не закрывает. */
  limits: string[]

  /** Термины словаря, употреблённые на странице (`lib/term-links.ts`). */
  terms?: string[]
  /** Куда идти дальше. */
  see?: { label: string; href: string }[]
}

export const FGIAS_PAGES: FgiasPage[] = [
  ...FGIAS_PAGES_A,
  ...FGIAS_PAGES_B,
  ...FGIAS_PAGES_C,
  ...FGIAS_PAGES_D,
]

export const fgiasPageBySlug = (slug: string): FgiasPage | undefined =>
  FGIAS_PAGES.find((p) => p.slug === slug)

/**
 * Запись реестра шаблонов, к которой относится страница.
 *
 * Возвращает `undefined`, если имя не совпало, — и это состояние ловит
 * `check:fgias-pages`: страница, потерявшая связь с реестром, покажет
 * число колонок из ниоткуда или не покажет вовсе, а выглядеть будет
 * целой.
 */
export const templateOf = (page: FgiasPage): FgiasTemplate | undefined =>
  FGIAS_TEMPLATES.find((t) => t.name === page.template)

/** Шаблоны, у которых своей страницы ещё нет. */
export const templatesWithoutPage = (): FgiasTemplate[] =>
  FGIAS_TEMPLATES.filter((t) => !FGIAS_PAGES.some((p) => p.template === t.name))
