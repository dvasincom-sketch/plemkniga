/**
 * Двадцать шаблонов ФГИАС ПР против того, что книга умеет отдать.
 *
 * ## Зачем список лежит в коде, а не в документе
 *
 * Он отвечает на вопрос, который задают каждую неделю и будут задавать
 * ещё год: «что книга уже умеет отдавать в государственный реестр,
 * а чего нет». Спрашивают хозяйства, спрашивает Ассоциация, спрашивает
 * тот, кто решает, вести ли учёт здесь. Ответ в переписке живёт до первой
 * правки; ответ на странице живёт, пока его не поправят вместе с кодом.
 *
 * ## Откуда числа
 *
 * Колонки сосчитаны по самим файлам шаблонов версии 2.6.0 — чтением,
 * а не с чужих слов. «Заполним» получено прогоном `check:fgias-readiness`
 * по живой базе: считались поля, которые в книге заведены **и заполняются**.
 * Считать по схеме было бы лестнее и бесполезнее — поле, которое никто
 * не вносит, даёт в выгрузке пустую ячейку и отказ реестра.
 *
 * Числа поэтому статические, а не считаются на лету. Расчёт при каждом
 * открытии страницы означал бы обход всей книги ради витрины, а главное —
 * менялся бы от хозяйства к хозяйству, тогда как отвечать надо про
 * платформу. Дата прогона стоит рядом: сведения устаревают, и молчать
 * об этом нельзя.
 */

