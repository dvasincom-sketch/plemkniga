/**
 * Форматы выгрузки — один список на карточку и на сам обработчик.
 *
 * ## Зачем реестр
 *
 * Карточка обещала «pdf, xls/xlsx, csv, json, xml», а обработчик умел два
 * формата: CSV и JSON. Ни один из них не был сломан — просто текст писали
 * отдельно от кода, и разойтись им было негде, кроме как разойтись.
 * Хозяйство, пришедшее за XML для своей программы учёта, узнавало правду
 * после трёх нажатий.
 *
 * Теперь список один: из него собирается и выпадающий список форматов,
 * и разбор параметра в обработчике. Пообещать формат, которого нет,
 * больше нельзя — обещание и есть реализация.
 *
 * ## Почему именно эти пять
 *
 * CSV и TXT — одна и та же таблица с разными разделителями. Это
 * не прихоть: точку с запятой ждёт Excel, табуляцию — программы учёта,
 * и в выгрузках хозяйств встречаются оба. XML — те же поля разметкой,
 * для обмена с системами, которым нужна схема, а не таблица. JSON —
 * записи целиком, как они лежат в книге. XLSX — настоящая книга Excel.
 *
 * ## Почему XLSX всё-таки завёлся
 *
 * Здесь до недавнего было написано обратное: XLSX не заведён сознательно,
 * потому что CSV открывается тем же Excel и стоит одной функции, а книга
 * потребовала бы сборки настоящего файла. Довод был верным ровно наполовину
 * и рассыпался о ту самую колонку, ради которой выгрузку и делают.
 *
 * Индивидуальный номер состоит из цифр и числом не является. Excel,
 * открывая CSV, решает иначе: `0987654321` он читает числом и теряет
 * ведущий ноль — не в показе, а в значении, и файл, сохранённый после
 * такого открытия, загрузится обратно другим животным. Сказать «это
 * текст» в CSV нечем: формат не переносит типов вовсе, о чём и весь
 * разговор. В книге ячейке тип задаётся, и номер остаётся номером.
 *
 * Второй довод — требование №11 технического задания, где XLS назван
 * прямо. Но он второй: требование можно было бы закрыть и объяснением,
 * а ведущий ноль объяснением не вернуть.
 *
 * PDF по-прежнему не заведён и не будет. Это документ для чтения, а не
 * данные: выгружать в него стадо значит делать таблицу, которую нельзя
 * ни загрузить обратно, ни посчитать. Для документов у нас своя дорога —
 * племенное свидетельство.
 */

export type ExportFormat = {
  value: string
  label: string
  /** Расширение файла и часть имени. */
  ext: string
  mime: string
  /** Строка под названием в списке: кому и зачем этот формат. */
  hint: string
}

export const EXPORT_FORMATS: readonly ExportFormat[] = [
  /*
   * XLSX стоит первым, потому что первым его и выбирают. Прежний первый,
   * CSV, оставлен рядом намеренно: он весит впятеро меньше и читается
   * чем угодно, включая то, что книгу Excel не откроет.
   */
  {
    value: 'xlsx',
    label: 'XLSX',
    ext: 'xlsx',
    mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    hint: 'Книга Excel — номера остаются текстом, ведущие нули не теряются',
  },
  {
    value: 'csv',
    label: 'CSV',
    ext: 'csv',
    mime: 'text/csv; charset=utf-8',
    hint: 'Таблица с точкой с запятой — открывается в Excel, но номер он прочтёт числом',
  },
  {
    value: 'txt',
    label: 'TXT',
    ext: 'txt',
    mime: 'text/plain; charset=utf-8',
    hint: 'Та же таблица с табуляцией — для программ учёта',
  },
  {
    value: 'xml',
    label: 'XML',
    ext: 'xml',
    mime: 'application/xml; charset=utf-8',
    hint: 'Те же поля разметкой — для обмена между системами',
  },
  {
    value: 'json',
    label: 'JSON',
    ext: 'json',
    mime: 'application/json; charset=utf-8',
    hint: 'Записи целиком, как они лежат в книге',
  },
]

export const exportFormat = (v?: string | null): ExportFormat =>
  EXPORT_FORMATS.find((f) => f.value === String(v ?? '').toLowerCase()) ?? EXPORT_FORMATS[0]!

/**
 * Сколько записей уходит в один файл.
 *
 * Потолок есть, и он назван вслух — в карточке выгрузки. Молчаливый
 * потолок здесь опаснее обычного: файл выглядит целым, хозяйство считает
 * по нему средние и не знает, что последних записей в нём нет.
 */
export const EXPORT_LIMIT = 20_000

/* ------------------------------------------------------------------ */

const cell = (v: unknown): string => (v === null || v === undefined ? '' : String(v))

/**
 * Таблица с табуляцией.
 *
 * Кавычек и экранирования в этом формате нет — по построению: разделитель
 * не может встретиться внутри значения, потому что мы его оттуда убираем.
 * Табуляция и перенос строки заменяются пробелом; на наших полях (номера,
 * клички, числа) это не теряет ничего, а строка, разъехавшаяся на две,
 * потеряла бы всю запись.
 *
 * BOM в начале — как и в CSV: без него Excel читает UTF-8 как местную
 * кодировку и показывает кириллицу вопросами.
 */
export function toTsv(headers: string[], rows: unknown[][]): string {
  const clean = (v: unknown) => cell(v).replace(/[\t\r\n]+/g, ' ')
  const lines = [headers.map(clean).join('\t'), ...rows.map((r) => r.map(clean).join('\t'))]
  return '﻿' + lines.join('\r\n')
}

/** Экранирование значений и текста в XML. */
const xmlText = (v: unknown): string =>
  cell(v)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    /*
     * Управляющие символы XML 1.0 не принимает вовсе — ни экранированными,
     * ни как есть. Файл с ними не откроется ни одним разбором, поэтому
     * они выбрасываются, а не заменяются. Табуляция, перевод строки
     * и возврат каретки в список не входят: они разрешены.
     */
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')

/**
 * Те же поля, что в таблице, — разметкой.
 *
 * Имена элементов берутся из ключей полей, а не из заголовков: заголовок
 * написан для человека («Инд.№»), а имя элемента читает программа,
 * и русские буквы с точкой в нём хоть и допустимы, но приносят
 * получателю ровно те хлопоты, ради избавления от которых он и просил XML.
 *
 * Пустые поля выводятся пустыми элементами, а не пропускаются: набор
 * элементов у каждой записи одинаков, и разбор на стороне получателя
 * не должен угадывать, отсутствует поле или отсутствует значение.
 */
export function toXml(
  fields: { key: string; title: string }[],
  rows: unknown[][],
  meta: Record<string, unknown> = {},
): string {
  const attrs = Object.entries(meta)
    .filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => ` ${k}="${xmlText(v)}"`)
    .join('')

  const items = rows.map((row) => {
    const inner = fields
      .map((f, i) => `    <${f.key}>${xmlText(row[i])}</${f.key}>`)
      .join('\n')
    return `  <animal>\n${inner}\n  </animal>`
  })

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<animals${attrs}>`,
    ...items,
    '</animals>',
    '',
  ].join('\n')
}
