import { randomInt } from 'node:crypto'
import type { Payload } from 'payload'
import type { Document } from '@/payload-types'

/**
 * Проверка подлинности выданного документа — тем, у кого нет учётной записи.
 *
 * ## Чего требует ТЗ
 *
 * UC-03: держатель бумаги должен уметь проверить её подлинность, не входя
 * в систему. Свидетельство юридически значимо, по нему продают животное
 * за сотни тысяч, и покупатель обязан иметь способ убедиться, что бумага
 * настоящая, — не звонком в Ассоциацию, а сам.
 *
 * ## Почему номера мало
 *
 * Номера идут подряд: `RU-2026-0001`, `RU-2026-0002`. Открой проверку
 * по одному номеру — и любой желающий за вечер выгрузит из книги, какие
 * животные каким хозяйствам принадлежат, обойдя и публичность записей,
 * и точечный доступ. Поэтому к номеру добавлен короткий код, напечатанный
 * на самом бланке: номер называет документ, код доказывает, что документ
 * у вас в руках.
 *
 * ## Почему код короткий
 *
 * Его переписывают глазами с бумаги. Восемь знаков из алфавита без
 * похожих букв — это 27⁸ ≈ 2,8 · 10¹¹ сочетаний: перебирать нечем,
 * набирать руками можно. Длинный токен, как у ссылок на просмотр, здесь
 * был бы вредительством: его набирают не мышью, а с листа.
 *
 * ## Что проверка показывает и чего не показывает
 *
 * Показывает: существует ли такой документ, действует ли он, на какое
 * животное выдан и совпадают ли данные книги с тем, что напечатано.
 * Не показывает продуктивность, оценку и родословную: проверка отвечает
 * на вопрос «бумага настоящая?», а не заменяет доступ к карточке.
 */

/**
 * Алфавит без похожих знаков: нет `0`/`O`, `1`/`I`/`L`, `5`/`S`, `8`/`B`.
 *
 * Код переписывают с бумаги, часто с плохой печати. Каждая пара
 * неразличимых знаков — это звонок в Ассоциацию «у меня не принимает код»,
 * и звонок этот делает человек, который как раз усомнился в подлинности.
 *
 * Знаков остаётся 27, длина 8 — это 27⁸ ≈ 2,8 · 10¹¹ сочетаний. Перебор
 * по сети бессмыслен даже без ограничения частоты запросов, а набрать
 * с листа можно за десять секунд.
 */
const ALPHABET = '234679ACDEFGHJKMNPQRTUVWXYZ'

export const CERT_CODE_LENGTH = 8

export const newCertificateCode = (): string =>
  Array.from({ length: CERT_CODE_LENGTH }, () => ALPHABET[randomInt(ALPHABET.length)]).join('')

/**
 * Приведение введённого кода к каноническому виду.
 *
 * С бумаги переписывают как получится: строчными, с пробелами, с дефисом
 * посередине. Отказывать из-за регистра значит отказывать по причине,
 * которой человек не видит.
 */
export const normalizeCode = (raw: unknown): string =>
  String(raw ?? '')
    .toUpperCase()
    .replace(/[^0-9A-Z]/g, '')

/** Адрес проверки — он же содержимое QR-кода на бланке. */
export const verifyUrl = (number: string, code: string, base = ''): string =>
  `${base}/certificate/${encodeURIComponent(number)}?k=${encodeURIComponent(code)}`

export type CertificateCheck =
  | { status: 'unknown' }
  | { status: 'need-code'; number: string }
  | { status: 'ok'; doc: Document }

/**
 * Найти документ по номеру и коду.
 *
 * Несуществующий номер и неверный код отвечают по-разному, и это
 * осознанная разница с ссылками на просмотр. Там одинаковый ответ защищал
 * от перебора; здесь перебирать нечего — номер человек читает с бумаги,
 * которая у него в руках, и «такого номера нет» это и есть тот ответ,
 * ради которого он пришёл: бумага поддельная.
 *
 * Ошибиться при этом легче в коде, чем в номере: восемь случайных знаков
 * против осмысленного `RU-2026-0137`. Поэтому неверный код возвращает
 * «введите код», а не «документа нет»: иначе человек с настоящей бумагой
 * и опечаткой услышит, что его свидетельство поддельное.
 */
export async function checkCertificate(
  payload: Payload,
  number: string,
  code: unknown,
): Promise<CertificateCheck> {
  const { docs } = await payload.find({
    collection: 'documents',
    where: { number: { equals: number } },
    limit: 1,
    depth: 1,
    overrideAccess: true,
  })

  const doc = docs[0] as Document | undefined
  if (!doc) return { status: 'unknown' }

  const expected = normalizeCode((doc as { publicCode?: string }).publicCode)
  const given = normalizeCode(code)

  /*
   * У документа без кода проверить нечего.
   *
   * Так выглядят бумаги, выданные до появления проверки: код им проставила
   * миграция, но бланк на руках напечатан без него. Пускать такие
   * по одному номеру нельзя — это и есть перебор, от которого код защищает.
   */
  if (!expected) return { status: 'need-code', number }
  if (!given || given !== expected) return { status: 'need-code', number }

  return { status: 'ok', doc }
}

export type SnapshotDiff = { label: string; onPaper: string; inBook: string }

/**
 * Расхождения бумаги с книгой.
 *
 * Главная ценность проверки — не «документ существует», а «данные с тех пор
 * не менялись». Бумага, выданная год назад, могла устареть честно:
 * животное сменило владельца, поправили дату рождения. Покупатель должен
 * увидеть это сам, а не узнать после сделки.
 *
 * Сравниваются только те поля, которые печатаются на бланке крупно
 * и решают в сделке. Сверять весь снимок значило бы утопить одно важное
 * расхождение в двадцати незначащих.
 */
export function snapshotDiff(
  snapshot: unknown,
  live: { identNumber?: unknown; name?: unknown; birthDate?: unknown; owner?: unknown },
): SnapshotDiff[] {
  /*
   * Снимок плоский: `identNumber`, `name`, `owner` лежат в корне,
   * а не под ключом `animal` (см. `CertificateView`). Первая редакция
   * искала их во вложенном объекте, не находила ничего — и молча
   * сообщала «расхождений нет» при любых расхождениях. Проверка,
   * которая всегда отвечает «всё хорошо», хуже отсутствующей.
   */
  const snap = (snapshot ?? {}) as Record<string, unknown>
  const out: SnapshotDiff[] = []

  const cmp = (label: string, onPaper: unknown, inBook: unknown) => {
    const a = String(onPaper ?? '').trim()
    const b = String(inBook ?? '').trim()
    if (!a || !b) return
    if (a !== b) out.push({ label, onPaper: a, inBook: b })
  }

  const ownerName =
    live.owner && typeof live.owner === 'object'
      ? ((live.owner as { name?: string }).name ?? '')
      : ''

  cmp('Индивидуальный номер', snap.identNumber, live.identNumber)
  cmp('Кличка', snap.name, live.name)
  cmp('Хозяйство', snap.owner, ownerName)

  return out
}
