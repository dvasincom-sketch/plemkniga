import type { Payload } from 'payload'
import { hasCalved } from '@/lib/sql-herd'

/**
 * Полнота записи: передано ли всё, без чего подтверждать нечего.
 *
 * ## Чем это не заслон противоречий
 *
 * `verification-gate.ts` спрашивает «нет ли в данных расхождения».
 * Здесь спрашивают другое: «данные вообще есть?». Запись без единого
 * отёла и без единой дойки не противоречит ничему — противоречить
 * нечему, — и заслон пропускал её молча. Ассоциация ставила знак
 * наивысшей достоверности на пустую карточку, и формально была права:
 * всё, что прислали, сошлось.
 *
 * Обещание книги звучит иначе: «данные не имеют расхождений **и в полной
 * мере соответствуют реальной картине**». Вторая половина обещания
 * до сих пор не проверялась ничем.
 *
 * ## Почему состав именно такой
 *
 * Правило одно: требуем то, без чего запись нельзя ни прочитать,
 * ни сравнить, — и не требуем ничего сверх. Каждое лишнее требование
 * это хозяйство, которое не может подтвердить верные данные, и оно
 * дороже, чем кажется: невыполнимый порог заставляет обходить порог,
 * а не заполнять данные.
 *
 * **Дата рождения.** Без неё не считается ничего: ни возраст первого
 * отёла, ни номер лактации по возрасту, ни проверка «родитель моложе
 * потомка». Это не поле карточки, а точка отсчёта всей записи.
 *
 * **Порода.** Книга голштинская. Запись без породы нельзя ни поставить
 * в сравнение со сверстницами, ни включить в отчёт по стаду.
 *
 * **Отец.** Записью в книге или номером в родословной. Книга — про
 * происхождение; запись без отца не имеет племенной ценности вовсе,
 * и подтверждать в ней нечего. Номер принимается наравне со связью:
 * у импортированных животных отец в российской книге не заведён,
 * и требовать связь значило бы закрыть верификацию всему импорту.
 *
 * **Мать.** Тем же способом. Мать без номера — это разорванная материнская
 * линия: по такой записи нельзя ни посчитать инбридинг потомка,
 * ни проверить семейство.
 *
 * **Отёл — у коровы.** Корова без единого отёла это либо не корова,
 * либо потерянная история. Тёлок и быков требование не касается:
 * у них отёла нет по определению.
 *
 * **Контрольные дойки — если заявлена продуктивность.** Карточка,
 * где написан удой за 305 дней, а замеров нет ни одного, показывает
 * число, взятое неизвестно откуда. Требуется {@link MIN_TESTS} замеров
 * на животное. Не заявляете продуктивность — требование не работает:
 * пустая лактация честнее выдуманной.
 *
 * ## Почему по животному, а не по лактации
 *
 * Просилось «шесть замеров на каждую заявленную лактацию», и это было бы
 * точнее. Но номер лактации в карточке и номер в замере приходят
 * из разных источников — первый из выгрузки хозяйства, второй
 * из лаборатории или из ручного ввода — и расходятся сплошь и рядом.
 * Правило, сопоставляющее их по номеру, отказывало бы хозяйствам
 * с полными данными из-за нашей же несведённой нумерации.
 *
 * Требование по животному слабее и честнее: оно спрашивает «продуктивность
 * вообще измеряли?», а не «сойдётся ли третья лактация с третьей».
 * Сведение нумерации — отдельная работа, и до неё строгий вариант
 * не поставить.
 *
 * ## Откуда шесть замеров
 *
 * Метод контрольных доек считает лактацию по отрезкам между замерами
 * (ICAR, test-interval method). При месячном интервале на 305 дней
 * приходится десять замеров — это норма практики, а не порог. Шесть
 * взяты нижней границей: при более редких замерах отрезок между ними
 * переваливает за 75 дней, и кривая лактации между двумя точками
 * восстанавливается уже не по данным, а по предположению.
 *
 * Порог назван здесь одним числом намеренно: он спорный, его будут
 * двигать, и двигать его должно быть одно место, а не шесть условий
 * в запросе.
 */

/** Минимум контрольных доек на лактацию с заявленным удоем. */
export const MIN_TESTS = 6

export type GapCode = 'birth' | 'breed' | 'father' | 'mother' | 'calving' | 'tests'

export const GAP_LABEL: Record<GapCode, string> = {
  birth: 'дата рождения',
  breed: 'порода',
  father: 'отец: запись или номер',
  mother: 'мать: запись или номер',
  calving: 'хотя бы один отёл',
  tests: `контрольные дойки (минимум ${MIN_TESTS}, если заявлен удой за 305 дней)`,
}

/** Порядок показа: от того, без чего не читается запись, к частностям. */
export const GAP_ORDER: GapCode[] = ['birth', 'breed', 'father', 'mother', 'calving', 'tests']

/** Почему это требуется — показывается хозяйству до подачи заявки. */
export const GAP_WHY: Record<GapCode, string> = {
  birth: 'от неё считаются возраст первого отёла, номера лактаций и проверки родословной',
  breed: 'без породы запись не сравнить со сверстницами и не включить в отчёты',
  father: 'книга подтверждает происхождение; без отца подтверждать нечего',
  mother: 'без матери рвётся материнская линия и не считается инбридинг потомка',
  calving: 'корова без отёла — это либо не корова, либо потерянная история',
  tests: 'удой за 305 дней без замеров — число, взятое неизвестно откуда',
}

export type Gap = {
  animalId: number
  ident: string
  missing: GapCode[]
}

/**
 * Чего не хватает записям — одним запросом на весь список.
 *
 * По одному запросу на животное здесь нельзя: заявка бывает на сотни
 * записей, и разбор превратился бы в тысячу обращений к базе ради
 * шести условий.
 */
export async function completenessGaps(payload: Payload, ids: number[]): Promise<Gap[]> {
  if (!ids.length) return []

  const { rows } = await payload.db.pool.query(
    `
    select
      a.id::int                                          as id,
      a.ident_number                                     as ident,
      (a.birth_date is null)                             as no_birth,
      (a.breed_id is null)                               as no_breed,
      (a.father_id is null
         and coalesce(a.pedigree_text_father_id, '') = '') as no_father,
      (a.mother_id is null
         and coalesce(a.pedigree_text_mother_id, '') = '') as no_mother,
      (a.kind = 'cow' and not ${hasCalved()}) as no_calving,
      /*
       * Заявлена продуктивность — должны быть замеры. Заявкой считается
       * удой за 305 дней хотя бы в одной строке лактаций карточки:
       * итоговое число — это то, на что смотрят, и то, что попадает
       * в отчёты и в свидетельство.
       */
      (exists (select 1
                 from animals_lactations l
                where l._parent_id = a.id
                  and l.milk305 is not null
                  and l.milk305 > 0)
       and (select count(*) from milk_tests t where t.animal_id = a.id) < $2) as thin_tests
      from animals a
     where a.id = any($1::int[])
    `,
    [ids, MIN_TESTS],
  )

  const gaps: Gap[] = []
  for (const r of rows as Record<string, unknown>[]) {
    const missing: GapCode[] = []
    if (r.no_birth) missing.push('birth')
    if (r.no_breed) missing.push('breed')
    if (r.no_father) missing.push('father')
    if (r.no_mother) missing.push('mother')
    if (r.no_calving) missing.push('calving')
    if (r.thin_tests) missing.push('tests')
    if (missing.length) {
      gaps.push({ animalId: Number(r.id), ident: String(r.ident ?? r.id), missing })
    }
  }
  return gaps
}

/**
 * Текст отказа — рядом с правилом, а не в действии.
 *
 * Тот же довод, что у заслона противоречий: разведи правило и его
 * объяснение по файлам, и сообщение переживёт правку правила.
 */
export const gapsMessage = (gaps: Gap[]): string => {
  const uniq = [...new Set(gaps.flatMap((g) => g.missing))].map((c) => GAP_LABEL[c])
  return (
    `Записей с неполными данными — ${gaps.length}. Не хватает: ` +
    `${uniq.slice(0, 3).join('; ')}${uniq.length > 3 ? ` и ещё ${uniq.length - 3}` : ''}. ` +
    'Подтверждение Ассоциации означает не только «расхождений нет», но и «передано всё ' +
    'необходимое». Дополните записи либо выведите их из заявки замечанием.'
  )
}
