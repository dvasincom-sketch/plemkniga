import type { AgeGroup } from '@/lib/dictionaries'

/**
 * Возрастная группа и отёлы: кто кого поправляет.
 *
 * ## Три ответа на один вопрос, из которых остался один
 *
 * На вопрос «корова ли это» в карточке отвечали три места: поле «Тип
 * животного», поле «Возрастная группа» и записи отёлов. Прогон по живой
 * базе показал, что расходятся они у четверти стада, и что «Тип животного»
 * не отвечает вовсе: он на девяносто три процента был умолчанием формы —
 * шестьдесят три телёнка и девяносто шесть тёлок числились «Коровой»
 * просто потому, что поле никто не трогал, — и ни разу не противоречил
 * полу, то есть не добавлял к нему ничего. Поле убрано.
 *
 * Осталось два: группа в карточке и отёлы. Здесь описано, как они
 * относятся друг к другу.
 *
 * ## Отёл повышает группу и никогда не понижает
 *
 * Соблазн был обратный: раз отёл — факт, а группа — утверждение,
 * пересчитывать группу из числа отёлов целиком. На живой базе это стоило
 * бы двухсот семидесяти восьми коров: у них коровья группа и ни одного
 * отёла в базе — не потому, что они не телились, а потому, что отёлы
 * за прежние годы не загружены. Пересчёт разжаловал бы их в тёлки одним
 * скриптом и молча.
 *
 * Поэтому правило несимметрично, и несимметрично осознанно. Запись отёла —
 * доказательство, что животное телилось: тёлка обязана стать первотёлкой.
 * Отсутствие записи не доказывает ничего: событие могло быть и не быть
 * записанным. Это та же мысль, что в решении №226 о разборе значений —
 * пустая ячейка и непонятая ячейка суть разные ответы, — только сказанная
 * не про ячейку, а про целую коллекцию.
 *
 * ## Почему группа осталась хранимой, а не вычисляемой
 *
 * Вычислять её на лету было бы стройнее и неверно по существу. Довод
 * пришёл от самого ФГИАС ПР: в шаблоне «Основные сведения» рядом
 * с колонкой «Половозрастная группа» стоит колонка «Дата определения
 * половозрастной группы» — и так же устроены порода и назначение,
 * у каждой своя дата определения. Государственный реестр хранит не функцию
 * от событий, а зафиксированное решение и день, когда его приняли.
 * Вычисляемое поле такой даты иметь не может.
 *
 * ## Быки сюда не попадают
 *
 * Группа «бык-производитель» из шкалы выпадает: она не выше и не ниже
 * коровьих, она про другое животное. Сравнивать её рангом значило бы
 * однажды «повысить» быка до третьей лактации. Отёл у самца отклоняется
 * загрузкой отдельно и раньше.
 */

/**
 * Порядок групп по возрасту.
 *
 * Числа тут не значат ничего, кроме порядка, и наружу не отдаются:
 * сравнение идёт только внутри этого файла. Пропуск в нумерации оставлен
 * намеренно — если однажды между тёлкой и первотёлкой заведут «нетель»,
 * её вставят без пересчёта соседей.
 */
const RANK: Partial<Record<AgeGroup, number>> = {
  calf: 10,
  heifer: 20,
  firstCalf: 30,
  cow2: 40,
  cow3: 50,
}

/** Какой группе соответствует число отёлов. Ноль отёлов не значит ничего. */
export const groupByCalvings = (calvings: number): AgeGroup | null => {
  if (calvings >= 3) return 'cow3'
  if (calvings === 2) return 'cow2'
  if (calvings === 1) return 'firstCalf'
  return null
}

/**
 * Группа, которую надо поставить, — или `null`, если менять нечего.
 *
 * Возвращает `null` в трёх случаях, и все три означают «не трогай»:
 * отёлов нет, животное вне коровьей шкалы (бык), группа уже не ниже
 * положенной. Отдельного признака «понизить» не существует по построению:
 * функция физически не умеет вернуть группу ниже текущей.
 */
export function raiseAgeGroup(
  current: AgeGroup | null | undefined,
  calvings: number,
): AgeGroup | null {
  const target = groupByCalvings(calvings)
  if (!target) return null

  /*
   * Бык остаётся быком. Пустая группа — случай отдельный: рангов у неё нет,
   * но и терять доказанный отёл незачем, поэтому пустая группа заполняется.
   */
  if (current === 'bull') return null

  const now = current ? RANK[current] : undefined
  if (now === undefined) return target

  const to = RANK[target]!
  return to > now ? target : null
}
