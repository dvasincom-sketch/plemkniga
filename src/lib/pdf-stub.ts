/**
 * Настоящий маленький PDF — для синтетики и для проверок.
 *
 * ## Зачем это понадобилось
 *
 * Демонстрационные протоколы лаборатории и файлы в прогонах сначала
 * собирались строкой вида `%PDF-1.4 ...`. Payload такие не принимает:
 * он читает буфер и требует у PDF не только заголовка, но и таблицы
 * перекрёстных ссылок с меткой конца файла. Прогон падал на создании
 * файла, и падал не там, где была ошибка, — сообщение говорило
 * «Invalid PDF file» про поле `file`, а причина была в трёх строках
 * подделки.
 *
 * ## Почему настоящий, а не тот же обман поаккуратнее
 *
 * Достаточно было дописать в хвост `xref` и `%%EOF` — проверка Payload
 * смотрит именно на эти подстроки. Но файл после этого открывался бы
 * битым: демонстрационный протокол лежит в карточке животного, и его
 * однажды нажмут. Файл, который система приняла, а читалка не открыла,
 * выглядит как поломка системы.
 *
 * Поэтому здесь собирается маленький, но действительный документ:
 * одна страница, одна строка текста, правильные смещения в таблице
 * ссылок. Смещения считаются, а не проставляются: набранные руками,
 * они разъезжаются при первой же правке содержимого — и разъезжаются
 * молча, потому что большинство читалок такой файл чинит на лету.
 */

/** Экранирование по правилам PDF: строки в скобках, скобки — служебные. */
const esc = (s: string) => s.replace(/([\\()])/g, '\\$1')

/**
 * Одностраничный PDF с одной строкой текста.
 *
 * Кириллица не поддерживается намеренно: встроенный Helvetica знает
 * только латиницу, а таскать шрифт ради подписи на служебном файле
 * дороже, чем написать подпись латиницей.
 */
export function pdfStub(line = 'Plemkniga test document'): Buffer {
  const text = esc(line)
  const stream = `BT /F1 14 Tf 40 120 Td (${text}) Tj ET`

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 200] ' +
      '/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ]

  let body = '%PDF-1.4\n'
  const offsets: number[] = []
  objects.forEach((o, i) => {
    offsets.push(body.length)
    body += `${i + 1} 0 obj\n${o}\nendobj\n`
  })

  const xrefAt = body.length
  let xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (const off of offsets) xref += `${String(off).padStart(10, '0')} 00000 n \n`

  const trailer =
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n` +
    `startxref\n${xrefAt}\n%%EOF\n`

  return Buffer.from(body + xref + trailer, 'latin1')
}
