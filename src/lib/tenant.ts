/**
 * Книга по заголовку `Host`.
 *
 * Порт и регистр снимаются, как и при опознании витрины: `Host`
 * регистронезависим, а на своей машине приходит с портом.
 *
 * Всё неизвестное — голштинская книга, а не ошибка. На своей машине,
 * на старом адресе и по прямому обращению к серверу хост будет любым,
 * и падать на этом нельзя: непонятный хост означает «обычная работа»,
 * а не «кто-то подделал заголовок». Демонстрация же — единственный
 * особый случай, и он называется прямо.
 */
export const tenantFor = (host?: string | null): Tenant => {
  const clean = (host ?? '').split(':')[0].trim().toLowerCase()
  return DEMO_HOST && clean === DEMO_HOST ? DEMO : HOLSTEIN
}

/** Домен книги по её ключу — для ссылок между книгами. */
export const hostOf = (t: Tenant): string => (t.key === 'demo' ? DEMO_HOST : BOOK_HOST)

/**
 * Подпись к полю кровности.
 *
 * Живёт здесь, а не в двух компонентах, которые её показывают: подпись
 * одна и та же в форме записи животного и в карточке происхождения,
 * и разойдясь однажды, она сообщала бы, что это два разных поля.
 *
 * Меняется именно подпись, а не поле: кровность считают в любой книге,
 * меняется только то, по какой породе. У многопородной книги улучшающая
 * порода у каждого животного своя, и назвать её в общей подписи нельзя.
 */
export const bloodLabel = (t: Tenant): string =>
  t.breed ? `Кровность ${t.breed.blood}, %` : 'Кровность по улучшающей породе, %'
