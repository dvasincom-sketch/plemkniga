/**
 * Чья это книга.
 *
 * ## Зачем понадобилось
 *
 * Книга писалась под одну организацию, и это правильно: продукт, который
 * с первого дня «для всех», обычно не годится никому. Но принадлежность
 * растворилась в коде — знак, имя, самарский адрес, телефон, почта,
 * правовые документы, государственный учёт и порода лежат вперемешку
 * с механикой учёта, в восьми файлах реквизиты и в шести десятках ФГИАС.
 *
 * Пока книга одна, это незаметно. Как только рядом встаёт вторая —
 * демонстрационная, английская, без России и без голштинов, — выясняется,
 * что убирать нечего: убирать пришлось бы по одному вхождению, и каждое
 * следующее изменение возвращало бы их обратно.
 *
 * Здесь собрано всё, что отвечает на вопрос «чья книга», и ничего,
 * что отвечает на вопрос «как считать». Разделение проходит ровно
 * по этой черте: правила подсчёта индекса, разбор родословной, проверки
 * сходимости — общие, они не зависят от того, чья книга. Имя на бланке,
 * государственный реестр и порода — зависят.
 *
 * ## Почему по хосту, а не по настройке сборки
 *
 * Соблазн был поставить переменную окружения и собирать два образа.
 * Так нельзя: тогда «одна система, две книги» превращается в две системы,
 * которые расходятся при первой же правке, — а именно этого мы и избегаем.
 * Хост читается на каждый запрос, и обе книги живут из одного кода.
 *
 * ## Чего здесь нарочно нет
 *
 * Списка хозяйств, пользователей и данных. Настройка говорит, чья книга,
 * а не что в ней лежит: данные разводятся базой и правами, и подменять
 * это настройкой значило бы завести второй, более слабый способ
 * отгородить чужое поголовье от посторонних.
 */

export type TenantKey = 'holstein' | 'demo'

export type Tenant = {
  key: TenantKey

  /**
   * Организация, ведущая книгу.
   *
   * `short` — как её называют в тексте («Ассоциация»), `full` — как она
   * подписывается на документах. Раздельно, потому что в предложении
   * «вопросы по членству — в Ассоциацию» полное имя не читается,
   * а на племенном свидетельстве короткое не имеет силы.
   */
  org: {
    short: string
    full: string
    address: string | null
    /** Как показывать и как звонить: `+7 846 931-25-95` против `+78469312595`. */
    phone: { text: string; href: string } | null
    mail: string
    telegram: string | null
    /**
     * Имя для знака, разбитое на строки вручную.
     *
     * Не выводится из `full` переносом по словам: у знака ширина задана
     * рисунком, и машинный перенос ломает его на четыре строки там, где
     * человек разбил бы на три. Строк ровно столько, сколько влезает.
     */
    mark: string[]
  }

  /**
   * Государственный учёт.
   *
   * `fgias` — российский ФГИАС ПР. `null` — книга не отчитывается
   * государству вовсе; такое бывает не только у демонстрации:
   * в Армении и Киргизии государственного реестра племенных животных
   * попросту нет (см. `docs/strany-eaes.md`).
   *
   * Это не признак «показывать раздел», а признак «есть ли такая
   * обязанность». Разница существенная: из неё следует и меню,
   * и выгрузки, и то, обязательно ли поле УНСМ.
   */
  state: 'fgias' | null

  /**
   * Порода, если книга ведётся по одной.
   *
   * `null` — многопородная книга. Это не то же самое, что «порода
   * неизвестна»: у многопородной книги порода есть у каждого животного,
   * просто она не предопределена книгой и её выбирают при записи.
   *
   * `blood` — та самая форма из подписи «Кровность по голштину, %».
   * Она хранится целым словом, а не выводится из `name`, и это
   * не лень: русский требует здесь дательного падежа от другой основы —
   * «голштинская» даёт «по голштину», а не «по голштинской». Вывести это
   * правилом нельзя, склеивать строку из корня и окончания — верный
   * способ получить «по симментальску» у следующей породы. Три слова,
   * записанные руками, честнее любого правила.
   *
   * У многопородной книги подпись становится «Кровность по улучшающей
   * породе, %»: кровность там считают тоже, но улучшающая порода
   * у каждого животного своя.
   */
  breed: { code: string; name: string; blood: string } | null

  /**
   * Правовые документы организации: политика конфиденциальности
   * и политика обработки. Они называют конкретное юридическое лицо
   * с конкретным ИНН, и показывать их от имени другой книги нельзя —
   * это было бы ложным обещанием, данным от чужого имени.
   */
  legal: boolean

  /** Язык интерфейса книги. */
  lang: 'ru' | 'en'
}

