/**
 * Разбор чисел и дат из чужой таблицы.
 *
 * ## Зачем отдельный модуль
 *
 * Разбор жил двумя короткими функциями внутри `actions/data.ts`, и обе
 * возвращали `undefined` на всём, чего не поняли. Возвращать «не знаю»
 * тем же значением, каким обозначена пустая ячейка, — и есть тот способ,
 * которым книга теряла данные молча: «3,85 %» в колонке жира давало
 * `undefined`, поле оставалось пустым, строка принималась, и в сводке
 * стояло «обновлено 500». Никакой ошибки, никакого следа, и найти это
 * потом можно только вручную, сверяя карточки с файлом.
 *
 * Поэтому здесь разбор отвечает парой: что получилось и что не получилось.
 * Пустая ячейка и непонятая ячейка — разные ответы, а не один.
 *
 * Отдельным файлом, а не рядом с загрузкой, по двум причинам. Первая:
 * `actions/data.ts` помечен `'use server'`, и наружу оттуда разрешено
 * отдавать только асинхронные функции — синхронный разбор пришлось бы
 * держать без `export`, то есть без проверки. Вторая: проверку на этот
 * разбор хочется гонять без базы и без сети, а `check:import-values`
 * так и устроен.
 *
 * ## Чего этот модуль намеренно не делает
 *
 * Не переводит единицы. «Удой 8,5» в тоннах и «удой 8,5» в тысячах
 * килограммов выглядят одинаково, и догадаться, что имелось в виду,
 * нельзя ничем, кроме разговора с хозяйством. Система, которая угадала
 * неверно и промолчала, хуже той, которая записала как есть: во втором
 * случае число хотя бы совпадает с файлом. Единицы — вопрос сопоставления
 * колонок, а не разбора значения.
 */

/** Что получилось и что не получилось. Оба поля пустые — ячейка пустая. */
export type Parsed<T> = { value?: T; problem?: string }

/**
 * Написания, которыми в выгрузках обозначают «не заполнено».
 *
 * Список важен ровно тем, что эти значения **не** ошибка. Прочерк
 * в колонке жира означает, что жир не мерили, и жаловаться на него значит
 * завалить протокол приёмки сотней строк, в которых всё в порядке, —
 * а в таком протоколе перестают искать настоящие ошибки.
 *
 * `00.00.0000` и `0000-00-00` сюда же: так пустую дату пишет СЕЛЭКС.
 * До этой правки первое из них не просто не распознавалось — оно
 * попадало под шаблон «день.месяц.год», уходило в `new Date('0000-00-00')`
 * и роняло `toISOString` с `RangeError`, то есть валило разбор всего
 * файла на строке, где по смыслу просто ничего не заполнено.
 */
const BLANKS = new Set([
  '',
  '-',
  '--',
  '–',
  '—',
  '.',
  '?',
  'н/д',
  'н.д.',
  'нд',
  'нет данных',
  'нет',
  '#н/д',
  '#n/a',
  'n/a',
  'na',
  'null',
  'nan',
  'undefined',
  '00.00.0000',
  '00/00/0000',
  '0000-00-00',
])

const isBlank = (s: string) => BLANKS.has(s.toLowerCase())

/*
 * Пробелы, которыми разделяют тысячи.
 *
 * Обычный `\s` в JS уже покрывает неразрывный пробел и узкий неразрывный,
 * но полагаться на это не хочется: правило это неочевидное, оно тут
 * ключевое, и читающий код обязан видеть, что о неразрывном пробеле
 * подумали. Перечисление стоит рядом с `\s`, а не вместо него.
 */
const SPACES = /[\s    ﻿]/g

/**
 * Число из ячейки.
 *
 * ## Про знак процента
 *
 * «3,85 %» в колонке «Жир, %» — это 3,85, а не ошибка: знак повторяет
 * единицу, уже названную в заголовке. Раньше `Number('3,85%')` давал `NaN`,
 * и значение исчезало целиком. Отрезается только хвостовой процент;
 * «кг», «т» и прочие единицы не отрезаются намеренно — отрезать их значило
 * бы утверждать, что число уже в наших единицах, а мы этого не знаем.
 *
 * ## Про запятую
 *
 * Одна запятая считается десятичной: так пишет русский Excel, и «3,85»
 * в колонке жира встречается на порядок чаще, чем «3,85» в значении
 * трёх тысяч восьмисот пятидесяти. Разбирать её как разделитель тысяч
 * было бы точнее для англоязычных выгрузок и катастрофой для наших:
 * жирность 3,85 стала бы 385 процентов, и это ровно тот вид ошибки,
 * который проходит все проверки диапазона на удое и не проходит ни одной
 * на жире — то есть замечается через месяц.
 *
 * Когда в числе есть и запятая, и точка, десятичным считается тот знак,
 * что стоит правее: так однозначно читаются и `10.458,5`, и `10,458.5`.
 */
export function parseNumber(raw: string | undefined): Parsed<number> {
  const s = (raw ?? '').trim()
  if (isBlank(s)) return {}

  /*
   * Ошибка формулы приходит текстом ячейки (`#ДЕЛ/0!`, `#ССЫЛКА!`) —
   * так её отдаёт чтение книги, и это сделано нарочно, чтобы поломка
   * в файле не превращалась в пустую клетку. Здесь она и называется.
   * `#Н/Д` в этот разбор не попадает: оно выше объявлено пустотой.
   */
  if (s.startsWith('#')) return { problem: `ошибка формулы в ячейке: ${s}` }

  let t = s.replace(SPACES, '')

  if (t.endsWith('%')) t = t.slice(0, -1)

  const lastComma = t.lastIndexOf(',')
  const lastDot = t.lastIndexOf('.')

  if (lastComma >= 0 && lastDot >= 0) {
    const thousands = lastComma > lastDot ? '.' : ','
    t = t.split(thousands).join('')
    t = t.replace(',', '.')
  } else if (lastComma >= 0) {
    t = t.replace(',', '.')
  }

  /*
   * Показатель степени принимается: в чужих выгрузках он попадается
   * следом округления, а числа он не портит. Длинный номер животного,
   * доехавший до нас как `1,23E+11`, сюда не попадает вовсе — номер
   * разбирается как текст, и превращать его в число здесь было бы
   * худшим, что можно сделать.
   */
  if (!/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(t))
    return { problem: `«${s}» — не число` }

  const n = Number(t)
  if (!Number.isFinite(n)) return { problem: `«${s}» — не число` }

  return { value: n }
}

/* ------------------------------------------------------------------ */

const pad = (n: number) => String(n).padStart(2, '0')

/**
 * Год, до которого не бывает живых записей, и год, после которого
 * не бывает записей вовсе.
 *
 * Нижняя граница нужна не ради изящества. Шаблоны ФГИАС ПР во всех
 * строках-примерах несут дату `1111-11-01`, и хозяйство, забывшее удалить
 * пример перед загрузкой, заводило бы животное, рождённое в двенадцатом
 * веке. Верхняя ловит опечатку в веке — `3026` вместо `2026`.
 *
 * Порог 1900 выбран как заведомо недостижимый: самая старая запись,
 * которая может понадобиться, — предок в родословной, и глубже начала
 * двадцатого века родословные не ведутся.
 */
const YEAR_MIN = 1900
const yearMax = () => new Date().getUTCFullYear() + 1

/**
 * Век для двузначного года.
 *
 * `26` — это 2026, а `85` — это 1985. Граница по двадцать девятому году
 * выбрана не произвольно: до неё лежат даты, которые встречаются в файлах
 * как настоящие (тёлка две тысячи двадцать шестого года), после неё —
 * только предки в родословной. Живого животного тридцатых годов не бывает,
 * а предок девяностых — обычное дело.
 *
 * Считать всё двухтысячными было бы проще и предсказуемее, но предок
 * 1998 года стал бы 2098-м, то есть датой из будущего; проверка «отёл
 * не раньше рождения» такую дату иногда пропускает, и в книге появилось
 * бы животное, родившееся позже собственного потомка.
 */
const century = (yy: number) => (yy <= 29 ? 2000 + yy : 1900 + yy)

/**
 * Дата — строкой `ГГГГ-ММ-ДДT00:00:00.000Z`.
 *
 * ## Почему `Date.parse` убран целиком
 *
 * Он разбирал ISO и врал на всём остальном, причём врал молча и
 * по-разному. `5.03.2026` он читал по американскому порядку и выдавал
 * второе мая. `март 2026` он вообще-то понимал — как тридцать первое
 * декабря две тысячи двадцать пятого. `45731` превращал в год сорок пять
 * тысяч семьсот тридцатый. Ни один из трёх случаев не давал ни ошибки,
 * ни следа в протоколе.
 *
 * Здесь разбираются только те написания, которые названы; всё прочее
 * возвращается с причиной. Это скучнее и длиннее, но у длины есть
 * свойство, которого нет у `Date.parse`: каждое принимаемое написание
 * видно в коде.
 *
 * ## Почему сборка идёт через `Date.UTC`, а не через строку
 *
 * Первый вариант собирал `new Date(\`${y}-${m}-${d}T00:00:00.000Z\`)`
 * и на этом же проверял существование дня — и не проверял: `2026-02-31`
 * такой конструктор отдаёт как «недействительная дата», а `2026-02-30`
 * в некоторых средах молча переносит на второе марта. Поэтому день
 * проверяется обратным ходом: собрали через `Date.UTC`, разобрали
 * геттерами `getUTC*` и сверили, те ли числа вернулись. Часовых поясов
 * в этом пути нет ни на одном шаге — урок из разбора книг Excel, где
 * местные геттеры однажды сдвинули дату рождения на сутки.
 */
export function parseDate(raw: string | undefined): Parsed<string> {
  const s = (raw ?? '').trim()
  if (isBlank(s)) return {}
  if (s.startsWith('#')) return { problem: `ошибка формулы в ячейке: ${s}` }

  let y: number | undefined
  let m: number | undefined
  let d: number | undefined

  /* ISO, в том числе со временем: так приходят и наши выгрузки, и ФГИАС. */
  const iso = /^(\d{4})-(\d{1,2})-(\d{1,2})(?:[T ].*)?$/.exec(s)
  if (iso) {
    y = Number(iso[1])
    m = Number(iso[2])
    d = Number(iso[3])
  }

  /*
   * Русское написание — и с точками, и через косую, и через дефис.
   * Порядок всегда «день, месяц, год»: файлы приходят из русских программ
   * учёта, и месяц впереди в них не встречается. Написание `03/15/2026`
   * с пятнадцатым месяцем поэтому не переставляется молча, а называется
   * ошибкой — переставить его значило бы принять решение за того, кто
   * единственный знает, что имелось в виду.
   */
  if (!iso) {
    const ru = /^(\d{1,2})[./-](\d{1,2})[./-](\d{2}|\d{4})$/.exec(s)
    if (ru) {
      d = Number(ru[1])
      m = Number(ru[2])
      const yy = Number(ru[3])
      y = ru[3].length === 2 ? century(yy) : yy
    }
  }

  /*
   * Серийный номер Excel. Возникает, когда книгу пересохранили в CSV:
   * дата в тексте остаётся числом дней от 30 декабря 1899 года.
   *
   * Принимаются только пятизначные и шестизначные: четырёхзначное число
   * в колонке даты — это почти наверняка год, а не 16 июля 1905-го,
   * и молча прочитать его датой значило бы завести ту же ошибку с другой
   * стороны. Год без дня и месяца поэтому называется отдельно.
   */
  if (y === undefined && /^\d{4}$/.test(s)) {
    return { problem: `«${s}» — только год, без дня и месяца` }
  }

  if (y === undefined && /^\d{5,6}$/.test(s)) {
    const serial = Number(s)
    if (serial >= 1 && serial <= 2958465) {
      const at = new Date(Date.UTC(1899, 11, 30) + serial * 86400000)
      y = at.getUTCFullYear()
      m = at.getUTCMonth() + 1
      d = at.getUTCDate()
    }
  }

  if (y === undefined || m === undefined || d === undefined)
    return { problem: `«${s}» — не дата` }

  const at = new Date(Date.UTC(y, m - 1, d))
  if (at.getUTCFullYear() !== y || at.getUTCMonth() !== m - 1 || at.getUTCDate() !== d)
    return { problem: `«${s}» — такого дня нет в календаре` }

  if (y < YEAR_MIN || y > yearMax())
    return { problem: `«${s}» — год ${y} не похож на настоящий` }

  return { value: `${y}-${pad(m)}-${pad(d)}T00:00:00.000Z` }
}
