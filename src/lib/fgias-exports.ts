/**
 * Какие шаблоны ФГИАС ПР книга отдаёт кнопкой.
 *
 * ## Один список на карточку и на обработчик
 *
 * Та же беда, что была у форматов выгрузки (`export-formats.ts`): карточка
 * обещала пять форматов, обработчик умел два, и разойтись им было негде,
 * кроме как разойтись. Здесь список один с самого начала: из него
 * собираются и кнопки в кабинете, и разбор параметра в ручке. Пообещать
 * шаблон, которого нет, стало нельзя.
 *
 * ## Почему только тринадцать из двадцати
 *
 * Остальные семь книга либо не заполнит вовсе, либо заполнит
 * настолько частично, что файл не примут. Опись по всем двадцати живёт
 * на вкладке «ФГИАС ПР» в эволюции продукта — там ей и место: это
 * ответ на вопрос «что будет», а здесь кнопки на то, что есть.
 *
 * ## Порядок не алфавитный
 *
 * «Основные сведения» стоят первыми, потому что без них остальные
 * шаблоны пусты: базовые номера животных приходят обратным файлом
 * только после их сдачи. Список читается как порядок работ, и это его
 * главное свойство.
 */

