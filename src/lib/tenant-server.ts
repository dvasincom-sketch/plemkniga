import { headers } from 'next/headers'
import { type Tenant, tenantFor } from '@/lib/tenant'

/**
 * Книга текущего запроса.
 *
 * ## Почему отдельный файл
 *
 * `next/headers` работает только на сервере: файл, который его подключает,
 * нельзя внести в клиентский компонент — сборка развалится, причём
 * с сообщением про совсем другое место. А само описание книг
 * (`lib/tenant.ts`) нужно и на клиенте, и в проверках, и в промежуточном
 * обработчике на краю сети, где `next/headers` тоже нет.
 *
 * Поэтому чистые данные лежат там, а чтение заголовка — здесь. Первая
 * редакция держала всё в одном файле, и первый же клиентский компонент,
 * которому понадобилось имя организации, уронил сборку.
 *
 * ## Про статические страницы
 *
 * Обращение к заголовкам делает страницу динамической — она перестаёт
 * собираться заранее. Плата здесь почти нулевая: из пятидесяти четырёх
 * страниц книги пятьдесят одна и так динамическая, потому что смотрит,
 * кто вошёл. Оставшиеся три — правовые документы и «Эволюция продукта»,
 * и как раз им знать книгу необходимо: политика конфиденциальности
 * называет юридическое лицо поимённо, и показывать её от имени другой
 * книги нельзя.
 */
export const currentTenant = async (): Promise<Tenant> => {
  const h = await headers()
  return tenantFor(h.get('host'))
}
