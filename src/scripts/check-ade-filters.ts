import { DATE_FIELD, halfAnimalPair, parseAdeQuery } from '@/lib/ade/query'
import { ADE_COLLECTIONS } from '@/lib/ade/core'

/**
 * Разбор фильтров выборки — на настоящих именах стандарта.
 *
 * ## Что здесь ломается молча
 *
 * Фильтр со своим именем. Он работает, прогоны зелёные, а клиент
 * по стандарту им воспользоваться не может: он присылает
 * `meta-modified-from`, мы ждём `modifiedSince`, параметр уходит
 * в незнакомые — и партнёр получает всю книгу вместо изменённого
 * за сутки. Ошибки при этом нет ни у кого: ответ верный, просто
 * не тот, о котором просили.
 *
 * Ровно так у нас и было. Имена теперь берутся из объявлений
 * `components/parameters` в схемах адресов ICAR, и этот прогон стоит,
 * чтобы они оттуда не уехали.
 *
 * ## Почему проверка не ходит в базу
 *
 * Разбор строки запроса — чистое превращение текста в условия,
 * и проверять его надо там, где это дёшево. Применение условий
 * к данным проверяется живым прогоном; здесь — только то, что из адреса
 * получилось ровно ожидаемое.
 *
 *   npm run check:ade-filters
 */

const fails: string[] = []
const fail = (m: string) => fails.push(m)

const q = (search: string) => parseAdeQuery(new URL(`https://example.test/x?${search}`))

/* ------------------------------------------------------------------ *
 *  Имена — из стандарта                                              *
 * ------------------------------------------------------------------ */

const STANDARD: [search: string, check: (r: ReturnType<typeof q>) => boolean, what: string][] = [
  [
    'meta-modified-from=2026-04-01T00:00:00Z',
    (r) => r.modifiedFrom === '2026-04-01T00:00:00.000Z',
    'начало диапазона по дате изменения',
  ],
  [
    'meta-modified-to=2026-05-01T00:00:00Z',
    (r) => r.modifiedTo === '2026-05-01T00:00:00.000Z',
    'конец диапазона по дате изменения',
  ],
  ['date-from=2026-04-01', (r) => Boolean(r.dateFrom), 'начало диапазона по дате события'],
  ['date-to=2026-04-30', (r) => Boolean(r.dateTo), 'конец диапазона по дате события'],
  [
    'animal-id=1234567890&animal-scheme=ru.holstein-russia.animal',
    (r) => r.animal?.id === '1234567890' && r.animal.scheme === 'ru.holstein-russia.animal',
    'пара «идентификатор + схема»',
  ],
  ['page=3&pageSize=50', (r) => r.page === 3 && r.pageSize === 50, 'страница и размер'],
]

for (const [search, check, what] of STANDARD) {
  if (!check(q(search))) fail(`«${search}» не разобралось — ${what}`)
}

/*
 * Наше прежнее имя не должно работать молча. Оно не в списке известных,
 * значит обязано попасть в незнакомые и быть названным клиенту, —
 * иначе тот, кто писал под старое поведение, не узнает, что фильтр
 * перестал действовать.
 */
if (!q('modifiedSince=2026-04-01').unknown.includes('modifiedSince')) {
  fail('«modifiedSince» не назван незнакомым — старый клиент не узнает, что фильтр не работает')
}

console.log(`Имён стандарта разобрано: ${STANDARD.length}`)

/* ------------------------------------------------------------------ *
 *  Границы диапазона                                                 *
 * ------------------------------------------------------------------ */

/*
 * `from` включается, `to` — нет. Проверяется не значением, а тем,
 * что оба конца вообще разбираются: перепутанные включения ловятся
 * живым прогоном, а здесь — потеря конца диапазона, после которой
 * выборка молча становится открытой справа.
 */
const both = q('meta-modified-from=2026-01-01T00:00:00Z&meta-modified-to=2026-02-01T00:00:00Z')
if (!both.modifiedFrom || !both.modifiedTo) fail('оба конца диапазона не разобрались вместе')

/* Негодная дата — не значение, а отсутствие: иначе выборка отдаст пустоту. */
if (q('meta-modified-from=вчера').modifiedFrom !== undefined) {
  fail('негодная дата принята — выборка отдала бы пустоту без объяснения')
}

/* ------------------------------------------------------------------ *
 *  Половина пары                                                     *
 * ------------------------------------------------------------------ */

const HALF: [search: string, half: boolean][] = [
  ['animal-id=123', true],
  ['animal-scheme=ru.holstein-russia.animal', true],
  ['animal-id=123&animal-scheme=ru.holstein-russia.animal', false],
  ['', false],
]

for (const [search, half] of HALF) {
  const got = halfAnimalPair(new URL(`https://example.test/x?${search}`))
  if (got !== half) fail(`«${search || '(пусто)'}»: половина пары — ${got}, ожидалось ${half}`)
}

/* Половина пары не должна давать фильтр по животному. */
if (q('animal-id=123').animal) {
  fail('«animal-id» без схемы дал фильтр — номер без схемы не определяет животное')
}

console.log(`Случаев с парой «идентификатор + схема»: ${HALF.length + 1}`)

/* ------------------------------------------------------------------ *
 *  Поле даты у каждой коллекции                                      *
 * ------------------------------------------------------------------ */

/*
 * У каждой отдаваемой коллекции должно быть решено, по какому полю
 * идёт `date-from`. Забытая коллекция означает, что фильтр по ней
 * молча не работает: клиент просит апрель, получает всё.
 *
 * `null` — законный ответ: у животного нет даты события вовсе.
 * Но он должен быть записан, а не отсутствовать.
 */
for (const c of ADE_COLLECTIONS) {
  if (!(c in DATE_FIELD)) {
    fail(`у коллекции «${c}» не решено, по какому полю идёт date-from — фильтр молча не сработает`)
  }
}

console.log(`Коллекций с решённым полем даты: ${Object.keys(DATE_FIELD).length}`)

/* ------------------------------------------------------------------ */

if (fails.length) {
  console.log('')
  for (const f of fails) console.log(`  ✗ ${f}`)
  process.exit(1)
}

console.log('\n  ✓ фильтры разбираются по именам стандарта')
process.exit(0)
