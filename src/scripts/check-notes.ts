import { existsSync, readFileSync } from 'node:fs'
import { NOTES } from '@/lib/notes'
import { BASE_SOURCE } from '@/lib/index-base-source'
import { TRAIT_BASE } from '@/lib/breeding-index'

/**
 * Разборы: страница на месте, паспорт заполнен, источники ведут наружу.
 *
 * ## Что здесь может сломаться молча
 *
 * Разбор существует в двух местах сразу: строкой в списке (`lib/notes.ts`)
 * и страницей под своим адресом. Список показывается всем, страница —
 * только тому, кто нажал. Разъехаться они могут в обе стороны, и обе
 * тихие: строка без страницы даёт «страница не найдена» тому, кого мы
 * позвали читать; страница без строки лежит в сети, куда никто не ведёт.
 *
 * ## Почему проверяются источники, а не только их наличие
 *
 * Разбор без работающей ссылки на первоисточник — тот самый пересказ,
 * от которого весь раздел и отличается (`docs/kontent-plan.md`). Сетевая
 * доступность здесь не проверяется: чужой сайт может лежать, и падать
 * из-за этого своей проверкой значит поставить свою сборку в зависимость
 * от чужого хостинга. Проверяется то, за что отвечаем мы: ссылка есть,
 * она внешняя и сказано, что именно по ней взято.
 *
 * ## Один адрес — одно название
 *
 * Шесть разборов ссылались на общую посадочную страницу руководств ICAR
 * и подписывали её пятью разными названиями разделов: «Section 2 —
 * Identification and recording of young stock», «Section 2 — Disposal
 * and culling reasons», «Section 5 — Milk recording and reproduction
 * data». Ни одного из этих разделов у ICAR нет: раздел 2 называется
 * «Cattle Milk Recording», раздел 5 — «Conformation Recording».
 * Читатель, пошедший по ссылке, попадал в общий список и решал,
 * что не нашёл нужное место сам.
 *
 * Сетевой доступности проверка по-прежнему не касается, но одно
 * несоответствие ловится без сети: один и тот же адрес, подписанный
 * по-разному. Настоящий источник, процитированный дважды, называется
 * одинаково; разные названия у одного URL означают, что название
 * придумано под нужду страницы.
 *
 * ## Что проверяется у базы сравнения
 *
 * Что происхождение описано у всех признаков базы. Полноту гарантирует
 * и язык (`Record<TraitKey, …>`), но проверка ловит второй случай,
 * которого язык не видит: признак, выброшенный из базы и забытый
 * в описании источника, — то есть строку про число, которого больше нет.
 */

const PAGES = 'src/app/(frontend)/site/[locale]/razbory'

let failures = 0
const fail = (text: string) => {
  failures += 1
  console.log(`  ✗ ${text}`)
}

const today = new Date().toISOString().slice(0, 10)

for (const note of NOTES) {
  const page = `${PAGES}/${note.slug}/page.tsx`

  if (!existsSync(page)) {
    fail(`${note.slug} — есть в списке, страницы нет: ${page}`)
    continue
  }

  const src = readFileSync(page, 'utf8')
  /* Страница знает свой слуг сама: расхождение здесь ломает метатеги. */
  if (!src.includes(`const SLUG = '${note.slug}'`)) {
    fail(`${note.slug} — страница называет себя иначе, чем список`)
  }

  if (note.passport.length < 3) fail(`${note.slug} — паспорт короче трёх строк`)
  if (!note.author) fail(`${note.slug} — разбор без имени автора`)
  if (note.date > today) fail(`${note.slug} — дата разбора в будущем: ${note.date}`)
  if (note.sources.length === 0) fail(`${note.slug} — разбор без источников`)

  for (const s of note.sources) {
    if (!s.url?.startsWith('https://')) fail(`${note.slug} — источник без внешней ссылки: ${s.title}`)
    if (!s.what) fail(`${note.slug} — не сказано, что взято из источника: ${s.title}`)
  }

  /*
   * Надёжность оценки не называется достоверностью.
   *
   * «Достоверность» в книге занято: так называется уровень доверия
   * к записи — черновик, заявлено хозяйством, подтверждено лабораторией,
   * верифицировано Ассоциацией. Это про то, кто ручается за данные,
   * и к числу дочерей отношения не имеет. Разбор о R звал ту же величину
   * достоверностью шесть десятков раз, тогда как словарь, поля карточки
   * и расчёт зовут её надёжностью, — и читатель, встретив оба слова,
   * не имел способа понять, что это разные величины.
   *
   * Ловится именно связка «достоверность оценки», а не слово вообще:
   * «уровень достоверности» и шаблон реестра «Достоверность
   * происхождения» законны и должны остаться.
   */
  const clash = /достоверност\w*\s+(оценк|прогноз)/i.exec(src)
  if (clash) {
    fail(
      `${note.slug} — «${clash[0]}»: надёжность оценки в книге называется надёжностью, ` +
        'а достоверность — это уровень доверия к записи',
    )
  }

  /*
   * Обязательный раздел жанра — «чего разбор не доказывает». Он не в данных,
   * а на странице, и проверяется по тексту: правило про него записано
   * в `docs/kontent-plan.md` и в шапке `lib/notes.ts`, а забыть его легче
   * всего именно потому, что страница без него выглядит законченной.
   */
  if (!/не\s+доказывает/.test(src)) {
    fail(`${note.slug} — на странице нет раздела «чего это не доказывает»`)
  }

  console.log(`  ✓ ${note.slug}`)
}

/* ------------------- Один адрес — одно название ------------------------- */

const titleByUrl = new Map<string, { title: string; slug: string }>()
for (const note of NOTES) {
  for (const src of note.sources) {
    if (!src.url) continue
    const seen = titleByUrl.get(src.url)
    if (!seen) {
      titleByUrl.set(src.url, { title: src.title, slug: note.slug })
      continue
    }
    if (seen.title !== src.title) {
      fail(
        `один адрес под двумя названиями: «${seen.title}» (${seen.slug}) ` +
          `и «${src.title}» (${note.slug}) — ${src.url}`,
      )
    }
  }
}

/* --------------------- Происхождение чисел базы --------------------------- */

const keys = new Set(TRAIT_BASE.map((t) => t.key))
for (const key of Object.keys(BASE_SOURCE)) {
  if (!keys.has(key as never)) fail(`Описан источник для признака «${key}», а в базе его нет`)
}

console.log(
  failures === 0
    ? `\nРазборов: ${NOTES.length}, все со страницей, паспортом и источниками.`
    : `\nНеувязок: ${failures}`,
)
process.exit(failures === 0 ? 0 : 1)
