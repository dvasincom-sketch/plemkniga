import { readFileSync } from 'node:fs'
import { AREA_LABEL, AREA_ORDER, CHECKS } from '@/lib/check-registry'
import { PROBE_CODES } from '@/lib/probes'

/**
 * Реестр проверок против того, что вправду можно запустить.
 *
 * ## Из-за чего появилась
 *
 * Пять проверок жили мимо реестра: заведены в `package.json`, работают,
 * а на странице состояния их нет и `check:all` про них не знает.
 *
 * Это хуже отсутствующей проверки. Отсутствующая честна: её нет, и видно,
 * что её нет. А страница состояния показывала полный на вид список
 * и молчала о том, что список неполон, — при том, что вся её польза
 * в ответе на вопрос «всё ли проверено». Человек читал «тридцать одна
 * проверка, все зелёные» и понимал это как «книга проверена», хотя пять
 * правил никто не спрашивал.
 *
 * ## Почему расхождение возникает само
 *
 * Проверка заводится в один приём: пишется скрипт, добавляется строка
 * в `package.json`, запускается. Всё работает — и на этом останавливаются.
 * Реестр нужен не автору, а читателю страницы, и потому забывается
 * ровно тем, кто мог бы его пополнить.
 *
 * ## Что сверяется
 *
 * В обе стороны. Проверка без записи в реестре — невидимка. Запись
 * без проверки — обещание запуска, который упадёт «команда не найдена»
 * в самый неподходящий момент, потому что реестр читают, когда что-то
 * уже случилось.
 *
 * Отдельно — признак `probe`. Он говорит странице состояния, что проверку
 * умеет прогнать само приложение и потому она попадает в ночной прогон.
 * Реализация пробы живёт в другом файле (`lib/probes.ts`), и связаны они
 * только именем: поставить признак и забыть написать пробу можно, и тогда
 * ночной прогон каждую ночь отчитывается находкой «такой пробы нет» —
 * то есть проверка выглядит красной по причине, к данным отношения
 * не имеющей. Обратное расхождение тише и хуже: написанная проба,
 * не объявленная в реестре, не гоняется вовсе, а страница обещает,
 * что гоняется.
 *
 *   npm run check:registry
 */

const fails: string[] = []
const fail = (m: string) => fails.push(m)

/*
 * `check:all` — не проверка, а тот, кто их запускает. Держать его
 * в реестре значило бы показать на странице состояния строку «прогнать
 * всё», которую человек и нажимает, глядя на эту страницу.
 */
const RUNNERS = new Set(['check:all'])

const pkg = JSON.parse(readFileSync('package.json', 'utf8')) as {
  scripts?: Record<string, string>
}

const all = Object.keys(pkg.scripts ?? {})
const checks = all.filter((n) => n.startsWith('check:'))
const registered = CHECKS.map((c) => c.code)

/*
 * Вперёд смотрим только на `check:*`. Обратно — на все команды разом:
 * в реестре законно живут `doctor`, `smoke` и ревизии `audit:*`,
 * которые проверками называются по существу, а по имени нет. Первая
 * редакция сверяла обе стороны по одной выборке `check:*` и объявила
 * восемь настоящих команд несуществующими — проверка была наведена
 * не туда, а не реестр сломан.
 */
for (const name of checks) {
  if (RUNNERS.has(name)) continue
  if (!registered.includes(name)) {
    fail(`«${name}» запускается, но в реестре её нет — на странице состояния она невидима`)
  }
}

for (const code of registered) {
  if (!all.includes(code)) {
    fail(`«${code}» есть в реестре, но такой команды нет — обещание запуска, которого не будет`)
  }
}

/* Дубли: две записи об одной проверке дадут две строки на странице. */
const seen = new Set<string>()
for (const code of registered) {
  if (seen.has(code)) fail(`«${code}» записан в реестре дважды`)
  seen.add(code)
}

/*
 * Разделы. Запись с разделом, которого нет в порядке вывода, просто
 * не нарисуется — молча, без ошибки, и проверка снова станет невидимкой.
 */
for (const c of CHECKS) {
  if (!AREA_ORDER.includes(c.area)) fail(`«${c.code}»: раздел «${c.area}» не выводится на странице`)
  if (!AREA_LABEL[c.area]) fail(`«${c.code}»: у раздела «${c.area}» нет подписи`)
}

/*
 * Признак `probe` против того, что вправду написано в `lib/probes.ts`.
 */
const probes = new Set(PROBE_CODES)
for (const c of CHECKS) {
  if (c.probe && !probes.has(c.code)) {
    fail(`«${c.code}»: объявлена пробой, а пробы нет — ночной прогон найдёт «такой пробы нет»`)
  }
}
for (const code of probes) {
  const spec = CHECKS.find((c) => c.code === code)
  if (!spec) fail(`проба «${code}» написана, а записи в реестре нет — её никто не запускает`)
  else if (!spec.probe) fail(`«${code}»: проба написана, но в реестре не объявлена — не гоняется`)
}

/*
 * Описание. Пустое `what` оставляет на странице заголовок без объяснения,
 * а вся затея была в том, чтобы читающий понял правило, не открывая код.
 */
for (const c of CHECKS) {
  if (!c.what.trim()) fail(`«${c.code}»: нет описания`)
  if (!c.title.trim()) fail(`«${c.code}»: нет названия`)
}

console.log(`Команд check:* — ${checks.length}, из них запускающих — ${RUNNERS.size}`)
console.log(`Записей в реестре — ${registered.length}, из них проб — ${probes.size}`)
console.log(
  `По разделам: ${AREA_ORDER.map(
    (a) => `${AREA_LABEL[a]} ${CHECKS.filter((c) => c.area === a).length}`,
  ).join(', ')}`,
)

if (fails.length) {
  console.log('')
  for (const f of fails) console.log(`  ✗ ${f}`)
  process.exit(1)
}

console.log('\n  ✓ реестр проверок совпадает с тем, что можно запустить')
process.exit(0)
