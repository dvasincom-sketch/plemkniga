import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import {
  DEMO_HOST,
  DEMO_READY,
  PRODUCT_MAIL,
  SHARED_PATHS,
  SITE_HOSTS,
  SITE_PREFIX,
  isSharedPath,
  isSiteHost,
  isProductAsset,
  localeless,
  redirectToSite,
  rewriteToSite,
} from '@/lib/hosts'

/**
 * Разведение доменов — без поднятого сервера.
 *
 * ## Почему это нельзя оставить без прогона
 *
 * Промежуточный обработчик работает только там, где есть настоящий
 * заголовок `Host`, то есть на боевых доменах. На своей машине книга
 * открывается по `localhost`, витринная ветка не включается вовсе,
 * и ошибка в ней не проявляется ни разу за всю разработку — она ждёт
 * выкладки.
 *
 * Хуже того, ошибка тут не падает, а **показывает не то**. Перепутанный
 * хост означает витрину вместо кабинета: человек, который каждый день
 * заходит вносить отёлы, видит рекламную страницу и решает, что систему
 * сломали.
 *
 * ## Что здесь ломается молча
 *
 * **Двойная приставка.** Внутренний переход на `/site/ru` без проверки
 * превратился бы в `/site/site/ru`. Ловится только на боевом домене
 * и только вторым щелчком — первый-то открывает страницу нормально.
 *
 * **Порт в заголовке.** На своей машине хост приходит как
 * `plem.online:3000`, и сравнение целиком не сходится. Тот, кто
 * поднимет витрину локально, получит книгу и потратит вечер.
 *
 * **Регистр.** Заголовок `Host` регистронезависим, и браузеры этим
 * пользуются.
 *
 * **Косая черта на корне.** `/` обязан стать `/site`, а не `/site/`:
 * это разные адреса для поисковика, и второй потянет за собой
 * перенаправление, ради избавления от которого всё и затевалось.
 *
 *   npm run check:hosts
 */

const fails: string[] = []
const fail = (m: string) => fails.push(m)

/* ------------------------------------------------------------------ *
 *  Опознание хоста                                                   *
 * ------------------------------------------------------------------ */

const SITE: [host: string, why: string][] = [
  ['plem.online', 'основной домен витрины'],
  ['www.plem.online', 'он же с www'],
  ['PLEM.ONLINE', 'заголовок Host регистронезависим'],
  ['plem.online:3000', 'с портом — так приходит на своей машине'],
  ['WWW.Plem.Online:443', 'регистр и порт разом'],
]

const BOOK: [host: string, why: string][] = [
  ['holstein.plem.online', 'книга — не витрина'],
  ['holstein.plem.online:3000', 'книга с портом'],
  ['dvasincom-sketch-plemkniga-6202.twc1.net', 'старый адрес книги'],
  ['localhost:3000', 'своя машина'],
  ['', 'пустой заголовок'],
  /*
   * Похожий, но чужой домен. Проверка нужна: сравнение по вхождению
   * подстроки — обычная ошибка в таких списках, и `plem.online.evil.ru`
   * прошло бы её насквозь.
   */
  ['plem.online.evil.ru', 'чужой домен с нашим именем внутри'],
  ['notplem.online', 'чужой домен, оканчивающийся на наш'],
]

for (const [host, why] of SITE) {
  if (!isSiteHost(host)) fail(`«${host}» не опознан как витринный (${why})`)
}

for (const [host, why] of BOOK) {
  if (isSiteHost(host)) fail(`«${host}» опознан как витринный, а не должен (${why})`)
}

if (!isSiteHost(null) === false) fail('пустой хост опознан как витринный')

console.log(`Домены витрины: ${SITE_HOSTS.join(', ')}`)
console.log(`Проверено заголовков Host: ${SITE.length + BOOK.length + 1}`)

/* ------------------------------------------------------------------ *
 *  Превращение адреса                                                *
 * ------------------------------------------------------------------ */

const REWRITE: [from: string, to: string | null, why: string][] = [
  ['/', SITE_PREFIX, 'корень без косой черты на конце'],
  ['/ru', '/site/ru', 'язык'],
  ['/kk', '/site/kk', 'другой язык'],
  ['/about', '/site/about', 'произвольный путь'],
  ['/a/b/c', '/site/a/b/c', 'вложенный путь'],
  [SITE_PREFIX, null, 'уже витринный — не трогать'],
  /*
   * Файлы из public/. Из-за их отсутствия здесь витрина не отдавала
   * ни одного собственного файла — включая знак, лежащий там с первого
   * дня, — и обнаружилось это только через видео, которое страница
   * показывала, а сервер не отдавал.
   */
  ['/logo.svg', null, 'знак — файл, а не страница'],
  ['/product/demo.mp4', null, 'запись работы'],
  ['/product/demo-poster.jpg', null, 'заставка записи'],
  ['/scalar-theme.css', null, 'оформление справочника'],
  ['/scalar/standalone.js', null, 'файл во вложенной папке'],
  /*
   * Обратный случай, ради которого список расширений не сплошной:
   * машинное описание интерфейса — страница, а не файл, и его адрес
   * обязан переписаться, иначе интегратор получит 404 там, где мы
   * обещаем обмен.
   */
  ['/api-docs/openapi.json', '/site/api-docs/openapi.json', 'описание собирается, а не лежит'],
  ['/site/ru', null, 'уже витринный с языком'],
  ['/site/a/b', null, 'уже витринный, вложенный'],
]

for (const [from, to, why] of REWRITE) {
  const got = rewriteToSite(from)
  if (got !== to) fail(`«${from}» → ${got}, ожидалось ${to} (${why})`)
}

/* ------------------------------------------------------------------ *
 *  Старые адреса без языка                                           *
 * ------------------------------------------------------------------ */

/*
 * Вложенные адреса без языка отвечали «страница не найдена»: заглушки
 * стояли только у верхних страниц раздела. Проверяется здесь потому же,
 * почему и остальное в этом файле, — обработчик не запустить без
 * поднятого сервера, а функцию можно.
 */
const LEGACY: [from: string, to: string | null, why: string][] = [
  ['/razbory/baza-sravneniya', '/ru/razbory/baza-sravneniya', 'разбор по старой ссылке'],
  ['/fgias/otel', '/ru/fgias/otel', 'страница шаблона'],
  ['/breeds/golshtinskaya', '/ru/breeds/golshtinskaya', 'страница породы'],
  ['/slovar/servis-period', '/ru/slovar/servis-period', 'статья словаря'],
  ['/rules', '/ru/rules', 'верхняя страница раздела'],
  ['/ru/rules', null, 'язык уже назван'],
  ['/en/breeds/holstein', null, 'язык уже назван, вложенный'],
  ['/tour', null, 'страница без языковых копий'],
  ['/evolution', null, 'страница без языковых копий'],
  ['/ade/v1/datasets', null, 'машинный обмен — не страница витрины'],
  ['/logo.svg', null, 'файл, а не страница'],
  ['/animals/123', null, 'адрес книги, не витрины'],
]

for (const [from, to, why] of LEGACY) {
  const got = localeless(from)
  if (got !== to) fail(`«${from}» → ${got}, ожидалось ${to} (${why})`)
}

/* Двойная приставка: то, ради чего проверка на «уже витринный» и стоит. */
const once = rewriteToSite('/ru')
if (once && rewriteToSite(once) !== null) {
  fail('повторное превращение дало вторую приставку — будет /site/site/ru')
}

/*
 * Похожий, но другой путь. `/sitemap.xml` начинается с тех же букв,
 * что и приставка, и наивная проверка `startsWith('/site')` сочла бы
 * его уже витринным — то есть перестала бы отдавать карту сайта.
 */
if (rewriteToSite('/sitemap.xml') !== '/site/sitemap.xml') {
  fail('«/sitemap.xml» принят за витринный путь: проверка приставки без разделителя')
}
if (rewriteToSite('/sites') !== '/site/sites') {
  fail('«/sites» принят за витринный путь')
}

/*
 * Материалы витрины. Их отличие от прочей статики в том, что на домене
 * книги они не отдаются вовсе: запись работы в кабинете — рассказ
 * о продукте, и под именем Ассоциации она выглядит чужой.
 *
 * Отдельно проверяется похожее начало: «/products/…» — не наша папка,
 * и наивная проверка вхождения увела бы такой адрес с домена книги
 * неизвестно куда.
 */
const PRODUCT: [path: string, yes: boolean, why: string][] = [
  ['/product/demo.mp4', true, 'запись работы'],
  ['/product/demo-poster.jpg', true, 'заставка записи'],
  ['/product/', true, 'сама папка'],
  ['/products/cow.jpg', false, 'другое слово, начинается так же'],
  ['/logo.svg', false, 'знак книги — общий'],
  ['/product', false, 'без косой черты это уже не папка'],
]

for (const [path, yes, why] of PRODUCT) {
  if (isProductAsset(path) !== yes) {
    fail(`«${path}»: материал витрины ${isProductAsset(path)}, ожидалось ${yes} (${why})`)
  }
}

console.log(`Проверено превращений адреса: ${REWRITE.length + 3}`)

/* ------------------------------------------------------------------ *
 *  Сквозные страницы                                                 *
 * ------------------------------------------------------------------ */

/*
 * «Соответствие», карта ICAR и описание интерфейса переехали
 * на витринный домен. На домене книги их старые адреса должны уводить
 * туда, а всё остальное — оставаться на месте.
 *
 * Ошибка здесь тихая и злая в обе стороны. Слишком широкое правило
 * уведёт на витрину кабинет хозяйства; слишком узкое оставит
 * на домене книги вторую копию страницы соответствия — а она обязана
 * быть одна, иначе разойдётся при первой правке.
 */
const SHARED: [path: string, why: string][] = [
  ['/compliance', 'сама страница'],
  ['/icar', 'карта разделов'],
  ['/icar/gaps', 'вложенная страница разбора'],
  ['/api-docs', 'описание интерфейса'],
  ['/api-docs/openapi.json', 'машинное описание внутри неё'],
  ['/tour', 'английская экскурсия по книге'],
  ['/ade', 'чем проверяется обмен'],
  /*
   * «Эволюция продукта» переехала на витрину вместе со страницей.
   * Раньше этот случай стоял в списке «не сквозных» с пометкой
   * «страница книги, а не продукта» — и был бы поводом отменить переезд,
   * если бы проверка судила о правильности. Она судит о согласии кода
   * с решением; решение изменилось, и случай переехал вместе с файлом.
   */
  ['/evolution', 'рассказ о системе, а не о голштинской книге'],
  ['/org', 'кто содержит платформу'],
  ['/fgias', 'разбор двадцати шаблонов реестра'],
  ['/rules', 'каталог правил проверки'],
  ['/economics', 'разбор экономического индекса'],
]

const NOT_SHARED: [path: string, why: string][] = [
  ['/', 'корень книги'],
  ['/account', 'кабинет хозяйства'],
  ['/account/ranking', 'раздел кабинета'],
  ['/association/herds', 'кабинет Ассоциации'],
  ['/privacy', 'правовой документ Ассоциации'],
  /*
   * Похожие по началу, но чужие. Наивная проверка вхождения приняла бы
   * их за сквозные и увела бы с домена книги неизвестно куда.
   */
  ['/compliance-report', 'другое слово, начинается так же'],
  ['/icarus', 'другое слово, начинается так же'],
  ['/api-docsets', 'другое слово, начинается так же'],
  ['/tourism', 'другое слово, начинается так же'],
  ['/adept', 'другое слово, начинается так же'],
  ['/organizations', 'другое слово, начинается так же'],
  ['/evolutionary', 'другое слово, начинается так же'],
  ['/rulesets', 'другое слово, начинается так же'],
  ['/economicsummary', 'другое слово, начинается так же'],
  ['/breedstock', 'другое слово, начинается так же'],
  /*
   * Машинные адреса внутри сквозных. Слово в пути то же, хозяин другой:
   * `/ade` рассказывает о проверке обмена и живёт на витрине, `/ade/v1`
   * и есть обмен — с данными книги, правами на её локации и токенами,
   * выданными на её домене.
   *
   * Правило «всё, что внутри сквозного, тоже сквозное» уводило обмен
   * на витрину постоянным перенаправлением: интегратор получал 404
   * после перехода, а выглядело это как «в книге ничего нет». Заодно
   * 308 сохраняет метод, и клиент, следующий за перенаправлением сам,
   * отправил бы токен книги на чужой домен.
   */
  ['/ade/v1', 'сам обмен, а не страница о нём'],
  ['/ade/v1/locations', 'перечень локаций обмена'],
  ['/ade/v1/locations/ru.holstein-russia.orgid/1/test-day-results', 'выдача обмена'],
  ['/ade/v1/batches/locations/ru.holstein-russia.orgid/1/weights', 'пакетный приём'],
]

for (const [path, why] of SHARED) {
  if (!isSharedPath(path)) fail(`«${path}» не опознан как сквозной (${why})`)

  const away = redirectToSite(path)
  const expected = `https://${SITE_HOSTS[0]}${path}`
  if (away !== expected) {
    fail(`«${path}» уводит на ${away}, ожидалось ${expected} (${why})`)
  }
}

/* ------------------------------------------------------------------ *
 *  Показательный домен закрыт, пока за ним нет своих данных          *
 * ------------------------------------------------------------------ */

/*
 * Приложение одно, база одна: открытый демонстрационный домен показывает
 * настоящую книгу Ассоциации. Один раз это уже случилось — в день,
 * когда домен заработал. Правило слишком дорогое, чтобы держать его
 * в голове, поэтому оно проверяется здесь.
 */
if (DEMO_READY) {
  console.log('  · DEMO_READY выставлен: демонстрационный домен отдаёт книгу, а не заглушку')
} else if (!DEMO_HOST) {
  fail('домен показательной книги не задан — заслонке не за чем следить')
}

for (const [path, why] of NOT_SHARED) {
  if (isSharedPath(path)) fail(`«${path}» опознан как сквозной, а не должен (${why})`)
  if (redirectToSite(path) !== null) fail(`«${path}» уводит с домена книги, а должен остаться (${why})`)
}

/*
 * На витринном домене сквозная страница переписывается, как и всё
 * остальное: она физически лежит под `site/`. Проверка на случай,
 * если кто-нибудь решит «сквозные не трогаем» и выключит переписывание
 * для них — тогда `plem.online/compliance` перестанет находиться вовсе.
 */
for (const [path] of SHARED) {
  if (rewriteToSite(path) !== `${SITE_PREFIX}${path}`) {
    fail(`на витрине «${path}» не переписывается в ${SITE_PREFIX}${path}`)
  }
}

console.log(
  `Сквозных путей: ${SHARED_PATHS.length}, ` +
    `проверено адресов: ${SHARED.length + NOT_SHARED.length}`,
)

/* ------------------------------------------------------------------ *
 *  Почта продукта                                                    *
 * ------------------------------------------------------------------ */

/*
 * Витрина не должна писать на почту Ассоциации: в самом домене её ящика
 * стоят имя страны и породы, и хозяйство из другой страны читает адрес
 * как «это решение не про меня» — при том, что письмо идёт разработчику.
 *
 * Проверяется по дереву витрины целиком, а не по одному файлу: адрес
 * стоит в четырёх местах — две кнопки, подвал витрины и подвал страниц
 * продукта, — и вернуть старый можно в любое из них.
 */
const siteTree = 'src/app/(frontend)/site'
const shellFile = 'src/components/site/ProductShell.tsx'

for (const dir of [siteTree, shellFile]) {
  const files: string[] = []
  const walk = (p: string) => {
    if (statSync(p).isDirectory()) {
      for (const e of readdirSync(p)) walk(join(p, e))
      return
    }
    if (p.endsWith('.tsx') || p.endsWith('.ts')) files.push(p)
  }
  walk(dir)

  for (const file of files) {
    const text = readFileSync(file, 'utf8')
    if (text.includes('holstein-russia')) {
      fail(`${file}: витрина пишет на почту Ассоциации, а должна на ${PRODUCT_MAIL}`)
    }
  }
}

if (!PRODUCT_MAIL.endsWith(`@${SITE_HOSTS[0]}`)) {
  fail(`почта продукта «${PRODUCT_MAIL}» не на витринном домене`)
}

console.log(`Почта продукта: ${PRODUCT_MAIL}`)

/* ------------------------------------------------------------------ */

if (fails.length) {
  console.log('')
  for (const f of fails) console.log(`  ✗ ${f}`)
  process.exit(1)
}

console.log('\n  ✓ домены разводятся верно, приставка не удваивается')
process.exit(0)
