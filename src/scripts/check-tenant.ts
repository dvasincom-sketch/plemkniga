import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { DEMO_HOST } from '@/lib/hosts'
import { TENANTS, tenantFor } from '@/lib/tenant'

/**
 * Принадлежность книги отделена от системы.
 *
 * ## Что здесь ломается молча
 *
 * Реквизиты возвращаются в код сами. Не злым умыслом: правя страницу,
 * проще вписать телефон рядом, чем вспомнить, что он берётся из настройки.
 * Одно такое вхождение ничего не ломает у голштинской книги — она этот
 * телефон и показывает, — а у показательной книги выставляет чужой
 * самарский номер посреди английской страницы. Заметить это можно только
 * открыв вторую книгу, то есть почти никогда.
 *
 * Поэтому проверка идёт от обратного: она берёт реквизиты **из самой
 * настройки** и ищет их по дереву. Ни один из них не выписан здесь
 * буквами — иначе проверка спотыкалась бы о собственный текст, а заодно
 * разошлась бы с настройкой при первой же правке реквизитов.
 *
 * ## Про комментарии
 *
 * Комментарии вычищаются перед поиском. Рассказать в пояснении, что здесь
 * раньше стоял самарский адрес, — законно и полезно; проверка, которая
 * на это ругается, заставляет стирать объяснения.
 *
 *   npm run check:tenant
 */

const fails: string[] = []
const fail = (m: string) => fails.push(m)

const { holstein, demo } = TENANTS

/* ------------------------------------------------------------------ *
 *  Опознание книги по хосту                                          *
 * ------------------------------------------------------------------ */

const DEMO_HOSTS: [host: string, why: string][] = [
  [DEMO_HOST, 'домен показательной книги'],
  [DEMO_HOST.toUpperCase(), 'заголовок Host регистронезависим'],
  [`${DEMO_HOST}:3000`, 'с портом — так приходит на своей машине'],
]

const BOOK_HOSTS: [host: string, why: string][] = [
  ['holstein.plem.online', 'действующая книга'],
  ['plem.online', 'витрина — книгу отсюда не открывают, но падать нельзя'],
  ['localhost:3000', 'своя машина'],
  ['', 'пустой заголовок'],
  /*
   * Похожие, но чужие. Сравнение по вхождению подстроки — обычная ошибка
   * в таких списках, и любой из этих хостов прошёл бы её насквозь,
   * получив показательную книгу вместо голштинской.
   */
  [`${DEMO_HOST}.evil.ru`, 'чужой домен с нашим именем внутри'],
  [`not${DEMO_HOST}`, 'чужой домен, оканчивающийся на наш'],
  ['demo.plem.online.attacker.test', 'поддельный поддомен'],
]

for (const [host, why] of DEMO_HOSTS) {
  if (tenantFor(host).key !== 'demo') fail(`«${host}» не опознан как показательная книга (${why})`)
}

for (const [host, why] of BOOK_HOSTS) {
  if (tenantFor(host).key !== 'holstein') {
    fail(`«${host}» опознан как показательная книга, а не должен (${why})`)
  }
}

if (tenantFor(null).key !== 'holstein') fail('пустой хост не даёт голштинскую книгу')

console.log(`Проверено заголовков Host: ${DEMO_HOSTS.length + BOOK_HOSTS.length + 1}`)

/* ------------------------------------------------------------------ *
 *  Показательная книга — без России и без породы                     *
 * ------------------------------------------------------------------ */

/*
 * Это и была постановка задачи: «тот же holstein, только без специфики
 * России и без конкретной породы». Здесь она записана исполнимо.
 */
if (demo.state !== null) fail('у показательной книги есть государственный учёт')
if (demo.breed !== null) fail('показательная книга привязана к породе')
if (demo.legal) fail('показательная книга обещает правовые документы, которых нет')
if (demo.lang !== 'en') fail('показательная книга не по-английски')
if (demo.org.address || demo.org.phone) {
  fail('у показательной книги выдуманные реквизиты — доверие к странице держится на их отсутствии')
}

/*
 * Кириллица в именах показательной книги. Отдельная проверка, потому что
 * поле можно заполнить «правильно по смыслу» и по-русски разом: «Демо-книга»
 * прошло бы все условия выше и встало бы в заголовок английской страницы.
 */
const CYRILLIC = /[А-Яа-яЁё]/
for (const [field, value] of Object.entries({
  short: demo.org.short,
  full: demo.org.full,
  mark: demo.org.mark.join(' '),
})) {
  if (CYRILLIC.test(value)) fail(`показательная книга: «${field}» по-русски — «${value}»`)
}

console.log(`Показательная книга: ${demo.org.full}, ${demo.org.mail}`)

/* ------------------------------------------------------------------ *
 *  Реквизиты не вписаны в код                                        *
 * ------------------------------------------------------------------ */

/*
 * Иголки берутся из настройки: ни один реквизит не выписан в этом файле,
 * и менять его при смене телефона не придётся.
 *
 * Слово «Ассоциация» само по себе в список не входит намеренно. Оно
 * встречается в двух с лишним сотнях файлов и почти везде законно:
 * «Ассоциация» — это роль в системе, тот, кто ведёт книгу, а не имя
 * конкретной организации. Ловим только то, что однозначно принадлежит
 * одному юридическому лицу.
 */
const NEEDLES: [needle: string, what: string][] = [
  [holstein.org.full, 'полное имя организации'],
  [holstein.org.address ?? '', 'почтовый адрес'],
  [holstein.org.phone?.text ?? '', 'телефон'],
  [holstein.org.phone?.href ?? '', 'телефон для набора'],
  [holstein.org.mail, 'почта организации'],
  /*
   * Подпись кровности. Иголка узкая нарочно: имя породы само по себе
   * встречается в разборе аналитики законно — там оно называет
   * популяцию, по которой взята литературная матрица корреляций,
   * то есть источник данных, а не хозяина книги. А вот дательная форма
   * «по голштину» бывает ровно в одном месте — в подписи к полю,
   * и в книге другой породы она стала бы неправдой.
   */
  [holstein.breed?.blood ?? '', 'подпись кровности'],
]

/*
 * Настройка книг — единственное место, где реквизиты стоять обязаны.
 * Сид наполняет базу и тоже называет организацию по имени: это данные,
 * а не разметка, и они уедут вместе с базой, а не с кодом.
 */
const ALLOWED = [
  'src/lib/tenant.ts',
  'src/seed/',
  'src/migrations/',
  'payload-types.ts',
  /*
   * Правовые документы называют юридическое лицо, и это их содержание,
   * а не оформление. Подставлять имя из настройки нельзя: получился бы
   * чужой текст со своим именем на нём — документ, которого никто
   * не писал. Взамен обе страницы отвечают «не найдено» у книги без
   * юридического лица (`legal`), то есть содержимое недостижимо.
   */
  'src/app/(frontend)/privacy/page.tsx',
  'src/app/(frontend)/data-policy/page.tsx',
  /*
   * Витрина называет действующую книгу по имени намеренно: «на ней ведёт
   * книгу такая-то ассоциация» — это довод в пользу продукта, факт о мире,
   * а не реквизит нашей книги. Только в русском наборе строк; следит
   * за этим check:i18n, у которого своё правило про отсылки к стране.
   */
  'src/lib/i18n/',
  /*
   * Псевдонимы загрузки. «кровность по голштину» здесь не подпись,
   * а то, что мы **понимаем**: так называют колонку в файлах, которые
   * хозяйства присылают годами. Убрать псевдоним — перестать принимать
   * эти файлы, то есть сломать загрузку ради опрятности.
   */
  'src/lib/import-format.ts',
  /*
   * Тексты витрины — тот же случай, что и наборы строк выше, только
   * лежат они не в `i18n`. Витрина рассказывает о продукте и называет
   * действующую книгу по имени намеренно: «на ней ведёт книгу такая-то
   * ассоциация» — довод в пользу продукта, а не реквизит нашей книги.
   * Нарисованный экран показывает ту же книгу, и подпись поля на нём —
   * часть картинки; словарь объясняет, что означает подпись «кровность
   * по голштину» у действующей книги.
   *
   * Граница проходит не по папке, а по назначению: это страницы о том,
   * как устроен продукт, и подставлять в них имя из настройки значило бы
   * заставить показательную книгу рассказывать о себе то, чего с ней
   * не было.
   */
  'src/lib/breeds-page-text.ts',
  'src/lib/book-screens-text.ts',
  'src/lib/terms/',
  'src/app/(frontend)/demo-soon/page.tsx',
]

/** Комментарии заменяются пробелами: длина строки сохраняется, текст исчезает. */
const stripComments = (t: string): string =>
  t
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/\/\/[^\n]*/g, (m) => m.replace(/[^\n]/g, ' '))

const files: string[] = []
const walk = (p: string) => {
  if (statSync(p).isDirectory()) {
    for (const e of readdirSync(p)) walk(join(p, e))
    return
  }
  if (p.endsWith('.ts') || p.endsWith('.tsx')) files.push(p)
}
walk('src')

let scanned = 0
for (const file of files) {
  if (ALLOWED.some((a) => file.startsWith(a) || file.endsWith(a))) continue
  if (file.startsWith('src/scripts/')) continue

  scanned += 1
  /*
   * Пробелы схлопываются перед поиском.
   *
   * Реквизит в разметке переносится на другую строку сколько угодно раз,
   * и поиск по точной строке его не находил: «Ассоциации производителей
   * КРС\n голштинской породы» — то же имя, а для `includes` другое.
   * Ровно так мимо прогона прошли два места, включая страницу о самой
   * системе, которую показывают на всех доменах.
   */
  const text = stripComments(readFileSync(file, 'utf8')).replace(/\s+/g, ' ')

  for (const [needle, what] of NEEDLES) {
    if (needle && text.includes(needle.replace(/\s+/g, ' '))) {
      fail(`${file}: ${what} вписан в код — должен браться из настройки книги`)
    }
  }
}

console.log(`Просмотрено файлов: ${scanned}, реквизитов: ${NEEDLES.filter(([n]) => n).length}`)

/* ------------------------------------------------------------------ *
 *  Государственный реестр — за заслонкой                             *
 * ------------------------------------------------------------------ */

/*
 * ФГИАС ПР — российская обязанность, а не свойство племенного учёта.
 * Всё, что его показывает, обязано сперва спросить книгу.
 *
 * Правило намеренно грубое: «упоминаешь реестр — читаешь книгу». Оно
 * не проверяет, что заслонка поставлена верно, — этого текстом
 * не проверить. Оно ловит другое, и более частое: новую страницу
 * с выгрузкой или новым полем реестра, про которую просто забыли.
 * Забыть здесь легко, потому что у голштинской книги всё работает.
 *
 * Витрина исключена: она рассказывает про реестр как про свойство
 * продукта, а не показывает его данные.
 */
const STATE_WORD = 'ФГИАС'
let guarded = 0

for (const file of files) {
  if (!file.startsWith('src/app/')) continue
  if (file.startsWith('src/app/(frontend)/site/')) continue

  /*
   * Смотрим и на имя файла. Выгрузка живёт по адресу `export/fgias`,
   * а в самом коде слово «ФГИАС» стоит только в пояснениях — которые
   * отсюда вычищены. Проверка по одному тексту прошла бы мимо
   * единственного места, откуда данные реестра уходят наружу.
   */
  const text = stripComments(readFileSync(file, 'utf8'))
  const named = file.toLowerCase().includes('fgias')
  if (!named && !text.includes(STATE_WORD)) continue

  guarded += 1
  if (!text.includes('currentTenant')) {
    fail(`${file}: показывает государственный реестр, не спросив, чья книга`)
  }
}

console.log(`Страниц с государственным реестром: ${guarded}`)

/* ------------------------------------------------------------------ */

if (fails.length) {
  console.log('')
  for (const f of fails) console.log(`  ✗ ${f}`)
  process.exit(1)
}

console.log('\n  ✓ принадлежность книги отделена от системы')
process.exit(0)
