import { copyFileSync, existsSync, mkdirSync, statSync } from 'node:fs'
import path from 'node:path'

/**
 * Положить справочник API (Scalar) в `public/scalar`.
 *
 * ## Почему свой файл, а не CDN
 *
 * Страница с внешним скриптом перестаёт работать ровно тогда, когда
 * до внешнего адреса не дотянуться, — а система разворачивается
 * в хозяйствах и ведомствах, где до половины интернета не дотягиваются
 * штатно. Документация API, которая открывается не у всех, — это
 * документация, на которую нельзя сослаться.
 *
 * У этого правила есть продолжение, о котором легко забыть: сама
 * библиотека по умолчанию тянет из своей сети два шрифта, Inter
 * и JetBrains Mono. Поэтому в настройке справочника стоит
 * `withDefaultFonts: false`, а шрифт задаётся наш — тот, что уже
 * загружен книгой. Файл без CDN и шрифты с CDN — это половина решения,
 * и работает она ровно до первого отключённого интернета.
 *
 * ## Почему один файл
 *
 * У Scalar есть сборка для браузера, в которой стили встроены в скрипт:
 * `dist/browser/standalone.js`. Отдельной таблицы стилей нет вовсе, значит
 * нет и порядка подключения, который можно перепутать, — а с Swagger UI
 * мы на этом порядке как раз и стояли.
 *
 * ## Почему это шаг сборки, а не файл в репозитории
 *
 * Скопированный в репозиторий, он стал бы третьей копией библиотеки —
 * рядом с записью в package.json и содержимым node_modules — и первая же
 * смена версии оставила бы его прежним. Здесь источник один: пакет.
 *
 * Запускается автоматически перед `dev` и `build`. Если пакета нет,
 * скрипт не падает: страница `/api-docs` умеет сказать об этом сама
 * и увести к описанию в формате JSON, которое от библиотеки не зависит.
 */

const SOURCE = 'node_modules/@scalar/api-reference/dist/browser/standalone.js'
const TARGET_DIR = 'public/scalar'
const TARGET_NAME = 'standalone.js'

const from = path.resolve(process.cwd(), SOURCE)
const to = path.resolve(process.cwd(), TARGET_DIR)

if (!existsSync(from)) {
  console.warn(
    '[plemkniga] @scalar/api-reference не установлен — страница /api-docs покажет ' +
      'ссылку на описание в формате JSON вместо интерактивного справочника. ' +
      'Установить: npm i @scalar/api-reference',
  )
  process.exit(0)
}

mkdirSync(to, { recursive: true })
copyFileSync(from, path.join(to, TARGET_NAME))

/*
 * Размер печатается намеренно. Библиотека браузерная и грузится по запросу,
 * то есть на память контейнера не влияет вовсе, — но она приезжает
 * к человеку, и знать, сколько именно, надо до того, как об этом скажет
 * хозяйство с мобильным интернетом.
 */
const kb = Math.round(statSync(path.join(to, TARGET_NAME)).size / 1024)
console.log(`[plemkniga] Scalar: ${TARGET_DIR}/${TARGET_NAME}, ${kb} КБ`)
