/**
 * Проверочные файлы на чужие форматы — генератор.
 *
 * ## Зачем генератор, а не файлы руками
 *
 * Половина набора двоичная: книга Excel, windows-1251, UTF-16 с меткой
 * порядка байтов. Такие файлы нельзя ни прочитать в обзоре правок,
 * ни поправить в редакторе, ни объяснить в отзыве. А главное — нельзя
 * доверять: файл в 1251, собранный вслепую, легко оказывается файлом
 * в бессмыслице, и проверка на нём проходит по случайности.
 *
 * Здесь каждый байт получается из кода, который видно. Правку набора
 * видно в обзоре, а сами файлы лежат в репозитории рядом и открываются
 * человеком — они и есть предмет проверки.
 *
 * ## Чем отличается от `data/proverka`
 *
 * Тот набор — для ручной проверки через интерфейс: семь файлов, все
 * в UTF-8 с точкой с запятой, и ломают они данные. Этот ломает **разбор**:
 * кодировку, разделитель, положение шапки, служебные строки, листы книги.
 * Пересечение одно — файл `04` того набора, и оно намеренное: там ловушки
 * внутри строки, здесь вокруг неё.
 *
 *   npm run make:proverka-formaty
 */

const DIR = 'data/proverka-formaty'

/**
 * Строка в байтах windows-1251.
 *
 * Таблицей, а не `Buffer.from(s, 'latin1')`: latin1 пересаживает кириллицу
 * не туда, и вышел бы файл не в 1251, а в бессмыслице — на котором
 * проверка прошла бы, ничего не проверив. Тот же приём, что в `check:csv`.
 */
const toWin1251 = (s: string): Uint8Array => {
  const out: number[] = []
  for (const ch of s) {
    const c = ch.codePointAt(0)!
    if (c < 0x80) out.push(c)
    else if (c >= 0x410 && c <= 0x44f) out.push(c - 0x410 + 0xc0)
    else if (c === 0x401) out.push(0xa8)
    else if (c === 0x451) out.push(0xb8)
    else if (c === 0x2116) out.push(0xb9)
    else if (c === 0x00ab) out.push(0xab)
    else if (c === 0x00bb) out.push(0xbb)
    else out.push(0x3f)
  }
  return Uint8Array.from(out)
}

/** UTF-16LE с меткой порядка байтов — «Текст Юникод» в списке форматов Excel. */
const toUtf16le = (s: string): Uint8Array => {
  const out = new Uint8Array(2 + s.length * 2)
  out[0] = 0xff
  out[1] = 0xfe
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i)
    out[2 + i * 2] = c & 0xff
    out[3 + i * 2] = c >> 8
  }
  return out
}

const files: { name: string; bytes: Uint8Array | Buffer; what: string }[] = []

const text = (name: string, body: string, what: string, enc: 'utf8' | 'bom' = 'utf8') =>
  files.push({
    name,
    bytes: new TextEncoder().encode(enc === 'bom' ? '﻿' + body : body),
    what,
  })

