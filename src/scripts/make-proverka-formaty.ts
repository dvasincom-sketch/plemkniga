function main() {
  mkdirSync(DIR, { recursive: true })

  for (const f of files) {
    writeFileSync(join(DIR, f.name), f.bytes)
    console.log(`  ${f.name.padEnd(42)} ${f.what}`)
  }

  console.log(`\nЗаписано файлов: ${files.length} в ${DIR}\n`)
}

main()
