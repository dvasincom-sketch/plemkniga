import 'dotenv/config'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

/**
 * Проверка страницы `/api-docs` на живом сервере.
 *
 * ## Что здесь ломается молча
 *
 * Справочник — единственная страница книги, собранная из чужой библиотеки,
 * и всё, что с ней случается, случается тихо: она остаётся работоспособной
 * и просто перестаёт быть частью сайта.
 *
 * **Файл библиотеки может не доехать.** `public/scalar/` собирается перед
 * сборкой и в репозиторий не попадает, `public/scalar-theme.css` лежит
 * рядом и попадает. Достаточно один раз описать копирование в образ
 * по имени каталога, и библиотека останется на машине сборки.
 *
 * **Переменную палитры могут переименовать.** Цвета берутся из палитры
 * книги через `var(--color-…)`. `var()` с неизвестным именем — не ошибка,
 * а «значение не задано»: цвет тихо остаётся тем, что дала библиотека.
 *
 * **Может вернуться обращение наружу.** Библиотека по умолчанию тянет свои
 * шрифты из чужой сети и предлагает гонять пробные запросы через свой
 * прокси. Мы отключили и то и другое — но обе настройки живут в объекте,
 * который легко переписать, не заметив. Страница при этом работает: она
 * просто перестаёт открываться там, где до внешних адресов не дотянуться,
 * а токен хозяйства начинает ходить через чужой сервер.
 *
 * **Порядок слоёв может уехать.** Tailwind и Scalar раскладывают стили
 * по `@layer`, и приоритет браузер берёт из первого встреченного
 * объявления. Без нашей строки слои Scalar оказываются выше `utilities`
 * — и ломают не эту страницу, а соседние.
 *
 *   npm run check:api-docs
 *   BASE=https://… npm run check:api-docs
 */

const BASE = process.env.BASE ?? 'http://localhost:3000'

const TAG = 'CHK-API-DOCS'
let failures = 0

const check = (ok: boolean, what: string, detail = '') => {
  if (ok) console.log(`  ✓ ${what}`)
  else {
    failures += 1
    console.log(`  ✗ ${what}${detail ? ` — ${detail}` : ''}`)
  }
}

/**
 * Заголовок витринного домена в каждом запросе.
 *
 * Описание интерфейса переехало на витрину: физически оно лежит
 * под `site/`, а короткий адрес `/api-docs` собирает промежуточный
 * обработчик — но только когда в запросе стоит витринный `Host`.
 *
 * Без этого заголовка прогон, идущий на `localhost`, получил бы
 * перенаправление на боевой `plem.online` и проверял бы прод вместо
 * своей сборки — молча и с зелёным результатом.
 */
const SITE_HEADERS = { host: 'plem.online' }

const get = async (p: string) => {
  const res = await fetch(`${BASE}${p}`, { headers: SITE_HEADERS, redirect: 'manual' })
  return {
    status: res.status,
    /* Куда ведёт перенаправление: без этого «308» не отличить от «308 не туда». */
    location: res.headers.get('location'),
    body: res.ok ? await res.text() : '',
  }
}

const readLocal = (p: string) => readFile(path.resolve(process.cwd(), p), 'utf8')

async function main() {
  console.log(`${TAG}: страница справочника, ${BASE}\n`)

  /* ------------------------- файлы на месте ------------------------- */
  console.log('Файлы отдаются')

  const theme = await get('/scalar-theme.css')
  check(theme.status === 200, '/scalar-theme.css', `ответ ${theme.status}`)

  const lib = await get('/scalar/standalone.js')
  if (lib.status !== 200) {
    /*
     * Законное состояние: `copy-scalar` не падает, если пакета нет,
     * а страница умеет сказать об этом и увести к описанию в JSON.
     * Но молчать нельзя — иначе проверка оформления пройдёт на странице,
     * где оформлять нечего.
     */
    console.log(
      `  · библиотеки нет (/scalar/standalone.js → ${lib.status}); ` +
        'страница показывает ссылку на JSON, оформлять нечего',
    )
  } else {
    check(true, `/scalar/standalone.js (${Math.round(lib.body.length / 1024)} КБ)`)
  }

  /*
   * Короткий адрес и адрес страницы — разные вопросы, и оба стоит задать.
   *
   * `/api-docs` — старый адрес без языка: он обязан вести на русскую
   * копию постоянным перенаправлением (`localeless` в `lib/hosts.ts`).
   * Прогон ходит с `redirect: 'manual'` и потому видит сам ответ, а не
   * то, куда он привёл, — раньше это выглядело как «страница не отвечает».
   *
   * `/api-docs/openapi.json` языка не имеет вовсе: это файл описания,
   * который читают программы, и переброс его уводил бы в никуда.
   */
  const short = await get('/api-docs')
  check(
    short.status === 308 && (short.location ?? '').endsWith('/ru/api-docs'),
    'короткий адрес /api-docs ведёт на /ru/api-docs',
    `ответ ${short.status}${short.location ? ` → ${short.location}` : ''}`,
  )

  const page = await get('/ru/api-docs')
  check(page.status === 200, 'страница /ru/api-docs отвечает', `ответ ${page.status}`)
  const spec = await get('/api-docs/openapi.json')
  check(spec.status === 200, 'описание отдаётся', `ответ ${spec.status}`)

  /* ---------------------- ничего не тянется извне ---------------------- */
  console.log('\nСтраница ни к кому не ходит наружу')

  const component = await readLocal('src/components/ApiReference.tsx')
  check(
    /withDefaultFonts:\s*false/.test(component),
    'шрифты библиотеки отключены',
    'иначе Inter и JetBrains Mono приедут из чужой сети',
  )
  /*
   * Ищется присваивание, а не слово: в самом файле оно упоминается
   * объяснением, почему прокси не задан. Проверка, спотыкающаяся
   * о собственный комментарий, заставляет убрать комментарий — то есть
   * наказывает ровно за то, что нужно.
   */
  check(
    !/proxyUrl\s*:/.test(component),
    'прокси для пробных запросов не задан',
    'с ним токен хозяйства уходил бы на чужой сервер',
  )

  /* ---------------------- язык и чужая реклама ---------------------- */
  console.log('\nСправочник говорит по-русски и не рекламирует поставщика')

  check(/locale:\s*'ru'/.test(component), 'выбран русский словарь библиотеки')
  check(
    /showDeveloperTools:\s*'never'/.test(component),
    'панель разработчика выключена',
    'в ней живёт предложение платного тарифа',
  )
  check(
    /poweredByScalar:\s*''/.test(component),
    'подпись «Работает на Scalar» убрана переводом',
  )

  /*
   * Подписи, зашитые в разметку библиотеки, переписываются наблюдателем.
   * Проверяется здесь не то, что перевод красив, а то, что правило
   * ещё за что-то цепляется: обе строки взяты из бандла дословно,
   * и смена любой из них молча оставит на русской странице английское
   * место. Молча — потому что видно его только читалке либо тому, кто
   * дошёл до поля токена.
   */
  if (lib.status === 200) {
    check(
      lib.body.includes('QUxMIFlPVVIgQkFTRSBBUkUgQkVMT05HIFRPIFVT'),
      'заполнитель-шутка в поле токена ещё на месте и переписывается',
      'если строка изменилась — правило больше не срабатывает, надо обновить',
    )
    check(
      /Include \$\{[^}]+\} in request/.test(lib.body),
      'подписи флажков ещё вида «Include … in request»',
      'если формат изменился — правило больше не срабатывает, надо обновить',
    )
  }
  check(
    /QUxMIFlPVVIgQkFTRSBBUkUgQkVMT05HIFRPIFVT/.test(component),
    'правило подмены заполнителя описано',
  )
  check(
    /Include \(\.\+\) in request/.test(component),
    'правило подмены подписей флажков описано',
  )

  const themeSource = await readLocal('public/scalar-theme.css')
  check(
    /a\[href\*=['"]scalar\.com['"]\][\s\S]{0,80}display:\s*none/.test(themeSource),
    'ссылка на сайт поставщика скрыта',
    'без этого от неё осталась бы пустая нажимаемая область',
  )

  /*
   * И то же самое на живой странице — по словарю, а не по настройке.
   * Настройка может быть на месте, а библиотека — не понять её имени:
   * `showToolbar` она уже объявила устаревшим, и следующее переименование
   * пройдёт так же тихо. Русское слово в разметке означает, что словарь
   * не просто выбран, а применился.
   */
  if (lib.status === 200) {
    check(
      lib.body.includes('ru:{common:'),
      'русский словарь есть в самой библиотеке',
      'если его убрали из сборки, перевод молча вернётся к английскому',
    )
    check(
      /showDeveloperTools/.test(lib.body),
      'библиотека всё ещё знает про showDeveloperTools',
      'настройку могли переименовать — тогда панель вернётся',
    )
  }

  /*
   * И то же самое по факту — но проверяются загружаемые ресурсы, а не любые
   * внешние адреса в разметке.
   *
   * Сначала проверялось второе, и проверка падала на ссылке в подвале:
   * телеграм поддержки стоит на каждой странице книги и стоит законно.
   * Разница не в строгости, а в существе: `<a href>` — это предложение
   * человеку куда-то перейти, а `<script src>` и `<link href>` — это
   * загрузка, которая происходит сама и без которой страница не откроется.
   * «Страница ни к кому не ходит» — про второе.
   */
  const loaded = [
    ...page.body.matchAll(/<(?:script|link|img|iframe)\b[^>]*\b(?:src|href)="(https?:\/\/[^"]+)"/g),
  ]
    .map((m) => m[1])
    .filter((u) => new URL(u).host !== new URL(BASE).host)
  check(
    loaded.length === 0,
    'страница не загружает ничего с чужих адресов',
    loaded.join(', '),
  )

  /* --------------------------- порядок слоёв --------------------------- */
  console.log('\nПорядок слоёв объявлен до Tailwind')

  const globalsRaw = await readLocal('src/app/(frontend)/globals.css')

  /*
   * Комментарии вырезаются до поиска, и это не мелочь.
   *
   * Первая редакция искала `@import 'tailwindcss'` по всему файлу
   * и находила его в комментарии, который сама же и объясняет — тот стоит
   * выше объявления слоёв, и порядок получался перевёрнутым. Проверка
   * падала на исправном файле и требовала убрать объяснение, то есть
   * наказывала ровно за то, что нужно.
   *
   * Обиднее всего, что двадцатью строками выше в этом же файле записано
   * ровно это правило — про `proxyUrl`, — и написано оно было раньше.
   * Знать правило и не применить его во второй раз оказалось легко:
   * там оно было выводом из ошибки, здесь его надо было вспомнить.
   */
  const globals = globalsRaw.replace(/\/\*[\s\S]*?\*\//g, '')

  const layerAt = globals.indexOf('@layer scalar-base')
  const tailwindAt = globals.indexOf('@import')
  check(layerAt >= 0, 'объявление слоёв на месте')
  check(
    layerAt >= 0 && tailwindAt >= 0 && layerAt < tailwindAt,
    'слои объявлены раньше импорта Tailwind',
    'Tailwind при импорте объявляет порядок сам, и наш должен успеть первым',
  )
  for (const layer of ['scalar-base', 'scalar-theme', 'scalar-config', 'utilities']) {
    check(
      new RegExp(`@layer[^;]*\\b${layer}\\b`).test(globals),
      `слой ${layer} назван`,
    )
  }

  /* ------------- переменные палитры существуют в палитре ------------- */
  console.log('\nПеременные палитры объявлены в книге')

  const themeCss = theme.status === 200 ? theme.body : await readLocal('public/scalar-theme.css')
  const used = [...new Set([...themeCss.matchAll(/var\((--color-[a-z0-9-]+|--font-[a-z-]+)/g)].map((m) => m[1]))]
  check(used.length > 0, 'тема ссылается на переменные книги', `${used.length} имён`)

  const missing = used.filter((name) => !new RegExp(`${name}\\s*:`).test(globals))
  check(
    missing.length === 0,
    'каждое имя из темы объявлено в палитре',
    missing.length ? `не найдены: ${missing.join(', ')}` : '',
  )

  /* --------------------------- сама страница --------------------------- */
  console.log('\nСтраница не сводится к чужому справочнику')

  /*
   * Три сценария — то, ради чего страница переписана: список из девяноста
   * ручек отвечает тому, кто знает, что ищет, а приходят с задачей.
   * Если их однажды уберут «ради краткости», страница вернётся к тому,
   * с чего начинали, и заметить это по внешнему виду будет нельзя.
   */
  check(page.body.includes('С чего начать'), 'раздел со сценариями на месте')
  for (const word of ['Войти и получить токен', 'Выгрузить своё стадо', 'контрольную дойку']) {
    check(page.body.includes(word), `сценарий: ${word}`)
  }

  console.log(failures === 0 ? '\nВсё сошлось.' : `\nНе сошлось: ${failures}`)
  process.exit(failures === 0 ? 0 : 1)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
