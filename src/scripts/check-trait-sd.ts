import 'dotenv/config'
import { getPayload } from 'payload'
import config from '@payload-config'
import { poolOf } from '@/lib/sql'
import { TRAIT_BASE } from '@/lib/breeding-index'

/**
 * Стандартное отклонение признака: заявленное против измеренного.
 *
 * ## Зачем
 *
 * Индекс племенной ценности делит отклонение каждого признака на его
 * стандартное отклонение — тем самым приводя килограммы, месяцы и баллы
 * к одной шкале. Числа σ у нас заимствованные: они взяты из документа
 * CDCB и переведены в метрические единицы, и разбор базы сравнения
 * об этом говорит прямо.
 *
 * У двух признаков из одиннадцати перевода не было вовсе, и вместо него
 * стоит подстановка. Самая грубая — смертность приплода: в Net Merit
 * такого признака нет, есть живучесть коров (LIV, σ = 1,62 %) и живучесть
 * тёлок (HLIV, σ = 0,36 %), и у нас стоит первое — то есть отклонение,
 * измеренное **на других животных**. Наш признак при этом про судьбу
 * телёнка при отёле, и ближе к нему ни то ни другое.
 *
 * Спорить о том, какое чужое число подставить, бессмысленно. Своё
 * измеряется: у нас есть книга, и разброс оценок в ней — величина,
 * которую можно посчитать. Этот прогон её и считает.
 *
 * ## Чего он не делает
 *
 * Не правит `TRAIT_BASE`. Замена σ меняет порядок животных в рейтинге
 * и значение всех выданных документов, и делать это прогоном нельзя —
 * решение принимает человек, глядя на число и на объём выборки.
 *
 * ## Где он врёт и как это увидеть
 *
 * Засеянные данные сгенерированы тем же σ, что объявлено: на показательной
 * книге измеренное сойдётся с заявленным по построению, и зелёный ответ
 * не будет означать ничего. Поэтому рядом с каждым числом печатается,
 * сколько записей его дали, и прогон прямо говорит: сравнение имеет
 * смысл только там, где оценки пришли выгрузкой, а не севом.
 *
 *   npm run check:trait-sd
 *   npm run check:trait-sd -- --org=12
 */

const orgArg = process.argv.find((a) => a.startsWith('--org='))
const ORG = orgArg ? Number(orgArg.slice('--org='.length)) : null

/** Меньше этого числа записей — разброс считать не по чему. */
const MIN_ROWS = 30

/**
 * Во сколько раз измеренное может отличаться от заявленного.
 *
 * Не «на сколько процентов»: у σ важен порядок величины, а не точность.
 * Разница вдвое — повод посмотреть, разница вчетверо означает, что
 * заявленное число измерено на других животных или в других единицах.
 */
const LOUD = 3

async function main() {
  const payload = await getPayload({ config })
  const pool = poolOf(payload)

  if (!pool) {
    console.log('  ✗ прогон рассчитан на PostgreSQL-адаптер')
    process.exit(1)
  }

  console.log(`check:trait-sd: разброс оценок по книге${ORG ? `, хозяйство #${ORG}` : ''}\n`)
  console.log('Признак                     заявлено   измерено   записей   во сколько раз')
  console.log('─'.repeat(78))

  let loud = 0

  for (const trait of TRAIT_BASE) {
    /*
     * Путь признака — вложенное поле карточки вида `health.calfMortality`;
     * в базе оно лежит колонкой с подчёркиванием и суффиксом прогноза.
     * Собирается имя здесь, а не хранится вторым списком: второй список
     * разошёлся бы с `TRAIT_BASE` на первом же новом признаке.
     */
    const column = `${trait.path.replace('.', '_')}_forecast`
      .replace(/([a-z])([A-Z])/g, '$1_$2')
      .toLowerCase()

    let row: { sd: number | null; n: number } | null = null

    try {
      const res = await pool.query(
        `select stddev_samp("${column}")::float as sd, count("${column}")::int as n
           from animals
          where archived is not true
            ${ORG ? 'and organization_id = $1' : ''}`,
        ORG ? [ORG] : [],
      )
      row = (res.rows?.[0] ?? null) as { sd: number | null; n: number } | null
    } catch (e) {
      /*
       * Причина печатается, а не проглатывается.
       *
       * Первая редакция ловила ошибку и писала «колонка не читается» —
       * и на живой базе так сказала про все одиннадцать признаков разом,
       * хотя колонки на месте. Настоящая причина осталась внутри `catch`,
       * и вместо неё читатель получил одиннадцать одинаковых строк,
       * каждая из которых врала конкретно.
       *
       * Проглоченная ошибка — то же самое, что `.catch(() => [])`:
       * поломка превращается в тихую неправду, и разбираться приходится
       * не с ней, а с придуманным объяснением.
       */
      const why = e instanceof Error ? e.message : String(e)
      console.log(`${trait.label.padEnd(28)}${column}: ${why}`)
      continue
    }

    const n = row?.n ?? 0
    const sd = row?.sd ?? null

    if (n < MIN_ROWS || sd === null || sd === 0) {
      console.log(
        `${trait.label.padEnd(28)}${String(trait.sd).padStart(8)}   ` +
          `${'—'.padStart(8)}   ${String(n).padStart(7)}   не по чему считать`,
      )
      continue
    }

    const ratio = sd > trait.sd ? sd / trait.sd : trait.sd / sd
    const shout = ratio >= LOUD ? '  ← смотреть' : ''
    if (ratio >= LOUD) loud += 1

    console.log(
      `${trait.label.padEnd(28)}${String(trait.sd).padStart(8)}   ` +
        `${sd.toFixed(2).padStart(8)}   ${String(n).padStart(7)}   ` +
        `${ratio.toFixed(1).padStart(6)}${shout}`,
    )
  }

  console.log(
    '\nЗаявленное σ взято из документа CDCB и переведено в метрические единицы;' +
      '\nу смертности приплода и лёгкости отёла перевода не было — там подстановка' +
      '\n(разбор: /ru/razbory/baza-sravneniya).',
  )
  console.log(
    'Сравнение имеет смысл только там, где оценки пришли выгрузкой: на засеянных' +
      '\nданных измеренное сходится с заявленным по построению.',
  )

  /*
   * Прогон не падает. Расхождение σ — не поломка, а повод принять решение,
   * и решение это меняет рейтинг всех животных: валить им выкладку значило
   * бы требовать спешки там, где нужна осторожность.
   */
  console.log(
    loud === 0
      ? '\n  ✓ ни один признак не разошёлся с измеренным втрое'
      : `\n  ! признаков, разошедшихся втрое и больше: ${loud}`,
  )
  process.exit(0)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
