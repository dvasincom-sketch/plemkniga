import 'dotenv/config'
import { parseBoolean, parseDate, parseNumber } from '@/lib/import-values'

/**
 * Проверка разбора чисел и дат из чужой таблицы.
 *
 * ## Почему она утверждает значения, а не «разобралось»
 *
 * Проверка вида «файл загрузился» пропускает ровно тот класс ошибок,
 * ради которого заводится. `5.03.2026` разбиралось прекрасно — во второе
 * мая. `март 2026` разбиралось — в тридцать первое декабря предыдущего
 * года. Ни то, ни другое не давало ни исключения, ни пустого поля,
 * и любая проверка на «получилось ли» их бы прошла.
 *
 * Поэтому здесь у каждого случая написан ожидаемый ответ целиком:
 * либо точное значение, либо то, что причина названа. Третьего состояния
 * — «что-то вернулось» — у этой проверки нет.
 *
 * ## Почему без базы
 *
 * Разбор значения ничего не знает ни о стаде, ни о хозяйстве: на входе
 * строка из ячейки, на выходе число или дата. Заводить ради него живые
 * записи значило бы проверять заодно и права доступа, и хуки коллекций,
 * то есть получать красный экран по причинам, к разбору не относящимся.
 * Сценарий на живой базе у загрузки свой — `check:import-file`.
 *
 *   npm run check:import-values
 */

let failures = 0

const check = (ok: boolean, what: string, detail = '') => {
  if (ok) {
    console.log(`  ✓ ${what}`)
  } else {
    failures += 1
    console.log(`  ✗ ${what}${detail ? ` — ${detail}` : ''}`)
  }
}

/** Ожидаем точное число. */
const num = (raw: string, expected: number) => {
  const got = parseNumber(raw)
  check(
    got.value === expected && !got.problem,
    `«${raw}» → ${expected}`,
    got.problem ? `отказ: ${got.problem}` : `получили ${got.value}`,
  )
}

/** Ожидаем, что значение не принято и причина названа. */
const numFails = (raw: string) => {
  const got = parseNumber(raw)
  check(
    got.value === undefined && !!got.problem,
    `«${raw}» — не число, и это сказано`,
    got.value !== undefined ? `молча приняли ${got.value}` : 'причина не названа',
  )
}

/** Ожидаем пустоту без жалобы: так пишут «не заполнено». */
const numBlank = (raw: string) => {
  const got = parseNumber(raw)
  check(
    got.value === undefined && !got.problem,
    `«${raw}» — пусто, без жалобы`,
    got.problem ? `пожаловались: ${got.problem}` : `вернули ${got.value}`,
  )
}

/** Ожидаем точный день. Сравнивается день, а не строка целиком. */
const date = (raw: string, expected: string) => {
  const got = parseDate(raw)
  check(
    got.value?.slice(0, 10) === expected && !got.problem,
    `«${raw}» → ${expected}`,
    got.problem ? `отказ: ${got.problem}` : `получили ${got.value?.slice(0, 10)}`,
  )
}

const dateFails = (raw: string) => {
  const got = parseDate(raw)
  check(
    got.value === undefined && !!got.problem,
    `«${raw}» — не дата, и это сказано`,
    got.value !== undefined ? `молча приняли ${got.value.slice(0, 10)}` : 'причина не названа',
  )
}

const dateBlank = (raw: string) => {
  const got = parseDate(raw)
  check(
    got.value === undefined && !got.problem,
    `«${raw}» — пустая дата, без жалобы`,
    got.problem ? `пожаловались: ${got.problem}` : `вернули ${got.value}`,
  )
}

function main() {
  console.log('\nЧисла из русского Excel\n')

  num('3,85', 3.85)
  num('8450', 8450)
  num('8450.0', 8450)
  /*
   * Неразрывный пробел — не украшение отчёта, а то, чем Excel разделяет
   * тысячи при русской локали. Обычный пробел и неразрывный в файле
   * выглядят одинаково, а ведут себя по-разному, поэтому проверяются оба.
   */
  num('10 458', 10458)
  num('10 458', 10458)
  num('10 458,5', 10458.5)
  num('-2', -2)
  num('0,038', 0.038)

  console.log('\nЗнак процента не съедает значение целиком\n')

  /*
   * До правки `Number('3,85%')` давал `NaN`, поле оставалось пустым,
   * строка принималась, и в сводке стояло «обновлено». Это и есть
   * молчаливая порча: данные потеряны, а сообщение — успех.
   */
  num('3,85 %', 3.85)
  num('3,85%', 3.85)
  num('87,5 %', 87.5)

  console.log('\nОба разделителя сразу: десятичный — правый\n')

  num('10.458,5', 10458.5)
  num('10,458.5', 10458.5)

  console.log('\nПустые написания — пустота, а не ошибка\n')

  numBlank('')
  numBlank('-')
  numBlank('—')
  numBlank('н/д')
  numBlank('#Н/Д')

  console.log('\nТо, что числом не является, названо вслух\n')

  numFails('8 450 кг')
  numFails('около 8000')
  numFails('#ДЕЛ/0!')
  numFails('3,8,5')

  console.log('\nДаты, которые обязаны читаться\n')

  date('2026-03-15', '2026-03-15')
  date('2026-03-15 00:00:00', '2026-03-15')
  date('15.03.2026', '2026-03-15')
  date('15/03/2026', '2026-03-15')
  date('15-03-2026', '2026-03-15')

  /*
   * Однозначный день. Прежний разбор требовал ровно двух цифр, и такая
   * дата уходила в `Date.parse`, который читал её по американскому порядку:
   * `5.03.2026` становилось вторым мая. Ошибка тихая вдвойне — дата
   * не только неверная, но и правдоподобная.
   */
  date('5.03.2026', '2026-03-05')
  date('5.3.2026', '2026-03-05')

  console.log('\nДвузначный год: 00–29 — двухтысячные, дальше — девятисотые\n')

  date('15.03.26', '2026-03-15')
  date('15.03.30', '1930-03-15')
  date('20.07.85', '1985-07-20')

  /*
   * Два правила накладываются, и проверка обязана показать, как именно.
   *
   * Век для двузначного года переключается на тридцатом, а потолок года
   * стоит на «следующий от сегодняшнего». Поэтому `29` читается как 2029
   * и тут же отвергается — не как «непонятное написание», а как дата
   * из будущего, и в причине названо именно это. Написать в проверке
   * просто «не принято» значило бы не заметить, если однажды перестанет
   * работать первое правило: результат остался бы тем же, а смысл — нет.
   */
  const future = parseDate('01.01.29')
  check(
    future.value === undefined && (future.problem ?? '').includes('2029'),
    '«01.01.29» прочитано как 2029 и отвергнуто как будущее',
    future.problem ?? `приняли ${future.value}`,
  )

  console.log('\nСерийный номер Excel — из книги, пересохранённой в CSV\n')

  /*
   * 45731 — это 15 марта 2025 года. Прежний разбор отдавал его
   * `Date.parse`, и получался год сорок пять тысяч семьсот тридцатый.
   */
  date('45731', '2025-03-15')
  date('44197', '2021-01-01')

  console.log('\nПустая дата СЕЛЭКСа не роняет разбор\n')

  /*
   * `00.00.0000` попадало под шаблон «день.месяц.год», уходило
   * в `new Date('0000-00-00')` и роняло `toISOString` с `RangeError` —
   * то есть валило разбор файла на строке, где просто ничего не заполнено.
   */
  dateBlank('00.00.0000')
  dateBlank('0000-00-00')
  dateBlank('')
  dateBlank('-')

  console.log('\nТо, что датой не является, названо вслух\n')

  dateFails('март 2026')
  dateFails('31.02.2026')
  dateFails('30.02.2026')
  dateFails('03/15/2026')
  dateFails('2026')
  dateFails('вчера')
  dateFails('#ССЫЛКА!')

  console.log('\nЗаполнитель из шаблонов ФГИАС не становится датой рождения\n')

  /*
   * `1111-11-01` стоит в строке-примере каждого шаблона ФГИАС ПР.
   * Хозяйство, забывшее удалить пример перед загрузкой, заводило бы
   * животное двенадцатого века — и никакая проверка ниже по потоку
   * этого бы не заметила: дата настоящая, календарь сходится.
   */
  dateFails('1111-11-01')
  dateFails('01.01.1899')
  dateFails('01.01.3026')

  console.log('\nВисокосный год считается по календарю, а не по остатку\n')

  date('29.02.2024', '2024-02-29')
  dateFails('29.02.2025')

  console.log('\nЧасовой пояс на дату не влияет\n')

  /*
   * Разбор идёт арифметикой над `Date.UTC` и обратно через `getUTC*`:
   * местных геттеров в этом пути нет ни одного. Проверка сдвигает пояс
   * процесса и требует того же дня — урок из разбора книг Excel, где
   * дата рождения однажды уехала на сутки в зависимости от окружения.
   */
  const was = process.env.TZ
  for (const tz of ['UTC', 'Europe/Moscow', 'Pacific/Auckland', 'America/Los_Angeles']) {
    process.env.TZ = tz
    const got = parseDate('17.04.2023')
    check(got.value?.slice(0, 10) === '2023-04-17', `в поясе ${tz} — 17 апреля`, got.value)
  }
  process.env.TZ = was

  console.log('\nДа и нет: непонятное — вопрос, а не «нет»\n')

  /*
   * Правило «непустое значит да» было бы проще и неверно: в ведомостях
   * пишут «нет», «отсутствует», «0», и всё это непустое. Ошибка пошла
   * бы в дорогую сторону — реестр получил бы предложение семени,
   * которого нет.
   */
  for (const yes of ['да', 'Да', 'ДА', 'true', '1', 'есть', 'в наличии', '+']) {
    check(parseBoolean(yes).value === true, `«${yes}» — да`)
  }
  for (const no of ['нет', 'НЕТ', 'false', '0', 'отсутствует', 'не в наличии', '-']) {
    check(parseBoolean(no).value === false, `«${no}» — нет`)
  }

  /* Пусто — не «нет», а «не сказано»: поле остаётся незаполненным. */
  const blank = parseBoolean('')
  check(blank.value === undefined && !blank.problem, 'пусто не превращается в «нет»')

  /*
   * «Под запрос» — состояние, которого колонка не описывает. Решать
   * за человека, что он имел в виду, нельзя: значение называется
   * непонятым, а поле остаётся пустым.
   */
  const odd = parseBoolean('под запрос')
  check(odd.value === undefined && !!odd.problem, 'непонятное названо непонятым', odd.problem)

  console.log(failures === 0 ? '\nВсё сходится.\n' : `\nНе сходится: ${failures}.\n`)
  process.exit(failures === 0 ? 0 : 1)
}

main()
