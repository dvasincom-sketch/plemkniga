import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Серверные компоненты не передают функций.
 *
 * ## Что случилось
 *
 * Переключатель языка принимал `hrefOf: (locale) => string` — страница
 * знала, куда вести, а компонент только звал. Правильное разделение
 * ответственности и неработающий код: через границу «серверный компонент →
 * клиентский» проходят только данные, функцию нечем сериализовать.
 *
 * Хуже всего было то, **когда** это выяснилось. В разработке страница
 * работала: там оба компонента живут в одном процессе, и функция никуда
 * не едет. Упало на `next build`, при предварительной отрисовке одной
 * из шести языковых страниц, то есть через несколько минут сборки
 * и уже после того, как правку сочли готовой.
 *
 * ## Почему проверка смотрит на передающего, а не на принимающего
 *
 * Первая редакция искала пропсы-функции в объявлениях клиентских
 * компонентов — и нашла два законных случая. `error.tsx` принимает
 * `reset` от самого Next: это соглашение фреймворка, а не наша передача.
 * `RecordEvent` принимает `setDate` от другого клиентского компонента,
 * и там функция никуда не едет — оба живут в браузере.
 *
 * Правило, оказывается, не про клиентские компоненты вовсе. Оно про
 * границу: **в серверном компоненте не может быть пропса-функции**, кому
 * бы он ни предназначался. Это верно всегда и не требует знать, клиентский
 * ли получатель, — там и `onClick` нельзя.
 *
 * ## Что проверяется
 *
 * Файлы **без** `'use client'`. В разметке ищется пропс, значение
 * которого начинается прямо со стрелочной функции или `function`.
 * Стрелка внутри выражения — `items={list.map((x) => …)}` — не считается:
 * там функция вызывается на месте и наружу не уезжает.
 *
 * Проверка работает по тексту, а не по дереву разбора. Ложное срабатывание
 * стоит взгляда человека; пропуск стоит упавшей сборки через пять минут
 * после того, как правку сочли готовой.
 *
 *   npm run check:client-props
 */

const ROOT = 'src'
const fails: string[] = []

function walk(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry)
    if (statSync(path).isDirectory()) {
      walk(path, out)
      continue
    }
    if (path.endsWith('.tsx')) out.push(path)
  }
}

const files: string[] = []
walk(ROOT, files)

/*
 * Значение пропса — сразу функция.
 *
 * `\w+=\{` — начало пропса; дальше либо скобки со списком доводов, либо
 * одно имя, и сразу стрелка. Этим отсекается `items={list.map((x) => …)}`:
 * после `{` там стоит `list`, а за ним точка, а не стрелка.
 */
const INLINE_ARROW = /\b([A-Za-z_$][\w$]*)=\{\s*(?:async\s+)?(?:\([^()]*\)|[A-Za-z_$][\w$]*)\s*=>/g
const INLINE_FUNCTION = /\b([A-Za-z_$][\w$]*)=\{\s*(?:async\s+)?function\b/g

let serverFiles = 0

for (const file of files) {
  const text = readFileSync(file, 'utf8')

  /* Клиентские файлы не проверяем: внутри браузера функции ходят свободно. */
  if (/^\s*(\/\*[\s\S]*?\*\/\s*)?['"]use client['"]/.test(text)) continue
  serverFiles++

  const lines = text.split('\n')

  lines.forEach((line, i) => {
    const trimmed = line.trim()
    if (trimmed.startsWith('*') || trimmed.startsWith('//')) return

    for (const re of [INLINE_ARROW, INLINE_FUNCTION]) {
      re.lastIndex = 0
      let m: RegExpExecArray | null
      while ((m = re.exec(line))) {
        fails.push(
          `${file}:${i + 1}: пропс «${m[1]}» передан функцией. ` +
            `Серверный компонент функцию отдать не может — её нечем сериализовать. ` +
            `Передайте готовые данные: объект, массив, строку`,
        )
      }
    }
  })
}

console.log(`Просмотрено файлов: ${files.length}, из них серверных: ${serverFiles}`)

if (fails.length) {
  console.log('')
  for (const f of fails) console.log(`  ✗ ${f}`)
  process.exit(1)
}

console.log('\n  ✓ серверные компоненты не передают функций через границу')
process.exit(0)
