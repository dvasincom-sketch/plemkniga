import { MigrateUpArgs, MigrateDownArgs, sql } from '@payloadcms/db-postgres'

/**
 * Российский международный номер как отдельный вид идентификатора.
 *
 * ## Зачем ещё один формат
 *
 * Единого идентификатора у крупного рогатого скота в России нет. Одно
 * и то же животное ходит под национальным номером, под номером средства
 * маркирования, под инвентарным и под этим — две буквы кода региона
 * или организации, `RUS`, двенадцать цифр. Сейчас он распространён
 * шире прочих.
 *
 * До сих пор такой номер оставалось заводить либо как «внутрихозяйственный»
 * (и терять единственное, что о нём известно наверняка, — его вид), либо
 * как `icar`. Второе хуже: правило `icar` ждёт три буквы породы и две-три
 * буквы страны, и на `XXRUS880808231818` срабатывает **случайно** —
 * читает `XXR` как породу, а `US` как страну. Пока номер нигде
 * не разбирается на части, ошибка невидима; в первый же день, когда
 * из него понадобится код страны, получится США.
 *
 * ## Почему только значение перечисления и ничего больше
 *
 * Сопоставление записей между системами нумерации эта миграция не решает
 * и решать не должна. Цифры у разных номеров одного животного совпадают
 * не всегда — в одних хозяйствах это тот же номер в другой записи,
 * в других системы независимы. Значит, совпадение цифр — вопрос человеку,
 * а не основание слить записи, и живёт оно в проверке, а не в схеме.
 *
 * ## Про `ALTER TYPE ... ADD VALUE` внутри транзакции
 *
 * До PostgreSQL 12 такая команда в транзакции не выполнялась вовсе,
 * с 12-й выполняется — но новое значение нельзя использовать в той же
 * транзакции, где оно добавлено. Миграция им и не пользуется: она только
 * расширяет перечисление, а первая запись с этим форматом появится
 * отдельной командой.
 *
 * `IF NOT EXISTS` — на случай базы, где схему уже подтянул `drizzle push`
 * в режиме разработки: повторное добавление там иначе упало бы.
 *
 * Обратной миграции у значения перечисления нет: `ALTER TYPE ... DROP
 * VALUE` в PostgreSQL не существует. Откат оставляет значение на месте —
 * это безвредно, но сказать об этом надо вслух, иначе следующий человек
 * будет искать ошибку в собственном коде.
 *
 * Опорный объект для `npm run migrate:baseline` — само значение
 * перечисления, поэтому признак нестандартный: `constraint` тут не годится.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
  ALTER TYPE "public"."enum_animals_id_format" ADD VALUE IF NOT EXISTS 'rus';`)
}

export async function down(_args: MigrateDownArgs): Promise<void> {
  /*
   * Пусто намеренно. `ALTER TYPE ... DROP VALUE` в PostgreSQL нет,
   * а пересоздание типа потребовало бы переписать все колонки, которые
   * им пользуются, — цена, несоразмерная откату одного значения.
   * Лишнее значение в перечислении никому не мешает: записей с ним
   * после отката не останется.
   */
}
