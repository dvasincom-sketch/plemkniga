/**
 * Вывод ДНК-теста отдельным полем.
 *
 * ## Зачем колонка, а не разбор «Результата»
 *
 * Свидетельство требовало «проведён тест на достоверность происхождения»,
 * и требование считалось выполненным по наличию любой записи о тесте.
 * Тест, который отцовство **исключил**, требование удовлетворял — и
 * свидетельство выпускалось на заведомо неверную родословную.
 *
 * Чинить это разбором свободного текста в `result` нельзя. Там лежит
 * и «подтверждено», и «excluded», и «см. протокол», и пустая строка;
 * любое правило по подстроке ошибётся молча и в обе стороны. Вывод теста
 * система обязана знать полем, а не угадывать пересказом.
 *
 * ## Почему перечисление, а не varchar
 *
 * Обратная сторона решения из `20260822_090000_check_settings`, где `code`
 * намеренно оставлен строкой. Там значения заводятся кодом и растут вместе
 * с реестром проверок — привязывать их к миграции было бы вредно. Здесь
 * наоборот: выводов у теста ровно три, новые не появятся, и опечатка
 * в этом поле стоит выпущенного свидетельства.
 *
 * ## Почему поле необязательное
 *
 * У тестов, заведённых до этой правки, вывода нет и взяться ему неоткуда.
 * `NOT NULL` потребовал бы значения по умолчанию, то есть проставил бы
 * всем старым тестам догадку — «подтверждено» вернуло бы ту же дыру,
 * «исключено» оклеветало бы животных. `NULL` честно означает «неизвестно»:
 * свидетельство по такой записи не выпустится, пока вывод не проставят
 * руками, глядя в протокол.
 *
 * Написана руками по образцу `20260817_133000_access_grants`: `migrate:create`
 * в этом проекте подгребает в диф всё, что появилось после последнего снимка
 * схемы. Разбор — шапка той миграции.
 *
 * Опорный объект для `npm run migrate:baseline` — колонка
 * `animals_dna_tests.verdict`.
 */
