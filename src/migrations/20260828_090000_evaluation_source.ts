import { MigrateUpArgs, MigrateDownArgs, sql } from '@payloadcms/db-postgres'

/**
 * Имя привезённой оценки: кто считал и по какой базе.
 *
 * Карточка показывала чужую оценку безымянно, и на живой записи это дало
 * противоречие, которое нечем объяснить: наш расчёт ставит корову
 * в 99-й процентиль, привезённая оценка — в 13-й. Одно животное лучшее
 * в стране и хуже среднего сразу. Прежняя подпись «разные оценки
 * на разных базах» такое не покрывает: она объясняет расхождение
 * в сотню очков, а не в восемьдесят шесть процентилей.
 *
 * Ответить может только источник. Индекс TPI из американского каталога
 * и индекс областного расчётного центра — разные величины, и знать,
 * какая перед тобой, обязан читатель.
 *
 * Тип текстовый, а не перечисление: центров и баз много, список меняется,
 * и закрытый перечень означал бы, что оценку из нового источника некуда
 * положить. Отказываться от данных ради опрятности справочника
 * мы не будем.
 *
 * Ограничения по длине нет намеренно. Названия баз бывают длинными
 * («Interbull MACE, база быков голштинской породы 2024 года»), а обрезать
 * имя источника значит сделать его неузнаваемым — то есть вернуть ту же
 * безымянность другим способом.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
  ALTER TABLE "animals"
    ADD COLUMN IF NOT EXISTS "ipc_details_center" varchar,
    ADD COLUMN IF NOT EXISTS "ipc_details_base" varchar;`)
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  await db.execute(sql`
  ALTER TABLE "animals"
    DROP COLUMN IF EXISTS "ipc_details_center",
    DROP COLUMN IF EXISTS "ipc_details_base";`)
}
