import { NextResponse } from 'next/server'
import { ADE_VERSION } from '@/lib/ade/core'
import { ADE_DATASETS } from '@/lib/ade/datasets'
import { adeAuth } from '@/lib/ade/gate'

export const dynamic = 'force-dynamic'

/**
 * Перечень наборов данных — вход в обмен без знания о хозяйствах.
 *
 *   GET /ade/v1/datasets
 *
 * ## Почему это первый адрес, который зовут
 *
 * Стандарт строит обмен наборами так, чтобы клиент не держал у себя
 * список адресов: он спрашивает перечень, читает в каждом наборе поле
 * `changes` и дальше ходит по тому адресу, который получил. Появится
 * у нас двенадцатый набор — партнёр увидит его сам, без правки своей
 * программы и без письма от нас.
 *
 * Поэтому адреса в ответе относительные, как в примерах спецификации.
 * Собрать абсолютные можно было бы из заголовка `Host`, но ему нельзя
 * верить: подменённый заголовок увёл бы партнёра за нашими же данными
 * на чужой сервер.
 *
 * ## Почему список одинаков для всех
 *
 * Спецификация советует сужать перечень наборов по правам клиента.
 * Мы сужаем не перечень, а содержимое: наборы у нас — это разделы
 * стандарта, а не хозяйства, и скрывать сам факт существования раздела
 * не от кого. Права решают, чьи записи попадут в ленту, и это проверяется
 * на каждом её запросе.
 */
export async function GET(request: Request) {
  const auth = await adeAuth(request)
  if (!auth.ok) return auth.response

  return NextResponse.json(ADE_DATASETS, {
    headers: { 'X-ICAR-ADE-Version': ADE_VERSION, 'Cache-Control': 'no-store' },
  })
}
