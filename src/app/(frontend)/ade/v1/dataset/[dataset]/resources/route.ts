import { adePush } from '@/lib/ade/push'

export const dynamic = 'force-dynamic'

/**
 * Приём в набор — единственное число пути.
 *
 * ## Почему адрес два раза
 *
 * В самой спецификации написано и так, и так. Перечень наборов отдаёт
 * ссылки вида `/datasets/{name}`, а раздел про приём озаглавлен
 * `POST /dataset/{datasetid}/resources` — в единственном числе. Это
 * опечатка в тексте, но опечатка нормативная: интегратор, читающий
 * спецификацию сверху вниз, наберёт именно её.
 *
 * Отвечать ему «страница не найдена» и предлагать догадаться про лишнюю
 * букву — потратить его день на нашу принципиальность. Тот же довод,
 * по которому мы принимаем и `JWT`, и `Bearer`.
 *
 * Обработчик один и тот же, а не копия: разойдясь, две двери
 * принимали бы по-разному, и это было бы хуже отсутствия второй.
 * О расхождении в спецификации написано в adewg/ICAR отдельно.
 */
export async function POST(request: Request, { params }: { params: Promise<{ dataset: string }> }) {
  const { dataset } = await params
  return adePush(request, dataset)
}
