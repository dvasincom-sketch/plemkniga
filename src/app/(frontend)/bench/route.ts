import { NextResponse } from 'next/server'
import { timingSafeEqual } from 'node:crypto'
import { getClient } from '@/lib/payload'
import { runBench } from '@/lib/bench'

export const dynamic = 'force-dynamic'
/*
 * Замер идёт секундами и не должен обрываться на общем потолке.
 * Значение с запасом: на боевой базе в сотни животных всё укладывается
 * в секунды, но потолок ставится не под сегодняшний объём.
 */
export const maxDuration = 300

/**
 * Замер прода — на самом проде.
 *
 * ## Зачем понадобилась ручка, когда есть скрипт
 *
 * Замер боевого сервера надо делать на боевом сервере: запуск со своей
 * машины против прод-базы меряет не прод, а канал до него — каждый запрос
 * везёт задержку сети, и на сценариях в двадцать миллисекунд она и есть
 * весь результат.
 *
 * Способ «зайти в контейнер и запустить файл» упирается в площадку:
 * приложение развёрнуто из репозитория, и консоли внутрь контейнера
 * там нет — только логи и переменные окружения. Значит запустить замер
 * можно ровно одним способом: попросить об этом само приложение.
 *
 * ## Почему это не открытая дверь
 *
 * Маршрута нет, пока не задана переменная `BENCH_TOKEN`. Не «есть,
 * но отвечает 403», а именно нет: без переменной ответ — 404, тот же,
 * что у несуществующего адреса. Ручка, отвечающая «доступ запрещён»,
 * сообщает, что она существует; это приглашение подбирать ключ.
 *
 * Токен сравнивается за постоянное время. Обычное сравнение строк
 * выходит на первом несовпавшем знаке, и по времени ответа ключ
 * подбирается посимвольно — приём старый и рабочий.
 *
 * Замер только читает данные — ни одной записи в них он не делает.
 * Единственное, что он пишет, — свой собственный результат в коллекцию
 * замеров, чтобы вкладка «Эволюция продукта → Замер» показала его сразу.
 * Отчёт при этом возвращается и ответом: его можно забрать себе и вложить
 * в репозиторий рядом с замерами других сред.
 *
 * ## Порядок работы
 *
 * Переменная задаётся в панели на время замера и убирается после.
 * Пока она стоит, адрес живой, и это осознанная плата за отсутствие
 * консоли; убрать её — вопрос одной правки в панели, и маршрут исчезает.
 *
 *     GET /bench?token=…
 *     GET /bench?token=…&runs=3
 *
 * Метка среды необязательна: без неё замер записывается как «Прод».
 * Класть её в адрес кириллицей нельзя — обратный прокси отвечает
 * `400 Bad Request` на незакодированные не-ASCII байты, и до приложения
 * запрос не доходит вовсе. Проверено.
 */
export async function GET(request: Request) {
  const expected = process.env.BENCH_TOKEN ?? ''

  /*
   * Отсутствие переменной и неверный токен отвечают одинаково —
   * несуществующей страницей. Разные ответы на эти два случая
   * рассказывали бы, что здесь что-то есть.
   *
   * А вот в лог причина пишется поимённо, и это не противоречие.
   * Снаружи маршрут обязан быть неотличим от несуществующего адреса;
   * изнутри — обязан объяснять, почему не пустил. Без этого владелец
   * системы оказывается в положении злоумышленника: дёрнул, получил
   * «не найдено» и не может отличить незаданную переменную от опечатки
   * в ключе. Так и вышло при первом же запуске.
   *
   * Попытка с неверным ключом попадает в лог ещё и как след: подбор
   * ключа выглядит именно так.
   */
  const deny = (why: string) => {
    console.warn(`[bench] запрос отклонён: ${why}`)
    return new NextResponse('Not found', { status: 404 })
  }

  if (!expected) return deny('переменная BENCH_TOKEN не задана')
  if (expected.length < 16)
    return deny(`BENCH_TOKEN короче шестнадцати знаков (сейчас ${expected.length})`)

  const { searchParams } = new URL(request.url)
  const given = searchParams.get('token') ?? ''

  if (!given) return deny('в адресе нет параметра token')

  /*
   * Длины сравниваются отдельно и до `timingSafeEqual`: он требует
   * буферов одного размера и бросает исключение, если они разные.
   * Утечки здесь нет — длину токена всё равно видно по любому ответу.
   */
  const a = Buffer.from(given)
  const b = Buffer.from(expected)
  if (a.length !== b.length || !timingSafeEqual(a, b))
    return deny(`токен не подошёл (прислано знаков: ${given.length}, ожидается: ${expected.length})`)

  const runsParam = Number(searchParams.get('runs'))
  const runs = Number.isFinite(runsParam) && runsParam > 0 ? Math.min(runsParam, 50) : 10

  const label = (searchParams.get('label') ?? '').trim().slice(0, 60) || 'Прод'

  /*
   * Разбор выгрузки по слоям — только по явному требованию, и требование
   * это стоит понимать буквально.
   *
   * Первый замер на боевом сервере дошёл до этих сценариев и уронил
   * контейнер: `Reached heap limit — JavaScript heap out of memory`.
   * Двадцать тысяч документов Payload со всеми группами не помещаются
   * в память боевой машины. Замер, валящий то, что он меряет, —
   * не измерение, а поломка, и по умолчанию его здесь нет.
   *
   * Ключ оставлен на случай, если вопрос «сколько стоит слой» вернётся.
   * Но запускать его на проде — значит сознательно ронять прод, о чём
   * лог и предупреждает.
   */
  const heavy = searchParams.get('heavy') === '1'
  if (heavy)
    console.warn(
      '[bench] запрошен разбор по слоям: на боевой машине он однажды ' +
        'уже исчерпал память и убил процесс',
    )

  const payload = await getClient()

  /*
   * Замечания — не служебный шум: в них попадает то, из-за чего цифры
   * можно понять неверно. Например, что в базе меньше пятидесяти тысяч
   * записей, а требование сформулировано именно на них. В консоли
   * их печатает скрипт, здесь они едут вместе с отчётом.
   */
  const notes: string[] = []

  /*
   * Ход замера пишется в лог, а не только в ответ.
   *
   * Замер идёт секундами, и всё это время у смотрящего в панель нет
   * никаких признаков, что он вообще начался. Молчащий процесс, который
   * что-то делает минуту, неотличим от зависшего, — а перезапустить
   * контейнер посреди замера значит не получить ничего и не узнать
   * почему.
   */
  console.info(`[bench] замер начат: среда «${label}», прогонов ${runs}`)
  const startedAt = Date.now()

  const measured = await runBench(payload, {
    runs,
    label,
    heavy,
    onGroup: (name) => console.info(`[bench] ${name}`),
    onNote: (t) => {
      notes.push(t)
      console.info(`[bench] ${t}`)
    },
  })

  console.info(
    `[bench] замер закончен за ${Math.round((Date.now() - startedAt) / 1000)} с, ` +
      `строк ${measured.rows.length}, животных ${measured.animals}`,
  )

  /*
   * Результат ложится в базу той машины, на которой снят, — и вкладка
   * показывает его сразу, без коммита и деплоя.
   *
   * Это правка прежнего решения, а не дополнение к нему. Отчёт-файл
   * обосновывался тем, что замер привязан к версии кода; обоснование
   * верное, но решало не ту задачу: замер, снятый на боевом сервере,
   * должен там же и показаться, а между ним и страницей оказывались
   * коммит и выкладка. Файл при этом остался — он везёт замеры других
   * сред, которым в этой базе взяться неоткуда.
   *
   * Сбой записи не отменяет ответа: отчёт уже посчитан и уходит целиком,
   * а строка в логе говорит, что на витрину он не попал. Промолчать
   * здесь значило бы оставить человека ждать обновления страницы,
   * которого не будет.
   */
  const stored = await payload
    .find({
      collection: 'bench-runs',
      where: { label: { equals: measured.label } },
      limit: 1,
      depth: 0,
      overrideAccess: true,
    })
    .catch(() => null)

  const record = {
    label: measured.label,
    measuredAt: measured.server?.at ?? new Date().toISOString(),
    animals: measured.animals,
    runs: measured.runs,
    server: measured.server,
    rows: measured.rows,
    notes,
  }

  let saved = false
  try {
    if (stored?.docs.length)
      await payload.update({
        collection: 'bench-runs',
        id: stored.docs[0]!.id,
        data: record,
        overrideAccess: true,
      })
    else await payload.create({ collection: 'bench-runs', data: record, overrideAccess: true })
    saved = true
    console.info(`[bench] замер сохранён и показан на странице «Эволюция продукта»`)
  } catch (e) {
    console.error('[bench] замер посчитан, но в базу не записан:', e)
  }

  return NextResponse.json(
    { ...measured, notes, saved },
    {
      /*
       * Ответ не кэшируется ни на секунду. Замер — измерение, сделанное
       * сейчас; отданный из кэша, он превратился бы в измерение, сделанное
       * когда-то, и об этом никто бы не узнал.
       */
      headers: { 'Cache-Control': 'no-store' },
    },
  )
}
