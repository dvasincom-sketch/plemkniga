/**
 * Соответствие руководствам ICAR — карта, а не перевод.
 *
 * ## Почему здесь нет русского текста руководств
 *
 * Соблазн был прямой: перевести нужные разделы и выложить, показав тем самым
 * приверженность мировому опыту. Так делать нельзя, и причина не в лени.
 * Руководства принадлежат ICAR, публикация перевода целиком — нарушение
 * авторских прав, а к нарушению нельзя апеллировать как к доказательству
 * добросовестности: страница, ради которой пришлось нарушить чужое право,
 * доказывает ровно обратное тому, что собиралась доказать.
 *
 * Разрешение у ICAR запрошено отдельно (текст письма — в `docs/icar.md`),
 * и практика у них есть: атлас здоровья копыт переведён на несколько языков
 * с их ведома. Если разрешение придёт, эта страница пополнится переводами.
 * Пока — своими словами и со ссылкой на оригинал.
 *
 * ## Почему на странице написано и то, чего мы не делаем
 *
 * Список из одних галочек не читают: он выглядит рекламой и ею является.
 * Здесь три состояния — сделано, сделано частично, не наша область, — и
 * последнее честно занимает место. Заводчик, который откроет эту страницу,
 * узнает границы системы за минуту, а не за три месяца внедрения.
 *
 * ## Почему знака ICAR здесь нет
 *
 * Марка ICAR выдаётся Советом организации по статусу члена или по пройденной
 * проверке, а не за соответствие руководствам. Соответствие — это то, что
 * нужно доказать, чтобы подать заявку, а не то, что даёт право на знак.
 * Поэтому здесь только текст и ссылки: фактическое утверждение о собственной
 * работе разрешено, чужой знак — нет.
 *
 * ## Где смотреть
 *
 * Ссылка в подвале — `src/components/SiteFooter.tsx`. Письмо в ICAR
 * и разбор правил использования марки — `docs/icar.md`.
 */

