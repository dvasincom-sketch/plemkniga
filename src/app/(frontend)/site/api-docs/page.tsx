import { permanentRedirect } from 'next/navigation'
import { SITE_URL } from '@/lib/hosts'

/**
 * Старый адрес без языка.
 *
 * Страницы продукта переехали под язык (`/ru/api-docs`), а этот адрес
 * остаётся работать: ссылки на него уже разошлись по письмам
 * и презентациям, и ломать их значит терять тех, кто по ним придёт.
 *
 * `permanentRedirect`, а не `redirect`: комментарий обещал постоянное
 * перенаправление, а отдавалось временное — поисковая система при нём
 * держит в выдаче старый адрес и ходит по нему годами.
 *
 * На витринном домене сюда уже не попадают: старые адреса, включая
 * вложенные, уводит промежуточный обработчик (`localeless`
 * в `lib/hosts.ts`). Этот файл остаётся ради служебного пути `/site/api-docs`
 * на домене книги, и потому ведёт на витрину целым адресом, а не
 * относительным — относительный на книжном домене открыл бы «не найдено».
 */
export default function RedirectApiDocs() {
  permanentRedirect(`${SITE_URL}/ru/api-docs`)
}
