import { NextResponse } from 'next/server'
import { getClient } from '@/lib/payload'
import { buildOpenApi } from '@/lib/openapi'

export const dynamic = 'force-dynamic'

/**
 * Машинное описание API.
 *
 * ## Почему адрес не под /api
 *
 * Там всё занято: `/api/[...slug]` — это сам Payload, и файл описания
 * стал бы для него именем коллекции. Отсюда `/api-docs/openapi.json` —
 * рядом со страницей, которая его показывает.
 *
 * ## Почему оно открыто всем
 *
 * Описание не содержит данных: только имена коллекций и полей —
 * то же самое, что видно в любой форме книги. Закрывать его значит
 * мешать тем, кто собирается подключаться, и не мешать никому больше:
 * состав полей и так виден по ответам API.
 *
 * Отдаётся с `Cache-Control: no-store` намеренно. Описание строится
 * из живой конфигурации, и его ценность ровно в том, что оно всегда
 * совпадает с тем, что работает; закешированное описание — это опять
 * рукописный документ, только созданный автоматически.
 */
export async function GET(request: Request) {
  const payload = await getClient()

  /*
   * Адрес сервера — из переменной окружения, а не из заголовка запроса:
   * за прокси заголовок это то, что прислал клиент.
   *
   * Переменных две, и порядок между ними не случаен. `NEXT_PUBLIC_*`
   * Next подставляет **на сборке**: значение зашивается в бандл, и если
   * контейнер разворачивают на другом адресе, описание продолжает
   * называть адрес сборочной машины. Поймали это на проверке: сервер
   * поднят на одном порту, а в документе стоял другой.
   *
   * Поэтому первой спрашивается обычная серверная `SERVER_URL` — она
   * читается в момент запроса и переживает переезд. `NEXT_PUBLIC_SERVER_URL`
   * оставлена вторым вариантом: она уже задана в развёртываниях, и ломать
   * их ради порядка незачем.
   */
  const configured = process.env.SERVER_URL || process.env.NEXT_PUBLIC_SERVER_URL || ''
  const fallback = new URL(request.url).origin

  return NextResponse.json(buildOpenApi(payload, configured || fallback), {
    headers: { 'Cache-Control': 'no-store' },
  })
}
