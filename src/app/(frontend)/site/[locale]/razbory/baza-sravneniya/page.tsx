import type { Metadata } from 'next'
import { notFound } from 'next/navigation'
import { ProductFooter, ProductHeader } from '@/components/site/ProductShell'
import { NoteHeader, NoteNeighbours, NoteSources } from '@/components/site/NoteFrame'
import { TermsSeen } from '@/components/site/TermsSeen'
import { NOTES, noteBySlug } from '@/lib/notes'
import { pageMetadata } from '@/lib/seo'
import { isLocale, type Locale } from '@/lib/i18n/locales'
import { TRAIT_BASE, BASE_VERSION } from '@/lib/breeding-index'
import { BASE_SOURCE, NO_MATCH, POUND_TO_KG } from '@/lib/index-base-source'

const SLUG = 'baza-sravneniya'

/*
 * Сколько строк таблицы — допущение, а не выписка из документа.
 *
 * Считается, а не пишется словом: строк было «девять и две» на момент
 * письма, и первое же новое допущение разошлось бы с текстом молча.
 * Допущением считается всё, у чего в паспорте источника стоит `NO_MATCH`
 * или пересчёт в нашу шкалу, — то есть всё, чего в документе USDA
 * буквально нет.
 */
const GUESSED = TRAIT_BASE.filter((t) => {
  const m = BASE_SOURCE[t.key]
  return m.how === NO_MATCH || m.how.includes('пересчёт')
}).length

export async function generateMetadata(): Promise<Metadata> {
  const note = noteBySlug(SLUG)!
  return pageMetadata({
    title: note.title,
    description: note.lead,
    path: `/ru/razbory/${SLUG}`,
  })
}

/**
 * Разбор базы сравнения.
 *
 * ## Зачем он написан
 *
 * На витрине сказано, что база у нас заимствованная, и названа строкой
 * `CDCB-2025-metric`. Строка — не объяснение: она сообщает, что источник
 * есть, и ничего не говорит о том, что из него взято. Специалист, которому
 * этого мало, идёт искать сам — и находит документ на сорок страниц
 * по-английски.
 *
 * ## Что дал разбор помимо текста
 *
 * Сверка нашей таблицы с первоисточником нашла два признака, у которых
 * прямого соответствия в NM$ нет: смертность приплода и лёгкость отёла.
 * Числа там стоят от близких по смыслу признаков — и это подстановка,
 * которую до сих пор нигде не было видно. Теперь она названа на витрине,
 * то есть в самом неудобном для нас месте.
 *
 * Так и должно работать: разбор своего узла либо подтверждает его,
 * либо находит в нём то, что пряталось за короткой строкой.
 *
 * ## Почему числа берутся из кода, а не набраны руками
 *
 * Таблица признаков собирается из `TRAIT_BASE` — того самого массива,
 * по которому считается индекс. Набранная руками, она разошлась бы
 * с расчётом на первой же правке базы, и разошлась бы молча: страница,
 * объясняющая, откуда берутся числа, показывала бы не те числа.
 */
export default async function BaseNotePage({
  params,
}: {
  params: Promise<{ locale: string }>
}) {
  const { locale: raw } = await params
  if (!isLocale(raw)) notFound()
  const locale: Locale = raw
  const note = noteBySlug(SLUG)!

  /*
   * Столбец «как получено» — главный в таблице. Без него читатель вправе
   * считать, что все одиннадцать строк одинаково выписаны из документа
   * USDA, а для двух из них это неправда.
   *
   * Происхождение лежит в `lib/index-base-source.ts` полным набором
   * по ключам признаков: признак, добавленный в базу без указания
   * источника, не соберётся вовсе — вместо прочерка на витрине.
   */
  return (
    <>
      <ProductHeader locale={locale} />

      <main className="container-page pb-16">
        <NoteHeader note={note} />

        {/* ------------------------- Что такое база ---------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Зачем индексу вообще нужна база
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Индекс племенной ценности складывает признаки, измеренные в разных единицах:
            килограммы молока, килограммы жира, месяцы продуктивной жизни, баллы вымени.
            Сложить их напрямую нельзя — получится сумма несопоставимых величин, число
            без смысла. Поэтому каждый признак сперва переводится в одну общую меру:
            на сколько он отклоняется от среднего, выраженного в собственных стандартных
            отклонениях этого признака.
          </p>

          <div className="mt-6 rounded-2xl bg-ink-50 px-6 py-5 text-[15px] leading-relaxed">
            <code className="text-[15px]">I = Σ wᵢ · (EBVᵢ − μᵢ) / σᵢ</code>
            <p className="mt-3 text-[14px] text-ink-500">
              μ и σ — среднее и стандартное отклонение признака по референтной группе.
              Это и есть база сравнения. Без неё в формуле остаются веса и оценки,
              а величины, приводящей их к одной шкале, нет.
            </p>
          </div>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Отсюда простое следствие, которое обычно проговаривают неохотно: одни и те же
            оценки животного на разных базах дают разный индекс. Число «+512» — не свойство
            коровы, а её положение относительно названной группы. Поэтому версия базы
            хранится вместе с результатом и печатается в документе: без неё через полгода
            нечем объяснить, откуда взялось выданное число.
          </p>
        </section>

        {/* ---------------------------- Ноль ----------------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Почему среднее у всех признаков нулевое
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Племенная ценность измеряется отклонением от базовой популяции, а не абсолютной
            величиной: «+512 кг молока» означает «на 512 килограммов больше, чем даёт
            базовая группа». Значит среднее по базе равно нулю по построению — и при смене
            базы его обнуляют заново, сдвигая все оценки разом.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Сдвиг этот не символический. В США базу меняют раз в пять лет; с 1 апреля 2025
            года она отсчитывается от коров рождения 2020 года, а не 2015-го. По
            предварительной оценке CDCB, у голштинов при этом вычлось 750 фунтов молока
            (340 кг), 45 фунтов жира (20 кг), 30 фунтов белка (14 кг) и 2,5 месяца
            продуктивной жизни. Ни одна корова при этом не изменилась — изменилось то,
            с чем её сравнивают.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Это ровно та причина, по которой каталожные числа быков нельзя сравнивать
            между поколениями каталогов, не глядя на базу, — и ровно та причина, по которой
            у нашей базы есть версия в названии.
          </p>
        </section>

        {/* --------------------------- Откуда числа ---------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Откуда взяты числа
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Из технического документа USDA — того, по которому считается американский
            индекс Net Merit. Индекс впервые опубликован в 1994 году лабораторией USDA
            и пересматривается каждые три-четыре года; редакцию 2025 года готовила
            лаборатория геномики и улучшения животных USDA (AGIL) под руководством
            Пола ВанРадена, а утверждал совет директоров CDCB в декабре 2024 года.
            В нём двенадцать отдельных признаков и пять композитов.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Нам от этого документа нужна одна таблица — стандартные отклонения признаков.
            Не веса: веса у нас свои, и профиль Ассоциации — не копия NM$. Именно
            отклонения, потому что это и есть мера, в которой считается индекс.
          </p>

          <h3 className="mt-8 text-[19px] font-medium leading-tight">
            Что означает «-metric» в названии версии
          </h3>

          <p className="mt-3 text-[16px] leading-relaxed text-ink-700">
            Американские величины даны в фунтах. Мы переводим их в килограммы
            коэффициентом {POUND_TO_KG.toString().replace('.', ',')} — это единственное,
            что мы делаем с исходными числами, и это проверяется калькулятором за минуту:
            566,88 × {POUND_TO_KG.toString().replace('.', ',')} ={' '}
            {(566.88 * POUND_TO_KG).toFixed(1).replace('.', ',')}.
            Название версии поэтому состоит из двух частей: откуда взято и что с этим
            сделано. Строка <code className="text-[15px]">{BASE_VERSION}</code> читается
            как утверждение, а не как ярлык.
          </p>
        </section>

        {/* ---------------------------- Таблица -------------------------------- */}
        <section className="mt-14">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Признак за признаком
          </h2>

          <div className="mt-6 overflow-x-auto">
            <table className="data-table w-full min-w-[720px] text-[14px]">
              <thead>
                <tr>
                  <th className="text-left">Признак</th>
                  <th className="w-[150px] text-right">σ в источнике</th>
                  <th className="w-[130px] text-right">σ у нас</th>
                  <th className="w-[110px] text-right">Единица</th>
                  <th className="w-[230px] text-left">Как получено</th>
                </tr>
              </thead>
              <tbody>
                {TRAIT_BASE.map((t) => {
                  const m = BASE_SOURCE[t.key]
                  const guess = m.how === NO_MATCH
                  return (
                    <tr key={t.key}>
                      <td>{t.label}</td>
                      <td className="text-right tabular-nums text-ink-500">
                        {m.source} {m.unit}
                      </td>
                      <td className="text-right tabular-nums">
                        {t.sd.toLocaleString('ru-RU', { maximumFractionDigits: 2 })}
                      </td>
                      <td className="text-right text-ink-500">{t.unit}</td>
                      <td className={guess ? 'text-[#9e3520]' : 'text-ink-500'}>{m.how}</td>
                    </tr>
                  )
                })}
              </tbody>
            </table>
          </div>

          <p className="mt-5 max-w-[75ch] text-[14px] leading-relaxed text-ink-500">
            Столбец «σ у нас» собирается из того же массива, по которому считается индекс.
            Переписать его сюда руками значило бы завести вторую правду, которая разойдётся
            с первой на ближайшей правке базы — и разойдётся молча.
          </p>
        </section>

        {/* ------------------------- Чего в источнике нет ---------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Два признака, которых в источнике нет
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            {TRAIT_BASE.length - GUESSED} строк таблицы совпадают с документом USDA дословно
            или переводом единиц. Остальные {GUESSED} — нет, и об этом надо говорить прямо,
            потому что от стандартного отклонения зависит вклад признака в индекс.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            <strong className="font-medium">Смертность приплода.</strong> Такого признака
            в Net Merit нет. Есть живучесть коров (LIV, σ = 1,62 %) и живучесть тёлок
            (HLIV, σ = 0,36 %). У нас стоит 1,62 — то есть отклонение живучести коров.
            Разница между двумя вариантами больше, чем кажется, и направление у неё
            обратное привычному: отклонение стоит в знаменателе. Оценка делится на σ,
            прежде чем войти в индекс, — поэтому с σ = 1,62 тот же прогноз двигает
            итог в четыре с половиной раза слабее, чем с σ = 0,36. Взяв живучесть коров
            вместо живучести тёлок, мы приглушили смертность приплода, а не усилили.
            Это не ошибка расчёта — это допущение, и до нынешнего разбора оно нигде
            не было названо.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            <strong className="font-medium">Лёгкость отёла.</strong> В Net Merit этот блок
            выражен деньгами — Calving Ability $ со стандартным отклонением 13,1 доллара.
            У нас признак измеряется баллом и σ = 1,3. Пересчёта из долларов в баллы
            не существует: это разные величины, и совпадение порядка не делает их одной.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Обе подстановки касаются признаков с малым весом, и на порядок животных
            в книге они влияют слабо. Но «влияют слабо» — это оценка, а не отсутствие
            влияния, и её место на странице, а не в комментарии к коду.
          </p>
        </section>

        {/* --------------------------- Почему чужая ---------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Почему база заимствованная
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Потому что своей нет. Собственная база сравнения — это результат работы
            расчётного центра: оценки по модели животного на национальной популяции,
            из которых получают компоненты дисперсии, а из них — стандартные отклонения.
            Такой оценки по российским голштинам, доступной и опубликованной,
            на сегодня нет.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Заимствование при этом не произвольное: голштин — порода международная,
            и разброс племенных ценностей внутри неё сопоставим между странами.
            Это допущение, и оно названо допущением. Альтернативы у него две, и обе хуже:
            не считать индекс вовсе или посчитать его на выдуманных числах.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Что произойдёт, когда собственная выборка накопится: таблица пересчитывается
            по ней, версия базы меняется, ранее выпущенные документы остаются со старой
            версией и остаются объяснимыми. Переделывать книгу под это не придётся —
            ради этого у базы и есть версия.
          </p>
        </section>

        {/* ------------------------ Чего это не доказывает --------------------- */}
        <section className="mt-14 max-w-[75ch] rounded-2xl border border-ink-100 bg-white p-6 sm:p-8">
          <h2 className="text-[20px] font-medium leading-tight">Чего этот разбор не доказывает</h2>

          <div className="mt-5 space-y-4 text-[15px] leading-relaxed text-ink-500">
            <p>
              <strong className="font-medium text-ink-700">
                Что наш индекс сопоставим с официальным NM$.
              </strong>{' '}
              Не сопоставим. Мы берём из документа USDA только стандартные отклонения,
              а сама оценка животного считается у нас на своих данных и по своему профилю.
              Сравнивать наше число с каталожным NM$ или TPI нельзя — совпадёт оно только
              случайно.
            </p>
            <p>
              <strong className="font-medium text-ink-700">
                Что мы считаем истинное генетическое отклонение.
              </strong>{' '}
              Строго его получают из компонент дисперсии по модели животного, и это работа
              расчётного центра. У нас считается разброс оценок. Разница существенная,
              и она названа на странице экономического индекса тоже.
            </p>
            <p>
              <strong className="font-medium text-ink-700">
                Что веса Net Merit подходят российскому хозяйству.
              </strong>{' '}
              Веса — вопрос отдельный от базы, и их мы у CDCB не берём. Экономический
              профиль считается на российских ценах, а профиль Ассоциации — на своих
              долях влияния.
            </p>
          </div>
        </section>

        <TermsSeen slugs={note.terms} />
        <NoteSources note={note} />
        <NoteNeighbours notes={NOTES} current={SLUG} />
      </main>

      <ProductFooter lang={locale} />
    </>
  )
}
