/**
 * Разбор: выбытие за год.
 *
 * ## Зачем написан
 *
 * Доля выбытия — единственное число на экране «Отчёты», которое хозяйство
 * умеет улучшать, ничего не меняя: достаточно перестать выбраковывать.
 * Отчёт при этом покажет успех, а стадо станет хуже, и никакая подпись
 * под числом от этого не спасёт — спасает только объяснение, из чего
 * число собрано. Поэтому разбор начинается не с толкования, а с двух
 * предикатов запроса: что стоит в числителе и что в знаменателе.
 *
 * Второе, ради чего он написан: первотёлки. Их выбытие говорит
 * о выращивании тёлок и о подборе, а не о старении стада, и в общем
 * итоге оно тонет — сорок голов из четырёхсот выглядят одинаково,
 * из скольких бы первотёлок они ни состояли. Вынести их отдельным
 * числом стоило именно поэтому, и объяснить это надо здесь.
 *
 * ## Почему условия показаны кусками SQL
 *
 * Тот же довод, что в разборе удоя по группам. «Выбытие считается
 * за двенадцать месяцев» — проверяемое утверждение, и проверять его
 * читатель должен не на слово. Предикаты на странице собираются вызовами
 * из `lib/sql-herd.ts`, то есть из того же места, откуда их берёт запрос
 * отчёта и переход к списку в `herd-drilldown.ts`. Набранные словами,
 * они разошлись бы с запросом на первой же правке правила — и разошлись
 * бы молча.
 *
 * ## Почему «Структура по лактациям» разбирается тут
 *
 * Так решено в реестре разборов (`lib/notes.ts`): у той карточки три
 * числа и ни одного решения, которое требовалось бы объяснять отдельно,
 * а всё, что о ней стоит сказать, относится к выбытию. Высокая доля
 * первой лактации и высокая доля выбытия — одно и то же явление,
 * померенное с двух сторон: сколько ушло и кем заменили. Разводить это
 * по двум страницам значило бы разорвать единственную связку, ради
 * которой обе карточки стоят на одном экране.
 *
 * ## Что нашлось по дороге
 *
 * Числитель и знаменатель считаются по разным множествам. Выбывшие
 * берутся без проверки пола и без проверки архива — «сколько хозяйство
 * потеряло», и это осознанно, — а живые в знаменателе это `liveFemale`
 * без архива, то есть только самки, зато вместе с тёлками и телятами.
 * Доля поэтому не «доля коров, выбывших за год»: сверху могут стоять
 * быки, снизу стоит весь ремонт. Сказано об этом на странице прямо,
 * потому что подпись на экране («% от стада с выбывшими») этой разницы
 * не называет.
 *
 * Второе: «из них первотёлок» считается по `lactations <= 1`, то есть
 * включает животных без единого отёла. Это защищено доводом
 * в `herd-drilldown.ts` — выбывшая тёлка есть та же непокрытая стоимость
 * выращивания, только полная, — и довод верный; неверна подпись, потому
 * что тёлка первотёлкой не была. Разбор называет число тем, что оно
 * считает.
 *
 * Третье, и самое неприятное: `culledYear` смотрит на дату выбытия,
 * а событие «выбытие» в ленте и перемещение вида «Выбраковка» её
 * не проставляют — оба меняют только состояние животного. Корова,
 * выбывшая через кабинет, из знаменателя уходит (она больше не `alive`)
 * и в числитель не попадает. Отчёт от этого не врёт, но занижает,
 * и объяснить читателю, почему у него «выбытие 3 %», надо до того,
 * как он этому обрадуется.
 *
 * ## Отвергнутые варианты
 *
 * Считать долю от среднегодового поголовья, как принято в зарубежных
 * сводках, не стали: среднегодовое восстанавливается по истории движения,
 * а история движения в книге неполна — часть выбытий проведена без даты.
 * Точное деление на неточный остаток выглядело бы строже и врало бы
 * увереннее. Довод записан на странице, а не только здесь.
 *
 * Заводить рядом «долю вынужденного выбытия» отдельным числом тоже
 * не стали. Вынужденное от добровольного отличает только проставленная
 * причина, и в хозяйстве, где половина строк без причины, такое число
 * считалось бы по половине данных, а показывалось бы как целое.
 */

