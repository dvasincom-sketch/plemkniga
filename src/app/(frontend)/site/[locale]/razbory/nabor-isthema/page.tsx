import type { Metadata } from 'next'
import { notFound } from 'next/navigation'
import { ProductFooter, ProductHeader } from '@/components/site/ProductShell'
import { NoteHeader, NoteNeighbours, NoteSources } from '@/components/site/NoteFrame'
import { TermsSeen } from '@/components/site/TermsSeen'
import { NOTES, noteBySlug } from '@/lib/notes'
import { pageMetadata } from '@/lib/seo'
import { isLocale, type Locale } from '@/lib/i18n/locales'
import { AFC_REFERENCE_BANDS, AFC_REFERENCE_META } from '@/lib/afc-reference'

const SLUG = 'nabor-isthema'

export async function generateMetadata(): Promise<Metadata> {
  const note = noteBySlug(SLUG)!
  return pageMetadata({
    title: note.title,
    description: note.lead,
    path: `/ru/razbory/${SLUG}`,
  })
}

/**
 * Разбор справочного набора, на котором стоит полоса сравнения в отчёте
 * «Возраст первого отёла».
 *
 * ## Зачем он написан
 *
 * В отчёте рядом с распределением хозяйства стоит британское, и подпись
 * под ним умещает источник в одну строку. Для числа этого мало: полоса
 * сравнения меняет решение — хозяйство, увидев себя хуже полосы, начинает
 * что-то делать. Значит должно быть место, где сказано, чья это полоса,
 * как она посчитана и чего по ней делать нельзя.
 *
 * ## Почему это разбор, а не пересказ статьи
 *
 * Пересказать Истхэма может кто угодно, и пересказов достаточно.
 * Здесь другое: у нас есть его исходные данные, мы посчитали по ним сами,
 * получили сходимость с публикацией и расхождения — и то и другое
 * показываем. Это и есть содержание, которого нет в пересказах: не «что
 * написано в статье», а «что получилось, когда мы её проверили».
 *
 * ## Чего в разборе нет намеренно
 *
 * Совета «телите в столько-то месяцев». Возраст без живой массы советует
 * неправильно, а массы тёлок в системе нет (`docs/vozrast-pervogo-otela.md`,
 * раздел 5). Разбор доводит читателя до правильной формулировки — возраст
 * при условии массы — и на этом останавливается.
 */
export default async function EasthamNotePage({
  params,
}: {
  params: Promise<{ locale: string }>
}) {
  const { locale: raw } = await params
  if (!isLocale(raw)) notFound()
  const locale: Locale = raw
  const note = noteBySlug(SLUG)!

  /** Сходимость с публикацией — доказательство, что колонки прочитаны верно. */
  /*
   * Левый столбец считается из самого набора, правый набран из публикации.
   * Иначе сходимость доказывала бы сама себя: два одинаковых числа, набранных
   * рукой, сходятся всегда.
   */
  const early = AFC_REFERENCE_BANDS.find((b) => b.key === 'early')
  const veryLate = AFC_REFERENCE_BANDS.find((b) => b.key === 'veryLate')
  const AGREEMENT: [что: string, унас: string, встатье: string][] = [
    ['Коров в расчёте', AFC_REFERENCE_META.cows.toLocaleString('ru-RU'), '396 534'],
    ['Средний возраст, мес.', AFC_REFERENCE_META.meanAfc.toLocaleString('ru-RU'), '29,1'],
    ['Медиана, мес.', String(AFC_REFERENCE_META.medianAfc), '28'],
    ['Доля до 24 мес.', `${(early?.share ?? 0).toLocaleString('ru-RU')} %`, '12,3 %'],
    ['Доля 31 мес. и старше', `${(veryLate?.share ?? 0).toLocaleString('ru-RU')} %`, '40,9 %'],
  ]

  return (
    <>
      <ProductHeader locale={locale} />

      <main className="container-page pb-16">
        <NoteHeader note={note} />

        {/* ---------------------------- Что это -------------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Что это за набор
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Работа Истхэма с соавторами 2018 года — одно из самых крупных наблюдений
            за возрастом первого отёла: 396 534 коровы
            из {AFC_REFERENCE_META.herds.toLocaleString('ru-RU')} британских хозяйств, отёлы
            2006–2008 годов, наблюдение продолжено до 2012-го. Авторы смотрели, что
            происходит с коровой дальше в зависимости от того, в каком возрасте она
            отелилась впервые.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Важное для нас: исходные записи выложены авторами на Dryad под лицензией CC0.
            Это редкость — обычно доступна только статья, — и именно поэтому набор годится
            в справочную полосу: не «по данным исследований», а конкретные записи,
            которые можно взять и посчитать самому.
          </p>
        </section>

        {/* ------------------------- Почему считали сами ----------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Почему мы посчитали заново, а не переписали из статьи
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Причин две, и вторая важнее первой.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Первая простая: четыре кривые из пяти даны в публикации рисунками.
            Переписывать оттуда нечего — с рисунка снимаются глазом только порядок
            величин и форма.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Вторая — существо дела. У Истхэма опубликованы предсказанные средние
            из смешанной модели, скорректированные на хозяйство, сезон, год и быка.
            А наша страница считает по стаду сырые арифметические средние: иначе она
            считать не умеет и не должна — у одного хозяйства нет ни сезонов, ни быков
            в количестве, на котором такие поправки имеют смысл. Положив рядом
            скорректированные числа, мы сравнили бы сырое со скорректированным
            и показали бы хозяйству расхождение там, где его нет.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Правило общее и стоит того, чтобы его повторить: справочная величина должна
            быть посчитана так же, как считается своя. Иначе сравниваются не стада,
            а способы счёта.
          </p>
        </section>

        {/* ---------------------------- Сходимость ----------------------------- */}
        <section className="mt-14">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Сходимость: чем проверяется, что колонки прочитаны верно
          </h2>

          <p className="mt-5 max-w-[75ch] text-[16px] leading-relaxed text-ink-700">
            Первое, что случается при работе с чужим набором, — колонку понимают неправильно
            и получают правдоподобное число из не той величины. Защита от этого одна:
            посчитать то, что автор опубликовал, и сравнить.
          </p>

          <div className="mt-6 overflow-x-auto">
            <table className="data-table w-full min-w-[520px] text-[14px]">
              <thead>
                <tr>
                  <th className="text-left">Величина</th>
                  <th className="w-[170px] text-right">Наш расчёт</th>
                  <th className="w-[170px] text-right">В публикации</th>
                </tr>
              </thead>
              <tbody>
                {AGREEMENT.map(([what, ours, theirs]) => (
                  <tr key={what}>
                    <td>{what}</td>
                    <td className="text-right tabular-nums">{ours}</td>
                    <td className="text-right tabular-nums text-ink-500">{theirs}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <p className="mt-5 max-w-[75ch] text-[14px] leading-relaxed text-ink-500">
            Расхождение по числу коров — 63 головы, 0,016 %: столько записей не прошло
            наши же проверки на правдоподобность возраста. Остальные величины совпадают
            в пределах округления, и это единственное доказательство правильного чтения,
            которое вообще бывает.
          </p>
        </section>

        {/* ------------------------- Что показываем ---------------------------- */}
        <section className="mt-14">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Что из набора показывается хозяйству
          </h2>

          <p className="mt-5 max-w-[75ch] text-[16px] leading-relaxed text-ink-700">
            Только распределение — четыре группы, те же, на которые разбито собственное
            стадо. Это факт о британских коровах и никакого причинного утверждения
            в себе не несёт.
          </p>

          <div className="mt-6 grid grid-cols-2 gap-4 lg:grid-cols-4">
            {AFC_REFERENCE_BANDS.map((b) => (
              <div key={b.key} className="rounded-2xl border border-ink-100 bg-white p-5">
                <div className="text-[24px] font-medium leading-none tabular-nums text-forest-600">
                  {b.share.toLocaleString('ru-RU')} %
                </div>
                <p className="mt-3 text-[13px] leading-snug text-ink-500">
                  {b.label}
                  <br />
                  {b.cows.toLocaleString('ru-RU')} коров
                </p>
              </div>
            ))}
          </div>

          <p className="mt-5 max-w-[75ch] text-[16px] leading-relaxed text-ink-700">
            А кривые исходов — удой первой лактации, соматика, межотельный период, дожитие
            до второго отёла — не показываются как ориентир «что будет, если снизить
            возраст». Они сырые и смешаны с качеством хозяйства: отёл в 21 месяц получается
            только там, где хорошо выращивают тёлок, а такие хозяйства и доят больше.
            Наш удой за первую лактацию при 21 месяце — 7 385 кг против 6 617 у Истхэма,
            и разница в 768 килограммов не ошибка расчёта: это эффект хозяйства, который
            модель убирает, а среднее нет.
          </p>
        </section>

        {/* --------------------------- Расхождения ----------------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Известные расхождения с публикацией
          </h2>

          <div className="mt-5 space-y-4 text-[16px] leading-relaxed text-ink-700">
            <p>
              <strong className="font-medium">Соматика.</strong> У нас 127 тыс. клеток/мл
              при 21 месяце против 72,8 тыс. у Истхэма. Причина известна: наше —
              арифметическое среднее, его — обратно преобразованное из логарифма,
              то есть геометрическое. У правоскошенного распределения арифметическое
              всегда выше, и отношение 1,74 для соматики обычное.
            </p>
            <p>
              <strong className="font-medium">Дожитие до второго отёла в хвосте.</strong>{' '}
              При 42 месяцах у нас 43,7 % против 64,9 %. Форма кривой совпадает, уровень
              нет, и причину выяснить не удалось: вероятно, разные определения «дожил» —
              у нас наличие записи о втором отёле, у него вероятность из модели.
              По опубликованному тексту это не проверяется, и мы не выдаём догадку
              за объяснение.
            </p>
            <p>
              <strong className="font-medium">Межотельный период</strong> у нас
              систематически длиннее на 14–29 дней — та же разница сырого и модельного.
            </p>
          </div>

          <p className="mt-5 text-[15px] leading-relaxed text-ink-500">
            При этом три экстремума из четырёх совпали с опубликованными точно:
            пожизненный суточный удой максимален при 22 месяцах, межотельный период
            минимален при 23, дожитие до второго отёла максимально при 22. Форма связи
            воспроизводится — расходятся уровни, и расходятся объяснимо.
          </p>
        </section>

        {/* ------------------------ Что из этого следует ----------------------- */}
        <section className="mt-14 max-w-[75ch]">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Что из этого следует российскому хозяйству
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Британское распределение — линейка, а не цель. Разница принципиальная: линейка
            показывает, насколько ваше стадо отличается от большой популяции, а цель
            назначает, куда двигаться. Второго это распределение не умеет: другая страна,
            другие годы, другое кормление.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Тут же кроется главная ловушка темы. Западные работы дают оптимум 22–24 месяца,
            российские нередко 26–28, и соблазнительно объяснить это тем, что «у нас другой
            скот». Объяснение неверное, и показывают это сами российские работы: они
            делятся надвое не по региону и не по породе, а по интенсивности выращивания.
            Поздний оптимум дают стада с низкими приростами; на интенсивно выращенном
            поголовье — осеменение в 14–16 месяцев при 400–410 кг — оптимум совпадает
            с британским.
          </p>

          <div className="mt-6 rounded-2xl bg-brand-50 px-6 py-5">
            <p className="text-[16px] leading-relaxed text-ink-700">
              Правильная формулировка звучит так: ориентир — 22–25 месяцев{' '}
              <strong className="font-medium">при условии</strong> 400 кг живой массы
              к 14–15 месяцам. 26–28 месяцев — не цель, а компенсация низких приростов.
            </p>
          </div>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Разница между двумя прочтениями стоит денег: в первом случае хозяйству надо
            менять возраст осеменения, во втором — кормление, и совет «телите в 24 месяца»,
            выданный стаду, где тёлки к пятнадцати месяцам весят 360 кг, — это совет
            отелить недоразвитую корову.
          </p>
        </section>

        {/* ------------------------ Чего это не доказывает --------------------- */}
        <section className="mt-14 max-w-[75ch] rounded-2xl border border-ink-100 bg-white p-6 sm:p-8">
          <h2 className="text-[20px] font-medium leading-tight">Чего этот разбор не доказывает</h2>

          <div className="mt-5 space-y-4 text-[15px] leading-relaxed text-ink-500">
            <p>
              <strong className="font-medium text-ink-700">
                Что снижение возраста первого отёла само по себе улучшает исходы.
              </strong>{' '}
              Работа наблюдательная. Она показывает связь, а не причину, и смешанная модель
              с поправками на хозяйство, сезон и быка права на слово «поэтому» не даёт.
            </p>
            <p>
              <strong className="font-medium text-ink-700">
                Что британское распределение — норма для России.
              </strong>{' '}
              Это распределение британских стад 2006–2008 годов, и оно описывает их,
              а не задаёт норму кому бы то ни было.
            </p>
            <p>
              <strong className="font-medium text-ink-700">
                Что по возрасту можно давать рекомендацию.
              </strong>{' '}
              Возраст без живой массы советует неправильно, а массы тёлок в системе
              сейчас нет. Пока её нет, книга показывает факт и связь и не называет цель —
              это ограничение названо прежде, чем его нашли.
            </p>
          </div>
        </section>

        <TermsSeen slugs={note.terms} />
        <NoteSources note={note} />
        <NoteNeighbours notes={NOTES} current={SLUG} />
      </main>

      <ProductFooter lang={locale} />
    </>
  )
}
