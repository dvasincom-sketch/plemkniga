/**
 * Разбор: инбридинг, посчитанный по неполной родословной.
 *
 * ## Зачем он написан
 *
 * Коэффициент инбридинга читают как измерение животного — вроде удоя
 * или живой массы. А это сумма по записям: сколько общих предков нашлось
 * в карточках, столько и вошло в число. Отсюда единственная мысль, ради
 * которой разбор и затевался: пропуск в родословной всегда занижает
 * коэффициент и никогда не завышает. Показанное число — нижняя оценка,
 * и зоотехник, который об этом не знает, читает «мало родства» там,
 * где написано «мало записей».
 *
 * Разбор поэтому начинается с направления ошибки, а не с формулы.
 * Формула нужна дальше — чтобы объяснить, почему направление именно такое.
 *
 * ## Почему числа считаются, а не набраны руками
 *
 * Порог берётся из `lib/herd-analytics.ts`, глубины обхода — из
 * `lib/mating.ts` и `lib/ancestry.ts`, а обе таблицы (степени родства
 * и вклад по коленам) собираются той же формулой Райта, по которой
 * считает подбор. Набранная руками таблица разошлась бы с расчётом
 * на первой правке глубины, и разошлась бы молча: страница, объясняющая
 * происхождение чисел, показывала бы не те числа.
 *
 * Совпадение порога с коэффициентом двоюродных здесь не подписано словами
 * «6,25 %», а получается сложением путей — если однажды порог сдвинут,
 * страница перестанет утверждать равенство, которого больше нет.
 *
 * ## Почему разбор кончается тремя отрицаниями
 *
 * Тема располагает к проповеди: показал таблицу — и читатель уходит
 * с убеждением, что инбридинг это вред, ноль это чистота, а 6,25 % —
 * запрет. Все три вывода неверны, и все три удобны. Поэтому они названы
 * в конце прямо.
 */

/* ------------------------------ Типографика ------------------------------- */

/**
 * Дробное число по-русски: запятая, без хвостовых нулей.
 *
 * Пять знаков после запятой — не про точность, а про честность таблицы
 * глубины: (1/2)⁷ это ровно 0,78125, и округлённое «0,78» в столбце,
 * где рядом стоит 0,00019, выглядело бы обрывом ряда, а не числом.
 */
const dec = (v: number, digits = 5): string =>
  v.toLocaleString('ru-RU', { maximumFractionDigits: digits })

/** Проценты: между числом и знаком — неразрывный пробел. */
const p = (v: number, digits = 5): string => `${dec(v, digits)}${NBSP}%`

/** Колена: неразрывный пробел между числом и словом. Глубины у нас 6 и 9. */
const gen = (n: number): string => `${n}${NBSP}колен`

const SUP = '⁰¹²³⁴⁵⁶⁷⁸⁹'
const sup = (n: number): string =>
  String(n)
    .split('')
    .map((d) => SUP[Number(d)])
    .join('')

/* ------------------------------ Арифметика -------------------------------- */

/**
 * Путь к общему предку: сколько колен от быка и сколько от коровы.
 *
 * Колено считается от самого животного, как в обходе `mating.ts`: родитель
 * — первое колено, сам зверь — нулевое. Нулевое нужно ради спаривания отца
 * с дочерью, где общий предок — сам бык.
 */
type Path = [bull: number, cow: number]

/** Вклад одного пути в коэффициент родства по Райту, %. */
const share = ([b, c]: Path): number => 0.5 ** (b + c + 1) * 100

/** Коэффициент родства: сумма по всем путям ко всем общим предкам. */
const kinship = (paths: Path[]): number => paths.reduce((sum, x) => sum + share(x), 0)

/**
 * Слагаемое словами. Во всех учебных случаях пути одинаковой длины,
 * поэтому сумма сворачивается в «столько-то раз одна дробь».
 */
const term = (paths: Path[]): string => {
  const e = paths[0][0] + paths[0][1] + 1
  return `${paths.length > 1 ? `${paths.length}${NBSP}× ` : ''}(1/2)${sup(e)}`
}

