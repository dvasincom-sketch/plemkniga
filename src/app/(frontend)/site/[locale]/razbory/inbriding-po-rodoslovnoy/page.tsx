const FULL_SIBS = kinship([[1, 1], [1, 1]])
const HALF_SIBS = kinship([[1, 1]])
const COUSINS = kinship([[2, 2], [2, 2]])
const HALF_COUSINS = kinship([[2, 2]])

/**
 * Вклад общего предка по коленам — на один путь с каждой стороны.
 *
 * Ряд доводится до девятого колена, чтобы разница между глубиной подбора
 * и глубиной карточки была видна числами, а не обещанием «там мало».
 */
