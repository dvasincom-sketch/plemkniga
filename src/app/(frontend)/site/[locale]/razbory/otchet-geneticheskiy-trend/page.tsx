/**
 * Разбор: генетический тренд и инбридинг в отчётах по стаду.
 *
 * ## Зачем написан
 *
 * Наклон линии читают как оценку работы: вверх — хорошо подбирали,
 * вниз — плохо. Ни то ни другое из графика не следует. В точку года
 * входят три разные вещи сразу — свой отбор, покупка чужих животных
 * и база сравнения, относительно которой посчитаны оценки, — и последняя
 * двигает всю линию разом, не изменив ни одного животного. Хозяйство,
 * которое этого не знает, объясняет себе сдвиг базы селекционным
 * успехом или провалом; оба объяснения одинаково ложны и одинаково
 * убедительны.
 *
 * Со второй линией то же самое с другой стороны. Средний инбридинг
 * считается по записанному, а записано не всё: пустая родословная даёт
 * красивое число, и стадо тем «чище», чем хуже его учёт.
 *
 * ## Почему цена смены базы посчитана, а не описана словами
 *
 * «Смена базы сдвигает индекс» — фраза, с которой соглашаются и о которой
 * забывают. Число забыть труднее. Поэтому сдвиг переведён здесь в очки
 * индекса: на весах профиля Ассоциации, на стандартных отклонениях
 * из `TRAIT_BASE` и на том же масштабе `INDEX_SCALE`, по которым считает
 * сам расчёт. Правка любого из трёх мест меняет число на странице вместе
 * с расчётом, а не оставляет его памятником.
 *
 * Совпадение порога с коэффициентом двоюродных тоже не подписано словами,
 * а получается сложением путей по Райту: сдвинется порог — страница
 * перестанет утверждать равенство, которого больше нет.
 *
 * ## Что нашлось по дороге
 *
 * График строится на `animals.ipc` — хранимом поле карточки, а не
 * на посчитанном индексе. Посчитанный лежит в `index-values` вместе
 * с версией базы и годом рождения; на графике его нет. То есть у чисел,
 * из которых собран «генетический тренд», версия базы рядом не стоит,
 * и сравнивать точки разных лет между собой можно только с оговоркой.
 * Оговорка названа на странице прямо, а не спрятана в примечание.
 */

/* ------------------------------ Арифметика -------------------------------- */

/** Признак базы по ключу: σ берётся оттуда же, откуда его берёт расчёт. */
const trait = (key: TraitKey) => TRAIT_BASE.find((t) => t.key === key)!

/** Вес признака в профиле Ассоциации, %. Признака без веса в профиле нет. */
const weight = (key: TraitKey): number => ASSOCIATION_PROFILE.weights[key] ?? 0

/**
 * Сдвиг оценок при смене базы CDCB 1 апреля 2025 года.
 *
 * Четыре величины — предварительная оценка самого CDCB по голштинам,
 * названная в разборе базы сравнения. Здесь они данные, а не результат:
 * всё, что из них выводится — килограммы, доли стандартного отклонения
 * и очки индекса, — считается ниже на константах расчёта.
 */
const BASE_SHIFT: { key: TraitKey; pounds?: number; own?: number }[] = [
  { key: 'milk', pounds: 750 },
  { key: 'fatKg', pounds: 45 },
  { key: 'proteinKg', pounds: 30 },
  { key: 'productiveLongevity', own: 2.5 },
]

type Shift = (typeof BASE_SHIFT)[number]

/** Строка сдвига по признаку — по ключу, а не по месту в списке. */
const shiftOf = (key: TraitKey): Shift => BASE_SHIFT.find((s) => s.key === key)!

/** Сдвиг в единицах самого признака: фунты переводятся, месяцы уже наши. */
const amountOf = (s: Shift): number => (s.pounds === undefined ? s.own! : s.pounds * POUND_TO_KG)

/**
 * Как сдвиг назван у источника.
 *
 * Окончание склоняется, а не дописано буквой: правки в этом списке
 * неизбежны, а «45 фунта» замечает только тот, кто и без того всё знает.
 */
const sourceLabel = (s: Shift): string =>
  s.pounds === undefined
    ? `${nf(s.own!, 1)}${NBSP}${plural(s.own!, 'месяц', 'месяца', 'месяцев')}`
    : `${nf(s.pounds, 0)}${NBSP}${plural(s.pounds, 'фунт', 'фунта', 'фунтов')}`

/** Тот же сдвиг в стандартных отклонениях признака. */
const sigmasOf = (s: Shift): number => amountOf(s) / trait(s.key).sd

/** И он же в очках индекса: вес профиля на доли σ, умноженные на масштаб. */
const pointsOf = (s: Shift): number => (weight(s.key) / 100) * sigmasOf(s) * INDEX_SCALE

/** Сколько очков индекса стоила бы такая смена базы всему стаду сразу. */
const SHIFT_POINTS = BASE_SHIFT.reduce((sum, s) => sum + pointsOf(s), 0)

/*
 * Сколько признаков сдвинулось больше чем на своё стандартное отклонение.
 *
 * Считается, а не пишется словом. В тексте стояло «три признака из четырёх»
 * при четырёх из четырёх: продуктивное долголетие сдвинулось на 1,47 σ,
 * и таблица строкой выше это показывала. Утверждение противоречило
 * собственной колонке — и было единственным в разделе, что не бралось
 * из кода.
 */
const ABOVE_SIGMA = BASE_SHIFT.filter((s) => sigmasOf(s) > 1).length

/** Вклад одного пути к общему предку по Райту, %. */
const wrightShare = (fromSire: number, fromDam: number): number =>
  0.5 ** (fromSire + fromDam + 1) * 100

/** Двоюродные: общие дед и бабка — два пути по два колена с каждой стороны. */
const COUSINS = wrightShare(2, 2) * 2

/** Полусибсы — для верхней ступени разговора о числе. */
const HALF_SIBS = wrightShare(1, 1)

/** Проценты по-русски: запятая и неразрывный пробел перед знаком. */
const pc = (v: number, digits = 2): string =>
  `${v.toLocaleString('ru-RU', { maximumFractionDigits: digits })}${NBSP}%`

