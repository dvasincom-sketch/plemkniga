/**
 * Разбор: что делать с породой, у которой нет ни геномики, ни книги.
 *
 * ## Зачем он написан
 *
 * Про малочисленные породы в отрасли говорят двумя способами, и оба
 * бесполезны читателю. Первый — пафос о сохранении генофонда, после
 * которого не остаётся ни одного действия. Второй — «нужна геномная
 * оценка», после которого остаётся ожидание технологии, которая
 * к породе в несколько сотен голов не придёт никогда, и это следует
 * из её устройства, а не из очереди в лабораторию.
 *
 * Разбор занимает третью позицию: назвать предел метода спокойно
 * и перечислить то, что работает без него. Ничего нового в этом списке
 * нет — учёт происхождения, коэффициент родства, порог при подборе,
 * отбор по потомству. Всё это старше геномики и ею не отменено.
 *
 * ## Почему числа считаются, а не набраны руками
 *
 * Состояние пород — из `breedCatalog()`, то есть из того же вызова,
 * которым живёт страница `/ru/breeds`. Поголовье — из выписки ВНИИплем
 * (`lib/breed-pages.ts`), порог — из `lib/herd-analytics.ts`, глубина
 * расчёта — из `lib/mating.ts`. Набранное руками разошлось бы с витриной
 * в первый же месяц, и разошлось бы молча: страница, которая учит
 * проверять числа, показывала бы не те числа.
 *
 * ## Почему таблица накопления инбридинга подписана как модель
 *
 * Она посчитана формулой Райта из числа быков в обороте, а не измерена
 * ни на одной популяции. Такая таблица убедительна ровно настолько,
 * насколько верны её допущения, — поэтому допущения названы прямо над
 * ней, а не в примечании: случайный подбор, много матерей, замкнутая
 * популяция. Направленный отбор делает картину хуже, и об этом сказано
 * тут же: число в таблице — нижняя граница, а не прогноз.
 *
 * ## Почему разбор кончается тремя отрицаниями
 *
 * Тема располагает к обещанию: «заведите книгу — сохраните породу».
 * Это неправда, и приятная. Породу сохраняют хозяйства, которые её
 * держат; книга делает их работу видимой и управляемой, и не больше
 * того. Сказать это должен сам разбор — до того, как за него это
 * скажет первый читатель, который поверил и обманулся.
 */

/* ------------------------------ Типографика ------------------------------- */

/** Проценты по-русски: десятичная запятая и неразрывный пробел перед знаком. */
const p = (v: number, digits = 2): string => `${nf(v, digits)}${NBSP}%`

/** Голов из тысяч голов: в источнике поголовье записано в тыс. голов. */
const heads = (thousands: number): string => Math.round(thousands * 1000).toLocaleString('ru-RU')

/* ------------------------- Накопление инбридинга -------------------------- */

/**
 * Эффективная численность популяции при `sires` быках в обороте.
 *
 * Полная формула — Ne = 4·Nm·Nf/(Nm+Nf). Матерей в стаде на порядки
 * больше, чем отцов, и при Nf ≫ Nm выражение стремится к 4·Nm: узкое
 * место в замкнутой популяции всегда со стороны быков, а не коров.
 * Упрощение названо здесь, а не спрятано в расчёте, потому что именно
 * оно делает таблицу читаемой одним столбцом «быков».
 */
const effectiveSize = (sires: number): number => 4 * sires

/** Прирост инбридинга за одно поколение, %: ΔF = 1/(2·Ne). */
const deltaF = (sires: number): number => (100 * 1) / (2 * effectiveSize(sires))

/** Накопленный инбридинг через `t` поколений, %: F = 1 − (1 − ΔF)ᵗ. */
const afterGenerations = (sires: number, t: number): number =>
  100 * (1 - (1 - deltaF(sires) / 100) ** t)

/**
 * Через сколько поколений накопленный инбридинг перейдёт порог внимания.
 *
 * Считается перебором, а не логарифмом: ответ нужен целым числом поколений,
 * а логарифм пришлось бы округлять вверх — и на строке, где порог
 * переходится ровно, округление дало бы поколение, которого нет.
 */
const generationsToThreshold = (sires: number): number => {
  for (let t = 1; t <= 100; t += 1) if (afterGenerations(sires, t) >= INBREEDING_THRESHOLD) return t
  return 100
}

