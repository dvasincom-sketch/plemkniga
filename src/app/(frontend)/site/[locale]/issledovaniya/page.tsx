import type { Metadata } from 'next'
import Link from 'next/link'
import { notFound } from 'next/navigation'
import { ProductFooter, ProductHeader } from '@/components/site/ProductShell'
import { PRODUCT_MAIL } from '@/lib/hosts'
import { STUDIES } from '@/lib/studies'
import { pageMetadata } from '@/lib/seo'
import { isLocale, type Locale } from '@/lib/i18n/locales'

export async function generateMetadata(): Promise<Metadata> {
  return pageMetadata({
    title: 'Исследования — что нужно, чтобы проверить работу на живой книге',
    description:
      'Берём опубликованную работу и отвечаем на вопрос, которого не задаёт никто, кроме ' +
      'нас: какие поля книги для этого читаются, сколько записей с ними есть и чего ' +
      'не хватает.',
    path: '/ru/issledovaniya',
  })
}

/**
 * Указатель раздела «Исследования».
 *
 * ## Почему раздел отдельный, а не подраздел разборов
 *
 * У них разный материал и разная ответственность. Разбор объясняет то,
 * что уже считает книга, и отвечает за это целиком. Здесь работа чужая,
 * и наша половина — только вторая: что нужно от базы, чтобы это
 * проверить. Смешать их значило бы поставить рядом текст, за который
 * мы отвечаем, и текст, где половина утверждений принадлежит другим
 * людям, — и читатель не отличил бы одно от другого.
 *
 * ## Почему на карточке стоит, что мы прочли
 *
 * Потому что это первое, что определяет цену текста. Страница по работе,
 * из которой у нас только аннотация, не вправе пересказывать её выводы;
 * прятать это до входа на страницу значит продавать сильное обещание
 * и отдавать слабое.
 *
 * ## Про блок для соискателя
 *
 * Он зовёт написать, а не обещает условия. Обезличивание, договор,
 * упоминание платформы в работе — решения Ассоциации, и ни одного
 * из них пока нет. Написать «данные предоставляются на таких-то
 * условиях» было бы обещанием от чужого имени: соискатель спланировал
 * бы работу, а отвечать за отказ пришлось бы тем, кто ничего
 * не обещал.
 */
export default async function StudiesPage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale: raw } = await params
  if (!isLocale(raw)) notFound()
  const locale: Locale = raw

  return (
    <>
      <ProductHeader locale={locale} />

      <main className="container-page pb-16">
        <section className="max-w-[75ch]">
          <p className="text-[14px] uppercase tracking-wide text-forest-500">Исследования</p>

          <h1 className="mt-3 text-[34px] font-medium leading-tight sm:text-[44px]">
            Что нужно, чтобы проверить это на живой племенной книге
          </h1>

          <p className="mt-6 text-[17px] leading-relaxed text-ink-700">
            Здесь не пересказывают чужие статьи. Пересказ стоит ровно столько, сколько стоит
            наше чтение, и проверить его можно только сходив в первоисточник — а он и так
            по ссылке. Мы отвечаем на другой вопрос: что нужно от базы, чтобы эту работу
            повторить.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-500">
            У каждой работы шесть частей, и порядок не переставляется: что она утверждает;
            что нужно для проверки — поля книги поимённо; что у нас есть сегодня — числом
            из кода; чего не хватает; чем наш ответ будет отличаться; чего пересчёт
            не докажет. Где счёт по живой книге сделать нельзя, так и сказано: не считался.
          </p>
        </section>

        <section className="mt-10 space-y-4">
          {STUDIES.map((s) => (
            <Link
              key={s.slug}
              href={`/${locale}/issledovaniya/${s.slug}`}
              className="block max-w-[75ch] rounded-2xl border border-ink-100 bg-white p-6 transition-colors hover:border-forest-500 sm:p-8"
            >
              <h2 className="text-[20px] font-medium leading-snug sm:text-[22px]">{s.title}</h2>

              <p className="mt-3 text-[15px] leading-relaxed text-ink-700">{s.lead}</p>

              <p className="mt-4 text-[13px] leading-relaxed text-ink-500">
                {s.work.journal}, {s.work.year} ·{' '}
                {s.work.read === 'full'
                  ? 'прочитан полный текст'
                  : 'прочитана только открытая часть'}
              </p>

              <p className="mt-2 text-[13px] text-ink-400">
                {s.author} ·{' '}
                {new Date(s.date).toLocaleDateString('ru-RU', {
                  day: 'numeric',
                  month: 'long',
                  year: 'numeric',
                })}
              </p>
            </Link>
          ))}
        </section>

        {/*
           Приглашение к разговору, а не объявление об условиях.

           Всё, что здесь названо, уже существует и проверяемо: выборка,
           поля, воспроизводимый расчёт. Всё, чего здесь нет, — порядок
           доступа — не забыто, а не решено, и об этом сказано прямо.
           Соискатель, которому пообещали данные и отказали через месяц,
           теряет год работы; названная неопределённость обходится ему
           в одно письмо.
        */}
        <section className="mt-14 max-w-[75ch] rounded-2xl border border-ink-100 bg-ink-50 p-6 sm:p-8">
          <h2 className="text-[24px] font-medium leading-tight sm:text-[28px]">
            Если вы пишете диссертацию или статью
          </h2>

          <p className="mt-5 text-[16px] leading-relaxed text-ink-700">
            Три вещи, которые платформа может дать и которых обычно не хватает именно
            в такой работе. Первая — выборка: не сводная таблица из отчёта, а животные
            с событиями, датами и происхождением. Вторая — поля: они названы теми же
            именами, что в коде, и потому вы заранее знаете, что именно получите
            и чего в этом не будет. Третья — воспроизводимость расчёта: то, как считается
            возраст первого отёла, сервис-период или метод контроля, описано и проверяется
            прогонами, поэтому цифру в вашей работе можно будет пересчитать, а не принять
            на веру.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Что для этого нужно с вашей стороны: вопрос, сформулированный так, чтобы на него
            отвечали поля, а не пожелания; названный период и названные признаки; и понимание,
            что часть записей окажется неполной — какая именно, мы скажем до начала,
            а не после.
          </p>

          <p className="mt-4 text-[16px] leading-relaxed text-ink-700">
            Чего мы здесь не обещаем — условий доступа. Обезличивание, договор, упоминание
            платформы в публикации: это решения Ассоциации, которая ведёт книгу, и ни одного
            из них пока нет. Поэтому правильное начало — письмо, а не заявка по форме.
            Напишите, какой вопрос вы хотите задать данным, и мы ответим, что из этого
            в книге есть сегодня и на каком поголовье.
          </p>

          <p className="mt-5 text-[16px]">
            <a
              href={`mailto:${PRODUCT_MAIL}`}
              className="font-medium text-forest-600 underline underline-offset-4 hover:text-forest-500"
            >
              {PRODUCT_MAIL}
            </a>
          </p>
        </section>

        {/*
           Почему раздел по-русски — на самой странице, а не только
           в комментарии: читатель на казахском адресе видит русский
           текст и вправе знать, что это не поломка.
        */}
        <p className="mt-10 max-w-[75ch] text-[14px] leading-relaxed text-ink-500">
          Раздел выходит только по-русски — как разборы и словарь. Шесть языков от текста,
          вся ценность которого в точности формулировок, дали бы пять машинных переводов.
          Появится проверенный перевод — появится и язык.
        </p>
      </main>

      <ProductFooter lang={locale} />
    </>
  )
}
