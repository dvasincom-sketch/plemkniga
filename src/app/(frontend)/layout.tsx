import type { Metadata } from 'next'
import React, { Suspense } from 'react'
import './globals.css'
import { currentTenant } from '@/lib/tenant-server'
import { Metrika } from '@/components/Metrika'
import { BOOK_HOST, SITE_HOSTS, SITE_LOCALE_HEADER, isSiteHost } from '@/lib/hosts'
import { headers } from 'next/headers'
import { isLocale, type Locale } from '@/lib/i18n/locales'
import { PAGE_MESSAGES } from '@/lib/i18n/page-messages'

/*
 * Заголовок и язык берутся у книги, а не вписаны.
 *
 * Постоянное `metadata` здесь не годится: оно вычисляется один раз
 * на сборку, а книг две и они различаются по заголовку запроса.
 * Голштинское имя во вкладке показательной книги — первое, что увидел бы
 * гость, ещё не открыв страницу.
 *
 * `lang` важнее, чем кажется: по нему читающая программа выбирает голос
 * и правила чтения. Английская страница, помеченная `ru`, будет прочитана
 * вслух русским произношением — то есть неразборчиво.
 */
export async function generateMetadata(): Promise<Metadata> {
  const t = await currentTenant()

  /*
   * Основание для относительных адресов в разметке для поисковых систем.
   *
   * Без него `canonical: '/ru/breeds'` уезжает в разметку как есть,
   * а относительный адрес там не принимается — страница остаётся
   * без указания основной, и поисковая система решает сама, какую
   * из копий считать главной.
   *
   * Домен берётся из заголовка запроса, а не у книги: на витрине
   * и в книге он разный, а раскладка одна на оба домена. Взяв его
   * у книги, мы проставили бы витринным страницам книжный адрес —
   * то есть отдали бы поисковой системе указание считать главной
   * страницу на чужом домене.
   */
  const h = await headers()
  const site = isSiteHost(h.get('host'))
  const host = site ? SITE_HOSTS[0]! : BOOK_HOST

  /*
   * Хвост заголовка вкладки — на языке страницы.
   *
   * Он приклеивается ко всякому заголовку: «The rules by which the book
   * argues with a record — Племенная книга». Английская страница
   * с русским хвостом выглядит наполовину переведённой в двух самых
   * заметных местах сразу — во вкладке браузера и в поисковой выдаче,
   * то есть до того, как страницу вообще открыли.
   *
   * Язык страницы кладёт в заголовок запроса промежуточный обработчик
   * при переписывании витринного адреса; у книги его нет, и хвост
   * остаётся русским — книга русская.
   *
   * Хвост берётся из общего набора подписей, а не из развилки «английский
   * или русский». Развилка тут и стояла — и пережила перевод витрины
   * на все шесть языков: казахская страница получала русский хвост
   * во вкладке и в выдаче, то есть ровно тот шов, ради которого перевод
   * и затевался. Набор строк такого пережить не может: язык в нём
   * не забудешь, потому что без него не соберётся.
   */
  const raw = h.get(SITE_LOCALE_HEADER)
  const locale = isLocale(raw) ? raw : 'ru'
  const suffix = site ? PAGE_MESSAGES[locale].suffix : 'Племенная книга'

  return {
    metadataBase: new URL(`https://${host}`),
    title: {
      /*
       * Заголовок без своего: у витрины это имя продукта, у книги —
       * имя книги вместе с организацией, которая её ведёт.
       */
      default: site
        ? locale === 'en'
          ? 'PLEM online — a herdbook for any breed'
          : 'ПЛЕМ online — племенная книга для любой породы'
        : `Племенная книга — ${t.org.full}`,
      template: `%s — ${suffix}`,
    },
    description:
      'Информационная система для сбора, хранения и анализа данных о крупном рогатом скоте (КРС) с целью определения наиболее перспективных быков-производителей для селекции.',
    /*
     * Разметка для соцсетей и мессенджеров. Ссылку на книгу присылают
     * в переписке чаще, чем набирают руками, и без этих полей она
     * разворачивается голым адресом — то есть выглядит подозрительно
     * ровно там, где решают, открывать её или нет.
     */
    openGraph: {
      type: 'website',
      /*
       * Язык карточки — язык страницы, а не язык арендатора домена.
       *
       * Стояло `t.lang`, то есть язык книги, и витрина на всех шести
       * языках разворачивалась в переписке как русская. Та же ошибка,
       * что была у `<html lang>`: язык брали у домена, хотя он приходит
       * заголовком от промежуточного обработчика и уже посчитан выше.
       */
      locale: site ? OG_LOCALE[locale] : t.lang === 'ru' ? 'ru_RU' : 'en_US',
      /*
       * Имя сайта — своё у каждого домена, и здесь оно было чужим.
       *
       * Стояло `t.org.full`, то есть организация, ведущая книгу, — и
       * на витрине ссылка разворачивалась именем голштинской ассоциации,
       * в том числе на английских страницах, где оно ещё и по-русски.
       * Это та же подмена, из-за которой с витрины убирали шапку и подвал
       * книги, только теперь она вылезала в мессенджере — там, где решают,
       * открывать ссылку или нет, и куда никто из нас не смотрел.
       */
      siteName: site ? 'ПЛЕМ online' : t.org.full,
      /*
       * Картинка превью — по домену, потому что представляются разные
       * лица: витрина продуктом, книга организацией. Картинка одна
       * на все страницы домена и без слов, кроме имени: карточка
       * с заголовком статьи требует изображения на страницу, а их
       * полторы сотни, и половина из них разъедется в первый же месяц.
       *
       * Собраны они из знака и гарнитуры продукта скриптом, а не нарисованы
       * руками: `docs/reshenya.md`.
       */
      images: [
        {
          url: site ? '/og-plem.png' : '/og-book.png',
          width: 1200,
          height: 630,
          alt: site ? 'ПЛЕМ online' : t.org.full,
        },
      ],
    },
    /*
     * Крупная карточка, а не миниатюра сбоку: картинка 1200×630 в узкой
     * карточке обрезается до полосы, на которой знак не читается.
     */
    twitter: { card: 'summary_large_image' },
    /*
     * Значка сайта не было вовсе — ни во вкладке, ни в закладках,
     * ни на телефоне на домашнем экране. Вкладку находят по значку,
     * а не по заголовку: заголовок в узкой вкладке не виден.
     *
     * У витрины он рисованный (`public/icon-plem.svg`): знак продукта
     * составлен из букв, и вектор остаётся резким на любом экране.
     * У книги — голова из знака ассоциации, вырезанная из `logo.svg`.
     */
    icons: { icon: site ? '/icon-plem.svg' : '/icon-book.png' },
    robots: { index: true, follow: true },
  }
}

/**
 * Код языка в разметке для соцсетей: язык и страна, как требует Open Graph.
 *
 * Страна выбрана по тому, где на этом языке читают наши страницы, а не
 * по «главной» стране языка: белорусский — Беларусь, киргизский —
 * Киргизия, и так далее. Для английского оставлено `en_US` как самое
 * распространённое написание.
 */
const OG_LOCALE: Record<Locale, string> = {
  ru: 'ru_RU',
  en: 'en_US',
  kk: 'kk_KZ',
  hy: 'hy_AM',
  be: 'be_BY',
  ky: 'ky_KG',
}

export default async function FrontendLayout({ children }: { children: React.ReactNode }) {
  const t = await currentTenant()

  /*
   * Язык страницы, а не язык книги.
   *
   * `<html lang>` читают программа чтения с экрана, переводчик браузера
   * и поисковая система. Пока он брался у арендатора домена, английская
   * страница витрины объявляла себя русской: читалка произносила
   * английский текст русскими правилами, а браузер предлагал перевести
   * уже переведённое.
   *
   * Адреса в обвязке нет, поэтому язык кладёт в заголовок промежуточный
   * обработчик при переписывании адреса (`middleware.ts`). Нет заголовка —
   * значит это книга, и язык у неё свой.
   */
  const header = (await headers()).get(SITE_LOCALE_HEADER)
  const lang = header && isLocale(header) ? header : t.lang

  return (
    <html lang={lang}>
      <body className="min-h-screen bg-canvas antialiased">
        {children}
        {/*
           Счётчик читает адрес страницы, а он в Next доступен только
           внутри границы ожидания: без неё сборка страниц заранее
           падает целиком. Разбор, где счётчик молчит и почему, —
           в самом компоненте.
        */}
        <Suspense fallback={null}>
          <Metrika id={process.env.YANDEX_METRIKA_ID} />
        </Suspense>
      </body>
    </html>
  )
}
