import type { Metadata } from 'next'
import './(frontend)/globals.css'
import { NotFoundContent } from '@/components/NotFound'

export const metadata: Metadata = { title: 'Страница не найдена — Племенная книга' }

/**
 * «Не найдено» для адресов, не совпавших ни с одним маршрутом.
 *
 * ## Почему здесь свои `html` и `body`
 *
 * Общая раскладка проекта лежит в группе маршрутов
 * (`app/(frontend)/layout.tsx`), а группы не создают сегментов адреса.
 * Адрес, не попавший ни в один маршрут, до раскладки группы не доходит —
 * и страница обязана быть самостоятельной: со своим `html`, своим `body`
 * и собственным подключением стилей. Без этого Next показывает
 * встроенную английскую страницу на чёрном фоне, и весь смысл затеи
 * пропадает.
 *
 * ## Почему без шапки и подвала
 *
 * Шапка знает, кто вошёл, и спрашивает об этом сервер. На странице,
 * которая рисуется вне раскладки, эта зависимость лишняя: ошибка в ней
 * означала бы, что страница «не найдено» сама не открывается. Здесь
 * нужен минимум, который не может сломаться.
 */
export default function RootNotFound() {
  return (
    <html lang="ru">
      <body className="min-h-screen bg-canvas antialiased">
        <main className="container-page pb-8">
          <NotFoundContent />
        </main>
      </body>
    </html>
  )
}
