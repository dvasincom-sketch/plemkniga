import { Breadcrumbs } from '@/components/Breadcrumbs'

/**
 * Общий каркас страницы кабинета: порядок частей задан здесь, а не в каждой.
 *
 * ## Зачем
 *
 * Порядок сложился сам и одинаково выдержан на двенадцати страницах обоих
 * кабинетов: меню, потом хлебные крошки у вложенных, потом заголовок,
 * потом вводный абзац. Но держался он на памяти автора — и на тринадцатой
 * странице сломался: заголовок с абзацем встали над меню, потому что так
 * читалось при написании в одиночку.
 *
 * Заметно это не при написании, а при переходе: человек идёт из «Качества
 * книги» в «Новые колонки», и меню под ним прыгает на двести точек вниз.
 * Ошибку такого рода не ловит ни один просмотр отдельной страницы, потому
 * что каждая по отдельности выглядит разумно.
 *
 * ## Почему меню первым
 *
 * Оно единственное, что не меняется от страницы к странице. Всё, что стоит
 * выше неизменного, заставляет искать неизменное заново при каждом
 * переходе — и меню перестаёт быть точкой опоры, ради которой существует.
 *
 * Заголовок при этом не теряется: он сразу под меню и набран вдвое крупнее
 * всего вокруг.
 *
 * ## Почему компонент, а не правило в гайде
 *
 * Правило в гайде уже было — и не помогло: гайд читают, когда пишут первую
 * страницу, а тринадцатую пишут по памяти о двенадцатой. Каркас, который
 * нельзя собрать в другом порядке, не требует помнить.
 */
export function CabinetPage({
  nav,
  crumbs,
  title,
  intro,
  children,
}: {
  /** Меню кабинета: `<AccountNav />` или `<AssociationNav />`. */
  nav: React.ReactNode
  /**
   * Хлебные крошки — только у вложенных страниц.
   *
   * У раздела первого уровня их нет намеренно: крошка «Кабинет
   * Ассоциации / Хозяйства» повторяет меню, стоящее строкой выше,
   * и означает ровно то же самое.
   */
  crumbs?: { label: string; href?: string }[]
  title: string
  /** Вводный абзац: о чём раздел и чего в нём ждать. */
  intro?: React.ReactNode
  children: React.ReactNode
}) {
  return (
    <main className="container-page pb-8">
      {nav}

      {crumbs && crumbs.length > 0 && <Breadcrumbs items={crumbs} />}

      <div className="min-w-0">
        <h1 className="text-[30px] font-medium leading-tight sm:text-[36px]">{title}</h1>

        {intro && (
          <div className="mt-4 max-w-[80ch] text-[15px] leading-relaxed text-ink-700">{intro}</div>
        )}

        {children}
      </div>
    </main>
  )
}
