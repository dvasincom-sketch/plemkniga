import { InfoTip } from '@/components/InfoTip'
import { FORMULAS, type FormulaKey } from '@/lib/formulas'

/**
 * Число, посчитанное книгой, — с формулой под пунктиром.
 *
 * ## Что означает подчёркивание
 *
 * Ровно одно: это число посчитала книга, и она отвечает за него сама.
 * Привезённые числа не подчёркиваются — за них отвечает тот, кто прислал,
 * и объяснять чужую формулу мы не вправе.
 *
 * Различать их важнее, чем кажется. На одной карточке рядом стоят наш
 * индекс и индекс расчётного центра, наша надёжность и пятибалльная
 * оценка из выгрузки. Выглядят одинаково, а проверить можно только одно
 * из двух — и человек должен видеть, какое именно, до того как примет
 * решение о спаривании или покупке.
 *
 * ## Почему пунктир, а не значок рядом
 *
 * Посчитанных чисел на карточке больше десятка. Кружок «i» у каждого
 * превратил бы её в россыпь значков, и главное — кружок объясняет
 * «что-то поблизости», а подчёркивание объясняет именно это число.
 *
 * ## Почему в подсказке формула, а не пересказ
 *
 * Пересказ вроде «надёжность зависит от числа дочерей» не даёт проверить
 * ничего. Зоотехник, который не может пересчитать индекс на бумаге,
 * обязан ему не верить — и правильно делает. Поэтому в подсказке сама
 * формула, расшифровка обозначений и объяснение, почему считается именно
 * так; последнего в коде нет, поэтому оно и написано руками.
 */
export function Computed({
  formula,
  children,
  label,
}: {
  formula: FormulaKey
  children: React.ReactNode
  /** Чем подписать кнопку для читающих с экрана. */
  label?: string
}) {
  const f = FORMULAS[formula]

  return (
    <InfoTip label={label ?? `Как считается: ${f.title}`} trigger={children}>
      <p className="mb-2 font-medium text-ink-900">{f.title}</p>

      {/*
         Формула набрана моноширинным и на подложке: это не проза,
         и читать её надо как формулу — со знаками, стоящими друг
         под другом при переносе.
      */}
      <p className="mb-3 overflow-x-auto rounded-lg bg-canvas px-3 py-2 font-mono text-[12.5px] leading-relaxed text-ink-900">
        {f.math}
      </p>

      <ul className="mb-3 space-y-1">
        {f.legend.map((l) => (
          <li key={l} className="flex gap-2">
            <span aria-hidden="true" className="text-ink-300">
              ·
            </span>
            <span>{l}</span>
          </li>
        ))}
      </ul>

      <p>{f.why}</p>
    </InfoTip>
  )
}
