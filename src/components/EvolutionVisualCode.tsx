/**
 * Вкладка «Визуальный код».
 *
 * ## Зачем она есть
 *
 * Правила оформления в этом проекте складывались по одному, каждое после
 * своей ошибки, и жили в комментариях к коду и в журнале решений. Пока
 * систему пишет один человек, этого хватает; на втором она рассыпается —
 * не потому, что второй хуже, а потому, что правило, которое нигде
 * не названо, соблюдать нечем.
 *
 * ## Почему это не «дизайн-система» в обычном смысле
 *
 * Здесь нет каталога компонентов с их отступами: он полезен, но описывает,
 * *как* сделано, а не *почему*. Копировать отступы можно и без него —
 * посмотрев в соседний файл. Нельзя без него другого: понять, какое
 * решение принимается, когда правила молчат.
 *
 * Поэтому каждое правило записано вместе с тем случаем, из которого оно
 * выросло. Правило без причины через полгода читается как вкусовщина,
 * и первый же спор заканчивается его отменой.
 *
 * ## Главная мысль, из которой следует остальное
 *
 * Племенная книга — свидетельство. Её показания используют в сделках,
 * и цена ошибки здесь не «неудобно», а «продали не то животное». Значит
 * оформление обязано отвечать за точность: не украшать число, а говорить,
 * откуда оно; не заполнять пустоту, а называть её; не показывать
 * посчитанное наравне с измеренным.
 *
 * ## Почему примеры живые
 *
 * Всё, что здесь показано, набрано теми же классами, что и в самой книге.
 * Картинка с образцами устаревает молча: палитра меняется, картинка
 * остаётся, и через год раздел учит неправде. Живой образец меняется
 * вместе с системой.
 */

const Rule = ({
  title,
  children,
  example,
}: {
  title: string
  children: React.ReactNode
  /** Живой образец: набран теми же классами, что и в книге. */
  example?: React.ReactNode
}) => (
  <article className="card">
    <h3 className="panel-heading">{title}</h3>
    <div className="max-w-[80ch] space-y-3 text-[15px] leading-relaxed text-ink-700">
      {children}
    </div>
    {example && <div className="mt-5 rounded-xl bg-canvas p-4">{example}</div>}
  </article>
)

