/**
 * Мера строки одна на весь раздел — и у текста, и у плашки ограничений.
 *
 * Разнобой мер читается как небрежность: правый край гуляет от блока
 * к блоку, и взгляд ищет его заново на каждом. Шестьдесят с небольшим
 * знаков вместо семидесяти восьми: на широком экране прежняя мера
 * давала строку почти в тысячу точек, а на такой длине глаз теряет
 * начало следующей строки.
 */
const MEASURE = 'max-w-[64ch]'

function B({ children }: { children: ReactNode }) {
  return <b className="text-ink-900">{children}</b>
}

/** Подпись части сценария: мелкая, разрядкой, над содержимым. */
function Label({ children }: { children: string }) {
  return (
    <p className="mb-1.5 text-[12px] font-medium uppercase tracking-[0.08em] text-ink-400">
      {children}
    </p>
  )
}

