function StoryBlock({ story, n }: { story: Story; n: number }) {
  return (
    <article className="border-t border-ink-100 pt-8 first:border-0 first:pt-0">
      {/*
         Номер вынесен в поле слева. Он не украшение: по нему сценарий
         называют вслух («второй в разделе про стадо»), и он же держит
         левый край заголовка на одной линии с текстом ниже.
      */}
      <div className="sm:flex sm:gap-5">
        <span className="hidden shrink-0 pt-1 text-[15px] tabular-nums text-ink-300 sm:block">
          {String(n).padStart(2, '0')}
        </span>

        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-baseline gap-x-3 gap-y-2">
            <h4 className="text-[20px] font-medium leading-snug">{story.title}</h4>
            {story.actors.map((a) => (
              <span
                key={a}
                className={`rounded-lg px-2 py-0.5 text-[12px] whitespace-nowrap ${ACTOR[a].tone}`}
              >
                {ACTOR[a].label}
              </span>
            ))}
            {story.planned && (
              <span className="rounded-lg bg-[#f2f2f2] px-2 py-0.5 text-[12px] whitespace-nowrap text-ink-500">
                пока нет
              </span>
            )}
          </div>

          {/* ---------------------------- Хотят ---------------------------- */}
          <div className="mt-5">
            <Label>Чего хотят</Label>
            <p className={`${MEASURE} text-[15px] leading-relaxed text-ink-700`}>{story.want}</p>
          </div>

          {/* --------------------------- Получают -------------------------- */}
          <div className="mt-5">
            <Label>Что получают</Label>
            {story.lead && (
              <p className={`${MEASURE} text-[15px] leading-relaxed text-ink-900`}>{story.lead}</p>
            )}

            {/*
               Перечисление набрано перечислением, и у каждого пункта
               свой короткий заголовок. Первая редакция складывала
               шесть фактов в один абзац: пять строк сплошного текста
               выглядят как одно утверждение, а были шестью, и глазу
               не за что зацепиться.
            */}
            <dl className={`${MEASURE} mt-3 space-y-2.5`}>
              {story.get.map((p) => (
                <div key={p.head} className="sm:flex sm:gap-3">
                  <dt className="shrink-0 text-[15px] font-medium leading-relaxed text-ink-900 sm:w-[15.5rem]">
                    {p.head}
                  </dt>
                  <dd className="text-[15px] leading-relaxed text-ink-700">{p.text}</dd>
                </div>
              ))}
            </dl>
          </div>

          {/* --------------------------- Не будет -------------------------- */}
          {/*
             Ограничения на своём фоне и не мельче основного текста.
             Мелкий шрифт под абзацем читается как оговорка, которую можно
             пропустить, — а пропускают её ровно те, кому она нужна.
          */}
          <div className={`${MEASURE} mt-5 rounded-xl bg-canvas px-4 py-4`}>
            <Label>Чего не будет</Label>
            <ul className="list-disc space-y-2 pl-5 text-[15px] leading-relaxed text-ink-700">
              {story.limits.map((l, i) => (
                <li key={i}>{l}</li>
              ))}
            </ul>
          </div>

          {story.where && (
            <p className="mt-3 text-[13px] text-ink-500">Где: {story.where}</p>
          )}
        </div>
      </div>
    </article>
  )
}

