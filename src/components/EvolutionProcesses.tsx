/**
 * Бизнес-процессы: кто, чего хочет, что получает и чего не получит.
 *
 * ## Чем это отличается от «Документации»
 *
 * Документация написана для того, кто будет строить интеграцию: модель
 * данных, правила доступа, контракты обмена. Она отвечает на вопрос
 * «как устроено». Здесь другой читатель и другой вопрос: участник —
 * хозяйство, Ассоциация, сервисная организация, государство — приходит
 * узнать, **что он может сделать и что из этого выйдет**.
 *
 * Разделять их пришлось потому, что смешанный текст не читает никто:
 * зоотехник спотыкается о слово «коллекция», интегратор пролистывает
 * рассказ про подбор быка.
 *
 * ## Почему сценарий разложен, а не написан абзацами
 *
 * Первая редакция давала каждому сценарию два абзаца сплошного текста.
 * Читалось это плохо, и по понятной причине: в «что получают» лежало
 * по шесть фактов подряд — форматы, кодировки, разделители, карантин,
 * построчный отчёт, — и ни за один из них глаз не мог зацепиться.
 * Абзац в пять строк выглядит как одно утверждение, а был шестью.
 *
 * Теперь то, что перечисляется, набрано перечислением: у каждого пункта
 * своя строка и короткий заголовок, по которому его находят глазами.
 * Связный довод остаётся абзацем — списком его набирать так же неверно,
 * как перечисление абзацем.
 *
 * ## Мера строки
 *
 * Шестьдесят с небольшим знаков вместо семидесяти восьми. На широком
 * экране прежняя мера давала строку почти в тысячу точек: глаз теряет
 * начало следующей строки и перечитывает её заново, и усталость от этого
 * приписывают тексту, а не вёрстке.
 *
 * ## Почему у каждого сценария названы ограничения
 *
 * Это главное здесь. Система, которая говорит только о том, что умеет,
 * порождает ожидания, которых не выполнит, — и разочарование приходит
 * не в момент чтения, а в момент, когда на неё уже положились. Названное
 * ограничение стоит дешевле: его учитывают заранее либо решают, что оно
 * несущественно.
 *
 * Ограничения пишутся конкретно. «Возможны неточности» — не ограничение,
 * а извинение; «инбридинг считается на шесть колен» — ограничение.
 *
 * ## Почему гармошкой
 *
 * Сценариев больше тридцати. Развёрнутый список на десять экранов читают
 * по диагонали. Открывается любое число разделов: соседние сценарии
 * сравнивают чаще, чем читают один, и захлопывать предыдущий было бы
 * работой против читателя.
 */

