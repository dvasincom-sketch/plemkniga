function StoryBlock({ story }: { story: Story }) {
  return (
    <article className="border-t border-ink-100 pt-6 first:border-0 first:pt-0">
      <div className="flex flex-wrap items-baseline gap-x-3 gap-y-2">
        <h4 className="text-[19px] font-medium leading-snug">{story.title}</h4>
        {story.actors.map((a) => (
          <span
            key={a}
            className={`rounded-lg px-2 py-0.5 text-[12px] whitespace-nowrap ${ACTOR[a].tone}`}
          >
            {ACTOR[a].label}
          </span>
        ))}
        {story.planned && (
          <span className="rounded-lg bg-[#f2f2f2] px-2 py-0.5 text-[12px] whitespace-nowrap text-ink-500">
            пока нет
          </span>
        )}
      </div>

      <P>
        <B>Чего хотят.</B> {story.want}
      </P>
      <P>
        <B>Что получают.</B> {story.get}
      </P>

      {/*
         Ограничения набраны на своём фоне и не мельче основного текста.
         Мелкий шрифт под абзацем читается как оговорка, которую можно
         пропустить, — а пропускают её ровно те, кому она предназначена.
      */}
      <div className="mt-4 rounded-xl bg-canvas px-4 py-3.5">
        <p className="text-[13px] font-medium text-ink-900">Чего не будет</p>
        <ul className="mt-2 max-w-[76ch] list-disc space-y-1.5 pl-5 text-[14px] leading-relaxed text-ink-700">
          {story.limits.map((l, i) => (
            <li key={i}>{l}</li>
          ))}
        </ul>
      </div>

      {story.where && <p className="mt-3 text-[13px] text-ink-500">Где: {story.where}</p>}
    </article>
  )
}

