'use client'

import { useEffect, useState } from 'react'
import { dateTimeRu, FALLBACK_TIME_ZONE } from '@/lib/format'

/**
 * Момент времени в поясе читателя, с подписью пояса.
 *
 * ## Почему компонент, а не функция
 *
 * Пояс читателя знает только браузер, а первую отрисовку делает сервер.
 * Функция, спрашивающая пояс у окружения, на сервере ответила бы поясом
 * контейнера — и до этой правки именно так и было: время показывалось
 * в UTC, потому что контейнер живёт в UTC, а никто этого не объявлял.
 *
 * ## Почему сначала рисуется запасной пояс, а потом местный
 *
 * Соблазн был не рисовать ничего до того, как станет известен пояс.
 * Так делать нельзя по двум причинам. Пустое место на первой отрисовке
 * — это прыжок вёрстки, когда время появляется; а страница без
 * работающих сценариев осталась бы вовсе без времени, хотя показать
 * его есть чем. Поэтому сервер рисует время в московском поясе
 * с подписью «GMT+3», и подпись эта не обманывает: там действительно
 * московское время. После того как страница ожила, оно молча становится
 * местным — и подпись меняется вместе с ним.
 *
 * Расхождения при гидратации здесь нет по построению: первый рендер
 * в браузере даёт то же самое, что дал сервер, — местный пояс
 * подставляется только после, из `useEffect`.
 *
 * ## Почему `<time>`, а не `<span>`
 *
 * В `dateTime` лежит исходная метка целиком, с секундами и смещением.
 * Показанное время округлено до минут и переведено в чей-то пояс —
 * а машине, читающей страницу, нужен сам момент, и брать его из текста,
 * разбирая «GMT+3», было бы способом однажды ошибиться.
 */
export function Moment({ iso, className }: { iso?: string | null; className?: string }) {
  /*
   * Пояс держится в состоянии, а не вычисляется при отрисовке: вычисление
   * прямо в теле дало бы на сервере одно, а в браузере другое — то есть
   * ровно то расхождение, ради избавления от которого компонент и заведён.
   */
  const [timeZone, setTimeZone] = useState(FALLBACK_TIME_ZONE)

  useEffect(() => {
    /*
     * Определение обёрнуто в try: `resolvedOptions` бросает в браузерах
     * с урезанным набором данных о поясах. Отказ здесь означает, что
     * останется московское время с честной подписью, — это хуже местного
     * времени и несравнимо лучше пустоты на месте даты.
     */
    try {
      const tz = Intl.DateTimeFormat().resolvedOptions().timeZone
      if (tz) setTimeZone(tz)
    } catch {
      /* остаётся запасной пояс */
    }
  }, [])

  if (!iso) return <span className={className}>—</span>

  return (
    <time dateTime={iso} className={className}>
      {dateTimeRu(iso, timeZone)}
    </time>
  )
}
