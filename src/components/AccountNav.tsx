import Link from 'next/link'

/**
 * Навигация личного кабинета.
 *
 * Это второй уровень навигации, и он намеренно не похож на первый: меню сайта
 * в шапке — простые текстовые ссылки, здесь — вертикальный список плашек.
 * Раньше оба уровня выглядели одинаковыми рядами кнопок, из-за чего читались
 * как одно меню, хотя между собой никак не связаны.
 *
 * Ряд стоит горизонтально под шапкой: вертикальная колонка отнимала ширину
 * у основного содержимого, а таблицам ширина нужнее. Меню видно на всех
 * страницах кабинета и в карточке своего животного, поэтому из карточки
 * всегда понятно, в каком разделе вы находитесь.
 */

/**
 * У большинства разделов адрес один и тот же — `/account?tab=…`, они живут
 * на одной странице. «Доступы» — отдельный маршрут: там три списка, свои
 * запросы и свои серверные действия, и складывать это в общую страницу
 * значило бы тянуть их на каждое открытие кабинета.
 */
export const ACCOUNT_TABS = [
  { key: 'animals', label: 'Мои животные', hint: 'Стадо и поиск по нему' },
  /*
   * Раздел назывался «События», а подпись под ним гласила «Загрузки данных
   * и их проверка» — название спорило с собственной подписью, и права была
   * подпись. Событий в разделе была одна таблица из пяти блоков.
   *
   * Хуже другое: слово «события» означало в системе три разные вещи —
   * этот раздел, коллекцию `events` и вкладку карточки животного. Человек,
   * пришедший записать отёл, шёл в «События» и не находил там отёлов.
   * Теперь раздел называется тем, что в нём лежит, а слово «события»
   * осталось за событиями: лентой и карточкой животного.
   */
  { key: 'data', label: 'Данные', hint: 'Ввод, проверка и лента событий' },
  { key: 'documents', label: 'Документы', hint: 'Файлы организации' },
  {
    key: 'access',
    label: 'Доступы',
    hint: 'Кому открыты ваши данные',
    href: '/account/access',
  },
  /*
   * Сотрудники и журнал стояли здесь и переехали в настройки.
   *
   * Верхнее меню — это то, чем пользуются каждый день: стадо, данные,
   * документы, доступы. Состав сотрудников правят раз в месяц, журнал
   * открывают, когда что-то случилось. Соседство с «Моими животными»
   * ставило их в один ряд с ежедневной работой и заодно растянуло меню
   * до семи пунктов, которые перестали читаться одним взглядом.
   *
   * Разделы настроек — в `SettingsNav`.
   */
  {
    key: 'settings',
    label: 'Настройки',
    hint: 'Видимость, сотрудники, журнал, реквизиты',
  },
] as const

export type AccountTabKey = (typeof ACCOUNT_TABS)[number]['key']

/**
 * Адрес раздела кабинета.
 *
 * Правило простое — у раздела либо свой адрес, либо вкладка на общей
 * странице, — и именно поэтому его нельзя было держать в двух местах.
 * Меню кабинета считало его правильно, выпадающее меню под именем
 * пользователя — по своей копии, где про `href` не знали. «Доступы»
 * оттуда вели на `/account?tab=access`: вкладка с таким именем на общей
 * странице есть, содержимого у неё нет — оно давно переехало
 * на собственную страницу, — и человек попадал на пустой экран
 * с заголовком.
 *
 * Ошибка не в забытой строке, а в том, что правило было записано дважды.
 * Теперь оно записано один раз, и следующий раздел, получивший свой
 * адрес, разойтись уже не сможет.
 */
export const accountTabHref = (tab: { key: string; href?: string }): string =>
  tab.href ?? `/account?tab=${tab.key}`

export function AccountNav({ active }: { active?: AccountTabKey }) {
  return (
    <nav aria-label="Разделы личного кабинета" className="mb-8">
      <ul className="flex gap-3 overflow-x-auto pb-1">
        {ACCOUNT_TABS.map((t) => {
          const isActive = active === t.key
          return (
            <li key={t.key} className="flex-none">
              <Link
                href={accountTabHref(t)}
                aria-current={isActive ? 'page' : undefined}
                className={`block rounded-xl px-5 py-3 transition-colors ${
                  isActive
                    ? 'bg-forest-500 text-white'
                    : 'bg-white text-ink-900 shadow-[0_1px_3px_rgb(23_24_26_/_0.08)] hover:bg-[#f6f6f6]'
                }`}
              >
                <span className="block whitespace-nowrap text-[15px] font-medium">{t.label}</span>
                <span
                  className={`mt-0.5 block whitespace-nowrap text-[12px] leading-snug ${
                    isActive ? 'text-white/75' : 'text-ink-500'
                  }`}
                >
                  {t.hint}
                </span>
              </Link>
            </li>
          )
        })}
      </ul>
    </nav>
  )
}
