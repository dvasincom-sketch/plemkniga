import Link from 'next/link'

/**
 * Переключатель разделов второго уровня.
 *
 * ## Зачем отдельный компонент
 *
 * Такой ряд плашек был написан дважды — в профиле пользователя и в разделе
 * данных — одинаковыми классами, скопированными из файла в файл. Копия
 * живёт ровно до первой правки: поменяв отступ в одном месте, второе
 * забывают, и два переключателя, означающие одно и то же, начинают
 * выглядеть по-разному. Человек узнаёт элемент по виду быстрее, чем читает
 * подпись, — значит, вид обязан быть один.
 *
 * ## Почему ссылки, а не кнопки с состоянием
 *
 * Разделы второго уровня — это разные наборы данных, и каждый стоит своих
 * запросов к базе. Ссылка перерисовывает страницу на сервере и позволяет
 * запросить только то, что показано; кнопка со внутренним состоянием
 * потребовала бы принести всё сразу и спрятать лишнее. Заодно раздел
 * получает собственный адрес: на него можно сослаться и вернуться назад
 * кнопкой браузера.
 *
 * Исключение — справочник колонок загрузки (`ColumnReference`): там
 * переключатель стоит на странице, где выше лежит результат только что
 * выполненной загрузки, и перерисовка стёрла бы его. Там вкладки на
 * состоянии, и в самом файле написано почему.
 *
 * ## Про подпись под названием
 *
 * Её здесь нет намеренно. В первой редакции профиля подписи стояли —
 * получался двухэтажный переключатель, в котором непонятно, что чему
 * подчинено, при том что верхнее меню кабинета устроено ровно так же.
 * Название раздела объясняет себя само; подсказка осталась в `title`,
 * она нужна раз в жизни, при первом знакомстве.
 */

export type SubTab = {
  key: string
  label: string
  /** Подсказка в `title` — для первого знакомства, не для чтения каждый раз. */
  hint?: string
  href: string
}

export function SubTabs({
  label,
  items,
  active,
  className = '-mt-4 mb-8',
}: {
  /** Что это за набор разделов — для читающей программы. */
  label: string
  items: readonly SubTab[]
  active: string
  /**
   * Отступы. Умолчание рассчитано на единственное правильное место —
   * сразу под меню раздела, у которого свой нижний отступ.
   *
   * Раньше умолчание было другим, а вызывающие стороны его переопределяли:
   * ряд стоял то над заголовком страницы, то под ним. Теперь место у него
   * одно на всём сайте, и переопределять отступ незачем — параметр остался
   * на случай раскладки, которой пока нет.
   */
  className?: string
}) {
  return (
    <nav aria-label={label} className={className}>
      <ul className="flex flex-wrap gap-2">
        {items.map((t) => {
          const isActive = t.key === active
          return (
            <li key={t.key}>
              <Link
                href={t.href}
                aria-current={isActive ? 'page' : undefined}
                title={t.hint}
                className={`block rounded-lg px-3.5 py-1.5 text-[14px] leading-6 transition-colors ${
                  isActive
                    ? 'bg-forest-500 text-white'
                    : 'bg-white text-ink-900 shadow-[0_1px_3px_rgb(23_24_26_/_0.08)] hover:bg-[#f6f6f6]'
                }`}
              >
                {t.label}
              </Link>
            </li>
          )
        })}
      </ul>
    </nav>
  )
}
