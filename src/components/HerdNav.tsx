import { SubTabs } from '@/components/SubTabs'

/**
 * Разделы «Стада».
 *
 * ## Что было не так
 *
 * Отчёты и документы лежали в двух разных местах и оба не там, где их ищут.
 * «Возраст первого отёла» стоял карточкой под таблицей стада — то есть ниже
 * семидесяти строк и трёх экранов прокрутки, и ссылка на него была
 * единственной во всей системе. «Документы» были разделом верхнего уровня,
 * а внутри — таблица из двух строк, и каждая строка про животное.
 *
 * Оба относятся к стаду, и оба теперь стоят рядом с ним подразделами.
 * От этого верхнее меню стало короче на пункт, а отчёт перестал быть тем,
 * до чего нужно доскроллить.
 *
 * ## Почему архив не подраздел
 *
 * Соблазн был: архив — такой же список, и просится четвёртой плашкой.
 * Но архив — это тот же список с тем же поиском и той же разбивкой,
 * включённый признаком `archive=1`, и подраздел означал бы, что поиск
 * внутри архива должен помнить, из какой плашки пришёл. Ссылка на архив
 * стоит там, где о нём узнают: в строке над таблицей, рядом с числом
 * записей в нём.
 */

export const HERD_SUBTABS = [
  { key: 'list', label: 'Список', hint: 'Поиск по стаду и таблица животных' },
  { key: 'reports', label: 'Отчёты', hint: 'Считаются из того, что уже внесено' },
  { key: 'documents', label: 'Документы', hint: 'Свидетельства и прочие бумаги' },
] as const

export type HerdSub = (typeof HERD_SUBTABS)[number]['key']

/**
 * Рейтинг стоит в этом ряду, но не входит в `HERD_SUBTABS`, и это не описка.
 *
 * Три подраздела выше — куски одной страницы `/account`, переключаемые
 * параметром `sub`. Рейтинг — отдельный маршрут: ему нужен свой запрос
 * по всей книге, свои разряды и свой профиль в адресе, и втискивать это
 * в общий параметр значило бы завести четвёртый смысл у `?sub=`.
 *
 * Разделение здесь ровно затем, чтобы `/account?tab=herd&sub=ranking`
 * не открывал пустую вкладку: такого ключа среди подразделов нет,
 * и разбор честно откатывается к списку.
 */
const RANKING_TAB = {
  key: 'ranking',
  label: 'Рейтинг',
  hint: 'Места ваших животных среди всей книги',
  href: '/account/ranking',
} as const

export function HerdNav({ active }: { active: HerdSub | 'ranking' }) {
  return (
    <SubTabs
      label="Разделы стада"
      active={active}
      items={[
        ...HERD_SUBTABS.map((s) => ({
          key: s.key as string,
          label: s.label as string,
          hint: s.hint as string,
          href: s.key === 'list' ? '/account?tab=herd' : `/account?tab=herd&sub=${s.key}`,
        })),
        { key: RANKING_TAB.key, label: RANKING_TAB.label, hint: RANKING_TAB.hint, href: RANKING_TAB.href },
      ]}
    />
  )
}
