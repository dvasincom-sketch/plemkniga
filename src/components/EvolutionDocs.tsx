/**
 * Вкладка «Документация» — техническое описание платформы.
 *
 * Кому адресована. Не хозяйству, которое хочет завести карточку, — для него
 * есть сам интерфейс. Здесь читатель другой: инженер сервисной организации,
 * который прикидывает, во что обойдётся интеграция, и человек, который решает,
 * годится ли Ассоциация в технологические партнёры. Обоим нужны не достоинства,
 * а границы: что уже работает, что спроектировано, чего нет и почему.
 *
 * Отношение к `docs/` в репозитории. Там документы для того, кто правит код:
 * двадцать шесть файлов, каждый со своей глубиной, ссылками на строки и разбором
 * отвергнутых вариантов. Здесь — то же содержание, собранное в один документ
 * и выстроенное для чтения подряд: части, главы, подразделы, оглавление слева.
 * Не пересказ и не выжимка — другой порядок изложения для другого читателя.
 *
 * Почему содержание выводится из самого документа, а не задано отдельным
 * списком. Два независимых списка расходятся на второй правке — раздел
 * переименовали, в оглавлении осталось старое. Здесь оглавление собирается
 * из тех же данных, что и текст: разойтись нечему.
 */

type Sub = { id: string; title: string; body: ReactNode }
type Chapter = { id: string; title: string; lead?: ReactNode; subs: Sub[] }
type Part = { id: string; title: string; chapters: Chapter[] }

/* ------------------------------ мелкие формы ------------------------------ */

function P({ children }: { children: ReactNode }) {
  return <p className="mt-3 max-w-[78ch] text-[15px] leading-relaxed text-ink-700">{children}</p>
}

function L({ children }: { children: ReactNode }) {
  return (
    <ul className="mt-3 max-w-[78ch] list-disc space-y-1.5 pl-5 text-[15px] leading-relaxed text-ink-700">
      {children}
    </ul>
  )
}

function Code({ children }: { children: string }) {
  return (
    <pre className="mt-4 overflow-x-auto rounded-xl bg-basement px-4 py-3 text-[13px] leading-relaxed text-white/90">
      <code>{children}</code>
    </pre>
  )
}

function K({ children }: { children: ReactNode }) {
  return (
    <code className="rounded bg-canvas px-1.5 py-0.5 font-mono text-[13px] text-ink-900">
      {children}
    </code>
  )
}

function B({ children }: { children: ReactNode }) {
  return <b className="text-ink-900">{children}</b>
}

function Table({ head, rows }: { head: string[]; rows: ReactNode[][] }) {
  return (
    <div className="mt-4 overflow-x-auto">
      <table className="metric-table">
        <thead>
          <tr>
            {head.map((h) => (
              <th key={h}>{h}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>
              {r.map((c, j) => (
                <td key={j}>{c}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

/**
 * Отметка зрелости у раздела.
 *
 * Три состояния вместо двух: без «спроектировано» пришлось бы либо выдавать
 * замысел за готовое, либо молчать о нём — а для интегратора именно этот
 * слой важнее всего, он показывает, куда система движется.
 */
function Mark({ state }: { state: 'done' | 'designed' | 'planned' }) {
  const label = { done: 'работает', designed: 'спроектировано', planned: 'план' }[state]
  const tone = {
    done: 'bg-brand-50 text-forest-600',
    designed: 'bg-[#f2f2f2] text-ink-700',
    planned: 'bg-[#f2f2f2] text-ink-500',
  }[state]
  return (
    <span className={`rounded-lg px-2 py-0.5 text-[12px] whitespace-nowrap ${tone}`}>{label}</span>
  )
}

