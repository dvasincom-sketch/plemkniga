'use client'

import { ACCESS_SCOPES } from '@/lib/dictionaries'

/**
 * Что именно открывается: происхождение, продуктивность, оценка, документы.
 *
 * ## Почему флажки, а не плашки
 *
 * Список рисовался цветными плашками с настоящим чекбоксом под `sr-only`:
 * отмеченное зелёное, неотмеченное белое. Со стороны это выглядело
 * переключателем «или — или», хотя выбор здесь множественный, и по цвету
 * нельзя было понять, что плашки вообще нажимаются. Человек, решающий,
 * сколько своих данных открыть чужому, не должен догадываться о способе
 * ответа.
 *
 * Флажок говорит две вещи сразу: выбрать можно несколько и выбор
 * необязателен. Ровно то, что здесь верно.
 *
 * ## Почему пояснения видны, а не в подсказке
 *
 * Раньше состав области лежал в `title` — всплывающей подсказке, которой
 * нет на телефоне и о которой не догадаешься мышью. А состав тут и есть
 * решение: «продуктивность» — это ещё и случаи болезни, и осеменения.
 * Владелец, открывающий её вслепую, открывает больше, чем думает.
 *
 * ## Один список на три формы
 *
 * Заявитель просит, владелец решает, ссылка открывает. Раньше это были
 * три отдельные вёрстки одного и того же перечня, и две из трёх разошлись
 * с третьей. Список областей один — и показывать его должно одно место.
 */
export function ScopeChecklist({
  selected,
  onToggle,
  disabled = false,
}: {
  /**
   * Отмеченные области. Не передан — поле неуправляемое: браузер сам
   * следит за галочками, а форма собирает их при отправке. Так работает
   * выдача ссылки, где ничего не подставляется по цели.
   */
  selected?: string[]
  onToggle?: (value: string) => void
  disabled?: boolean
}) {
  const controlled = Array.isArray(selected)

  return (
    <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
      {ACCESS_SCOPES.map((s) => (
        <label
          key={s.value}
          className={`flex items-start gap-3 text-[14px] ${
            disabled ? 'cursor-default opacity-60' : 'cursor-pointer'
          }`}
        >
          <input
            type="checkbox"
            name="scopes"
            value={s.value}
            className="checkbox mt-0.5"
            disabled={disabled}
            {...(controlled
              ? { checked: selected!.includes(s.value), onChange: () => onToggle?.(s.value) }
              : {})}
          />
          <span>
            {s.label}
            <span className="block text-[13px] leading-snug text-ink-500">{s.hint}</span>
          </span>
        </label>
      ))}
    </div>
  )
}
