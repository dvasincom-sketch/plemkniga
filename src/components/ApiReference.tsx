'use client'

import { useEffect, useRef, useState } from 'react'
import { DEFAULT_LOCALE, type Locale } from '@/lib/i18n/locales'
import { pick, type Translated } from '@/lib/i18n/translated'

/**
 * Справочник API на странице.
 *
 * ## Почему Scalar, а не Swagger UI
 *
 * Swagger UI выглядел ровно тем, чем является, — интерфейсом, нарисованным
 * пятнадцать лет назад: системный шрифт, серо-синие чернила, палитра
 * от синего, которого в книге нет. Привести его к оформлению книги можно
 * было только отбивая у чужой таблицы стилей каждое правило — тремястами
 * строк с `!important`, которые ломались бы от любой смены версии.
 *
 * Scalar (MIT) устроен иначе: он объявляет свои переменные и обещает их
 * поддерживать. Оформление стало короче в пять раз именно потому, что
 * задаётся в предусмотренном месте.
 *
 * Отвергнут Redoc — он красивее для чтения и легче, но в нём нет
 * «Попробовать» вовсе. Документацию читают затем, чтобы выполнить запрос;
 * справочник, из которого нельзя, проверяется только глазами.
 *
 * ## Почему скрипт подключается из кода, а не тегом в разметке
 *
 * Библиотека не должна грузиться у тех, кто зашёл на соседнюю страницу.
 * Тег в разметке утащил бы её в общий пакет; здесь она запрашивается,
 * только когда открыли `/api-docs`.
 *
 * ## Почему не npm-компонент, а браузерная сборка
 *
 * Компонент попадает в серверную сборку и тянет за собой свои зависимости —
 * Vue и весь его набор. Контейнер и так живёт на пределе памяти; браузерная
 * сборка, загружаемая по запросу, к серверу не добавляет ничего.
 *
 * ## Что делать, если файла нет
 *
 * Сказать об этом и увести к описанию в формате JSON. Оно не зависит
 * ни от какой библиотеки, и любой инструмент — Postman, Insomnia, свой
 * генератор клиента — принимает его как есть. Пустой экран вместо этого
 * означал бы, что документации нет вовсе.
 */

type ScalarGlobal = {
  createApiReference?: (target: string | Element, config: Record<string, unknown>) => void
}

/**
 * На каком языке говорит сама библиотека.
 *
 * ## Почему не «язык страницы» напрямую
 *
 * Встроенных словарей у Scalar восемь: `en`, `ru`, `es`, `fr`, `de`,
 * `zh-CN`, `ar`, `pt` (`@scalar/types`, `ApiReferenceBuiltInLocale`).
 * Языков союза среди них нет ни одного, кроме русского. Передать
 * `kk` значило бы попросить словарь, которого не существует: библиотека
 * молча откатится на английский, и казахская страница получит
 * английский справочник вместо русского — то есть менее понятный
 * читателю из союза, а не более.
 *
 * ## Почему для остальных пяти именно русский
 *
 * По той же причине, по которой русский вообще выбран запасным языком
 * союза (`i18n/locales.ts`): вероятность, что зоотехник из страны ЕАЭС
 * читает по-русски, выше, чем что он читает по-английски. И текст
 * страницы вокруг справочника на этих языках всё равно показывается
 * русский — английский справочник посреди него читался бы как чужая
 * вставка.
 *
 * Свой словарь для казахского здесь не заводится намеренно: это
 * полторы сотни подписей чужого интерфейса, которые придётся тянуть
 * за каждой версией библиотеки.
 */
const SCALAR_LOCALE: Record<Locale, 'ru' | 'en'> = {
  ru: 'ru',
  en: 'en',
  kk: 'ru',
  hy: 'ru',
  be: 'ru',
  ky: 'ru',
}

/**
 * Слова самого компонента: пока грузится и если не загрузилось.
 *
 * Их четыре, и лежат они здесь, а не в наборе строк страницы: они
 * говорят о библиотеке, а не о нашем API, и меняются вместе с этим
 * файлом. Откат на русский — общий (`i18n/translated.ts`).
 */
type ReferenceText = {
  loading: string
  missing: { lead: string; tail: string; fixLead: string; fixMid: string; fixTail: string }
  /** Чем заменяется шутка авторов в поле для токена. */
  tokenPlaceholder: string
}

const TEXT: Translated<ReferenceText> = {
  ru: {
    loading: 'Загружаем справочник…',
    missing: {
      lead:
        'Интерактивный справочник не загрузился: файлы библиотеки не попали в сборку. ' +
        'Само описание при этом на месте и от библиотеки не зависит — откройте',
      tail: 'и подключите его в Postman, Insomnia или в генератор клиента.',
      fixLead: 'Чинится установкой пакета:',
      fixMid: '— файл копируется в',
      fixTail: 'перед сборкой.',
    },
    tokenPlaceholder: 'вставьте значение',
  },
  en: {
    loading: 'Loading the reference…',
    missing: {
      lead:
        'The interactive reference did not load: the library files did not make it into ' +
        'the build. The description itself is in place and does not depend on the ' +
        'library — open',
      tail: 'and load it into Postman, Insomnia or a client generator.',
      fixLead: 'Fixed by installing the package:',
      fixMid: '— the file is copied into',
      fixTail: 'before the build.',
    },
    tokenPlaceholder: 'paste a value',
  },
}

/**
 * Подписи, до которых не дотягивается словарь библиотеки.
 *
 * ## Почему это вообще понадобилось
 *
 * Встроенный русский словарь у Scalar хороший, но покрывает не всё: часть
 * строк зашита прямо в разметку, а не взята из переводов. Две из них
 * заметны на нашей странице.
 *
 * Первая — заполнитель поля, куда вставляют токен: `QUxMIFlPVVIgQkFTRSBB…`
 * Это шутка авторов, base64 от «ALL YOUR BASE ARE BELONG TO US». Место для
 * неё выбрано худшее из возможных: человек пришёл вставить токен и видит
 * строку, похожую на образец значения или на требуемый формат. Кто-нибудь
 * попробует вставить именно её.
 *
 * Вторая — подписи флажков у параметров запроса: «Include limit in
 * request». Глазами их не видно, но читающая программа произносит
 * их вслух, и на русской странице это единственное, что звучит
 * по-английски.
 *
 * ## Почему подмена, а не форк библиотеки
 *
 * Обе строки зашиты в разметку — настройкой их не достать. Остаются два
 * пути: держать свою сборку библиотеки ради двух строк либо поправить
 * их на месте. Первое означает вечное слияние чужих изменений; второе —
 * тридцать строк, которые перестают работать, если строка изменится.
 *
 * ## Почему это безопасно
 *
 * Правило привязано к точному тексту. Сменят авторы шутку или подпись —
 * совпадения не будет, и наш код просто ничего не сделает: ни поломки,
 * ни подмены не того. И замена сама себя останавливает — переписанное
 * под правило больше не подходит, поэтому наблюдатель не зацикливается
 * на собственной правке.
 */
type PatchRule = {
  attr: 'placeholder' | 'aria-label'
  from: RegExp
  to: (m: RegExpMatchArray) => string
}

/**
 * Правила подмены зависят от языка справочника, а не страницы.
 *
 * Шутка в поле для токена зашита в разметку и показывается на любом
 * языке — её подменяем всегда. А подписи флажков переводятся только
 * там, где справочник говорит по-русски: на английском они и так
 * английские, и переписывать их значило бы спорить с библиотекой
 * о её собственном языке.
 */
const patchRules = (scalarLocale: 'ru' | 'en', text: ReferenceText): PatchRule[] => [
  {
    attr: 'placeholder',
    from: /^QUxMIFlPVVIgQkFTRSBBUkUgQkVMT05HIFRPIFVT$/,
    to: () => text.tokenPlaceholder,
  },
  ...(scalarLocale === 'ru'
    ? [
        {
          attr: 'aria-label' as const,
          from: /^Include (.+) in request$/,
          /*
           * `row` — не имя параметра, а заглушка библиотеки для строки без имени.
           * Переносить её в русскую подпись значило бы произносить читалкой
           * «Включить „роу“ в запрос»: имя параметра оставляем как есть,
           * потому что оно и в запросе такое, а заглушку переводим.
           */
          to: (m: RegExpMatchArray) =>
            m[1] === 'row' ? 'Включить строку в запрос' : `Включить «${m[1]}» в запрос`,
        },
      ]
    : []),
]

const patchLabels = (root: HTMLElement, rules: PatchRule[]): void => {
  for (const rule of rules) {
    for (const el of root.querySelectorAll<HTMLElement>(`[${rule.attr}]`)) {
      const value = el.getAttribute(rule.attr) ?? ''
      const match = value.match(rule.from)
      if (match) el.setAttribute(rule.attr, rule.to(match))
    }
  }
}

export function ApiReference({
  specUrl,
  locale = DEFAULT_LOCALE,
}: {
  specUrl: string
  locale?: Locale
}) {
  const mount = useRef<HTMLDivElement>(null)
  const [state, setState] = useState<'loading' | 'ready' | 'missing'>('loading')

  const text = pick(TEXT, locale).value
  const scalarLocale = SCALAR_LOCALE[locale]

  useEffect(() => {
    let cancelled = false
    let observer: MutationObserver | null = null

    const theme = document.createElement('link')
    theme.rel = 'stylesheet'
    theme.href = '/scalar-theme.css'
    document.head.appendChild(theme)

    const script = document.createElement('script')
    script.src = '/scalar/standalone.js'

    script.onload = () => {
      if (cancelled) return
      const scalar = (window as unknown as { Scalar?: ScalarGlobal }).Scalar
      if (typeof scalar?.createApiReference !== 'function' || !mount.current) {
        setState('missing')
        return
      }

      scalar.createApiReference(mount.current, {
        url: specUrl,

        /*
         * Словари у библиотеки встроенные — свой писать не нужно.
         *
         * Сначала я собирался переводить подписи через `translations`,
         * подставляя их по одной. Оказалось, что в бандле уже лежат семь
         * словарей, и `ru` среди них — полный и приличного качества:
         * «Аутентификация», «Скопировать шаблон», «Показать все значения».
         * Свой перевод рядом с ним означал бы вторую версию тех же строк,
         * которая отстанет от библиотеки на первой же новой подписи.
         *
         * Язык был зашит русским, и на `/en/api-docs` английская страница
         * кончалась русским справочником: «Аутентификация», «Попробовать»,
         * «Скопировать шаблон» — там, где всё остальное переведено.
         * Какие языки библиотека знает и почему пяти языкам союза
         * достаётся русский — в `SCALAR_LOCALE` выше.
         *
         * `translations` оставлены для точечных поправок: словарь общий
         * на всех, а у нас книга, и кое-где уместнее своё слово.
         */
        localization: {
          locale: scalarLocale,
          translations: {
            /*
             * «Работает на Scalar» — строка подвала бокового меню.
             * Убрана не из неблагодарности: MIT требует сохранить
             * лицензию и уведомление об авторских правах в самих файлах,
             * и они на месте — заголовок бандла с ними приезжает
             * нетронутым. Надпись в интерфейсе — это марка поставщика,
             * а не то уведомление, и на странице ведомственной системы
             * она читается как реклама стороннего сервиса.
             *
             * Пустая строка убирает текст; саму ссылку прячет правило
             * в `scalar-theme.css` — иначе от неё осталась бы пустая
             * область, по которой всё ещё можно кликнуть.
             */
            footer: { poweredByScalar: '' },
          },
        },

        /*
         * Панель разработчика выключена совсем.
         *
         * По умолчанию она показывается на localhost — то есть на проде
         * её и так не было, — но именно в ней живёт предложение перейти
         * на платный тариф. Оставлять его в системе, которую показывают
         * заказчику, незачем: это чужое коммерческое предложение внутри
         * нашего интерфейса, и объяснять его происхождение придётся нам.
         */
        showDeveloperTools: 'never',

        /*
         * Тема библиотеки не применяется вовсе: цвета задаёт книга
         * в `scalar-theme.css`. С включённой темой пришлось бы
         * переопределять её же переменные поверх её же значений —
         * то есть спорить с библиотекой там, где можно просто
         * попросить её этого не делать.
         */
        theme: 'none',
        darkMode: false,
        /*
         * Переключателя ночного вида нет, потому что нет ночного вида:
         * кнопка, меняющая половину экрана на неоформленную, хуже
         * отсутствующей кнопки.
         */
        hideDarkModeToggle: true,

        /*
         * Свои шрифты — и это обязательная часть отказа от CDN, а не
         * оформление. С умолчанием библиотека тянет Inter и JetBrains Mono
         * из своей сети: файл лежал бы у нас, а шрифты приезжали бы
         * снаружи, и страница снова перестала бы открываться там, где
         * до внешних адресов не дотянуться.
         */
        withDefaultFonts: false,

        /*
         * Прокси не задан намеренно.
         *
         * По умолчанию библиотека предлагает гонять запросы «Попробовать»
         * через свой прокси в интернете — это решает чужую задачу: доступ
         * к API на другом домене, куда браузер не пустит из-за CORS.
         * Наш API стоит на том же домене, что и эта страница, и прокси
         * ему не нужен. А с прокси каждый пробный запрос вместе с токеном
         * хозяйства уходил бы на чужой сервер.
         */

        /*
         * Порядок разделов — тот, что задан в самом описании. По умолчанию
         * библиотека сортирует по алфавиту, и разложение по разделам,
         * ради которого приставки и заведены, рассыпалось бы: «Стадо ·
         * Животные» и «Стадо · Перемещения» разъехались бы по списку.
         */
        defaultOpenAllTags: false,
        tagsSorter: undefined,
        operationsSorter: undefined,
      })

      /*
       * Справочник рисуется постепенно и дорисовывается при раскрытии
       * разделов, поэтому один проход по разметке ничего бы не дал:
       * половины подписей в ней ещё нет. Наблюдатель проходит по тому,
       * что появилось, и на этом успокаивается — переписанное под правило
       * больше не подходит.
       */
      const rules = patchRules(scalarLocale, text)
      patchLabels(mount.current, rules)
      observer = new MutationObserver(() => {
        if (mount.current) patchLabels(mount.current, rules)
      })
      observer.observe(mount.current, {
        subtree: true,
        childList: true,
        attributeFilter: ['placeholder', 'aria-label'],
      })

      setState('ready')
    }

    script.onerror = () => {
      if (!cancelled) setState('missing')
    }

    document.body.appendChild(script)

    return () => {
      cancelled = true
      observer?.disconnect()
      theme.remove()
      script.remove()
    }
  }, [specUrl, scalarLocale, text])

  if (state === 'missing') {
    return (
      <div className="card mt-8">
        <p className="max-w-[70ch] text-[15px] leading-relaxed text-ink-700">
          {text.missing.lead}{' '}
          <a href={specUrl} className="underline underline-offset-4">
            {specUrl}
          </a>{' '}
          {text.missing.tail}
        </p>
        <p className="mt-3 max-w-[70ch] text-[14px] leading-relaxed text-ink-500">
          {text.missing.fixLead} <code>npm i @scalar/api-reference</code> {text.missing.fixMid}{' '}
          <code>public/scalar</code> {text.missing.fixTail}
        </p>
      </div>
    )
  }

  return (
    <div className="mt-10">
      {state === 'loading' && <p className="text-[14px] text-ink-500">{text.loading}</p>}
      {/*
         Своей рамки у справочника нет, в отличие от прежнего Swagger UI.
         Тот рисовал по своим правилам и на светлом фоне книги терялся,
         поэтому его ставили в карточку. Этот занимает всю ширину
         и раскладывается тремя колонками — карточка вокруг него отняла бы
         у средней колонки как раз ту ширину, ради которой три колонки
         и заводятся.
      */}
      <div ref={mount} />
    </div>
  )
}
