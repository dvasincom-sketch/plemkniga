'use client'

import { useEffect, useRef, useState } from 'react'

/**
 * Справочник API на странице.
 *
 * ## Почему Scalar, а не Swagger UI
 *
 * Swagger UI выглядел ровно тем, чем является, — интерфейсом, нарисованным
 * пятнадцать лет назад: системный шрифт, серо-синие чернила, палитра
 * от синего, которого в книге нет. Привести его к оформлению книги можно
 * было только отбивая у чужой таблицы стилей каждое правило — тремястами
 * строк с `!important`, которые ломались бы от любой смены версии.
 *
 * Scalar (MIT) устроен иначе: он объявляет свои переменные и обещает их
 * поддерживать. Оформление стало короче в пять раз именно потому, что
 * задаётся в предусмотренном месте.
 *
 * Отвергнут Redoc — он красивее для чтения и легче, но в нём нет
 * «Попробовать» вовсе. Документацию читают затем, чтобы выполнить запрос;
 * справочник, из которого нельзя, проверяется только глазами.
 *
 * ## Почему скрипт подключается из кода, а не тегом в разметке
 *
 * Библиотека не должна грузиться у тех, кто зашёл на соседнюю страницу.
 * Тег в разметке утащил бы её в общий пакет; здесь она запрашивается,
 * только когда открыли `/api-docs`.
 *
 * ## Почему не npm-компонент, а браузерная сборка
 *
 * Компонент попадает в серверную сборку и тянет за собой свои зависимости —
 * Vue и весь его набор. Контейнер и так живёт на пределе памяти; браузерная
 * сборка, загружаемая по запросу, к серверу не добавляет ничего.
 *
 * ## Что делать, если файла нет
 *
 * Сказать об этом и увести к описанию в формате JSON. Оно не зависит
 * ни от какой библиотеки, и любой инструмент — Postman, Insomnia, свой
 * генератор клиента — принимает его как есть. Пустой экран вместо этого
 * означал бы, что документации нет вовсе.
 */

type ScalarGlobal = {
  createApiReference?: (target: string | Element, config: Record<string, unknown>) => void
}

export function ApiReference({ specUrl }: { specUrl: string }) {
  const mount = useRef<HTMLDivElement>(null)
  const [state, setState] = useState<'loading' | 'ready' | 'missing'>('loading')

  useEffect(() => {
    let cancelled = false

    const theme = document.createElement('link')
    theme.rel = 'stylesheet'
    theme.href = '/scalar-theme.css'
    document.head.appendChild(theme)

    const script = document.createElement('script')
    script.src = '/scalar/standalone.js'

    script.onload = () => {
      if (cancelled) return
      const scalar = (window as unknown as { Scalar?: ScalarGlobal }).Scalar
      if (typeof scalar?.createApiReference !== 'function' || !mount.current) {
        setState('missing')
        return
      }

      scalar.createApiReference(mount.current, {
        url: specUrl,

        /*
         * Русский у библиотеки встроенный — свой словарь писать не нужно.
         *
         * Сначала я собирался переводить подписи через `translations`,
         * подставляя их по одной. Оказалось, что в бандле уже лежат семь
         * словарей, и `ru` среди них — полный и приличного качества:
         * «Аутентификация», «Скопировать шаблон», «Показать все значения».
         * Свой перевод рядом с ним означал бы вторую версию тех же строк,
         * которая отстанет от библиотеки на первой же новой подписи.
         *
         * `translations` оставлены для точечных поправок: словарь общий
         * на всех, а у нас книга, и кое-где уместнее своё слово.
         */
        localization: {
          locale: 'ru',
          translations: {
            /*
             * «Работает на Scalar» — строка подвала бокового меню.
             * Убрана не из неблагодарности: MIT требует сохранить
             * лицензию и уведомление об авторских правах в самих файлах,
             * и они на месте — заголовок бандла с ними приезжает
             * нетронутым. Надпись в интерфейсе — это марка поставщика,
             * а не то уведомление, и на странице ведомственной системы
             * она читается как реклама стороннего сервиса.
             *
             * Пустая строка убирает текст; саму ссылку прячет правило
             * в `scalar-theme.css` — иначе от неё осталась бы пустая
             * область, по которой всё ещё можно кликнуть.
             */
            footer: { poweredByScalar: '' },
          },
        },

        /*
         * Панель разработчика выключена совсем.
         *
         * По умолчанию она показывается на localhost — то есть на проде
         * её и так не было, — но именно в ней живёт предложение перейти
         * на платный тариф. Оставлять его в системе, которую показывают
         * заказчику, незачем: это чужое коммерческое предложение внутри
         * нашего интерфейса, и объяснять его происхождение придётся нам.
         */
        showDeveloperTools: 'never',

        /*
         * Тема библиотеки не применяется вовсе: цвета задаёт книга
         * в `scalar-theme.css`. С включённой темой пришлось бы
         * переопределять её же переменные поверх её же значений —
         * то есть спорить с библиотекой там, где можно просто
         * попросить её этого не делать.
         */
        theme: 'none',
        darkMode: false,
        /*
         * Переключателя ночного вида нет, потому что нет ночного вида:
         * кнопка, меняющая половину экрана на неоформленную, хуже
         * отсутствующей кнопки.
         */
        hideDarkModeToggle: true,

        /*
         * Свои шрифты — и это обязательная часть отказа от CDN, а не
         * оформление. С умолчанием библиотека тянет Inter и JetBrains Mono
         * из своей сети: файл лежал бы у нас, а шрифты приезжали бы
         * снаружи, и страница снова перестала бы открываться там, где
         * до внешних адресов не дотянуться.
         */
        withDefaultFonts: false,

        /*
         * Прокси не задан намеренно.
         *
         * По умолчанию библиотека предлагает гонять запросы «Попробовать»
         * через свой прокси в интернете — это решает чужую задачу: доступ
         * к API на другом домене, куда браузер не пустит из-за CORS.
         * Наш API стоит на том же домене, что и эта страница, и прокси
         * ему не нужен. А с прокси каждый пробный запрос вместе с токеном
         * хозяйства уходил бы на чужой сервер.
         */

        /*
         * Порядок разделов — тот, что задан в самом описании. По умолчанию
         * библиотека сортирует по алфавиту, и разложение по разделам,
         * ради которого приставки и заведены, рассыпалось бы: «Стадо ·
         * Животные» и «Стадо · Перемещения» разъехались бы по списку.
         */
        defaultOpenAllTags: false,
        tagsSorter: undefined,
        operationsSorter: undefined,
      })

      setState('ready')
    }

    script.onerror = () => {
      if (!cancelled) setState('missing')
    }

    document.body.appendChild(script)

    return () => {
      cancelled = true
      theme.remove()
      script.remove()
    }
  }, [specUrl])

  if (state === 'missing') {
    return (
      <div className="card mt-8">
        <p className="max-w-[70ch] text-[15px] leading-relaxed text-ink-700">
          Интерактивный справочник не загрузился: файлы библиотеки не попали в сборку.
          Само описание при этом на месте и от библиотеки не зависит — откройте{' '}
          <a href={specUrl} className="underline underline-offset-4">
            {specUrl}
          </a>{' '}
          и подключите его в Postman, Insomnia или в генератор клиента.
        </p>
        <p className="mt-3 max-w-[70ch] text-[14px] leading-relaxed text-ink-500">
          Чинится установкой пакета: <code>npm i @scalar/api-reference</code> — файл
          копируется в <code>public/scalar</code> перед сборкой.
        </p>
      </div>
    )
  }

  return (
    <div className="mt-10">
      {state === 'loading' && (
        <p className="text-[14px] text-ink-500">Загружаем справочник…</p>
      )}
      {/*
         Своей рамки у справочника нет, в отличие от прежнего Swagger UI.
         Тот рисовал по своим правилам и на светлом фоне книги терялся,
         поэтому его ставили в карточку. Этот занимает всю ширину
         и раскладывается тремя колонками — карточка вокруг него отняла бы
         у средней колонки как раз ту ширину, ради которой три колонки
         и заводятся.
      */}
      <div ref={mount} />
    </div>
  )
}
