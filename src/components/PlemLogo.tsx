/**
 * Знак продукта: ПЛЕМ и зелёный огонёк «online».
 *
 * ## Почему буквами, а не картинкой
 *
 * Знак состоит из слова, точки и слова — здесь нечего рисовать.
 * Текстом он остаётся резким на любом экране, читается программой чтения
 * с экрана как слово, а не как «изображение», ищется по странице
 * и не требует второго файла для тёмной темы.
 *
 * Картинка понадобится, только если у знака появится своя гарнитура.
 * Пока начертание берётся системное и плотное — так знак выглядит
 * одинаково и на машине разработчика, и на телефоне зоотехника,
 * не дожидаясь загрузки шрифта.
 *
 * ## Почему огонёк пульсирует и почему не всегда
 *
 * Пульсация означает ровно то, что написано рядом: система работает
 * сейчас. Это единственная её задача, и потому она медленная
 * и небольшая — мигающий или быстро дышащий элемент на каждой странице
 * утомляет и отвлекает от содержимого.
 *
 * При системной настройке «уменьшить движение» пульсация выключается
 * целиком, а огонёк остаётся. Это требование доступности WCAG 2.2,
 * и выполняется оно там же, где и остальные, — в общих стилях,
 * а не переключателем внутри компонента.
 *
 * ## Почему «online» строчными и серым
 *
 * Это не часть имени, а состояние. Набранное так же, как ПЛЕМ, оно
 * читалось бы как «ПЛЕМ ОНЛАЙН» — второе слово названия, которого нет.
 *
 * ## Где смотреть
 *
 * Пульсация — `plem-dot` в `src/app/(frontend)/globals.css`.
 */
export function PlemLogo({
  className = '',
  /**
   * Подпись для программы чтения с экрана.
   *
   * Знак составлен из трёх кусков, и без общей подписи он читается как
   * «плем, онлайн» с непонятной точкой посередине. Подпись собирает его
   * обратно в одно имя, а сами куски от чтения скрыты.
   */
  label = 'ПЛЕМ online',
}: {
  className?: string
  label?: string
}) {
  return (
    <span
      className={`inline-flex items-baseline gap-3 ${className}`}
      role="img"
      aria-label={label}
    >
      <span
        aria-hidden="true"
        className="text-[30px] font-black leading-none tracking-tight text-ink-900 sm:text-[34px]"
        /*
           Межбуквенный интервал чуть шире обычного: в наборе заглавными
           буквы слипаются, и «ПЛЕМ» читается как одно пятно. Величина
           подобрана на глаз по снимку знака, а не вычислена.
        */
        style={{ letterSpacing: '0.02em' }}
      >
        ПЛЕМ
      </span>

      <span aria-hidden="true" className="inline-flex items-baseline gap-2">
        {/*
           Огонёк выровнен по базовой линии соседнего слова, а не по центру
           строки: рядом со строчными буквами кружок, поставленный
           по середине высоты, зрительно уезжает вверх.
        */}
        <span className="plem-dot inline-block h-[10px] w-[10px] rounded-full bg-brand-500" />
        <span className="text-[24px] font-medium leading-none text-ink-500 sm:text-[26px]">
          online
        </span>
      </span>
    </span>
  )
}
