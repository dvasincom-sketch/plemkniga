/**
 * Знак продукта: ПЛЕМ и зелёный огонёк «online».
 *
 * ## Почему буквами, а не картинкой
 *
 * Знак состоит из слова, точки и слова — здесь нечего рисовать.
 * Текстом он остаётся резким на любом экране, читается программой чтения
 * с экрана как слово, а не как «изображение», ищется по странице
 * и не требует второго файла для тёмной темы.
 *
 * ## Гарнитура
 *
 * «ПЛЕМ» набран Unbounded — она лежит в зависимостях пакетом
 * `@fontsource-variable/unbounded` и подключается общими стилями, а имя
 * гарнитуры взято из `--font-display`. «online» осталось
 * в интерфейсной гарнитуре: в знаке это не часть имени, а подпись
 * о состоянии, и набранное тем же шрифтом оно читалось бы вторым словом
 * названия, которого нет.
 *
 * ## Почему «online» стоит вверху, а не на общей базовой линии
 *
 * Слова разного кегля, и выравнивание по базовой линии сажает мелкое
 * слово на низ крупного — знак получается тяжёлым снизу и пустым сверху.
 * Подпись о состоянии — надстрочная по смыслу: она сообщает не имя,
 * а то, что происходит с ним сейчас, и место такого сообщения над строкой,
 * а не под ней.
 *
 * Прижимается она к верху прописных, а не к самому верху строки:
 * у Unbounded над прописными есть запас на диакритику, и выравнивание
 * по краю поля оставило бы над знаком видимую щель.
 *
 * ## Почему огонёк пульсирует и почему не всегда
 *
 * Пульсация означает ровно то, что написано рядом: система работает
 * сейчас. Это единственная её задача, и потому она медленная
 * и небольшая — мигающий элемент на каждой странице утомляет.
 *
 * При системной настройке «уменьшить движение» пульсация выключается
 * целиком, а огонёк остаётся. Требование доступности WCAG 2.2;
 * выполняется в общих стилях, а не переключателем внутри компонента.
 *
 * ## Где смотреть
 *
 * Пульсация — `plem-dot` в `src/app/(frontend)/globals.css`, там же
 * объявлена гарнитура (`--font-display`) и класс крупных чисел
 * `.stat-value`, набранных ею же.
 *
 * ## Почему не `next/font`
 *
 * Так и было: Unbounded скачивалась во время сборки с Google и отдавалась
 * с нашего домена. Довод был верный — страница не должна зависеть
 * от чужого сервиса в момент открытия, — но решение оказалось лишним:
 * та же гарнитура уже лежала в зависимостях пакетом fontsource
 * и подключалась общими стилями ради крупных чисел.
 *
 * То есть каждая страница тянула Unbounded дважды, двумя разными
 * способами, и знак был набран одной копией, а числа — другой. Осталась
 * копия из пакета: она не требует Google даже на сборке.
 */
export function PlemLogo({
  className = '',
  /**
   * Подпись для программы чтения с экрана.
   *
   * Знак составлен из трёх кусков, и без общей подписи он читается как
   * «плем, онлайн» с непонятной точкой посередине. Подпись собирает его
   * обратно в одно имя, а сами куски от чтения скрыты.
   */
  label = 'ПЛЕМ online',
  /**
   * На чём стоит знак: на светлой странице или на тёмной полосе.
   *
   * Не «цвет знака», а именно подложка. Цветов у знака три — слово,
   * огонёк и подпись, — и меняются они не по отдельности: на тёмном
   * слово белеет, подпись бледнеет до половины прозрачности, а огонёк
   * остаётся тем же зелёным, потому что он и есть знак состояния.
   * Отдать это в `className` значило бы разрешить любую комбинацию,
   * включая ту, где огонёк теряется.
   */
  on = 'light',
}: {
  className?: string
  label?: string
  on?: 'light' | 'dark'
}) {
  const dark = on === 'dark'
  return (
    <span
      className={`inline-flex items-start gap-3 ${className}`}
      role="img"
      aria-label={label}
    >
      <span
        aria-hidden="true"
        className={`font-display text-[30px] font-extrabold leading-none sm:text-[34px] ${
          dark ? 'text-white' : 'text-ink-900'
        }`}
      >
        ПЛЕМ
      </span>

      {/*
         Небольшой сдвиг вниз: подпись выравнивается по верху прописных
         букв, а не по верхнему краю строки. Величина подобрана на глаз
         под запас Unbounded над прописными — вычислить её нечем,
         метрики шрифта в вёрстке недоступны.
      */}
      <span aria-hidden="true" className="inline-flex items-center gap-2 pt-[2px]">
        <span className="plem-dot inline-block h-[10px] w-[10px] rounded-full bg-brand-500" />
        <span
          className={`text-[19px] font-medium leading-none sm:text-[21px] ${
            dark ? 'text-white/60' : 'text-ink-500'
          }`}
        >
          online
        </span>
      </span>
    </span>
  )
}
