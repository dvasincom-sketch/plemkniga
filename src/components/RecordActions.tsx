import Link from 'next/link'
import { publicityLabel } from '@/lib/visibility'

/**
 * Управление своей записью — в правом конце строки пути.
 *
 * ## Как искалось место и почему нашлось это
 *
 * Блок переезжал четыре раза: подвал вкладки «Общие данные», ярус между
 * шапкой и меню разделов, кнопка со всплывающей панелью, третья колонка
 * шапки. Каждый вариант отвергался, и последний — по самой точной
 * причине: **новый элемент переставил старые**. Третья колонка сдвинула
 * вторую, и шапка у владельца перестала совпадать с шапкой у всех
 * остальных.
 *
 * Отсюда правило, которое и решило задачу: место для нового элемента
 * ищется не там, где ему логичнее всего быть, а там, где он **никого
 * не подвинет**. Такое место на странице было и пустовало — правый конец
 * строки пути. Хлебные крошки прижаты влево и занимают треть ширины;
 * остальные две трети — воздух.
 *
 * Что это даёт:
 *
 *  - шапка карточки не меняется вовсе: у владельца и у чужого она
 *    посимвольно одна и та же;
 *  - высота страницы не растёт: строка пути уже была;
 *  - смысл на месте: «вы находитесь здесь» и «вот что вы можете сделать
 *    с этой записью» — одна строка, левый и правый её конец. Так устроены
 *    все инструменты, где у записи есть действия.
 *
 * ## Почему словами, а не иконками
 *
 * «Убрать из книги» коробкой читается как «удалить», а архив обратим
 * тридцать дней; «видимость» глазом — как «предпросмотр». В системе,
 * где неверное нажатие убирает запись из книги, цена догадки выше
 * сэкономленных пикселей.
 *
 * ## Почему состояние стоит первым
 *
 * Владелец должен видеть, открыта запись или нет, до того, как что-нибудь
 * нажмёт. Состояние — не подпись к кнопкам, а первое, что здесь читают,
 * поэтому оно набрано плотнее ссылок.
 */
export function RecordActions({
  animalId,
  publicVisible,
  publicDetails,
  archived,
  open,
}: {
  animalId: number
  publicVisible: boolean
  publicDetails: boolean
  archived: boolean
  /** Что раскрыто под шапкой; адрес — единственный источник правды. */
  open: 'visibility' | 'archive' | null
}) {
  const link = (what: 'visibility' | 'archive', text: string) => {
    const active = open === what
    return (
      <Link
        href={active ? `/animals/${animalId}` : `/animals/${animalId}?manage=${what}`}
        scroll={false}
        aria-current={active ? 'true' : undefined}
        className={
          active
            ? 'font-medium text-forest-600'
            : 'text-ink-500 underline underline-offset-4 hover:text-forest-500'
        }
      >
        {text}
      </Link>
    )
  }

  return (
    <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-[13px] lg:justify-end">
      <span className="text-ink-500">
        Ваша запись:{' '}
        <span className="text-ink-900">
          {archived ? 'в архиве' : publicityLabel(publicVisible, publicDetails).toLowerCase()}
        </span>
      </span>

      {link('visibility', 'видимость')}
      {link('archive', archived ? 'вернуть из архива' : 'убрать из книги')}
    </div>
  )
}
