/**
 * Разбор своего стада: стопка листов и лупа.
 *
 * Лупа не залита, а обведена — в отличие от кружков с плюсом и галочкой.
 * Разница нужна: плюс и галочка означают совершённое действие, лупа —
 * рассматривание, и заливка сделала бы её третьей кнопкой в том же ряду.
 */
export const HerdScanIcon = () => (
  <Frame>
    <rect x="8" y="6" width="52" height="66" rx="5" fill="#d6d6d6" />
    <Sheet x={16} y={12} />
    <circle cx="72" cy="47" r="12" stroke="#9a9a9a" strokeWidth="5" fill="#f7f7f7" />
    <path d="m81 56 8 8" stroke="#9a9a9a" strokeWidth="5" strokeLinecap="round" />
  </Frame>
)

/**
 * Каталог правил: лист, где каждая строка отмечена галочкой.
 *
 * Один лист, а не стопка, и это не случайность: правила одни на всю книгу,
 * а стопка означала бы «у каждого свои».
 */
export const RulesIcon = () => (
  <Frame>
    <rect x="20" y="12" width="52" height="66" rx="5" fill="#efefef" stroke="#d0d0d0" />
    {LINES.map((i) => (
      <g key={i}>
        <path
          d={`m28 ${25 + i * 9} 2.6 2.6L35 ${21.5 + i * 9}`}
          stroke="#9a9a9a"
          strokeWidth="2.4"
          strokeLinecap="round"
          strokeLinejoin="round"
        />
        <rect
          x="40"
          y={23 + i * 9}
          width={i % 2 ? 18 : 24}
          height="4"
          rx="2"
          fill="#c9c9c9"
        />
      </g>
    ))}
  </Frame>
)

