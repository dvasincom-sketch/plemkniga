import { SubTabs } from '@/components/SubTabs'

/**
 * Разделы «Хозяйства» — на всех страницах раздела, а не только на первой.
 *
 * ## Что было не так
 *
 * Раздел назывался «Настройки» и перечислял в одном ряду три разные вещи:
 * настройку книги (видимость), управление хозяйством (сотрудники, журнал,
 * реквизиты) и личное (профиль, уведомления, биллинг). Последнее
 * дублировалось в меню под именем — единственное место в системе, где два
 * меню показывали одно и то же, и ровно из этого выросла ошибка №119:
 * два меню считали адрес раздела по своим правилам и разошлись.
 *
 * Личное отсюда ушло целиком: профиль и уведомления — страницы человека,
 * а не хозяйства, и живут они под именем. «Доступы» пришли сюда из верхнего
 * меню: кому открыты данные хозяйства — такая же его настройка, как то,
 * что видно в общей книге. «Профили ИПЦ» пришли из глубины страницы
 * настроек, где на них была одна текстовая ссылка.
 *
 * ## Почему один плоский ряд, а не вложенность
 *
 * Соблазн сгруппировать — «данные наружу» и «люди» — добавляет третий
 * уровень там, где всего шесть пунктов, и заставляет угадывать, к какой
 * группе отнесли нужное. Плоский ряд из шести читается целиком одним
 * взглядом, а угадывать в нём нечего.
 *
 * ## Про порядок и про то, чем открывается раздел
 *
 * Первой стоит видимость, и она же — первая страница раздела. Не потому,
 * что её правят чаще (правят реже всего), а потому, что она дороже всех
 * по последствиям: это единственный переключатель, которым стадо целиком
 * становится видно посторонним. Раздел «Хозяйство» открывается тем, что
 * решает, кто вас видит.
 *
 * Дальше — по частоте: доступы конкретным покупателям, состав сотрудников,
 * журнал. Журнал стоит рядом с сотрудниками намеренно: чаще всего в него
 * идут сразу после разговора о том, кто что сделал. Реквизиты и профили
 * весов — в конце: их заполняют один раз.
 */

