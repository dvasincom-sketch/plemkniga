import type { JsonLd as Node } from '@/lib/jsonld'

/**
 * Блок разметки для поисковых систем.
 *
 * ## Почему `<`, а не что-нибудь ещё
 *
 * Разметка вставляется в разметку страницы как есть, и единственная
 * последовательность, которой это опасно, — `</script`: браузер закончит
 * блок посреди объекта, и дальше разметка страницы поедет. Экранируется
 * поэтому именно `<`, а не кавычки: внутри JSON они уже экранированы,
 * и трогать их значило бы портить содержимое.
 *
 * Способ старый и скучный, и это его достоинство: никакой библиотеки
 * ради шести строк.
 *
 * ## Почему компонент, а не строка на странице
 *
 * Чтобы про экранирование помнить один раз. Забытое экранирование
 * не видно ни при какой правке: страница собирается, открывается
 * и ломается только тогда, когда в источник разбора попадёт работа
 * со словом `</script` в названии, — то есть однажды и внезапно.
 */
export function JsonLd({ data }: { data: Node }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, '\\u003c'),
      }}
    />
  )
}
