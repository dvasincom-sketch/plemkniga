import { SubTabs } from '@/components/SubTabs'

/**
 * Разделы «Данных» — на всех страницах раздела, а не только на его первой.
 *
 * ## Что было не так
 *
 * Переключатель «Записать / Проверка и подача / Лента» жил внутри страницы
 * кабинета. Стоило уйти на третий уровень — «Проверить моё стадо»,
 * «Верификация», «Загрузка данных» — и он пропадал: оставалось верхнее
 * меню кабинета и хлебные крошки. Со стороны это читается как выход
 * из раздела: человек нажал пункт меню, меню исчезло, и вернуться можно
 * только назад по крошкам или кнопкой браузера.
 *
 * Меню второго уровня для того и существует, чтобы между соседними
 * разделами ходить напрямую. Пропадая на самой глубине, где ходить
 * и нужно, оно работает ровно там, где без него можно обойтись.
 *
 * ## Почему отдельный компонент, а не пропс у `SubTabs`
 *
 * Список разделов и их адреса — одни на восемь страниц. Собирать его
 * в каждой значило бы восемь копий, которые разойдутся на первой правке
 * названия: страница `checks/herd` продолжала бы звать раздел «Проверка»,
 * когда он уже «Проверка и подача».
 */

export const DATA_SUBTABS = [
  { key: 'write', label: 'Записать', hint: 'Форма события и загрузка файлом' },
  {
    key: 'check',
    label: 'Проверка и подача',
    hint: 'Сначала разобрать самим, потом подать в Ассоциацию',
  },
  { key: 'feed', label: 'Лента', hint: 'Что записано за последнее время' },
] as const

export type DataSub = (typeof DATA_SUBTABS)[number]['key']

/**
 * Умолчательный отступ рассчитан на страницы третьего уровня: там ряд
 * стоит сразу под меню кабинета, у которого свой нижний отступ. Страница
 * самого раздела ставит его под заголовком и передаёт отступ свой.
 */
export function DataNav({
  active,
  className = '-mt-4 mb-8',
}: {
  active: DataSub
  className?: string
}) {
  return (
    <SubTabs
      label="Разделы данных"
      active={active}
      className={className}
      items={DATA_SUBTABS.map((s) => ({
        key: s.key,
        label: s.label,
        hint: s.hint,
        href: `/account?tab=data&sub=${s.key}`,
      }))}
    />
  )
}
