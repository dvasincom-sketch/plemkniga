import {
  FGIAS_MEASURED_AT,
  FGIAS_MEASURED_ON,
  FGIAS_TEMPLATES,
  FGIAS_TOTALS,
  type FgiasTemplateState,
} from '@/lib/fgias-templates'
import { unbounded } from '@/lib/fonts'

/**
 * Вкладка «ФГИАС ПР».
 *
 * ## Кому она отвечает
 *
 * Хозяйству, которое уже обязано сдавать данные в государственный реестр
 * и выбирает, где вести учёт. Вопрос у него один и прямой: если я веду
 * книгу, смогу ли я отдать из неё всё, что просит ФГИАС, — и если нет,
 * то чего не хватит.
 *
 * Отвечать на него в переписке дорого и ненадёжно: ответ живёт до первой
 * правки. Отвечать общими словами («интеграция запланирована») — хуже
 * вовсе: человек услышит «да» и обнаружит «нет» через полгода, когда
 * уже перенёс стадо.
 *
 * ## Почему таблица, а не рассказ
 *
 * У читателя двадцать шаблонов и один вопрос к каждому. Рассказ он
 * читать не станет: ему надо найти свой шаблон и увидеть три числа.
 * Поэтому колонок ровно столько, сколько нужно для решения: сколько
 * колонок в шаблоне, сколько из них книга заполнит, и чего не хватает
 * словами.
 *
 * ## Почему «заполним» меньше, чем могло бы
 *
 * Числа сосчитаны по живой базе, а не по схеме. Поле, заведённое
 * в системе и никем не заполняемое, в выгрузке даёт пустую ячейку,
 * а реестр отвергает запись за незаполненное обязательное поле. Считать
 * такие поля своими значило бы обещать то, чего не будет, — и обещать
 * тому, кто на это положится.
 *
 * Отсюда же строки, где «заполним» ниже, чем подсказывает схема: линейная
 * оценка совпадает по составу почти целиком, но шесть признаков из неё
 * в базе не заполнены ни разу.
 *
 * ## Чего вкладка не обещает
 *
 * Что реестр примет собранное. Кнопка на каждый из двадцати шаблонов
 * теперь есть, заголовки сверены с настоящими файлами — но принят ли
 * файл, знает только настоящая отправка. Сказано это вслух и вверху,
 * а не мелким шрифтом внизу.
 *
 * ## Почему страница переписывалась вместе с кодом
 *
 * Первая её редакция говорила «два шаблона собираются, кнопки пока нет»
 * и «пять шаблонов книга не ведёт вовсе». Обе фразы были правдой
 * ровно до той недели, когда кнопок стало двадцать. Витрина, отставшая
 * от кода, врёт убедительнее отсутствующей: её читают и на неё
 * полагаются.
 *
 * Числа таблицы от этого защищены — они собираются из `fgias-templates`,
 * а не переписываются сюда. Слова вокруг них защитить нечем, кроме
 * привычки править их тем же коммитом.
 */

const STATE_LABEL: Record<FgiasTemplateState, string> = {
  ready: 'отдадим',
  partial: 'частично',
  none: 'нечем',
}

/*
 * Цвет здесь несёт смысл, а не настроение: «нечем» и «отдадим» человек
 * различает взглядом раньше, чем читает. Но подпись стоит рядом всегда —
 * таблица, где состояние передано только цветом, не читается ни в печати,
 * ни тем, кто цвета не различает.
 */
const STATE_TONE: Record<FgiasTemplateState, string> = {
  ready: 'bg-[#e8f3ec] text-[#2e6b4c]',
  partial: 'bg-[#f6efdc] text-[#8c6714]',
  none: 'bg-[#f7e9e5] text-[#9e3520]',
}

const ORDER: FgiasTemplateState[] = ['ready', 'partial', 'none']

export function EvolutionFgias() {
  const sorted = [...FGIAS_TEMPLATES].sort((a, b) => {
    const byState = ORDER.indexOf(a.state) - ORDER.indexOf(b.state)
    if (byState !== 0) return byState
    return b.fill / b.columns - a.fill / a.columns
  })

  const ready = FGIAS_TEMPLATES.filter((t) => t.state === 'ready').length
  const none = FGIAS_TEMPLATES.filter((t) => t.state === 'none').length

  return (
    <div className="space-y-10">
      {/* ------------------------ Итог тремя числами ------------------------ */}

      <section>
        <div className="grid gap-4 sm:grid-cols-3">
          <div className="card">
            <p className="text-[13px] text-ink-500">Шаблонов реестра</p>
            <p className={`${unbounded.className} mt-1 text-[30px] font-medium leading-none tabular-nums`}>
              {FGIAS_TOTALS.templates}
            </p>
            <p className="mt-2 text-[14px] leading-snug text-ink-700">
              {/*
                 Кнопка есть у всех двадцати, и число «отдадим» говорит
                 не о ней, а о полноте: сколько шаблонов книга заполнит
                 целиком. Смешать эти два числа значило бы назвать пустой
                 файл готовым отчётом.
              */}
              У всех есть кнопка выгрузки; {ready} заполним целиком
              {none > 0 ? `, ${none} нечем — таких данных книга не ведёт` : ''}
            </p>
          </div>

          <div className="card">
            <p className="text-[13px] text-ink-500">Колонок во всех шаблонах</p>
            <p className={`${unbounded.className} mt-1 text-[30px] font-medium leading-none tabular-nums`}>
              {FGIAS_TOTALS.fill}
              <span className="text-[20px] text-ink-500"> из {FGIAS_TOTALS.columns}</span>
            </p>
            <p className="mt-2 text-[14px] leading-snug text-ink-700">
              есть чем заполнить — по живой базе, а не по схеме
            </p>
          </div>

          <div className="card">
            <p className="text-[13px] text-ink-500">Строк уехало бы сегодня</p>
            <p className={`${unbounded.className} mt-1 text-[30px] font-medium leading-none tabular-nums`}>
              {FGIAS_TOTALS.rowsReady.toLocaleString('ru-RU')}
            </p>
            <p className="mt-2 text-[14px] leading-snug text-ink-700">
              {/*
                 Число из прогона по живой базе, и с тех пор шаблонов
                 прибавилось. Подправить его «на глазок» под новый список
                 было бы легко и нечестно: тогда рядом с ним нельзя было
                 бы назвать день, когда его считали.
              */}
              по прогону {FGIAS_MEASURED_AT} и по тем шаблонам, что собирались к тому дню
            </p>
          </div>
        </div>

        <p className="mt-4 max-w-[80ch] text-[14px] leading-relaxed text-ink-500">
          Шаблоны — версии 2.6.0, прочитаны файлами: все двадцать шапок сверены с ними
          построчно, колонка за колонкой. «Заполним» — это поля, которые книга умеет положить
          в ячейку; строки, у которых обязательное поле пусто, выгрузка придерживает и называет
          причину, а не отправляет пустыми. Число строк — из прогона по живой базе{' '}
          {FGIAS_MEASURED_AT}: {FGIAS_MEASURED_ON}.
        </p>
      </section>

      {/* --------------------------- Таблица --------------------------- */}

      <section>
        <h2 className="text-[22px] font-medium">Шаблон за шаблоном</h2>

        <div className="card mt-4 overflow-x-auto">
          <table className="metric-table min-w-[900px]">
            <thead>
              <tr>
                <th className="text-left">Шаблон ФГИАС</th>
                <th className="text-right">Колонок</th>
                <th className="text-right">Заполним</th>
                <th className="text-left">Состояние</th>
                <th className="text-left">Что мешает и чего не хватает</th>
              </tr>
            </thead>
            <tbody>
              {sorted.map((t) => (
                <tr key={t.name}>
                  <td className="font-medium">{t.name}</td>
                  <td className="text-right tabular-nums">{t.columns}</td>
                  <td className="text-right tabular-nums">{t.fill}</td>
                  <td>
                    <span
                      className={`inline-block rounded px-2 py-0.5 text-[12px] leading-none ${STATE_TONE[t.state]}`}
                    >
                      {STATE_LABEL[t.state]}
                    </span>
                  </td>
                  <td className="max-w-[46ch] text-[14px] leading-snug text-ink-700">{t.gap}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* ------------------------ Что это значит ------------------------ */}

      <section>
        <h2 className="text-[22px] font-medium">Что из этого следует</h2>

        <div className="mt-4 grid gap-4 md:grid-cols-2">
          <div className="card space-y-3 text-[15px] leading-relaxed text-ink-700">
            <h3 className="text-[17px] font-medium text-ink-900">
              Ежемесячная отчётность закрыта почти целиком
            </h3>
            <p>
              Дойки, осеменения, отёлы и лактации — то, что хозяйство сдаёт чаще всего, — книга
              отдаёт полностью или почти. Обязательные поля в них заполняются железно: из
              двадцати двух тысяч строк не выпадает ни одна.
            </p>
            <p>
              Формат файла готов: каждый из двадцати шаблонов собирается кнопкой в кабинете.
              Не хватает одного — номера животного в реестре, а он приходит обратным файлом
              после первой же сдачи «Основных сведений».
            </p>
          </div>

          <div className="card space-y-3 text-[15px] leading-relaxed text-ink-700">
            <h3 className="text-[17px] font-medium text-ink-900">
              Родословная — самое дорогое место
            </h3>
            <p>
              Реестр требует три ряда предков, четырнадцать гнёзд, и все пятнадцать колонок
              шаблона — номера реестра. Колонки «Идентификатор учётной системы» там нет вовсе:
              предка нельзя назвать ни номером со свидетельства, ни кличкой.
            </p>
            <p>
              Значит порядок работ жёсткий — сначала «Основные сведения» на всё стадо вместе
              с предками, потом обратный файл, и только потом родословная. Плюс прежняя беда:
              книга уверенно знает отцов и почти не знает матерей, второй ряд целиком
              не собирается ни у одного животного. Это не наша особенность — так ведут учёт
              в отрасли.
            </p>
          </div>

          <div className="card space-y-3 text-[15px] leading-relaxed text-ink-700">
            <h3 className="text-[17px] font-medium text-ink-900">
              Кнопка есть у всех, полный файл — не у всех
            </h3>
            <p>
              Здесь были «пять шаблонов, которых книга не ведёт вовсе»: живая масса, три оценки
              экстерьера, спермопродукция. Теперь под каждый заведены поля, и каждый собирается
              кнопкой. Но заведённое поле — ещё не заполненное: у шаблонов, где записей пока
              никто не внёс, файл выйдет почти пустым.
            </p>
            <p>
              Три оценки экстерьера дались дороже прочих. У реестра там другая система
              измерения, а не другое поле: линейный признак говорит, <em>какое</em> животное,
              и середина шкалы у половины признаков и есть оптимум, а сводная оценка говорит,{' '}
              <em>насколько хорошо</em>. Пересчитать одну в другую нельзя, и формула дала бы
              правдоподобное число, которое ничего не меряет.
            </p>
          </div>

          <div className="card space-y-3 text-[15px] leading-relaxed text-ink-700">
            <h3 className="text-[17px] font-medium text-ink-900">
              Справочники реестра открыты, и это упрощает всё
            </h3>
            <p>
              Двадцать шаблонов заполняются не словами, а ключами: порода — это{' '}
              <code className="rounded bg-ink-100 px-1 text-[13px]">1bd6b3f1-648a-…</code>,
              а не «Голштинская». Пятьдесят один реестр ФГИАС отдаёт открыто, включая 556 пород
              и 10 580 линий.
            </p>
            <p>
              Книга сверяет с ними свои справочники и хранит государственный ключ рядом
              со своим. Побочная польза: сразу видно, каких наших пород в реестре нет
              и какие называются иначе.
            </p>
          </div>

          <div className="card space-y-3 text-[15px] leading-relaxed text-ink-700">
            <h3 className="text-[17px] font-medium text-ink-900">
              Данные не только уезжают, но и приезжают
            </h3>
            <p>
              Каждое поле, которое книга отдаёт реестру, она принимает загрузкой: ведомость
              бонитёра на восемнадцать признаков экстерьера, протокол лаборатории
              с генотипом ISAG, место рождения, склад спермопродукции. Иначе колонка в файле
              была бы обещанием, которое некому выполнить, — так однажды и вышло, и с тех пор
              за этим следит отдельная проверка.
            </p>
            <p>
              Обратный файл реестра книга узнаёт сама: базовые номера из него ложатся
              к животным по нашему ключу, и повторная загрузка того же файла ничего
              не задваивает.
            </p>
          </div>
        </div>
      </section>

      {/* ---------------------- Чего здесь нет ---------------------- */}

      <section>
        <h2 className="text-[22px] font-medium">Чего эта страница не обещает</h2>

        <div className="card mt-4 max-w-[80ch] space-y-4 text-[15px] leading-relaxed text-ink-700">
          <p>
            <strong className="font-medium text-ink-900">
              Что реестр примет собранное.
            </strong>{' '}
            Все двадцать шаблонов собираются кнопкой в кабинете, и шапка каждого сверена
            с настоящим файлом реестра построчно — а не переписана на слух. Но ни один такой
            файл ещё не был принят реестром: сказать, примет ли он его, может только настоящая
            отправка. До неё это готовность к отправке, а не сданная отчётность.
          </p>
          <p>
            <strong className="font-medium text-ink-900">
              Что полный файл выйдет у каждого шаблона.
            </strong>{' '}
            Кнопка есть у всех двадцати, но за частью из них записей пока нет ни одной:
            бонитировки, сводные оценки экстерьера, спермопродукция заведены только что.
            Такой файл выйдет почти пустым, и отчёт назовёт, чего не хватило, — это честнее
            отсутствующей кнопки, за которой человеку нечего сделать.
          </p>
          <p>
            <strong className="font-medium text-ink-900">
              Что книга знает номер вашего животного в реестре.
            </strong>{' '}
            Не знает и знать не может, пока хозяйство не сдало «Основные сведения» и не получило
            обратный файл. Внутренний ключ книги — не номер ФГИАС; подставить его в эту колонку
            значило бы завести в реестре второе животное рядом с настоящим. Поэтому строка
            без номера реестра в файл не попадает, а попадает в отчёт с названием того, чего
            не хватило.
          </p>
          <p>
            <strong className="font-medium text-ink-900">Что числа вечны.</strong> «Заполним»
            меняется вместе с тем, что хозяйства вносят, а шаблоны — вместе с версиями реестра.
            Дата прогона стоит рядом с числами намеренно: страница, показывающая прошлогоднее
            за нынешнее, хуже отсутствующей.
          </p>
          <p>
            <strong className="font-medium text-ink-900">Что реестр примет всё принятое.</strong>{' '}
            Здесь сказано, чем книга заполнит колонку. Примет ли реестр записанное — вопрос
            его собственных проверок, и ответ на него даёт только настоящая отправка.
          </p>
        </div>
      </section>
    </div>
  )
}
