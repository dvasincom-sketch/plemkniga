import Link from 'next/link'
import { findPublicAsset } from '@/lib/media'
import { currentTenant } from '@/lib/tenant-server'

/**
 * Знак организации, ведущей книгу.
 *
 * Положите свой логотип в `public/logo.svg` (или .png/.webp) — он подхватится
 * автоматически и заменит встроенную заглушку. Высота задаётся классом,
 * ширина подстраивается по пропорциям файла.
 *
 * Имя больше не вписано в разметку: знак стоит на каждой странице обеих
 * книг, и вписанное имя означало бы, что показательная книга подписана
 * голштинской ассоциацией — на каждой странице разом.
 *
 * Российский триколор в запасном рисунке рисуется только для книги
 * с государственным учётом. Это не украшение: полоса говорит о стране,
 * и в книге, у которой государственного реестра нет вовсе, она сообщала бы
 * неправду. Условие поставлено по `state`, а не по ключу книги, — потому
 * что связь именно такая, и следующая книга со своим реестром получит
 * верное поведение сама.
 */
export async function Logo({
  className = '',
  onDark = false,
  href = '/',
  label = 'На главную',
}: {
  className?: string
  /**
   * Знак стоит на тёмной подложке.
   *
   * Логотип цветной и с чёрной подписью — перекрашивать его нельзя,
   * а на тёмном он пропадает. Поэтому на тёмном фоне он ставится
   * на светлую плашку: знак остаётся ровно таким, каким его утвердили.
   */
  onDark?: boolean
  /**
   * Куда ведёт знак.
   *
   * Всегда вёл на главную, и для гостя это верно. Для того, кто вошёл, —
   * нет: главная страница общая и публичная, то есть знак работал кнопкой
   * «выйти из кабинета». А знак в шапке — привычная кнопка «домой», и дом
   * у вошедшего свой: кабинет хозяйства или кабинет Ассоциации. Подпись
   * при этом обязана меняться вместе с адресом, иначе читающая программа
   * произнесёт «на главную» про ссылку в кабинет.
   */
  href?: string
  label?: string
}) {
  const custom = findPublicAsset('logo')
  const t = await currentTenant()

  return (
    <Link
      href={href}
      className={`flex items-center gap-2.5 ${
        onDark ? 'rounded-xl bg-white px-3 py-2.5' : ''
      } ${className}`}
      aria-label={label}
    >
      {custom ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={custom}
          alt={t.org.full}
          className="h-[42px] w-auto"
        />
      ) : (
        <>
          <svg width="44" height="34" viewBox="0 0 44 34" fill="none" aria-hidden="true">
            {/* голова коровы */}
            <path
              d="M6 6c0-2.2 2-3.6 4-2.8l4.4 1.8C16.6 3.4 19.2 2.8 22 2.8s5.4.6 7.6 2.2L34 3.2c2-.8 4 .6 4 2.8v7.4c0 7.6-5.6 13.8-13.4 14.6-1.7.2-3.5.2-5.2 0C11.6 27.2 6 21 6 13.4V6Z"
              fill="#17181A"
            />
            <path
              d="M13.6 14.4c0-3.6 3.8-6.4 8.4-6.4s8.4 2.8 8.4 6.4c0 5-3.8 8.8-8.4 8.8s-8.4-3.8-8.4-8.8Z"
              fill="#fff"
            />
            <ellipse cx="18.2" cy="13.6" rx="1.5" ry="1.9" fill="#17181A" />
            <ellipse cx="25.8" cy="13.6" rx="1.5" ry="1.9" fill="#17181A" />
            <path
              d="M16.8 19.4c0-1.3 2.3-2.3 5.2-2.3s5.2 1 5.2 2.3-2.3 2.6-5.2 2.6-5.2-1.3-5.2-2.6Z"
              fill="#17181A"
              opacity=".25"
            />
            {/* триколор — только у книги с государственным учётом */}
            {t.state === 'fgias' && (
              <>
            <rect
              x="6"
              y="29.6"
              width="10.6"
              height="1.5"
              rx=".75"
              fill="#fff"
              stroke="#D9D9D9"
              strokeWidth=".4"
            />
            <rect x="16.6" y="29.6" width="10.6" height="1.5" rx=".75" fill="#0039A6" />
            <rect x="27.2" y="29.6" width="10.6" height="1.5" rx=".75" fill="#D52B1E" />
              </>
            )}
          </svg>
          <span className="hidden text-[8.5px] font-bold uppercase leading-[1.35] tracking-[0.02em] text-ink-900 sm:block">
            {t.org.mark.map((line, i) => (
              <span key={line}>
                {i > 0 && <br />}
                {line}
              </span>
            ))}
          </span>
        </>
      )}
    </Link>
  )
}
