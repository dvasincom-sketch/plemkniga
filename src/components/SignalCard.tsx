import Link from 'next/link'
import type { ReactNode } from 'react'
import { nf } from '@/lib/format'

/**
 * Карточка тревожного числа: сколько, чего и что с этим делать.
 *
 * ## Зачем общий компонент
 *
 * На «Обзоре» две такие полосы подряд: дела по данным («29 записей
 * неполны») и сигналы по стаду («6 тёлок в передержке»). Собраны они были
 * порознь и разошлись в мелочах — в отступах, в цвете подписи, в том,
 * показывать ли число вообще. Две полосы, стоящие одна под другой
 * и означающие одно и то же — «вот работа», — обязаны выглядеть
 * одинаково, иначе разница в виде читается как разница в смысле,
 * которой нет.
 *
 * ## Почему число вынесено из фразы
 *
 * Было «6 тёлок в передержке» одной строкой одним кеглем. Полосу
 * из пяти таких строк нельзя пробежать глазами: чтобы понять масштаб,
 * каждую нужно прочесть словами. А смотрят на неё именно бегло — это
 * первый экран кабинета, и вопрос к нему один: где сегодня хуже всего.
 *
 * Число вынесено наверх и набрано крупно, подпись читается под ним.
 * Склонение при этом не ломается: `plural` уже согласовал подпись
 * с числом, и «1» над «тёлка в передержке» читается так же верно,
 * как «6» над «тёлок в передержке».
 *
 * ## Почему не так крупно, как в «Стаде в числах»
 *
 * Прямо выше стоят шесть карточек сводки с числами в 34 пункта зелёным.
 * Сравняйся с ними полоса — и она стала бы читаться как продолжение
 * сводки, то есть как «состояние», а не как «работа». Кегль меньше,
 * цвет другой: зелёный у нас означает «хорошо», и красить им число
 * коров с маститом нельзя.
 *
 * ## Почему число бывает без числа
 *
 * У дела «загрузок ещё не было» количества нет вовсе — считать нечего.
 * Ноль сюда не подставить: «0» крупным кеглем над «загрузок ещё
 * не было» утверждает ровно обратное тому, что случилось, — будто
 * загрузок ноль из скольких-то. В таком случае заголовком становится
 * сама подпись.
 */

export type SignalCardProps = {
  href: string
  /** Число, которое читают первым. Пропуск — заголовком станет подпись. */
  count?: number | null
  label: string
  /** Из чего это число: база и доля. */
  note?: ReactNode
  /** Что это значит и что делать — одной фразой. */
  hint?: string
  /** Красным — то, что уже стоит денег; белым — то, что просит внимания. */
  urgent?: boolean
}

export function SignalCard({ href, count, label, note, hint, urgent }: SignalCardProps) {
  const hasCount = typeof count === 'number' && count > 0

  return (
    <Link
      href={href}
      className={`flex min-w-[210px] flex-1 basis-0 flex-col rounded-xl px-4 py-4 transition-colors ${
        urgent
          ? 'bg-[#fdecea] hover:bg-[#fbe0dc]'
          : 'bg-white shadow-[0_1px_3px_rgb(23_24_26_/_0.08)] hover:bg-[#f6f6f6]'
      }`}
    >
      {hasCount && (
        <span
          className={`stat-value text-[30px] leading-none tabular-nums ${
            urgent ? 'text-[#8a2d22]' : 'text-ink-900'
          }`}
        >
          {nf(count, 0)}
        </span>
      )}

      <span className={`block text-[15px] font-medium leading-snug ${hasCount ? 'mt-2' : ''}`}>
        {label}
      </span>

      {/*
         База и доля — отдельной строкой, а не рядом с числом.
         «4033 из 4790 коров выше порога» в одну строку читается как одно
         длинное число; разведённые, они читаются как утверждение
         и его масштаб.
      */}
      {note && <span className="mt-1.5 block text-[12px] leading-snug text-ink-700">{note}</span>}

      {hint && <span className="mt-1.5 block text-[12px] leading-snug text-ink-500">{hint}</span>}
    </Link>
  )
}

/**
 * Ряд карточек.
 *
 * `basis-0` здесь важнее, чем кажется: без него ширина карточки зависит
 * от длины её текста, и ряд получается разноширинным — соседние карточки
 * об одном и том же выглядят разными по весу, хотя различаются только
 * длиной подписи. С нулевой основой все растут от одного и делят строку
 * поровну.
 */
export function SignalRow({ children }: { children: ReactNode }) {
  return <div className="flex flex-wrap gap-3">{children}</div>
}
