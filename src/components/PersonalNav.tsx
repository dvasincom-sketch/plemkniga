import { SubTabs } from '@/components/SubTabs'

/**
 * Личные страницы человека — те, что не про хозяйство.
 *
 * ## Почему их отделили от настроек хозяйства
 *
 * Они лежали в одном ряду с видимостью стада, сотрудниками и журналом,
 * и одновременно в меню под именем. Два меню на одни и те же пункты —
 * это не удобство, а два места, где записано одно правило: они разойдутся,
 * и однажды разошлись (решение №119).
 *
 * Граница проходит не по важности, а по тому, чьё это. Уволится зоотехник —
 * его профиль, его подписка на письма и его лента уведомлений уйдут вместе
 * с ним, а видимость стада, состав сотрудников и журнал останутся
 * хозяйству. Всё, что уходит с человеком, — здесь.
 *
 * ## Про два разных слова «уведомления»
 *
 * Их было два, и оба назывались одинаково: страница `/account/notifications`
 * — это лента событий, а вкладка профиля `?tab=notifications` — настройка,
 * что из этого дублировать на почту. Один и тот же пункт меню вёл то
 * в список, то в переключатели.
 *
 * Теперь «Уведомления» — только лента, то есть то, что человек имеет в виду,
 * когда произносит это слово. Настройка называется «Письма»: она отвечает
 * на вопрос «что мне присылать», а не «что случилось».
 *
 * ## Почему ряд кабинета над ними не рисуется
 *
 * Плашки разделов хозяйства над личной страницей — ряд, в котором нечего
 * подсветить. Такой ряд сообщает «вы вне разделов», стоя внутри кабинета,
 * и человек начинает искать, куда попал. Вернуться отсюда есть чем: пункт
 * «Моё хозяйство» появился в шапке первым.
 */

export const PERSONAL_SUBTABS = [
  {
    key: 'user',
    label: 'Профиль',
    hint: 'Фамилия, телефон, должность',
    href: '/account/profile?tab=user',
  },
  {
    key: 'feed',
    label: 'Уведомления',
    hint: 'Что произошло: запросы, ответы, результаты проверок',
    href: '/account/notifications',
  },
  {
    key: 'notifications',
    label: 'Письма',
    hint: 'Что из уведомлений дублировать на почту',
    href: '/account/profile?tab=notifications',
  },
  {
    key: 'billing',
    label: 'Биллинг',
    hint: 'Оплата платных услуг',
    href: '/account/profile?tab=billing',
    /*
     * Только хозяйству. У сотрудника Ассоциации нет ни организации,
     * ни платных услуг: он сам эти услуги и оказывает. Пункт, ведущий
     * на пустую страницу, — не безобидная лишняя строка: человек нажимает,
     * ничего не находит и начинает искать, где спрятана оплата.
     *
     * На самой странице профиля вкладка отфильтрована давно, а в меню
     * под именем осталась: два места с одним правилом, и они разошлись.
     * Правило теперь одно и лежит здесь, рядом с пунктом.
     */
    farmOnly: true,
  },
] as const

export type PersonalSub = (typeof PERSONAL_SUBTABS)[number]['key']

/** Пункты, которые видит этот человек: у Ассоциации нет биллинга. */
export const personalTabsFor = (association: boolean) =>
  PERSONAL_SUBTABS.filter((t) => !(association && 'farmOnly' in t && t.farmOnly))

export function PersonalNav({
  active,
  association = false,
}: {
  active: PersonalSub
  association?: boolean
}) {
  return (
    <SubTabs
      label="Личные страницы"
      active={active}
      /*
       * Своего меню кабинета над этим рядом нет, поэтому и отрицательного
       * отступа быть не должно: умолчание `-mt-4` рассчитано на то, что
       * выше стоит ряд разделов со своим нижним отступом.
       */
      className="mb-8"
      items={personalTabsFor(association).map((s) => ({
        key: s.key,
        label: s.label,
        hint: s.hint,
        href: s.href,
      }))}
    />
  )
}
