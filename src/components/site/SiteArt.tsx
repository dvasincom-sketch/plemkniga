/**
 * Рисунки витрины говорят тем же языком, что и рисунки внутри книги.
 *
 * ## Что было не так
 *
 * Первая редакция нарисовала шестерню, проволочный глобус, коровник
 * с деревьями и стадо с ногами и головами, соединённое пунктиром.
 * Каждый рисунок был понятен сам по себе и все вместе — чужими: внутри
 * книги (`components/CardIcons.tsx`) рисуют иначе. Там плоские скруглённые
 * прямоугольники, три серых из одного набора, ни одного пунктира
 * и ни одного предмета из реального мира. Человек, пришедший с витрины
 * в книгу, попадал будто в другой продукт.
 *
 * ## Из чего теперь собрано
 *
 * Из одной детали — листа со строками. Она уже есть в книге и означает
 * там запись: у неё те же скругления, та же заливка `#efefef`, та же
 * обводка `#d0d0d0` и те же строки `#c9c9c9`. Стопка листов означает
 * «много записей», одиночный лист — «одна». Зелёный появляется ровно
 * там, где несёт смысл, и больше нигде.
 *
 * Отдельно про повторное использование: `Sheet` — один компонент,
 * и одинаковость листов на рисунке о стандарте не нарисована,
 * а обеспечена кодом. Рисунок утверждает «одна и та же запись читается
 * везде», и если бы листы рисовались порознь, первая же правка сделала
 * бы это утверждение ложным на самом рисунке.
 */

/** Лист с четырьмя строками — та же деталь, что в карточках книги. */
const Sheet = ({ x, y, accent = false }: { x: number; y: number; accent?: boolean }) => (
  <>
    <rect x={x} y={y} width="52" height="66" rx="6" fill="#efefef" stroke="#d0d0d0" />
    {[0, 1, 2, 3].map((i) => (
      <rect
        key={i}
        x={x + 9}
        y={y + 13 + i * 13}
        width={i % 2 ? 26 : 34}
        height="4"
        rx="2"
        fill={accent && i === 0 ? '#2E7D52' : '#c9c9c9'}
      />
    ))}
  </>
)

/** Серая стрелка вправо — тот же приём, что у значка загрузки файлом. */
const SheetArrow = ({ x, y, len = 26 }: { x: number; y: number; len?: number }) => (
  <path
    d={`M${x} ${y}h${len}m0 0-7-6m7 6-7 6`}
    fill="none"
    stroke="#9a9a9a"
    strokeWidth="3"
    strokeLinecap="round"
    strokeLinejoin="round"
  />
)

/**
 * Международный стандарт: наша запись и она же в чужой системе.
 *
 * Слева одиночный лист с зелёной первой строкой — наша запись. Справа
 * стопка: чужих систем много, и это единственная разница между двумя
 * сторонами рисунка. Строки на всех листах одни и те же, потому что
 * лист один и тот же компонент, — в этом всё утверждение.
 *
 * Шестерни и глобуса больше нет. Шестерня означала бы механизм проверки,
 * а проверяют не механизмом, а совпадением записей; глобус добавлял
 * «международность» украшением, ничего не сообщая.
 */
export function StandardArt({ title }: { title: string }) {
  return (
    <svg viewBox="0 0 184 88" className="h-[88px] w-full max-w-[184px]" role="img" aria-label={title}>
      <Sheet x={6} y={11} accent />
      <SheetArrow x={70} y={44} />
      <rect x="110" y="5" width="52" height="66" rx="6" fill="#d6d6d6" />
      <Sheet x={118} y={11} accent />
    </svg>
  )
}

