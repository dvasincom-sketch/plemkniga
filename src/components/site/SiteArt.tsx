/**
 * Большой рисунок первого экрана: одно животное среди всей книги.
 *
 * ## Что он говорит
 *
 * Ровно то, чего не умеет программа управления фермой. Серое поле —
 * всё поголовье книги. Светлая плашка внутри — своё стадо. Зелёная
 * метка — одно животное, и место у неё названо среди всех, а не среди
 * сорока соседок по двору.
 *
 * Довод этот главный, и потому он стоит первым: лучшая тёлка стада —
 * первое место среди сорока, а сорок седьмое среди двадцати тысяч —
 * другая цена и другой разговор с покупателем. Посчитать такое
 * в одиночку нельзя, для этого нужны все стада разом, и в этом
 * единственная настоящая выгода объединения.
 *
 * ## Что было раньше и почему заменено
 *
 * Разворот книги: страница записей, дерево происхождения, документ.
 * Рисунок был верным и ничего не говорил — «какой-то документ», серые
 * строки и дерево из прямоугольников, читавшееся как блок-схема. Хуже
 * того, он спорил с карточкой животного ниже по странице, нарисованной
 * тем же языком: два похожих рисунка на одном полотне заставляют искать
 * между ними разницу, которой нет.
 *
 * ## Почему без единой надписи
 *
 * Подпись внутри рисунка не переводится: на казахской странице она
 * осталась бы русской. Смысл несут три уровня серого и один зелёный,
 * а словами он сказан рядом, в подписи под рисунком, — там, где
 * перевод есть.
 *
 * ## Почему это не повтор полосы «Рейтинг»
 *
 * Там шкала: отрезок от первого места до последнего с отметкой. Здесь
 * поле: видно не положение на прямой, а размер того, среди чего считают.
 * Первый экран отвечает «среди скольких», раздел рейтинга — «на каком
 * месте».
 */
export function HeroArt({ title }: { title: string }) {
  const COLS = 18
  const ROWS = 10
  const CELL = 20
  const SIZE = 12

  /* Своё стадо — прямоугольник четыре на три, смещённый от середины:
     ровно посередине он читался бы как мишень, а не как «одно из». */
  const herd = { col: 4, row: 3, w: 4, h: 3 }
  const mine = { col: 6, row: 4 }

  const inHerd = (c: number, r: number) =>
    c >= herd.col && c < herd.col + herd.w && r >= herd.row && r < herd.row + herd.h

  const cells: { c: number; r: number }[] = []
  for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) cells.push({ c, r })

  return (
    <svg
      viewBox={`0 0 ${COLS * CELL} ${ROWS * CELL}`}
      className="h-auto w-full max-w-[420px]"
      role="img"
      aria-label={title}
    >
      {/* плашка своего стада — тот же приём, что у выбранной строки в книге */}
      <rect
        x={herd.col * CELL - 4}
        y={herd.row * CELL - 4}
        width={herd.w * CELL + 8 - (CELL - SIZE)}
        height={herd.h * CELL + 8 - (CELL - SIZE)}
        rx="10"
        fill="#EAF3EE"
        stroke="#BFD9C9"
      />

      {cells.map(({ c, r }) => {
        const own = inHerd(c, r)
        const it = c === mine.col && r === mine.row
        return (
          <rect
            key={`${c}-${r}`}
            x={c * CELL}
            y={r * CELL}
            width={SIZE}
            height={SIZE}
            rx="3"
            fill={it ? '#2E7D52' : own ? '#b9b9b9' : '#dcdcdc'}
          />
        )
      })}

      {/* обводка у выбранного животного: одного цвета мало, когда метка
          такого же размера, как соседние */}
      <rect
        x={mine.col * CELL - 4}
        y={mine.row * CELL - 4}
        width={SIZE + 8}
        height={SIZE + 8}
        rx="6"
        fill="none"
        stroke="#2E7D52"
        strokeWidth="2"
      />
    </svg>
  )
}

/**
 * Порода, у которой книги нет: пустой лист становится заполненным.
 *
 * Пунктирный контур здесь на месте — он и в родословной значит
 * «этого нет». Слева порода, о которой известно только имя; справа
 * та же порода с записями. Между ними стрелка, и это всё содержание
 * раздела: книга заводится, а не появляется сама.
 */
export function BreedBookArt({ title }: { title: string }) {
  return (
    <svg viewBox="0 0 184 88" className="h-[88px] w-full max-w-[184px]" role="img" aria-label={title}>
      <rect
        x="6"
        y="11"
        width="52"
        height="66"
        rx="6"
        fill="none"
        stroke="#c9c9c9"
        strokeDasharray="5 4"
      />
      <rect x="18" y="24" width="28" height="4" rx="2" fill="#d6d6d6" />

      <SheetArrow x={70} y={44} />

      <rect x="110" y="5" width="52" height="66" rx="6" fill="#d6d6d6" />
      <Sheet x={118} y={11} accent />
    </svg>
  )
}
