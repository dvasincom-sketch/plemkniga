import Link from 'next/link'
import { PlemLogo } from '@/components/PlemLogo'
import { LocaleSwitcher } from '@/components/LocaleSwitcher'
import { PAGE_MESSAGES } from '@/lib/i18n/page-messages'
import { LOCALE_CODES, type Locale } from '@/lib/i18n/locales'
import { BOOK_URL, PRODUCT_MAIL } from '@/lib/hosts'
import { PLATFORM } from '@/lib/platform'

/**
 * Обвязка страниц продукта: шапка и подвал витринного домена.
 *
 * ## Что было не так
 *
 * «Соответствие», карта ICAR и описание интерфейса переехали
 * на `plem.online`, но остались в обвязке книги: шапка со знаком
 * Ассоциации, разделами кабинета и счётчиком уведомлений, подвал
 * с самарским адресом и телефоном.
 *
 * Выглядело это сломанным — знак чужой, разделы ведут в кабинет,
 * которого на этом домене нет, — но хуже вида было содержание:
 * страница о продукте представлялась страницей голштинской ассоциации.
 * Читатель, пришедший узнать, по каким стандартам построена система,
 * попадал в чужую организацию.
 *
 * ## Почему это отдельная обвязка, а не признак у общей
 *
 * Соблазн был добавить в `SiteHeader` признак «мы на витрине» и прятать
 * лишнее. Так нельзя: шапка книги знает, кто вошёл, считает непрочитанные
 * уведомления и ходит за этим в базу — на каждое открытие страницы
 * о стандартах, которую читают анонимно и с чужого домена.
 *
 * Разделять надо не оформление, а принадлежность. Здесь ничего не знает
 * о пользователе и не касается базы вовсе.
 *
 * ## Почему страницы продукта только по-русски
 *
 * Витрина переведена на шесть языков, а «Соответствие» и карта ICAR —
 * нет. Это честное состояние, а не упущение: там пятьдесят абзацев
 * разбора, и переводить их без носителя языка значило бы получить
 * пятьдесят абзацев, которым нельзя верить, — на странице, вся ценность
 * которой в том, что ей верят.
 *
 * Поэтому переключателя языков в этой шапке нет: он обещал бы переводы,
 * которых не существует.
 */

export function ProductHeader({
  children,
  locale = 'ru',
  path,
}: {
  children?: React.ReactNode
  locale?: Locale
  /**
   * Адрес этой же страницы без языка: `/compliance`, `/breeds`.
   *
   * Переключатель обязан вести на **ту же** страницу на другом языке,
   * а не на главную. Уводить на главную значит терять место, куда
   * человек шёл, — и он уходит совсем, а не переключает язык.
   */
  path?: string
}) {
  const l = PAGE_MESSAGES[locale]

  return (
    <header className="container-page flex flex-wrap items-center justify-between gap-x-8 gap-y-4 py-8">
      {/*
         Знак ведёт на корень витринного домена. Сам он ссылкой
         не является — в отличие от знака Ассоциации, — и обёртка здесь
         не создаёт вложенных ссылок.
      */}
      <Link href="/" aria-label="ПЛЕМ online">
        <PlemLogo />
      </Link>

      <div className="flex flex-wrap items-center gap-x-6 gap-y-3">
        {children}

        {/*
           Переключатель языка стоит на каждой странице продукта,
           а не только на главной.

           Человек, выбравший язык на первом экране и ушедший
           в «Соответствие», прежде оказывался на русской странице
           без всякой возможности вернуться к своему языку иначе,
           чем через главную. Язык — свойство посетителя, а не одной
           страницы.
        */}
        {path && (
          <LocaleSwitcher
            active={locale}
            label={l.nav.language}
            hrefs={
              Object.fromEntries(LOCALE_CODES.map((c) => [c, `/${c}${path}`])) as Record<
                Locale,
                string
              >
            }
          />
        )}
      </div>
    </header>
  )
}

/**
 * Подвал продукта: четыре ссылки и почта.
 *
 * Ни адреса, ни телефона, ни правовых документов Ассоциации: они
 * называют другое лицо. Подписи разработчика тоже нет — последнее,
 * что видит уходящий, должно вести к системе.
 */
/**
 * Подписи подвала на двух языках.
 *
 * Полноценного набора строк здесь нет намеренно: подписей четыре, и заводить
 * ради них механику перевода значило бы построить дорогу к одному дому.
 * Как только страниц продукта на английском станет больше двух, это
 * перерастёт в общий набор — а пока лишний слой только мешал бы читать.
 */
export function ProductFooter({ lang = 'ru' }: { lang?: Locale }) {
  const l = PAGE_MESSAGES[lang].nav

  const links: { href: string; label: string }[] = [
    { href: lang === 'ru' ? '/' : `/${lang}`, label: l.about },
    { href: `/${lang}/breeds`, label: l.breeds },
    { href: `/${lang}/compliance`, label: l.compliance },
    { href: `/${lang}/api-docs`, label: l.api },
    { href: `/${lang}/org`, label: l.org },
    /*
     * «Эволюция продукта» переехала сюда из подвала книги вместе
     * с самой страницей. Адрес без языка, в отличие от соседей:
     * страница написана по-русски и переводить её мы не беремся —
     * поставить `/kk/evolution` значило бы пообещать казахский текст
     * и отдать русский.
     */
    { href: '/evolution', label: l.evolution },
    /*
     * Ссылка названа доменом, а не словами «Племенная книга».
     *
     * Разница смысловая. «Племенная книга» рядом с «О продукте»
     * и «Соответствием» читается как раздел этого же сайта — то есть
     * будто продукт и есть та самая книга. А это разные вещи:
     * `plem.online` — система, `holstein.plem.online` — одна конкретная
     * книга одной ассоциации, ведущаяся на ней.
     *
     * Домен снимает двусмысленность сам: видно, что уходишь в другое
     * место, ещё до нажатия.
     */
    { href: BOOK_URL, label: BOOK_URL.replace('https://', '') },
  ]

  return (
    <footer style={{ marginTop: 'var(--footer-air)' }} className="bg-basement py-10 text-white">
      <nav
        aria-label={lang === 'ru' ? 'Разделы продукта' : 'Product sections'}
        className="container-page flex flex-wrap items-center gap-x-8 gap-y-3 text-[14px]"
      >
        {links.map((l) =>
          /*
           * Внутренние адреса — через `Link`, внешний адрес книги —
           * обычной ссылкой: другой домен, и клиентский переход туда
           * невозможен.
           */
          l.href.startsWith('http') ? (
            <a
              key={l.href}
              href={l.href}
              className="text-white/50 underline underline-offset-4 transition-colors hover:text-white"
            >
              {l.label}
            </a>
          ) : (
            <Link
              key={l.href}
              href={l.href}
              className="text-white/50 underline underline-offset-4 transition-colors hover:text-white"
            >
              {l.label}
            </Link>
          ),
        )}

        <a
          href={`mailto:${PRODUCT_MAIL}`}
          className="text-white/70 underline underline-offset-4 transition-colors hover:text-white"
        >
          {PRODUCT_MAIL}
        </a>
      </nav>

      {/*
         Кто содержит систему — отдельной строкой под ссылками.

         В строку ссылок это не встаёт: там разделы, а здесь лицо,
         и уравнивать их значило бы предложить читателю выбирать между
         «Породами» и организацией как между двумя страницами. Форма
         указана короткой (`АНО «ПЛЕМ.ОНЛАЙН»`): полная занимает
         полстроки и вытесняет всё остальное, а полностью она стоит
         на самой странице организации.
      */}
      <p className="container-page mt-6 text-[13px] text-white/40">
        © {PLATFORM.since} {PLATFORM.legalShort}
      </p>
    </footer>
  )
}
