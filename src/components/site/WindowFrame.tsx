/**
 * Окно кабинета — общая рамка для всех нарисованных экранов.
 *
 * ## Зачем понадобилась
 *
 * Экранов в переключателе три, и рамка была только у одного: карточка
 * животного шла в обводке с шапкой, а родословная и разбор оценки —
 * голыми блоками. Переключаясь между вкладками, читатель видел не три
 * экрана одной системы, а три разных куска вёрстки, и первое, о чём
 * он думал, — «а это вообще из одной программы?».
 *
 * ## Почему кнопки окна, а не просто обводка
 *
 * Обводка говорит «это картинка в рамке». Три кружка и заголовок
 * говорят «это окно», то есть рабочее место, а не иллюстрация. Разница
 * та же, что у записи работы: без рамки браузера она читалась как ролик
 * про продукт, с рамкой — как сам продукт.
 *
 * Кружки серые, а не красный с жёлтым и зелёным. Цветные читались бы
 * как состояние — «здесь ошибка», — а это просто оконная рамка, и ей
 * нечего сообщать. Тот же довод, что у рамки вокруг записи работы.
 *
 * ## Почему в заголовке кличка, а не название раздела
 *
 * Название раздела уже стоит на вкладке прямо над окном, и повторять
 * его внутри значит сказать одно и то же дважды в двух сантиметрах
 * друг от друга. А кличка с номером отвечают на другой вопрос —
 * «что открыто», — и связывают три экрана в одно: видно, что
 * родословная и оценка относятся к тому же животному, что и карточка.
 *
 * Отсюда следует и исключение: у отчёта по стаду в заголовке стоит
 * хозяйство, а у заявки — её номер, потому что открыто там не животное.
 * Правило не «всегда кличка», а «то, над чем работают»; поставить
 * кличку туда, где показано стадо, значит соврать о предмете.
 */
export function WindowFrame({
  title,
  subtitle,
  children,
}: {
  /** Что открыто: кличка и номер, а не название раздела. */
  title: string
  /** Необязательная приписка справа — состояние записи. */
  subtitle?: string
  children: React.ReactNode
}) {
  return (
    <figure className="overflow-hidden rounded-2xl border border-ink-200 bg-white shadow-[0_1px_3px_rgb(23_24_26_/_0.08)]">
      <div className="flex items-center gap-3 border-b border-ink-100 bg-ink-50 px-4 py-2.5">
        {/*
           Кнопки закрытия, свёртывания и разворота. Они не работают
           и работать не должны: это рисунок окна, а не окно. Поэтому
           не `button`, а простые метки — кнопка, которая ничего
           не делает, обещает нажатие.
        */}
        <div className="flex gap-1.5" aria-hidden="true">
          {[0, 1, 2].map((i) => (
            <span key={i} className="h-2.5 w-2.5 rounded-full bg-ink-200" />
          ))}
        </div>

        <span className="truncate text-[12px] text-ink-500">{title}</span>

        {subtitle && (
          <span className="ml-auto shrink-0 rounded-md bg-white px-2 py-0.5 text-[11px] text-ink-400">
            {subtitle}
          </span>
        )}
      </div>

      {children}
    </figure>
  )
}
