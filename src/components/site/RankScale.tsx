'use client'

import { useEffect, useRef, useState } from 'react'
import { DEFAULT_LOCALE, type Locale } from '@/lib/i18n/locales'
import { screensText } from '@/lib/book-screens-text'

/**
 * Шкала места среди всей популяции — с движением.
 *
 * ## Что говорит движение
 *
 * То же, что рисунок первого экрана, только с другой стороны. Там —
 * «среди скольких», здесь — «на каком месте», и место у каждого
 * животного своё. Неподвижная шкала с числом 47 говорила про одну
 * тёлку; шкала, на которой отметка обходит весь список, говорит,
 * что счёт ведётся каждому.
 *
 * ## Почему здесь движение плавное, а на первом экране скачком
 *
 * Разные фигуры и разные утверждения. Поле — множество, и выделение
 * в нём перескакивает: «а вот другое хозяйство». Шкала — прямая,
 * и на прямой у величины есть соседи: между сорок седьмым и шестнадцатитысячным
 * местом лежат все промежуточные, и провести отметку через них честнее,
 * чем телепортировать. Число при этом считается вместе с отметкой,
 * а не подставляется в конце: иначе оно спорило бы с её положением
 * целую секунду.
 *
 * ## Про сами числа
 *
 * Они выдуманные, и это не беда: рисунок объясняет устройство,
 * а не показывает данные. Беда была бы в обратном — подставить сюда
 * настоящее животное настоящего хозяйства.
 *
 * Разряды у них разные по языкам, и это не оформление: «16,320»
 * русский читатель прочтёт как шестнадцать с третью. Поэтому и число,
 * и строка для голосового доступа приходят из набора строк экранов
 * (`lib/book-screens-text.ts`), а язык по умолчанию русский.
 *
 * ## Про тех, кому движение мешает
 *
 * Тот же порядок, что у поля на первом экране: системная просьба
 * «поменьше движения» останавливает показ на первой остановке.
 * Проверяется она здесь, а не медиавыражением, потому что число
 * считается кодом и остановить его правилом стиля нельзя.
 */

/** Сколько всего животных в списке — знаменатель у всех остановок. */
const TOTAL = 21_480

/**
 * Места, между которыми ходит отметка.
 *
 * ## Почему не 47, 312 и 1 208
 *
 * Первая редакция взяла три места из верхней части списка, и вышло
 * бессмысленно: сорок седьмое место — это две десятых процента шкалы,
 * триста двенадцатое — полтора. Отметка стояла в одной точке у левого
 * края, число рядом менялось, и получалась поломка: подпись говорит,
 * что место другое, а ползунок не двигается.
 *
 * Ошибка не в анимации, а в выборе чисел: три значения из одного угла
 * шкалы нельзя показать шкалой. Это тот же промах, что с ценой
 * за единицу против цены за шаг, — величины сравнимы только тогда,
 * когда сравнима их мера.
 *
 * ## Почему теперь такие
 *
 * Они разложены по всей длине, и это правда: в книге животные стоят
 * везде, а не только вверху. Начинается показ с середины — так у стоящей
 * страницы отметка не жмётся к краю, и человеку, у которого движение
 * выключено, видна шкала целиком, а не её начало.
 *
 * Сорок седьмое место оставлено: на него ссылается текст рядом
 * («лучшая тёлка стада»), и убрать его значило бы развести рисунок
 * с подписью.
 */
const STOPS = [8_940, 47, 16_320, 3_260]

/** Сколько стоит на остановке и сколько едет до следующей, мс. */
const HOLD = 2_600
const MOVE = 900

/**
 * Куда отметка не заезжает.
 *
 * У самого края подпись с числом обрезается половиной, а кружок
 * наезжает на конец дорожки. Четыре процента с каждой стороны —
 * запас на подпись; смысл при этом не страдает, потому что шкала
 * показывает положение, а не измеряет его с точностью до пикселя.
 */
const clamp = (percent: number) => Math.min(96, Math.max(4, percent))

export function RankScale({
  title,
  locale = DEFAULT_LOCALE,
}: {
  title: string
  locale?: Locale
}) {
  const t = screensText(locale)
  const [rank, setRank] = useState(STOPS[0]!)
  const frame = useRef<number>(0)

  useEffect(() => {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return

    let stop = 0
    let timer: ReturnType<typeof setTimeout>

    const glide = (from: number, to: number, started: number) => {
      const step = (now: number) => {
        const passed = Math.min(1, (now - started) / MOVE)
        /*
         * Замедление к концу: равномерное движение читается как машинное,
         * а отметка изображает не механизм, а перебор животных.
         */
        const eased = 1 - Math.pow(1 - passed, 3)
        setRank(Math.round(from + (to - from) * eased))
        if (passed < 1) frame.current = requestAnimationFrame(step)
        else timer = setTimeout(next, HOLD)
      }
      frame.current = requestAnimationFrame(step)
    }

    const next = () => {
      const from = STOPS[stop]!
      stop = (stop + 1) % STOPS.length
      glide(from, STOPS[stop]!, performance.now())
    }

    timer = setTimeout(next, HOLD)
    return () => {
      clearTimeout(timer)
      cancelAnimationFrame(frame.current)
    }
  }, [])

  /*
   * Положение считается из места, а не хранится отдельно: два числа,
   * означающие одно и то же, рано или поздно разъезжаются — и тогда
   * отметка стоит не там, где написано.
   */
  const share = (rank / TOTAL) * 100
  const at = `${clamp(share)}%`
  /* Заполнение — по настоящей доле, без запаса: полоса длиной
     в четыре процента при первом месте соврала бы о положении. */
  const fill = `${share}%`

  return (
    <div
      role="img"
      aria-label={`${title}: ${t.rank(t.number(rank), t.number(TOTAL))}`}
      className="w-full max-w-[320px]"
    >
      <div className="relative pt-7">
        <span
          className="absolute top-0 -translate-x-1/2 text-[13px] font-medium tabular-nums text-forest-600"
          style={{ left: at }}
        >
          {t.number(rank)}
        </span>

        <div className="h-3 w-full rounded-full bg-ink-100">
          <div className="h-3 rounded-full bg-forest-500" style={{ width: fill }} />
        </div>

        <span
          className="absolute -translate-x-1/2 rounded-full border-[3px] border-forest-500 bg-white"
          style={{ left: at, top: '1.5rem', height: '1.125rem', width: '1.125rem' }}
        />
      </div>

      <div className="mt-3 flex justify-between text-[12px] tabular-nums text-ink-500">
        <span>1</span>
        <span>{t.number(TOTAL)}</span>
      </div>
    </div>
  )
}
