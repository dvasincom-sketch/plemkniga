'use client'

import { useEffect, useRef } from 'react'

/**
 * Запись работы, идущая сама и без кнопок.
 *
 * ## Почему без панели управления
 *
 * Это не фильм, а рисунок, который движется: он показывает, как выглядит
 * кабинет, и не рассчитан на перемотку. Панель воспроизведения превращала
 * бы его в «контент, который надо посмотреть» — с решением, тратить ли
 * на это минуту. Движущаяся картинка такого решения не требует и потому
 * доносит больше.
 *
 * Взамен нажатие по записи ставит её на паузу и снимает с паузы. Отнять
 * управление совсем нельзя: движение в поле зрения мешает читать текст
 * рядом, и человеку нужен способ его остановить.
 *
 * ## Почему без звука, и это не выбор
 *
 * Браузеры не запускают со звуком ничего, чего не просили; со звуком
 * запись просто не начнётся. Отсюда и `muted` — не «мы решили без звука»,
 * а единственный способ, которым автозапуск вообще работает.
 *
 * ## Что здесь делает наблюдатель
 *
 * Запись останавливается, когда уезжает из поля зрения. Иначе браузер
 * продолжает раскодировать кадры и крутить вентилятор ради картинки
 * в трёх экранах выше, а на ноутбуке это заметно по расходу заряда.
 *
 * ## Про тех, кому движение мешает
 *
 * Системная настройка «меньше движения» ставится не из вкуса: у части
 * людей движущаяся картинка вызывает тошноту и головную боль. Для них
 * запись стоит на первом кадре, и это единственная причина, по которой
 * компонент вообще клиентский, — узнать настройку можно только в браузере.
 */
export function DemoPlayer({ src, poster }: { src: string; poster?: string }) {
  const ref = useRef<HTMLVideoElement>(null)

  useEffect(() => {
    const el = ref.current
    if (!el) return

    const calm = window.matchMedia('(prefers-reduced-motion: reduce)')
    if (calm.matches) return

    /*
     * Запуск может не состояться — например, при экономии трафика.
     * Отказ нужно поймать: невыполненное обещание всплывает в консоль
     * ошибкой, и она выглядит как поломка страницы, хотя браузер просто
     * поступил по своим правилам. Заставка при этом остаётся на месте.
     */
    const play = () => void el.play().catch(() => {})

    const eye = new IntersectionObserver(
      ([entry]) => {
        if (!entry) return
        if (entry.isIntersecting) play()
        else el.pause()
      },
      { threshold: 0.25 },
    )

    eye.observe(el)
    return () => eye.disconnect()
  }, [])

  return (
    <video
      ref={ref}
      className="block h-auto w-full cursor-pointer"
      muted
      loop
      playsInline
      preload="metadata"
      poster={poster}
      aria-label="Запись работы в кабинете. Нажатие останавливает и продолжает показ."
      onClick={(e) => {
        const el = e.currentTarget
        if (el.paused) void el.play().catch(() => {})
        else el.pause()
      }}
    >
      <source src={src} />
    </video>
  )
}
