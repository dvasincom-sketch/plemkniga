import { findPublicAsset } from '@/lib/media'
import { BOOK_HOST } from '@/lib/hosts'
import { DemoPlayer } from './DemoPlayer'

/**
 * Место под запись работы в кабинете.
 *
 * ## Зачем видео, когда есть нарисованные экраны
 *
 * Рисунок отвечает на вопрос «как это выглядит», запись — на вопрос
 * «как этим пользуются». Второй возникает у того, кто уже поверил
 * первому: он хочет увидеть не картинку, а движение — как открывается
 * карточка, как выпускается документ, как выглядит поиск по книге.
 *
 * ## Почему заглушка, а не «пока уберём блок»
 *
 * Блока, которого нет, не видно в вёрстке, и о нём забывают. Место,
 * которое ждёт файл, само напоминает о себе на каждой сборке —
 * и, что важнее, вёрстка вокруг него уже выверена: подставленный
 * позже файл не сдвинет соседние экраны.
 *
 * ## Как поставить запись
 *
 * Положите файл в `public/product/` под именем `demo` — подхватятся
 * `.mp4`, `.webm` или `.mov`. Рядом ложится `demo-poster` (`.jpg`,
 * `.png`, `.webp`) — первый кадр, который виден до нажатия.
 *
 * Папка `product/` не для порядка: всё в ней принадлежит витрине
 * и на домене книги не отдаётся вовсе (`lib/hosts.ts`). Запись работы,
 * лежащая рядом со знаком Ассоциации, отдавалась бы с её домена —
 * рассказ о продукте под именем организации, которая его не продаёт.
 *
 * ## Почему заставка обязательна, а не желательна
 *
 * Без неё браузер обязан скачать хоть сколько-то видео, чтобы нарисовать
 * первый кадр, — и на месте записи висит чёрный прямоугольник, пока это
 * происходит. Заставка весит шестьдесят килобайт и появляется сразу,
 * а само видео не качается вовсе, пока на него не нажали (`preload="none"`).
 *
 * ## Про мешок с данными в конце файла
 *
 * Первая присланная запись весила 50 МБ и не начинала играть, пока
 * не докачивалась почти целиком. Дело было не в размере: в MP4 есть
 * оглавление (`moov`), и записывающие программы по умолчанию кладут его
 * **в конец**. Браузер не может начать показ, не прочитав оглавление,
 * — значит качает весь файл ради последних семидесяти килобайт.
 *
 * Лечится пересборкой контейнера без перекодирования:
 *
 *     ffmpeg -i исходник.mp4 -c copy -movflags +faststart public/demo.mp4
 *
 * Заодно запись экрана хорошо ужимается: та же картинка при `-crf 26`
 * весит 4 МБ вместо 50, и текст в кабинете остаётся читаемым.
 *
 * ## Хранилище снаружи
 *
 * Пока запись одна, она едет вместе с выкладкой. Когда материалов станет
 * много — а они понадобятся и самой книге, — файлы переедут в хранилище
 * на нашем сервере, и адреса задаются переменными `DEMO_VIDEO_URL`
 * и `DEMO_POSTER_URL`.
 *
 * Переменные без приставки `NEXT_PUBLIC_`: компонент серверный, и адрес
 * подставляется при запросе. С приставкой он вшился бы в сборку, и смена
 * хранилища требовала бы пересборки — рака, на которую мы уже наступали.
 *
 * Полноценной библиотеки материалов здесь нарочно нет: сейчас файл один,
 * и слой, написанный под один файл, всё равно придётся переписать, когда
 * файлов станет много. Две переменные честнее выдуманной абстракции.
 *
 * ## Почему полоса тёмная
 *
 * Запись — это светящийся экран, и вокруг него нужна темнота: на светлой
 * странице яркий прямоугольник читается как ещё один блок вёрстки,
 * на тёмной — как окно, в которое смотрят. Тот же приём, по которому
 * тёмный зал делают в кинотеатре, а не в фойе.
 *
 * Цвет взят из книги — тот самый, которым отмечена карточка быка
 * (`basement`). Оговорка тут важная: переносится **палитра, а не
 * значение**. В книге тёмный означает «другой предмет разговора,
 * а не другая корова»; на витрине животных нет вовсе, и означать ему
 * тут нечего. Заводить ради одной полосы седьмой цвет значило бы
 * растить палитру там, где хватает имеющейся.
 *
 * ## Про рамку окна
 *
 * Запись обведена окном браузера: три кружка и строка адреса. Это
 * не украшение и не подражание чужим витринам.
 *
 * Без рамки движущийся прямоугольник посреди страницы читается как
 * рекламный ролик — то есть как что-то снятое **про** продукт. Рамка
 * говорит другое: это тот же браузер, в котором человек сейчас читает,
 * и внутри него работающий кабинет. Разница между «нам показали ролик»
 * и «я вижу, как это работает» — вся ценность записи.
 *
 * Адрес в строке настоящий и подставляется из настроек, а не написан
 * буквами. Нарисованный адрес разошёлся бы с доменом при первом же
 * переезде, и рамка, которая ручается за подлинность, начала бы врать
 * первой.
 *
 * ## Про автозапуск
 *
 * Первая редакция стояла на заставке и ждала нажатия — из соображения,
 * что автозапуск раздражает и тратит чужой трафик. Соображение верное
 * для фильма и неверное здесь: запись работает как рисунок, а рисунок
 * не спрашивают, показывать ли его. До нажатия почти никто не доходил,
 * и место под запись стояло молча.
 *
 * Поэтому запись идёт сама, без звука (иначе браузер её не запустит),
 * останавливается вне поля зрения и стоит на первом кадре у тех, кто
 * попросил систему поменьше двигать картинками. Всё это — в `DemoPlayer`,
 * который потому и клиентский.
 */
export function DemoVideo({
  title,
  lead,
  note,
}: {
  title: string
  lead: string
  /** Что делать, если файла ещё нет, — видно только нам. */
  note: string
}) {
  /*
   * Хранилище снаружи выигрывает у файла в сборке: если адрес задан,
   * значит файл уже переехал, и локальная копия — остаток, который
   * иначе продолжал бы показываться вместо новой записи.
   */
  const video = process.env.DEMO_VIDEO_URL || findPublicAsset('product/demo', ['mp4', 'webm', 'mov'])
  const poster =
    process.env.DEMO_POSTER_URL || findPublicAsset('product/demo-poster', ['jpg', 'jpeg', 'png', 'webp'])

  return (
    <section className="mt-20 rounded-2xl bg-basement p-8 text-white sm:p-10">
      <h2 className="text-[26px] font-medium leading-tight sm:text-[30px]">{title}</h2>
      <p className="mt-4 max-w-[70ch] text-[16px] leading-relaxed text-white/70">{lead}</p>

      {/*
         Тень убрана, а обводка стала светлой: тень на тёмном не видна
         вовсе, а тёмная рамка вокруг светлого окна на тёмном поле
         превратилась бы в щель между ними.
      */}
      <div className="mt-8 overflow-hidden rounded-2xl border border-white/10 bg-white">
        {/*
           Верх окна: кружки и строка адреса. Кружки серые, а не красный
           с жёлтым и зелёным, — цветные читались бы как состояние, а тут
           это просто оконная рамка, и цвет ей нечего сообщать.
        */}
        <div className="flex items-center gap-3 border-b border-ink-100 bg-ink-50 px-4 py-2.5">
          <div className="flex gap-1.5">
            {[0, 1, 2].map((i) => (
              <span key={i} className="h-2.5 w-2.5 rounded-full bg-ink-200" />
            ))}
          </div>
          <div className="flex-1 truncate rounded-md bg-white px-3 py-1 text-[11px] text-ink-400">
            {BOOK_HOST}
          </div>
        </div>

        {video ? (
          /*
             Показ идёт сам и без кнопок: разбор — в `DemoPlayer`.
             Прежняя редакция стояла на заставке и ждала нажатия, и это
             была ошибка расчёта. Запись здесь работает как рисунок,
             а рисунок не спрашивают, показывать ли его; нажатие
             и требовалось-то раз в жизни — чтобы убедиться, что кабинет
             существует, — а до нажатия почти никто не доходил.
          */
          <DemoPlayer src={video} poster={poster ?? undefined} />
        ) : (
          /*
           * Пока файла нет — не пустой прямоугольник, а объяснение.
           * Пустое место читается как поломка вёрстки; объяснённое —
           * как то, что оно и есть.
           */
          <div className="flex aspect-[16/9] flex-col items-center justify-center gap-3 bg-ink-50 px-6 text-center">
            <svg width="56" height="56" viewBox="0 0 56 56" fill="none" aria-hidden="true">
              <circle cx="28" cy="28" r="26" fill="#fff" stroke="#D7DBD9" />
              <path d="M23 20l14 8-14 8V20Z" fill="#2E7D52" />
            </svg>
            <p className="max-w-[46ch] text-[14px] leading-relaxed text-ink-500">{note}</p>
          </div>
        )}
      </div>
    </section>
  )
}
