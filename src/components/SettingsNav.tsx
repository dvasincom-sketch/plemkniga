/**
 * Разделы настроек — на всех страницах раздела, а не только на первой.
 *
 * ## Что было не так
 *
 * Настройки расползлись по трём непохожим местам. Видимость данных
 * и профили весов жили вкладкой в кабинете, личные данные и реквизиты —
 * на отдельной странице профиля со своим рядом вкладок, а сотрудники
 * и журнал операций, появившись, встали пунктами верхнего меню — рядом
 * с «Моими животными» и «Данными», то есть рядом с тем, чем пользуются
 * каждый день.
 *
 * От этого верхнее меню выросло до семи пунктов, а связь между ними
 * пропала: «Сотрудники» и «Журнал» — такие же настройки хозяйства, как
 * видимость и реквизиты, и человек, который пришёл «настроить», должен
 * был знать заранее, что часть настроек лежит в другом уровне меню.
 *
 * ## Почему один плоский ряд, а не вложенность
 *
 * Соблазн сгруппировать — «личное» и «хозяйство» — велик и вреден:
 * группировка добавляет третий уровень там, где всего семь пунктов,
 * и заставляет угадывать, к какой группе отнесли нужное. Плоский ряд
 * из семи читается целиком одним взглядом, а угадывать в нём нечего.
 *
 * ## Про порядок
 *
 * Слева то, что правят чаще и что касается всего хозяйства, справа —
 * личное и редкое. Журнал стоит рядом с сотрудниками намеренно: чаще
 * всего в него идут сразу после разговора о том, кто что сделал.
 */

