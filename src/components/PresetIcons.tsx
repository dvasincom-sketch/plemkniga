/**
 * Значки быстрого отбора.
 *
 * ## Почему они не из семейства `CardIcons`
 *
 * Те рисунки — картинки на дверях: крупные, серые, всегда на белом.
 * Здесь другое: плашка меняет цвет, когда отбор выбран, и рисунок обязан
 * меняться вместе с ней. Поэтому всё нарисовано `currentColor` — цвет
 * приходит от плашки, а не задан внутри. Серый значок на зелёном фоне
 * выглядел бы выключенным ровно там, где отбор включён.
 *
 * ## Почему знаки, а не иллюстрации
 *
 * Размер 22 пикселя. На нём стопка листов превращается в серое пятно,
 * а мужской знак, капля, развилка, щит и рубль узнаются силуэтом.
 * Задача этих значков — не рассказать, а дать зацепиться глазу: ряд
 * одинаковых прямоугольников читается дольше, чем ряд разных.
 *
 * ## Почему все они одного веса
 *
 * Плашки равноправны, и ни одна не должна выглядеть главнее соседей.
 * Вес значка задаётся не толщиной штриха — она у всех одна, — а длиной
 * линии: замкнутая фигура во весь квадрат весит вдвое больше трёх
 * отдельных штрихов. Отсюда правило: никаких больших замкнутых контуров.
 */

const S = {
  width: 22,
  height: 22,
  viewBox: '0 0 24 24',
  fill: 'none',
  'aria-hidden': true,
} as const

const stroke = {
  stroke: 'currentColor',
  strokeWidth: 1.7,
  strokeLinecap: 'round',
  strokeLinejoin: 'round',
} as const

/** Бык-производитель — мужской знак. */
const BullIcon = () => (
  <svg {...S}>
    <circle cx="10" cy="14" r="6" {...stroke} />
    <path d="M14.5 9.5 20 4m0 0h-5m5 0v5" {...stroke} />
  </svg>
)

/** Высокий удой — капля со стрелкой вверх. */
const MilkIcon = () => (
  <svg {...S}>
    <path d="M9 3.5c3.5 4 5.5 6.4 5.5 9a5.5 5.5 0 0 1-11 0c0-2.6 2-5 5.5-9Z" {...stroke} />
    <path d="M19 20v-9m0 0-2.5 2.5M19 11l2.5 2.5" {...stroke} />
  </svg>
)

/** Полная родословная — развилка на двух родителей. */
const PedigreeIcon = () => (
  <svg {...S}>
    <circle cx="5.5" cy="5" r="2.5" {...stroke} />
    <circle cx="18.5" cy="5" r="2.5" {...stroke} />
    <circle cx="12" cy="19" r="2.5" {...stroke} />
    <path d="M5.5 7.5v3a2 2 0 0 0 2 2h9a2 2 0 0 0 2-2v-3M12 12.5v4" {...stroke} />
  </svg>
)

/** Знак Ассоциации — щит с галочкой. */
const VerifiedIcon = () => (
  <svg {...S}>
    <path d="M12 3 4.5 6v6c0 4.2 3 7.4 7.5 9 4.5-1.6 7.5-4.8 7.5-9V6L12 3Z" {...stroke} />
    <path d="m8.8 12 2.3 2.3 4.1-4.6" {...stroke} />
  </svg>
)

/**
 * Продажа — знак рубля.
 *
 * Был ярлык с дырочкой под шнурок. Рисунок узнаваемый, но в ряду он
 * выбивался тяжестью: ярлык — замкнутая фигура во весь квадрат, и её
 * периметр даёт вдвое больше линии, чем у соседей, при той же толщине
 * штриха. Глаз читает это как «эта плашка главнее», хотя все семь
 * равноправны.
 *
 * Знак рубля состоит из трёх линий и весит столько же, сколько мужской
 * знак и щит. Смысл при этом не потерян: «выставлено на продажу» — это
 * про цену, а ярлык был про цену лишь по традиции значков.
 */
const SaleIcon = () => (
  <svg {...S}>
    <path d="M8 20V5h4.5a4 4 0 0 1 0 8H8" {...stroke} />
    <path d="M5.5 16.5h7" {...stroke} />
  </svg>
)

/**
 * Подтверждено ДНК — двойная спираль.
 *
 * Первая редакция рисовала три перекладины и две петли, и на двадцати двух
 * пикселях всё это слипалось в узел. Осталось по одному изгибу на нить
 * и две перекладины: спираль узнаётся пересечением, а не числом витков.
 */
const DnaIcon = () => (
  <svg {...S}>
    <path d="M6 3c0 6 12 6 12 9s-12 3-12 9" {...stroke} />
    <path d="M18 3c0 6-12 6-12 9s12 3 12 9" {...stroke} />
    <path d="M8 6.5h8M8 17.5h8" {...stroke} />
  </svg>
)

/**
 * Чистопородные — знак процента.
 *
 * Было кольцо с закрашенной долей: мысль верная — кровность это доля, —
 * но исполнение спорило с соседями. Замкнутый контур во весь квадрат
 * плюс штрих в четыре пикселя против общих одной целой семи давали
 * значок вдвое тяжелее остальных: в ряду он читался как главный.
 * Та же ошибка, что была у ярлыка продажи, и то же правило её ловит —
 * вес значка задаёт длина линии, а не смысл, который в него вложен.
 *
 * Процент весит столько же, сколько мужской знак и щит, и называет
 * ровно то, по чему идёт отбор: кровность по голштину в процентах.
 * Долю целого он показывает хуже кольца — но значок, который спорит
 * с соседями за внимание, врёт заметнее, чем значок, который
 * недоговаривает.
 */
const PurebredIcon = () => (
  <svg {...S}>
    <circle cx="7.5" cy="7.5" r="2.6" {...stroke} />
    <circle cx="16.5" cy="16.5" r="2.6" {...stroke} />
    <path d="M18.5 5.5 5.5 18.5" {...stroke} />
  </svg>
)

const BY_KEY: Record<string, () => React.ReactElement> = {
  bulls: BullIcon,
  milk: MilkIcon,
  pedigree: PedigreeIcon,
  verified: VerifiedIcon,
  dna: DnaIcon,
  purebred: PurebredIcon,
  sale: SaleIcon,
}

/**
 * Значок отбора по его ключу.
 *
 * Отбор без значка рисует пустое место того же размера, а не пропадает:
 * иначе плашки в ряду разъедутся по высоте, и новый отбор, добавленный
 * без картинки, испортит весь ряд, а не одну ячейку.
 */
export function PresetIcon({ preset }: { preset: string }) {
  const Icon = BY_KEY[preset]
  return Icon ? <Icon /> : <span className="block h-[22px] w-[22px]" aria-hidden="true" />
}
