/**
 * Отказ по правам — своим типом, а не текстом.
 *
 * ## Зачем
 *
 * Проверки прав написаны отрицаниями и доказываются попыткой: не вышло —
 * значит нельзя. Отличить отказ по правам от поломки запроса при этом
 * нечем: и то и другое приходит обычным `Error`. Первая редакция
 * различала их по словам в сообщении, и словарь синонимов немедленно
 * отстал — «Наблюдатель не может вносить данные» в него не попало,
 * и три верных запрета отчитались как неопознанные.
 *
 * Словарь синонимов вообще не годится: сообщения пишут людям, они
 * меняются, и проверка, зависящая от их формулировки, ломается от правки
 * запятой. Поэтому отказ теперь заявляет о себе сам.
 *
 * ## Почему и класс, и список текстов
 *
 * Класс — главный признак: `name === 'AccessDenied'`. Но Payload
 * заворачивает ошибку хука в свою и до вызывающего доносит не всегда
 * исходный объект, а текст доносит всегда. Поэтому каждый брошенный
 * отказ заодно записывается в набор `DENIED_TEXTS`, и проверка узнаёт
 * его по тексту, даже потеряв тип.
 *
 * Набор живёт в памяти процесса и растёт только теми сообщениями,
 * которые система вправду бросала. Это не словарь ожидаемых фраз,
 * а след того, что произошло, — отстать он не может по построению.
 */

export class AccessDenied extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'AccessDenied'
  }
}

/**
 * Тексты отказов, брошенных в этом процессе.
 *
 * Читает их `lib/access-attempt.ts`. Ограничения на размер нет намеренно:
 * различных сообщений об отказе в системе десятки, и живут они столько же,
 * сколько процесс.
 *
 * ## Почему набор лежит в `globalThis`
 *
 * Модуль загружается дважды: один раз — приложением и его хуками через
 * настройку Payload, другой — прогоном, который зовёт `attempt`. У двух
 * копий модуля два разных набора, и прогон читал пустой: три верных
 * запрета отчитались как неопознанные ровно поэтому, а не потому,
 * что признак плох.
 *
 * `globalThis` — единственное, что у копий общее. Приём известный и
 * применяется для того же: пул соединений и клиент Payload живут в нём
 * по той же причине.
 */
const store = globalThis as typeof globalThis & { __plemDeniedTexts?: Set<string> }
export const DENIED_TEXTS: Set<string> = (store.__plemDeniedTexts ??= new Set<string>())

/** Бросить отказ по правам. Возвращаемый тип — `never`: дальше кода нет. */
export function denyAccess(message: string): never {
  DENIED_TEXTS.add(message)
  throw new AccessDenied(message)
}
