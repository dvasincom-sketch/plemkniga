#!/usr/bin/env bash
#
# Шесть групп проверок: коммиты для партии от 23 августа.
#
# Скрипт ничего не собирает и не мигрирует — только коммитит. Порядок
# действий целиком описан ниже, и первые три шага делаются руками,
# потому что каждый из них может упасть, а падение сборки внутри
# скрипта, который уже что-то закоммитил, разбирать хуже, чем не начинать.
#
#   1. npm run generate:types   ← ОБЯЗАТЕЛЬНО ПЕРВЫМ
#   2. npm run db:sync          ← применить миграцию вердикта ДНК
#   3. перезапустить next dev   ← схема коллекций строится при старте
#   4. npx tsc --noEmit && npm run build
#   5. bash commit.sh
#   6. git push origin main
#
# Почему generate:types первым. `data-checks.ts` читает `t.verdict`
# у ДНК-теста. Поля в `payload-types.ts` до перегенерации нет, и tsc
# упадёт на строке, которая на самом деле верна.

set -u
cd ~/plemkniga || exit 1

# Прошлый раз коммиты молча не проходили из-за оставшегося lock-файла:
# git падал, `set -e` глушил всё остальное, и на экране было пусто.
# Поэтому проверяем явно и говорим вслух, а не удаляем втихую.
for lock in .git/index.lock .git/HEAD.lock; do
  if [ -e "$lock" ]; then
    echo "ВНИМАНИЕ: есть $lock."
    echo "Если git сейчас не запущен, удалите файл и повторите: rm $lock"
    exit 1
  fi
done

export GIT_AUTHOR_NAME="Dmitry Vasin"
export GIT_AUTHOR_EMAIL="dvasin.com@gmail.com"
export GIT_COMMITTER_NAME="Dmitry Vasin"
export GIT_COMMITTER_EMAIL="dvasin.com@gmail.com"

commit () {
  local msg="$1"; shift
  git add -- "$@" || return 1
  if git diff --cached --quiet; then
    echo "— нечего коммитить: $msg"
    return 0
  fi
  git commit -m "$msg" || return 1
  echo "✓ $msg"
}

